/**
 * 量面板.cjs —— 算一算「账本」小面板里的东西放不放得下
 *
 * 【为什么要在意这个】
 *   面板窗口是固定大小的（208 x 236，在 main.js 里）。里面的字要是
 *   加起来超过这个高度，CSS 又没写滚动条，**多出来的部分会直接被切掉**。
 *   而且那种错很安静：窗口看着正常，只是最后一行"输出"不见了。
 *
 *   所以这里把 HTML 里每一块的高度按 CSS 的规则加一遍，跟窗口对一下。
 *   （改面板的样式之后，跑一下这个。）
 *
 * 用法: node tools\量面板.cjs
 */
'use strict'

const 窗口宽 = 208
const 窗口高 = 236
const 边框 = 1
const 内宽 = 窗口宽 - 边框 * 2
const 内高 = 窗口高 - 边框 * 2

// 每一块的高度，来源是 renderer\账本.css 里那些数字
const 块们 = [
  // 顶栏：padding 6 + 5，字 11px 行高约 13，下边框 1
  ['顶栏（账本 ×）', 6 + 5 + 13 + 1],

  // 大数区：padding 10 + 8，钱 22px 行高 1.1 ≈ 24，小字 10px ≈ 12，中间 2
  ['这一句花了多少（大）', 10 + 8 + 24 + 2 + 12],

  // 两组：自己 padding 6+6，组名 10px≈12，组钱 15px≈18，组次 9px≈11，下面 8
  ['今天 / 一共（两格）', 8 + 6 + 6 + 12 + 2 + 18 + 11],

  // 明细三行：每行 2+2 的 padding + 10px 字≈15
  ['明细（输入/命中/输出）', 3 * (4 + 15)],

  // 底栏：padding 6 + 8 + 9px 字≈11
  ['底栏（命中率 / 流水）', 6 + 8 + 11],
]

let 合计 = 0
console.log('')
console.log('  窗口 ' + 窗口宽 + ' x ' + 窗口高 + '，里面能用的地方 ' + 内宽 + ' x ' + 内高)
console.log('')
for (const [名, 高] of 块们) {
  合计 += 高
  console.log('  ' + 名.padEnd(24, ' ') + String(高).padStart(4) + ' px')
}
console.log('  ' + '-'.repeat(30))
console.log('  ' + '合计'.padEnd(24, ' ') + String(合计).padStart(4) + ' px')
console.log('')

if (合计 <= 内高) {
  console.log('  ✓ 放得下，还剩 ' + (内高 - 合计) + ' px（这点余量是好的，字大小随系统缩放会变）')
} else {
  console.log('  ✗ 超了 ' + (合计 - 内高) + ' px —— 最后一行会被切掉，得把窗口调高或者把字缩小')
}

console.log('')
console.log('  宽度这边：最宽的一行是「其中命中缓存   1,234,567」，')
console.log('  两边 padding 各 10，中间留点空，大约需要 ' + (10 + 60 + 70 + 10) + ' px，窗口内宽 ' + 内宽 + ' px。')
console.log('  （数字用的 tabular-nums，位数变化时不会左右跳。）')
console.log('')
