/**
 * 测学习任务.cjs —— 那张待办清单，三边一起改，会不会乱
 *
 * 【它治什么】
 *   这个功能特殊在**三方都在写同一份文件**：
 *     · 他在抽屉里勾
 *     · 她在对话里用 [任务:] 加
 *     · 他自己也可能直接拿编辑器改
 *   所以最要紧的不是"能不能加"，是"**别人改过之后还对不对得上**"。
 *
 *   两格特别要盯的：
 *     · 勾一条时"对不上"必须**如实说找不到**，绝不能猜一条最像的勾上 ——
 *       猜错了清单会安静地变脏，而且他不会知道
 *     · 清单文件里**他自己写的东西**（标题、说明、随手记的）不能被抹掉
 *
 * 【不花钱】全程本地，一个模型请求都不发。
 *
 * 用法: node tools\测学习任务.cjs
 */
'use strict'

const fs = require('node:fs')
const path = require('node:path')

const 项目根 = path.resolve(__dirname, '..')
const 脑 = path.join(项目根, '脑')
const 测试目录 = path.join(项目根, '.cache', '_测学习任务')
const 测试文件 = path.join(测试目录, '任务.md')

// 【必须在 require 之前设】不然会去动真的 学习\任务.md
process.env.ELYSIA_任务文件 = 测试文件

let 过了 = 0
let 总数 = 0
function 检查(说明, 条件, 细节 = '') {
  总数++
  if (条件) {
    过了++
    console.log(`  ✓ ${说明}`)
  } else {
    console.log(`  ✗ ${说明}${细节 ? '   → ' + 细节 : ''}`)
  }
}

async function 主() {
  fs.rmSync(测试目录, { recursive: true, force: true })
  fs.mkdirSync(测试目录, { recursive: true })

  console.log('')
  console.log('  ════════════════════════════════════════════')
  console.log('   学习任务 —— 三边一起改，对得上吗')
  console.log('  ════════════════════════════════════════════')
  console.log('')

  const 学习任务 = require(path.join(脑, '学习任务.cjs'))
  const 工具表 = require(path.join(脑, '工具表.cjs'))

  // -------------------------------------------------------------
  console.log('  ── 一、文件这一层 ──')

  检查('路径落在测试目录里（没跑到真的学习区去）', 学习任务.路径() === 测试文件, 学习任务.路径())
  检查('刚开始没有这个文件', 学习任务.有吗() === false)
  检查('读不出来时给空清单，不报错', 学习任务.读().length === 0)

  检查('建了一个空的', 学习任务.建空的() === true)
  检查('  空壳里写着"还没有任务"', 学习任务.读().length === 0)
  检查('  再建一次不覆盖', 学习任务.建空的() === false)

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 二、加 ──')

  const 甲 = 学习任务.加('看完第一章课件')
  检查('加进去了', 甲.好 === true)
  const 乙 = 学习任务.加('装好 C 环境')
  检查('再加一条', 乙.好 === true)
  检查('  清单里现在两条', 学习任务.读().length === 2)

  const 丙 = 学习任务.加('看完第一章课件')
  检查('★ 一模一样的不会重复加', 丙.好 === false && 丙.说明.includes('已经在'), JSON.stringify(丙))
 检查('  清单还是两条', 学习任务.读().length === 2)

  const 丁 = 学习任务.加('   ')
  检查('空的加不进去', 丁.好 === false)
  const 戊 = 学习任务.加('啊'.repeat(300))
 检查('太长的加不进去（200 字上限）', 戊.好 === false)

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 三、勾 ──')

  const 己 = 学习任务.勾('看完第一章课件', true)
  检查('勾得上（原话）', 己.好 === true)
  检查('  统计跟着变了', 学习任务.统计().做完 === 1)

  const 庚 = 学习任务.勾('C 环境', true)
  检查('★ 只写一部分也勾得上（唯一就行）', 庚.好 === true && 庚.文字 === '装好 C 环境', JSON.stringify(庚))
  检查('  两条都做完了', 学习任务.统计().做完 === 2)

  const 辛 = 学习任务.勾('看完第一章课件', false)
  检查('取消勾选也认', 辛.好 === true && 学习任务.统计().做完 === 1)

  // 【最要紧的一格】找不到就如实说，不许猜
  const 壬 = 学习任务.勾('根本没这条任务', true)
  检查('★ 找不到就说找不到，绝不乱勾', 壬.好 === false && 壬.说明.includes('没有'), JSON.stringify(壬))
  检查('  清单一个字没动', 学习任务.统计().做完 === 1)

  // 对得上好几条的时候也不能猜
  学习任务.加('做完第一章的练习')
  学习任务.加('做完第二章的练习')
  const 癸 = 学习任务.勾('做完第', true)
  检查('★ 能对上好几条时：拒绝，并且把候选列出来', 癸.好 === false && 癸.说明.includes('好几条'), JSON.stringify(癸))

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 四、★ 他自己拿编辑器改过之后 ──')

  // 模拟：他手写了一段自己的东西，还删了一条、加了一条
  fs.writeFileSync(
    测试文件,
    '# 学习任务\n\n' +
      '## 这周\n\n' +
      '- [ ] 看完第一章课件\n' +
      '- [x] 装好 C 环境\n' +
      '\n' +
      '## 下周（我自己排的）\n\n' +
      '顺手记一句：老师说期中会考到第三章\n' +
      '- [ ] 第三章那三道题\n',
    'utf8',
  )

  const 读到的 = 学习任务.读()
  检查('★ 他手写的东西不影响读任务（标题、说明都读得出来）', 读到的.length === 3, JSON.stringify(读到的))
  检查('  完成状态读得对', 读到的[1].完成 === true && 读到的[0].完成 === false)

  const 勾他的 = 学习任务.勾('第三章那三道题', true)
  检查('★ 能勾他手写进去的那条', 勾他的.好 === true)
  检查('★ 他那句"老师说要考第三章"还在', fs.readFileSync(测试文件, 'utf8').includes('期中会考到第三章'))

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 五、删（只有他能做）──')

  const 删果 = 学习任务.删('看完第一章课件')
  检查('删得掉', 删果.好 === true)
  检查('  剩下两条', 学习任务.读().length === 2)
  const 删空 = 学习任务.删('没这条')
  检查('删不存在的：如实说', 删空.好 === false)

  // 【加新任务、以及删光之后：他手写的行都得活着】
  const 加他的 = 学习任务.加('预习第四章')
  const 改后 = fs.readFileSync(测试文件, 'utf8')
  检查('★ 加一条新任务：他的小标题还在', 加他的.好 === true && 改后.includes('## 下周（我自己排的）'))
  检查('★ 加一条新任务：他记的那句话还在', 改后.includes('期中会考到第三章'))
  检查('  新任务确实进去了', 学习任务.读().some((x) => x.文字 === '预习第四章'))

  学习任务.写([])
  const 空后 = fs.readFileSync(测试文件, 'utf8')
  检查('★ 删光之后留一句"（还没有任务。）"，不是一片空白', 空后.includes('（还没有任务。）'))
  检查('★ 删光之后他写的行也还在', 空后.includes('## 下周（我自己排的）') && 空后.includes('期中会考到第三章'))
  检查('  读出来是 0 条', 学习任务.读().length === 0)

  学习任务.加('背单词')
  检查('★ 有任务了，"（还没有任务。）"就该消失', !fs.readFileSync(测试文件, 'utf8').includes('（还没有任务。）'))

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 六、★ 她那块表里有没有"任务"这只手 ──')

  const 工 = 工具表.拿到('任务')
  检查('工具表里有「任务」', !!工)
  检查('  危险度是 safe（改清单不值得每次弹卡片）', 工 && 工.危险度 === 'safe')

  function 试(说法) {
    return 工.做(说法)
  }

  学习任务.写([{ 文字: '看完第二章', 完成: false }])

  const 她加 = 试('加 做完课后题')
  检查('她说「加」：加得上', 她加.好 === true, JSON.stringify(她加))
  const 她默 = 试('背下公式表')
  检查('她不说动词：也当"加"', 她默.好 === true, JSON.stringify(她默))

  const 她勾 = 试('勾 看完第二章')
  检查('她说「勾」：勾得上', 她勾.好 === true, JSON.stringify(她勾))
  const 她完 = 试('做完课后题')
  检查('她说「做完 xx」：当成勾（不是加）', 她完.好 === true)

  const 她找不着 = 试('勾 根本不存在的活儿')
  检查('★ 她勾一条没有的：如实说，不猜', 她找不着.好 === false && 她找不着.说明.includes('没有'), JSON.stringify(她找不着))

  // 【这一格盯的是"她不该有删"】
  const 她删 = 试('删 看完第二章')
  检查('★ 她说「删」：删不掉（那不是她的动作）', 学习任务.读().some((x) => x.文字 === '看完第二章'), JSON.stringify(她删))

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 七、给她看的那一段 ──')

  学习任务.写([
    { 文字: '看完第一章', 完成: true },
    { 文字: '做三道题', 完成: false },
  ])
  const 话 = 学习任务.拼给她()
  检查('带着清单本身', 话.includes('看完第一章') && 话.includes('做三道题'))
  检查('  写了"共几条、做完几条"', 话.includes('一共 2 条') && 话.includes('做完 1 条'))
  检查('  写了清单文件在哪', 话.includes(测试文件))
  检查('★ 提醒了她用 [任务:] 改，别直接写文件', 话.includes('[任务:]'))

  学习任务.写([])
  检查('空清单也说话（不然她分不清"没任务"和"没读到"）', 学习任务.拼给她().includes('清单是空的'))

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 八、收尾 ──')

  fs.rmSync(测试目录, { recursive: true, force: true })
  检查('测试目录擦掉了（没往真的学习区里丢垃圾）', !fs.existsSync(测试目录))

  console.log('')
  console.log('  ════════════════════════════════════════════')
  console.log(`   ${过了} / ${总数}`)
  console.log('  ════════════════════════════════════════════')
  console.log('')
  process.exit(过了 === 总数 ? 0 : 1)
}

主().catch((错误) => {
  console.log('  ✗ 测试自己炸了：' + (错误 && 错误.stack))
  process.exit(1)
})
