/** 只读时间线关系候选：全部使用假记忆库与系统临时目录。 */
'use strict'

const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const crypto = require('node:crypto')
const 模块 = require('../脑/记忆时间线候选.cjs')

let 总数 = 0
let 通过 = 0
function 检查(名称, 条件) {
  总数++
  if (!条件) throw new Error('未通过：' + 名称)
  通过++
  console.log('✓ ' + 名称)
}
function 哈希(文件) { return crypto.createHash('sha256').update(fs.readFileSync(文件)).digest('hex') }
function 结构(改 = {}) { return { 记忆类型: 'episodic', 元数据: { person: '用户本人', relationship: '本人' }, ...改 } }

const 绝对日 = 模块.解析事件时间文本('2026年9月18日第一次见面')
检查('中文绝对日期解析为事件日', 绝对日.状态 === '明确' && 绝对日.开始 === '2026-09-18' && 绝对日.依据 === '正文绝对日期')
const 跨月 = 模块.解析事件时间文本('明天去图书馆', '2026-10-31T08:00:00.000Z')
检查('相对日期按来源消息时间跨月换算', 跨月.开始 === '2026-11-01' && 跨月.依据.includes('来源消息时间'))
const 跨年 = 模块.解析事件时间文本('明年一月再看')
检查('缺少来源时间的相对年份不会强行换算', 跨年.状态 === '相对未解析' && !跨年.排序键)
const 周末 = 模块.解析事件时间文本('下周六去图书馆', '2026-10-22T08:00:00.000Z')
检查('相对星期按来源消息日期定位', 周末.开始 === '2026-10-31' && 周末.精度 === '日')
const 未知 = 模块.解析事件时间文本('昨天终于完成练习')
检查('相对时间没有消息时间时留在未解析组', 未知.状态 === '相对未解析' && 未知.原文 === '昨天')
const 月份 = 模块.解析事件时间文本('2026年9月开始军训')
检查('月份保存时间精度和完整区间', 月份.精度 === '月' && 月份.开始 === '2026-09-01' && 月份.结束 === '2026-09-30')
检查('非法结构化日期不会进入确定时间线', 模块.解析结构化事件时间({ 开始: '2026-02-30' }) === null)

const 晚说早事 = 模块.统一记录({ 编号: 'late', 类别: '经历', 内容: '2026年9月5日完成了第一次练习', 时间: '2026-10-20 10:00', ...结构() }, '长期记忆', 0)
检查('写入时间与事件时间分开保存', 晚说早事.事件时间.开始 === '2026-09-05' && 晚说早事.写入时间 === '2026-10-20 10:00')
const 无事件 = 模块.统一记录({ 编号: 'unknown', 类别: '经历', 内容: '昨天完成了第二次练习', 时间: '2026-01-01 00:00', ...结构() }, '长期记忆', 1)
检查('写入时间绝不冒充事件时间', 无事件.事件时间.状态 === '相对未解析' && !无事件.事件时间.排序键)
const 计划 = 模块.统一记录({ 编号: 'plan', 类别: '经历', 内容: '明天去图书馆', 创建于: '2099-01-01T00:00:00.000Z', 来源: { 消息时间: '2026-10-22T08:00:00.000Z', 提取方式: '模型提取' }, ...结构() }, '临时记忆', 2)
检查('计划事件使用消息时间解析且不受未来写入时间影响', 计划.事件时间.开始 === '2026-10-23' && 计划.计划状态 === '计划中')

const a = 模块.统一记录({ 编号: 'a', 类别: '经历', 内容: '2026年10月1日开始学习C语言', 事件时间: '2026-10-01', ...结构() }, '长期记忆', 0)
const b = 模块.统一记录({ 编号: 'b', 类别: '经历', 内容: '2026年10月5日后来继续学习C语言', 事件时间: '2026-10-05', ...结构() }, '长期记忆', 1)
const c = 模块.统一记录({ 编号: 'c', 类别: '经历', 内容: '2026年10月8日现在改成学习JavaScript', 事件时间: '2026-10-08', ...结构() }, '长期记忆', 2)
const d = 模块.统一记录({ 编号: 'd', 类别: '事实', 内容: '2026年10月1日喜欢喝咖啡', 事件时间: '2026-10-01', 记忆类型: 'semantic', 元数据: { person: '用户本人', relationship: '本人' } }, '长期记忆', 3)
const e = 模块.统一记录({ 编号: 'e', 类别: '事实', 内容: '2026年10月2日不喜欢喝咖啡', 事件时间: '2026-10-02', 记忆类型: 'semantic', 元数据: { person: '用户本人', relationship: '本人' } }, '长期记忆', 4)
const 别人 = 模块.统一记录({ 编号: 'other', 类别: '经历', 内容: b.内容, 事件时间: '2026-10-06', ...结构({ 元数据: { person: '小林', relationship: '朋友' } }) }, '长期记忆', 5)
const 关系 = 模块.关系候选([a, b, c, d, e, 别人], { 相似阈值: 0.2 })
检查('后续发展按事件先后给出方向', 关系.some((一) => 一.类型 === '后续发展' && 一.从编号 === 'a' && 一.到编号 === 'b'))
检查('更新只在有时间顺序与更新措辞时给出', 关系.some((一) => 一.类型 === '更新' && 一.到编号 === 'c'))
检查('肯定与否定只生成矛盾候选而不自动裁决', 关系.some((一) => 一.类型 === '矛盾' && [一.从编号, 一.到编号].includes('d') && [一.从编号, 一.到编号].includes('e')))
检查('相关且时间明确的记忆同时产生先于和后于候选', 关系.some((一) => 一.类型 === '先于' && 一.从编号 === 'a' && 一.到编号 === 'b') && 关系.some((一) => 一.类型 === '后于' && 一.从编号 === 'b' && 一.到编号 === 'a'))
检查('不同人物与关系不会被串联', !关系.some((一) => 一.从编号 === 'other' || 一.到编号 === 'other'))
检查('关系类型严格限制在白名单且不含因果', 关系.every((一) => 模块.关系白名单.includes(一.类型)) && !关系.some((一) => /因果|导致/.test(一.类型)))
const 同日无关甲 = 模块.统一记录({ 编号: 'date-x', 类别: '经历', 内容: '2026年10月16日上了高数课', ...结构() }, '长期记忆', 6)
const 同日无关乙 = 模块.统一记录({ 编号: 'date-y', 类别: '经历', 内容: '2026年10月16日修好了桌宠窗口', ...结构() }, '长期记忆', 7)
检查('相同日期本身不会把无关事件串成同一主题', 模块.关系候选([同日无关甲, 同日无关乙]).length === 0)

const 报告 = 模块.生成报告({ 记录们: [计划, 无事件, 晚说早事, b, a], 现在: () => new Date('2026-10-22T12:00:00.000Z'), 相似阈值: 0.3 })
检查('确定时间线始终按事件时间从早到晚', 报告.已确定时间线.map((一) => 一.编号).join(',') === 'late,a,b,plan')
检查('未知时间单独分组且不插入确定时间线', 报告.时间未确定.length === 1 && 报告.时间未确定[0].编号 === 'unknown')
检查('报告明确禁止写图、召回和因果推断', 报告.用途.includes('不写关系图') && 报告.规则.自动写入 === false && 报告.规则.因果 === '不自动推断')

const 临时条 = [
  { 编号: 't-ok', 类别: '近期计划', 内容: '明天去图书馆', 生命周期: '有效', 确认状态: '已确认', 到期于: '2026-11-01T00:00:00.000Z', 来源: { 消息时间: '2026-10-22T08:00:00.000Z', 提取方式: '模型提取' }, ...结构(), 关系: { 状态: '当前' } },
  { 编号: 't-pending', 类别: '近期计划', 内容: '后天去公园', 生命周期: '有效', 确认状态: '待确认', 到期于: '2026-11-01T00:00:00.000Z', ...结构() },
  { 编号: 't-replaced', 类别: '近期计划', 内容: '明天去旧地点', 生命周期: '有效', 确认状态: '已确认', 到期于: '2026-11-01T00:00:00.000Z', ...结构(), 关系: { 状态: '已被替代' } },
]
const 读取 = 模块.读取记忆({ 临时记忆库: { 查询: () => ({ 列表: 临时条 }) }, 长期记忆库: { 全部长期记忆: () => [] }, 现在: () => new Date('2026-10-22T00:00:00.000Z') })
检查('只读取有效已确认且当前版本的临时记忆', 读取.记录.length === 1 && 读取.记录[0].编号 === 't-ok')

const 临时根 = fs.mkdtempSync(path.join(os.tmpdir(), 'elysia-timeline-'))
try {
  const 原始文件 = path.join(临时根, '原始记忆.json')
  const 输出文件 = path.join(临时根, 'cache', '时间线候选.json')
  const 图文件 = path.join(临时根, '记忆', '关系图.json')
  fs.writeFileSync(原始文件, JSON.stringify([a, b, 无事件], null, 2), 'utf8')
  const 前 = 哈希(原始文件)
  const 假临时库 = { 查询: () => ({ 列表: [] }) }
  const 假长期库 = { 全部长期记忆: () => JSON.parse(fs.readFileSync(原始文件, 'utf8')) }
  const 甲 = 模块.生成并保存({ 输出文件, 临时记忆库: 假临时库, 长期记忆库: 假长期库, 现在: () => new Date('2026-10-22T01:00:00.000Z'), 相似阈值: 0.3 })
  const 乙 = 模块.生成并保存({ 输出文件, 临时记忆库: 假临时库, 长期记忆库: 假长期库, 现在: () => new Date('2026-10-22T02:00:00.000Z'), 相似阈值: 0.3 })
  const 盘 = JSON.parse(fs.readFileSync(输出文件, 'utf8'))
  检查('报告只原子写入指定缓存文件', fs.existsSync(输出文件) && 盘.用途.includes('只读时间线'))
  检查('重复生成保持输入指纹和候选编号稳定', 甲.报告.输入指纹 === 乙.报告.输入指纹 && JSON.stringify(甲.报告.关系候选.map((一) => 一.编号)) === JSON.stringify(乙.报告.关系候选.map((一) => 一.编号)))
  检查('生成报告不改原记忆且不创建关系图', 哈希(原始文件) === 前 && !fs.existsSync(图文件))
  检查('原子写入不遗留临时文件', !fs.readdirSync(path.dirname(输出文件)).some((名) => 名.endsWith('.tmp')))
} finally {
  fs.rmSync(临时根, { recursive: true, force: true })
}

let 报错 = false
try { 模块.关系候选([a, b], { 相似阈值: 0 }) } catch { 报错 = true }
检查('非法相似阈值会被拒绝', 报错)

console.log(`\n记忆时间线候选：${通过}/${总数} 通过`)
