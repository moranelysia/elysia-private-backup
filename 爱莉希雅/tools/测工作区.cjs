/**
 * 测工作区.cjs —— 他选的那个"干活目录"到底怎么影响她的权限
 *
 * 【为什么这个必须单独测】
 *   这是整个项目里**唯一一个"他随手就能扩大她权限"的地方**。
 *   他在界面上点一下选文件夹，那个目录就成了她能写的地方 ——
 *   所以他选了哪儿、没选哪儿，权限得跟着变，而且变得对。
 *
 *   三种情况都要量：
 *     1. 没选（默认）：只能写她的记忆目录 + 她家那一层
 *     2. 选了别的目录：那个目录也能写了
 *     3. 选了包含她代码的目录（比如整个 D 盘）：**代码还是不能写**
 *        —— 这条最要紧。不然他为了让她做个 PPT 选了 D 盘，
 *        她顺手就能把自己的代码改了。
 *
 * 用法: node tools\测工作区.cjs
 */
'use strict'

const fs = require('node:fs')
const path = require('node:path')

const 项目根 = path.resolve(__dirname, '..')
const 工作区根 = path.resolve(项目根, '..')

const 路径安全 = require(path.join(项目根, '脑', '路径安全.cjs'))
const 文件工具 = require(path.join(项目根, '脑', '工具', '文件工具.cjs'))

let 过了 = 0
let 总数 = 0

function 检查(说明, 条件, 细节 = '') {
  总数++
  if (条件) {
    过了++
    console.log(`  ✓ ${说明}`)
  } else {
    console.log(`  ✗ ${说明}${细节 ? '   → ' + 细节 : ''}`)
  }
}

/** 只看放不放行 */
function 能写吗(绝对) {
  return 路径安全.查(绝对, '写', { 要新建: true }).好
}

async function main() {
  console.log('')
  console.log('  ════════════════════════════════════════════')
  console.log('   他选的干活目录，怎么影响她的权限')
  console.log('  ════════════════════════════════════════════')

  // 造两个临时目录当"他选的工作区"。
  //
  // 【为什么必须建在工作区根**外面**】
  //   第一版建在里面（D:\新建文件夹\_ws-a），结果四个用例全"失败"——
  //   因为工作区根本来就在写白名单里，里面的东西当然都能写。
  //   那样测的就不是"他选的目录有没有生效"，而是"白名单有没有生效"。
  //   要测前者，目录就得在外面。
  const 甲 = path.join(工作区根, '..', '_ws-a')
  const 乙 = path.join(工作区根, '..', '_ws-b')
  fs.rmSync(甲, { recursive: true, force: true })
  fs.rmSync(乙, { recursive: true, force: true })
  fs.mkdirSync(甲, { recursive: true })
  fs.mkdirSync(乙, { recursive: true })
  console.log('')
  console.log(`  （测试用的两个目录：${甲} 、 ${乙}）`)

  // ---------------------------------------------------------------
  console.log('')
  console.log('  ── 一、没选工作区（默认）──')

  路径安全.设工作区(null)

  检查('能写她的记忆目录', 能写吗(path.join(项目根, '记忆', 'x.json')))
  检查('能写她家那一层', 能写吗(path.join(工作区根, 'x.md')))
  检查('不能写临时目录甲', !能写吗(path.join(甲, 'x.md')), '（没选它就不该能写）')
  检查('不能写她的代码', !能写吗(path.join(项目根, '脑', 'x.cjs')))

  // ---------------------------------------------------------------
  console.log('')
  console.log('  ── 二、选了甲 ──')

  路径安全.设工作区(甲)

  检查('甲里能写了', 能写吗(path.join(甲, 'x.md')))
  检查('甲里新建子目录也行', 能写吗(path.join(甲, '子目录', 'y.md')))
  检查('乙还是不能写', !能写吗(path.join(乙, 'x.md')))
  检查('她的记忆照样能写', 能写吗(path.join(项目根, '记忆', 'x.json')))
  检查('她的代码还是不能写', !能写吗(path.join(项目根, '脑', 'x.cjs')))

  // ---------------------------------------------------------------
  console.log('')
  console.log('  ── 三、选了一个"包住她代码"的大目录（最危险那种）──')
  //
  // 他为了让她做个 PPT，可能直接选 D:\新建文件夹（她的家）。
  // 那一层里就装着她的代码。所以"选了之后代码也不能写"这条必须成立。

  路径安全.设工作区(工作区根)

  检查('她家那一层能写', 能写吗(path.join(工作区根, 'x.md')))
  检查('**代码还是不能写**（脑里面）', !能写吗(path.join(项目根, '脑', 'x.cjs')), '这条要是破了，他选个目录就等于把她的代码交出去了')
  检查('界面代码不能写', !能写吗(path.join(项目根, 'renderer', 'x.js')))
  检查('AGENTS.md 不能写', !能写吗(path.join(工作区根, 'AGENTS.md')))
  检查('共同经历不能写', !能写吗(path.join(工作区根, '共同经历.md')))
  检查('钥匙文件不能写', !能写吗(path.join(项目根, '脑', '钥匙.txt')))
  检查('DSH 的配置不能写', !能写吗(path.join(工作区根, '.dsh', 'x.yml')))

  // ---------------------------------------------------------------
  console.log('')
  console.log('  ── 四、换个工作区，真的能落盘吗（走一遍工具）──')

  路径安全.设工作区(甲)
  const 结果 = await 文件工具.写(path.join(甲, 'note.md'), '写在甲里的', { 问: async () => true })
  检查('写到甲里成功', 结果.好, 结果.说明)
  检查('文件真的在甲里', fs.existsSync(path.join(甲, 'note.md')))

  路径安全.设工作区(乙)
  const 结果2 = await 文件工具.写(path.join(甲, 'note2.md'), '现在甲不该能写了', { 问: async () => true })
  检查('换成乙之后，甲就不能写了', !结果2.好, 结果2.说明)

  // ---------------------------------------------------------------
  console.log('')
  console.log('  ── 五、收尾 ──')

  路径安全.设工作区(null)
  fs.rmSync(甲, { recursive: true, force: true })
  fs.rmSync(乙, { recursive: true, force: true })
  检查('临时目录清干净了', !fs.existsSync(甲) && !fs.existsSync(乙))
  检查('清掉工作区之后，甲也不能写了', !能写吗(path.join(甲, 'x.md')))

  console.log('')
  console.log('  ════════════════════════════════════════════')
  console.log(`   ${过了} / ${总数}` + (过了 === 总数 ? '   ✓ 全过' : '   ✗ 有不对的'))
  console.log('  ════════════════════════════════════════════')
  console.log('')
}

main().catch((错误) => {
  console.log('✗ 测试自己出错了: ' + 错误.message)
  console.log(错误.stack.split('\n').slice(0, 4).join('\n'))
  process.exit(1)
})
