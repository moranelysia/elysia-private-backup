/** P1-D 本地相似度测试：纯字符串，不读写文件。 */
'use strict'
const assert = require('node:assert/strict')
const { 归一, 相似度, 判断重复 } = require('../脑/主动陪伴去重.cjs')
let 数量 = 0
function 检查(说明, 条件) { assert.ok(条件, 说明); 数量++; console.log('✓ ' + 说明) }

检查('归一化忽略标点、空格和全半角差异', 归一('嗨， 今天还好吗？') === 归一('嗨!今天还好吗?'))
检查('完全相同会被拦截', 判断重复('要不要休息一下呀？', ['要不要休息一下呀♪']).重复)
检查('只改少量措辞的长句会被拦截', 判断重复('忙了这么久，要不要稍微休息一下呀？', ['忙了这么久，要不要稍微歇一会儿呀？']).重复)
检查('不同话题不会被误拦截', !判断重复('窗外的晚霞应该很好看呢。', ['喝口水，休息一下吧。']).重复)
检查('很短的常用问候只有完全相同才拦', !判断重复('在吗', ['嗨呀']).重复 && 判断重复('在吗', ['在吗']).重复)
检查('相似度始终在零到一之间', 相似度('爱莉希雅', '爱莉希雅') === 1 && 相似度('苹果', '课程') >= 0 && 相似度('苹果', '课程') <= 1)
检查('最多只比较近期八条', !判断重复('最早那条独特内容', ['最早那条独特内容', ...Array(8).fill('后来完全不同')]).重复)
console.log(`\n主动陪伴去重：${数量}/${数量} 通过`)
