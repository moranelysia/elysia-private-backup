'use strict'
const assert = require('node:assert/strict')
const { 取域名, 来源归属, 来源类型, 日期状态, 检查单条, 评估材料 } = require('../脑/搜索来源.cjs')

let 数 = 0
function 测(名字, 条件) { assert.ok(条件, 名字); 数++; console.log('✓ ' + 名字) }

测('提取并统一小写域名', 取域名('HTTPS://WWW.CMA.GOV.CN/a') === 'www.cma.gov.cn')
测('拒绝本地文件协议', 取域名('file:///C:/secret.txt') === '')
测('同一站点的子域折叠为同一来源归属', 来源归属('docs.nodejs.org') === 'nodejs.org')
测('复合公共后缀保留注册主体', 来源归属('www.cma.gov.cn') === 'cma.gov.cn')
测('政府子域保守标记为政府公共机构域名', 来源类型('www.cma.gov.cn') === '政府/公共机构域名')
测('伪政府后缀不会通过', 来源类型('gov.cn.example.com') === '普通网页（未证明为官网）')
测('高校域名单独分类', 来源类型('news.tsinghua.edu.cn') === '高校/科研机构域名')
测('国际组织域名支持子域', 来源类型('data.who.int') === '国际组织域名')
测('代码平台不会冒充项目官网', 来源类型('github.com') === '代码托管平台')
测('普通网页明确未证明官网身份', 来源类型('nodejs.org') === '普通网页（未证明为官网）')
测('缺日期明确显示空态', 日期状态('') === '未提供日期')
测('相对日期不会冒充已核对时间', 日期状态('2 days ago') === '相对日期（待换算）')
测('绝对日期仍标为待核对', 日期状态('2026-10-15') === '已提供日期（待核对）')

const 单条 = 检查单条({ 链接: 'https://github.com/nodejs/node', 发布日期: '' })
测('单条结果标明证据仅是摘要', 单条.来源类型 === '代码托管平台' && 单条.证据范围.includes('未读取网页正文'))

const 评估 = 评估材料([
  { 标题: 'A', 链接: 'https://www.cma.gov.cn/a', 发布日期: '2026-10-15' },
  { 标题: 'B', 链接: 'https://example.com/b', 发布日期: '' },
  { 标题: 'C', 链接: 'https://example.com/c', 发布日期: '昨天' },
])
测('聚合不同域名且同域去重', 评估.审查.不同域名数 === 2)
测('聚合给出保守的不同来源数', 评估.审查.不同来源数 === 2)
测('聚合日期覆盖状态', 评估.审查.有日期数 === 2 && 评估.审查.日期覆盖 === '部分带日期')
测('多域名不宣称已经交叉验证', 评估.审查.来源覆盖.includes('仍需核对'))
测('聚合保留逐条来源标签', 评估.结果[0].来源类型 === '政府/公共机构域名' && 评估.结果[1].日期状态 === '未提供日期')

console.log(`搜索来源：${数}/${数} 通过`)
