/** P1-A 主动陪伴调度：假时钟、假定时器，不调用模型或写真实数据。 */
'use strict'
const assert = require('node:assert/strict')
const { 创建调度器, 规范配置, 在安静时段 } = require('../脑/主动陪伴.cjs')
let 数量 = 0
function 检查(说明, 条件) { assert.ok(条件, 说明); 数量++; console.log('✓ ' + 说明) }
function 环境(覆盖 = {}) {
  let 现在 = new Date('2026-10-16T12:00:00+08:00')
  let 计时 = null; let 清除数 = 0; let 到期数 = 0; const 账本变化 = []
  const 运行 = { 有正式对话: true }
  const 调度 = 创建调度器({
    现在: () => new Date(现在), 随机: () => 覆盖.随机 ?? 0,
    设定时器: (函数, 延迟) => { 计时 = { 函数, 延迟 }; return 计时 },
    清除时器: () => { 清除数++ }, 运行状态: () => 运行,
    到期: async () => { 到期数++; return 覆盖.发送成功 !== false },
    账本变了: (账本) => 账本变化.push({ ...账本 }),
    配置: 覆盖.配置 || {}, 账本: 覆盖.账本 || {},
  })
  return { 调度, 运行, 取计时: () => 计时, 取到期数: () => 到期数, 取清除数: () => 清除数, 取账本变化: () => 账本变化, 设现在: (值) => { 现在 = new Date(值) } }
}

async function main() {
  const 默认关 = 环境()
  默认关.调度.启动()
  检查('首次上线默认关闭且不安排计时', 默认关.调度.状态().配置.开启 === false && 默认关.取计时() === null)
  const 规 = 规范配置({ 开启: true, 最短分钟: 1, 最长分钟: 999, 每日上限: 99, 安静开始: '25:00' })
  检查('设置范围由本地裁剪', 规.最短分钟 === 5 && 规.最长分钟 === 720 && 规.每日上限 === 12 && 规.安静开始 === '23:30')
  检查('跨午夜安静时段判断正确', 在安静时段(new Date('2026-10-16T23:45:00+08:00'), 规) && 在安静时段(new Date('2026-10-17T07:59:00+08:00'), 规) && !在安静时段(new Date('2026-10-17T08:00:00+08:00'), 规))

  const 最短 = 环境({ 配置: { 开启: true } })
  最短.调度.启动()
  检查('随机值下界安排四十五分钟', 最短.取计时().延迟 === 45 * 60000)
  const 最长 = 环境({ 随机: 0.999999, 配置: { 开启: true } })
  最长.调度.启动()
  检查('随机值上界安排一百二十分钟', 最长.取计时().延迟 === 120 * 60000)
  const 第一次到期 = 最短.调度.状态().下次到期
  最短.调度.用户活动(new Date('2026-10-16T12:10:00+08:00').getTime())
  检查('真实用户活动会重置整轮空闲计时', 最短.调度.状态().下次到期 > 第一次到期 && 最短.取清除数() > 0)

  const 手测 = 环境({ 配置: { 开启: true, 最短分钟: 45, 最长分钟: 120 } })
  手测.调度.启动()
  检查('手动测试可立即走同一套检查与计数', (await 手测.调度.立即尝试()).触发 && 手测.调度.状态().今日次数 === 1)

  const 忙 = 环境({ 配置: { 开启: true, 最短分钟: 5, 最长分钟: 5 } })
  忙.调度.启动(); 忙.设现在('2026-10-16T12:05:00+08:00'); 忙.运行.正在回复 = true
  const 忙结果 = await 忙.调度.检查()
  检查('回复中不会打扰且五分钟后重查', !忙结果.触发 && 忙结果.原因.includes('忙碌') && 忙.取计时().延迟 === 5 * 60000 && 忙.取到期数() === 0)
  for (const 字段 of ['临时对话', '正在用工具', '正在录音', '正在播放语音', '正在编辑', '全屏', '勿扰']) {
    const 一 = 环境({ 配置: { 开启: true, 最短分钟: 5, 最长分钟: 5 } })
    一.调度.启动(); 一.设现在('2026-10-16T12:05:00+08:00'); 一.运行[字段] = true
    检查(`${字段}会阻止主动陪伴`, !(await 一.调度.检查()).触发 && 一.取到期数() === 0)
  }
  const 无正式 = 环境({ 配置: { 开启: true, 最短分钟: 5, 最长分钟: 5 } })
  无正式.运行.有正式对话 = false; 无正式.调度.启动(); 无正式.设现在('2026-10-16T12:05:00+08:00')
  检查('没有正式对话时不触发', !(await 无正式.调度.检查()).触发)

  const 安静 = 环境({ 配置: { 开启: true, 最短分钟: 5, 最长分钟: 5 } })
  安静.设现在('2026-10-16T23:25:00+08:00'); 安静.调度.启动(); 安静.设现在('2026-10-16T23:30:00+08:00')
  检查('进入安静时段后不触发并越过早八点', (await 安静.调度.检查()).原因 === '安静时段' && 安静.调度.状态().下次到期 > new Date('2026-10-17T08:00:00+08:00').getTime())

  const 成功 = 环境({ 配置: { 开启: true, 最短分钟: 5, 最长分钟: 5, 每日上限: 1 } })
  成功.调度.启动(); 成功.设现在('2026-10-16T12:05:00+08:00')
  检查('只有成功发送才计入每日次数', (await 成功.调度.检查()).触发 && 成功.调度.状态().今日次数 === 1)
  检查('发送次数变化会通知持久层', 成功.取账本变化().at(-1).今日次数 === 1 && 成功.取账本变化().at(-1).上次发送 > 0)
  成功.设现在('2026-10-16T12:10:00+08:00')
  检查('达到每日上限后当天不再触发', (await 成功.调度.检查()).原因 === '达到每日上限' && 成功.取到期数() === 1)

  const 失败 = 环境({ 发送成功: false, 配置: { 开启: true, 最短分钟: 5, 最长分钟: 5 } })
  失败.调度.启动(); 失败.设现在('2026-10-16T12:05:00+08:00')
  const 失败结果 = await 失败.调度.检查()
  检查('发送失败不消耗次数并十五分钟后重试', !失败结果.触发 && 失败.调度.状态().今日次数 === 0 && 失败.取计时().延迟 === 15 * 60000)
  失败.调度.停止()
  检查('关闭后立即取消计时', !失败.调度.状态().配置.开启 && 失败.调度.状态().下次到期 === 0)
  检查('持久账本只含日期次数和时间戳', Object.keys(成功.调度.账本()).sort().join(',') === ['上次发送', '今日次数', '发送日'].sort().join(','))
  console.log(`\n主动陪伴调度：${数量}/${数量} 通过`)
}
main().catch((错误) => { console.error(错误.stack || 错误.message); process.exitCode = 1 })
