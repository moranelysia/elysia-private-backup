/**
 * 测表情.cjs —— 专门测"她会不会真的动手"
 *
 * 【为什么单独写一个】
 *   2026-09-26 晚上出的事：他问「可以换个形态吗」，她答得好好的 ——
 *   「好嘞，这就换上♪……怎么样，这一身，比你想象中合身吧？」
 *   话说得像真换了，可桌面上那个她**一动都没动**。
 *
 *   原因是她那句回复里一个 [表情:xx] 标记都没有。
 *   从她的角度看，她"已经换了"（她在文字里换了）；
 *   从桌面的角度看，什么都没发生。
 *
 *   所以这个脚本专门盯这一件事：**她说换，到底有没有带标记。**
 *
 * 用法: node tools\测表情.cjs            跑一组固定的问法
 *       node tools\测表情.cjs "换个形态"  只测这一句
 */
'use strict'

const path = require('node:path')
const { 说话 } = require(path.resolve(__dirname, '..', '脑', '对话.cjs'))

// 这些都是他真会说的话（前两句是 2026-09-26 晚上他真说过的）
const 默认问法 = [
  { 他: '可以换个形态吗', 期望: '她得回一个形态类的标记' },
  { 他: '女仆吧', 期望: '得是 [表情:女仆形态]' },
  { 他: '笑一个给我看看', 期望: '星星眼或脸红' },
  { 他: '你今天怎么这么可爱', 期望: '被夸了，脸红最合适' },
  { 他: '别这样了，变回来', 期望: '得发"消失"版' },
  { 他: '你好呀', 期望: '打招呼，可以不发标记（这句不强求）' },
]

const 参数 = process.argv[2]

async function 跑一个(问法, 序号) {
  console.log('')
  console.log('────────────────────────────────────────')
  console.log(`第 ${序号} 句  他: ${问法.他}`)
  console.log(`          期望: ${问法.期望}`)

  const 结果 = await 说话({ 他说的话: 问法.他 })

  console.log('')
  console.log('  她: ' + 结果.她说的话.split('\n').join('\n      '))
  console.log('')

  if (结果.表情.length) {
    console.log('  ✓ 她要做: ' + 结果.表情.join('、'))
  } else {
    console.log('  ✗ 她没要做任何表情 —— 桌面上那个她不会动')
  }
  if (结果.记住.length) console.log('  （顺手记下了: ' + 结果.记住.join('、') + '）')

  return 结果.表情.length > 0
}

async function main() {
  const 问法们 = 参数 ? [{ 他: 参数, 期望: '看她发不发' }] : 默认问法

  console.log('')
  console.log('════════════════════════════════════════')
  console.log(' 她到底会不会真的动手')
  console.log('════════════════════════════════════════')
  console.log(' 每问一句，看她回复末尾有没有 [表情:xx] 标记。')
  console.log(' 有 = 桌面上那个她会动；没有 = 只有文字，白说。')

  let 有标记数 = 0
  for (let i = 0; i < 问法们.length; i++) {
    const 成 = await 跑一个(问法们[i], i + 1)
    if (成) 有标记数++
  }

  console.log('')
  console.log('════════════════════════════════════════')
  console.log(` 结果: ${问法们.length} 句里有 ${有标记数} 句带了标记`)
  console.log('════════════════════════════════════════')
  console.log('')
  console.log('（"你好呀"那句本来就可以不带，所以不是 100% 才正常。）')
  console.log('要是一句都没有，那就是人格提示里那段"什么时候必须写"还不够硬，')
  console.log('去 脑\\人格.cjs 里改那一段，再来跑这个。')
  console.log('')
}

main().catch((错误) => {
  console.log('✗ 出错了: ' + 错误.message)
  process.exit(1)
})
