/** 记忆叙述视角：全部使用隔离目录，不读取或改写正式记忆。 */
'use strict'

const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')

const 临时根 = fs.mkdtempSync(path.join(os.tmpdir(), 'elysia-memory-voice-'))
process.env.ELYSIA_DATA_DIR = path.join(临时根, '记忆')
process.env.ELYSIA_CACHE_DIR = path.join(临时根, '缓存')

let 总数 = 0
let 通过 = 0
function 检查(说明, 条件) {
  总数++
  if (!条件) throw new Error('✗ ' + 说明)
  通过++
  console.log('✓ ' + 说明)
}

function main() {
  const 叙述 = require('../脑/记忆叙述.cjs')
  const 记忆 = require('../脑/记忆.cjs')
  const 临时记忆 = require('../脑/临时记忆.cjs')
  const 日记 = require('../脑/记忆日记.cjs')
  const 私密日记 = require('../脑/私密日记.cjs')

  检查('用户和爱莉称呼会改成你和我', 叙述.整理正文('用户对爱莉表达爱意') === '你对我表达爱意')
  检查('共同经历中的第三人称代词会随明确称呼修正', 叙述.整理正文('用户表示接下来是他和爱莉两个人的故事') === '你表示接下来是你和我两个人的故事')
  检查('被引用的禁用称呼不会篡改原话', 叙述.整理正文('他不许我叫他「用户」', { 人物: '用户本人', 修正旧代词: true }) === '你不许我叫你「用户」')
  检查('机器人物分类可投影为她自己的视角', JSON.stringify(叙述.面向她的元数据({ backstory: '从用户本轮原话提取', person: '用户与爱莉希雅', relationship: '共同经历' })) === JSON.stringify({ backstory: '从你本轮原话提取', person: '你和我', relationship: '我们的共同经历' }))

  const 长期 = 记忆.记一条('事实', '用户希望爱莉记住这件事', '她')
  检查('长期记忆写入边界不会保存第三方系统称呼', 长期.内容 === '你希望我记住这件事' && !叙述.有第三方系统称呼(长期.内容))
  记忆.改一条('事实', 长期.编号, '他说他很感谢爱莉')
  检查('长期记忆修改边界也会修正旧第三人称代词', 记忆.列长期记忆().列表[0].内容 === '你说你很感谢我')

  const 临时库 = 临时记忆.创建临时记忆库({ 数据目录: path.join(临时根, '临时库'), 新编号: () => 'tmp-1' })
  const 临时 = 临时库.新增('近期事件', '他和爱莉完成了测试', { 元数据: { person: '用户与爱莉希雅', relationship: '共同经历', backstory: '用户主动记录' } })
  检查('临时记忆写入边界统一为你和我', 临时.内容 === '你和我完成了测试')

  const 日记结果 = 日记.校验生成结果({ 标题: '爱莉的一天', 模块: [{ 名字: '陪伴片段', 正文: '用户和爱莉聊了很久', 来源: ['聊天:1'] }] }, [{ 编号: '聊天:1' }])
  检查('普通日记生成结果统一为自己的口吻', 日记结果.标题 === '我的一天' && 日记结果.模块[0].正文 === '你和我聊了很久')
  const 旧日记投影 = 日记.共享日记投影({ 标题: '爱莉的一天', 模块: [{ 正文: '用户告诉她一个好消息' }], 来源: [{ 摘要: '用户和爱莉继续聊天' }] })
  检查('旧日记只读展示也统一成自己的口吻', 旧日记投影.标题 === '我的一天' && 旧日记投影.模块[0].正文 === '你告诉我一个好消息' && 旧日记投影.来源[0].摘要 === '你和我继续聊天')
  const 私密结果 = 私密日记.校验私密生成结果({ 触发: true, 标题: '爱莉没说出口的话', 微妙情绪: '想靠近，却有点不敢', 正文: '用户说起难处时，爱莉想靠近，却有点不敢', 来源: ['聊天:1'] }, [{ 编号: '聊天:1' }])
  检查('私密日记生成结果统一为自己的口吻', 私密结果.标题 === '我没说出口的话' && 私密结果.正文 === '你说起难处时，我想靠近，却有点不敢')

  const 提示 = fs.readFileSync(path.join(__dirname, '..', '脑', '提示词.cjs'), 'utf8')
  const 提取 = fs.readFileSync(path.join(__dirname, '..', '脑', '临时记忆提取.cjs'), 'utf8')
  const 整理 = fs.readFileSync(path.join(__dirname, '..', '脑', '记忆整理.cjs'), 'utf8')
  检查('显式记忆提示已改成你和我的示例', 提示.includes('[记住:你明天有早课]') && 提示.includes('[经历:你今天给我看了第一个小项目]'))
  检查('临时提取和后台整理都有第一人称硬约束', 提取.includes('禁止写“用户、用户本人、爱莉、爱莉希雅”') && 整理.includes('称眼前的人为“你”'))

  console.log(`\n记忆叙述口吻：${通过}/${总数} 通过`)
}

try { main() } finally { fs.rmSync(临时根, { recursive: true, force: true }) }
