/**
 * 测多对话.cjs —— 量"一段一段对话，互不干扰"
 *
 * 【他要的是什么 —— 2026-10-03】
 *   "每一段对话保留每一段对话的记忆，但对话与对话之间互不干扰。"
 *   左边一列对话，点哪段就只跟哪段说话。
 *
 * 【记性分两层，别量错】
 *     · **长期记忆**（事实 / 经历 / 小本子）—— 所有对话共用，换段也不动
 *     · **一段对话的上下文** —— 只有这一段看得见，别的对话一个字都进不来
 *   所以这个测试量的是后半句：**在一段里说的话，另一段里的她看不见。**
 *   （不是"她把他忘了"—— 那是两回事，第四组专门量这个。）
 *
 * 【它为什么敢动真的聊天记录】
 *   先记下文件原来的字节数，测完按字节数截回去；索引文件也先备份再还原。
 *   全写在 finally 里，中途出错也会还原。
 *
 * 用法: node tools\测多对话.cjs
 */
'use strict'

const fs = require('node:fs')
const path = require('node:path')

const 项目根 = path.resolve(__dirname, '..')
const 脑 = path.join(项目根, '脑')
const 记忆 = require(path.join(脑, '记忆.cjs'))

let 过了 = 0
let 总数 = 0
function 检查(说明, 条件, 细节 = '') {
  总数++
  if (条件) {
    过了++
    console.log(`  ✓ ${说明}`)
  } else {
    console.log(`  ✗ ${说明}${细节 ? '   → ' + 细节 : ''}`)
  }
}

function 长期记忆的指纹() {
  return [记忆.事实文件, 记忆.经历文件, 记忆.小本子文件]
    .map((f) => {
      try {
        return path.basename(f) + ':' + fs.statSync(f).size
      } catch {
        return path.basename(f) + ':没有'
      }
    })
    .join('|')
}

/** 往当前这一段里塞一句话（直接写文件，不过 说话() —— 那要花钱） */
function 塞一句(角色, 内容) {
  fs.appendFileSync(
    记忆.聊天文件,
    JSON.stringify({ 时间: '2099-01-01 00:00', 角色, 内容, 对话: 记忆.现在哪一段() }) + '\n',
    'utf8',
  )
}

function 读界面文件(名) {
  return fs.readFileSync(path.join(项目根, 'renderer', 名), 'utf8')
}

