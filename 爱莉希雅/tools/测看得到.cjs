/**
 * 测看得到.cjs —— 量"她能看见什么、看不见什么，而且看不见的要说出来"
 *
 * 【为什么值得单独一个测试 —— 2026-10-04 那天的事】
 *   他让她"派个小助手去看看 cyrene-源码 是什么"。
 *   她回来说："那个目录**根本不存在**，D:\新建文件夹 里压根没有这个文件夹。"
 *
 *   而那个目录一直都在。真正发生的是两件事：
 *     一、`列` 把禁地里的名字**从清单里悄悄抹掉了** ——
 *         小助手列完没看见它，只好说"没有"
 *     二、`cyrene-源码` 本来就不该在"连看都不给看"那一栏 ——
 *         它是参考源码，摆在那儿就是给人看的
 *
 *   最要命的是第一条：**一张缺了东西的清单，比没有清单更坏。**
 *   没有清单她会去问；缺了东西的清单，她会**据此下结论**，
 *   而且说得理直气壮。
 *
 * 【这个测试量什么】
 *   一、"可以读 / 只许读 / 连看都不给看"三档分得对不对
 *   二、**清单必须如实**：禁地里的东西要出现，只是得标一句"碰不到"
 *   三、两种失败要给**不同的原因**：不存在 vs 不许看 ——
 *       混成一句话，她就只能猜，而她会往"不存在"那边猜
 *
 * 【不碰任何文件】全是读。
 *
 * 用法: node tools\测看得到.cjs
 */
'use strict'

const fs = require('node:fs')
const path = require('node:path')

const 项目根 = path.resolve(__dirname, '..')
const 工作区根 = path.resolve(项目根, '..')
const 路径安全 = require(path.join(项目根, '脑', '路径安全.cjs'))
const 文件工具 = require(path.join(项目根, '脑', '工具', '文件工具.cjs'))

路径安全.注册({ 项目根, 工作区根 })

let 过了 = 0
let 总数 = 0
function 检查(说明, 条件, 细节 = '') {
  总数++
  if (条件) {
    过了++
    console.log(`  ✓ ${说明}`)
  } else {
    console.log(`  ✗ ${说明}${细节 ? '   → ' + 细节 : ''}`)
  }
}

async function main() {
  console.log('')
  console.log('  ════════════════════════════════════════════')
  console.log('   她看得见什么、看不见什么，看不见的说不说')
  console.log('  ════════════════════════════════════════════')
  console.log('')

  // -------------------------------------------------------------
  console.log('  ── 一、三档分得对不对 ──')
  //
  //   能读能写  /  只能读  /  连看都不给看
  //   一条规矩放在哪一档，决定的是"她能不能看"，不只是"能不能写"。

  const 参考源码 = path.join(工作区根, 'cyrene-源码')
  检查('参考源码在盘上（不然这个测试没意义）', fs.existsSync(参考源码))

  const 读它 = 路径安全.查(参考源码, '读')
  检查('**参考源码可以读**（他让她去看的就是这个）', 读它.好, 读它.原因)

  const 写它 = 路径安全.查(path.join(参考源码, 'x.ts'), '写', { 要新建: true })
  检查('但**不许写**它', 写它.好 === false)
  检查('说清楚了是"只能读不能写"', String(写它.原因).includes('只能读不能写'), 写它.原因)

  const 读禁地 = 路径安全.查(path.join(工作区根, 'backups'), '读')
  检查('真禁地（backups）连读都不给', 读禁地.好 === false)
  检查('说清楚了是"不能碰"', String(读禁地.原因).includes('不能碰'), 读禁地.原因)

  const 读钥匙 = 路径安全.查(path.join(项目根, '脑', '钥匙.txt'), '读')
  检查('钥匙连读都不给', 读钥匙.好 === false)

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 二、两种失败要给不同的原因 ──')
  //
  //   混成一句"找不到，或者不在她看的范围里"，她就只能猜 ——
  //   而她会往"不存在"那边猜（那天就是这么说的）。

  const 不存在 = 路径安全.查(path.join(工作区根, '这个目录肯定不存在-xqz'), '读')
  检查('不存在的路径：不给', 不存在.好 === false)
  检查(
    '它说的是"找不到"',
    不存在.原因.includes('找不到') || 不存在.原因.includes('不在她能看的范围'),
    不存在.原因,
  )
  检查(
    '**不许看**和**不存在**给的是两句不同的话',
    读禁地.原因 !== 不存在.原因,
    '两句一样的话，她就分不出是哪一种',
  )

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 三、清单必须如实（那天出事的就是这一条）──')

  const 列出来的 = await 文件工具.列(工作区根)
  检查('列得出来', 列出来的.好, 列出来的.说明)

  const 清单 = String(列出来的.内容 || '')
  const 盘上真有 = fs.readdirSync(工作区根)

  // 盘上有的，清单里都得有（哪怕碰不到）
  const 漏掉的 = 盘上真有.filter((名) => !清单.includes(名))
  检查('**盘上有的，清单里一个都不少**', 漏掉的.length === 0, `漏了：${漏掉的.join('、')}`)

  // 禁地里的那些，得出现，而且得带标记
  const 禁地们 = 盘上真有.filter((名) => 路径安全.禁地.includes(名))
  if (禁地们.length) {
    console.log(`     盘上有 ${禁地们.length} 样禁地：${禁地们.join('、')}`)
    检查('禁地里的名字照样列出来', 禁地们.every((名) => 清单.includes(名)))
    检查('而且挂了"碰不到"的记号', 禁地们.every((名) => new RegExp(名 + '.*碰不到').test(清单)))
    检查('末尾还提醒了一句"别当成没有"', 清单.includes('别当成'), 清单.slice(-80))
  } else {
    console.log('     （这个目录里没有禁地的东西，跳过这两格）')
    检查('禁地清单本身不为空', 路径安全.禁地.length > 0)
  }

  // 最直接的一格：那个把他坑了的目录，必须出现在清单里
  检查('**cyrene-源码 出现在清单里了**（那天就是它不见了）', 清单.includes('cyrene-源码'))

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 四、换个角度：小助手现在能不能看见它 ──')

  const 再列 = await 文件工具.列(参考源码)
  检查('直接列那个目录也列得出来', 再列.好, 再列.说明)
  检查('里面真有文件', String(再列.内容).length > 100, String(再列.内容).slice(0, 60))

  if (fs.existsSync(path.join(参考源码, 'src'))) {
    const 再读 = await 文件工具.读(path.join(参考源码, 'src', 'main', 'orchestrator', 'context-manager.ts'))
    检查('那份源码里的文件读得动', 再读.好, 再读.说明)
  }

  console.log('')
  console.log('  ════════════════════════════════════════════')
  console.log(`   ${过了} / ${总数}` + (过了 === 总数 ? '   ✓ 全过' : '   ✗ 有没过的'))
  console.log('  ════════════════════════════════════════════')
  console.log('')
  process.exit(过了 === 总数 ? 0 : 1)
}

main().catch((错误) => {
  console.log('✗ 测试自己出错了: ' + 错误.message)
  console.log(错误.stack.split('\n').slice(0, 4).join('\n'))
  process.exit(1)
})
