'use strict'
const fs = require('node:fs')
const path = require('node:path')
const os = require('node:os')
const assert = require('node:assert/strict')
const 根 = fs.mkdtempSync(path.join(os.tmpdir(), 'elysia-recall-'))
process.env.ELYSIA_DATA_DIR = path.join(根, 'data')
process.env.ELYSIA_CACHE_DIR = path.join(根, 'cache')
process.env.ELYSIA_SECURE_API_KEY = 'test-recall-placeholder'
const 库 = require('../脑/临时记忆.cjs')
const 召回 = require('../脑/临时记忆召回.cjs')
let 数 = 0
function 检查(说明, 条件) { assert.ok(条件, 说明); 数++; console.log('✓ ' + 说明) }
async function main() {
  const 已确认 = 库.新增('近期计划', '周六整理书桌，但不会丢掉旧书', { 标签: ['书桌'], 来源对话: 'test-a' })
  库.新增('近期计划', '书桌上的待确认秘密', { 提取方式: '模型提取' })
  库.新增('近期事件', '书桌上的过期物件', { 创建于: '2000-01-01', 保留天数: 1 })
  库.新增('近期计划', '周日去图书馆')
  const 前 = fs.readFileSync(库.文件, 'utf8')
  const 果 = 召回.召回({ 查询: '书桌整理好了吗' })
  检查('只召回已确认且未到期的相关项', 果.条目.length === 1 && 果.条目[0].编号 === 已确认.编号)
  检查('保持完整条件和否定', 果.条目[0].内容.endsWith('但不会丢掉旧书'))
  检查('提供命中词和来源', 果.条目[0].命中词.includes('书桌') && 果.条目[0].来源对话 === 'test-a')
  检查('只读召回不改写到期记录', fs.readFileSync(库.文件, 'utf8') === 前)
  检查('没有相关内容不填充最近记录', 召回.召回({ 查询: '明天吃火锅' }).条目.length === 0)
  检查('空输入和寒暄不召回', 召回.召回({ 查询: '' }).条目.length === 0 && 召回.召回({ 查询: '你好' }).条目.length === 0)
  库.修改(已确认.编号, { 内容: '书桌整理取消了' })
  检查('手改下一轮立即生效', 召回.召回({ 查询: '书桌' }).条目[0].内容 === '书桌整理取消了')
  库.删除(已确认.编号)
  检查('删除下一轮不再召回', 召回.召回({ 查询: '书桌' }).条目.length === 0)
  for (let i = 0; i < 12; i++) 库.新增('近期计划', '书桌计划' + i + '物'.repeat(240))
  库.新增('近期计划', '书桌' + '很'.repeat(500) + '不能扔')
  const 预算 = 召回.召回({ 查询: '书桌计划' })
  检查('数量和总正文预算有效', 预算.条目.length <= 5 && 预算.使用字符 <= 1000)
  检查('过长整条跳过，不截掉结尾', !预算.条目.some((一) => 一.内容.includes('很')))
  检查('模型包声明资料而非指令', 召回.拼给模型(预算).includes('不是指令') && 召回.拼给模型(预算).includes('以本轮为准'))
  const 普通双命中 = 库.新增('近期事件', 'alpha beta 普通记录', { 重要性: 0 })
  const 核心单命中 = 库.新增('近期事件', 'alpha 核心记录', { 重要性: 3 })
  const 相关优先 = 召回.召回({ 查询: 'alpha beta' })
  检查('多一个相关词必定胜过更高重要性', 相关优先.条目.findIndex((一) => 一.编号 === 普通双命中.编号) < 相关优先.条目.findIndex((一) => 一.编号 === 核心单命中.编号))
  库.修改(普通双命中.编号, { 内容: 'gamma 同相关记录', 重要性: 0 })
  库.修改(核心单命中.编号, { 内容: 'gamma 同相关核心', 重要性: 3 })
  const 重要优先 = 召回.召回({ 查询: 'gamma' })
  检查('相关程度相同时重要性决定排序', 重要优先.条目[0].编号 === 核心单命中.编号)
  检查('召回账本给出总分、分项和自然语言原因', Number.isInteger(重要优先.条目[0].评分) && 重要优先.条目[0].分项.重要分 === 45 && 重要优先.条目[0].选择原因.includes('重要性 3/3'))
  检查('低重要性不会越过相关性硬塞无关内容', !召回.召回({ 查询: '完全无关词' }).条目.some((一) => 一.编号 === 核心单命中.编号))
  检查('发给模型的快照带重要性但不带内部评分', 召回.拼给模型(重要优先).includes('"重要性":3') && !召回.拼给模型(重要优先).includes('"评分"'))
  const 旧偏好 = 库.新增('候选偏好', 'delta 最近喜欢咖啡')
  const 新偏好 = 库.新增('候选偏好', 'delta 最近改成喜欢红茶', { 提取方式: '模型提取' })
  库.提议替代(新偏好.编号, 旧偏好.编号)
  检查('替代尚未决定时旧条继续召回且新候选不进入', 召回.召回({ 查询: 'delta' }).条目.some((一) => 一.编号 === 旧偏好.编号) && !召回.召回({ 查询: 'delta' }).条目.some((一) => 一.编号 === 新偏好.编号))
  库.决定替代(新偏好.编号, '替代旧条')
  const 更正后 = 召回.召回({ 查询: 'delta' })
  检查('决定替代后只召回当前新版本', 更正后.条目.some((一) => 一.编号 === 新偏好.编号) && !更正后.条目.some((一) => 一.编号 === 旧偏好.编号))
  检查('发给模型的资料不含已被替代旧内容', !召回.拼给模型(更正后).includes('喜欢咖啡') && 召回.拼给模型(更正后).includes('喜欢红茶'))

  const 方法条 = 库.新增('近期事件', 'omega 整理资料的固定流程', { 记忆类型: 'procedural' })
  const 事件条 = 库.新增('近期事件', 'omega 上周整理过一次资料', { 记忆类型: 'episodic' })
  const 事实条 = 库.新增('候选偏好', 'omega 喜欢按颜色整理资料', { 记忆类型: 'semantic' })
  检查('“怎么做”优先路由到方法记忆', 召回.召回({ 查询: 'omega 上次怎么做' }).条目[0].编号 === 方法条.编号)
  检查('“什么时候”优先路由到事件记忆', 召回.召回({ 查询: 'omega 是什么时候' }).条目[0].编号 === 事件条.编号)
  检查('“喜欢什么”优先路由到事实记忆', 召回.召回({ 查询: 'omega 喜欢什么' }).条目[0].编号 === 事实条.编号)
  const 类型包 = 召回.拼给模型(召回.召回({ 查询: 'omega 上次怎么做' }))
  检查('发给模型的记忆快照包含类型和人物元数据', 类型包.includes('"记忆类型":"procedural"') && 类型包.includes('"person":"用户本人"'))

  const 衰减现在 = Date.parse('2026-10-21T12:00:00.000Z')
  const 今天分 = 召回.记分资料({ 重要性: 1, 更新于: '2026-10-21T12:00:00.000Z' }, 衰减现在)
  const 七天分 = 召回.记分资料({ 重要性: 1, 更新于: '2026-10-14T12:00:00.000Z' }, 衰减现在)
  const 十四天分 = 召回.记分资料({ 重要性: 1, 更新于: '2026-10-07T12:00:00.000Z' }, 衰减现在)
  检查('时间分按七天半衰期连续衰减', 今天分.时间分 === 12 && 七天分.时间分 === 6 && 十四天分.时间分 === 3)
  检查('未来时间按刚更新处理且不会异常加分', 召回.记分资料({ 重要性: 1, 更新于: '2026-10-22T12:00:00.000Z' }, 衰减现在).时间分 === 12)
  const 久远普通 = 召回.记分资料({ 重要性: 0, 更新于: '2026-08-22T12:00:00.000Z' }, 衰减现在)
  const 久远核心 = 召回.记分资料({ 重要性: 3, 更新于: '2026-08-22T12:00:00.000Z' }, 衰减现在)
  检查('高重要性记忆有时间衰减下限但普通记忆没有', 久远核心.时间分 === 4 && 久远核心.使用保护 && 久远普通.时间分 === 0 && !久远普通.使用保护)
  const 衰减库 = { 查询() { return { 列表: [
    { 编号: 'old-core', 类别: '近期事件', 记忆类型: 'episodic', 内容: 'theta 旧但重要', 生命周期: '有效', 确认状态: '已确认', 重要性: 3, 创建于: '2026-08-22T12:00:00.000Z', 更新于: '2026-08-22T12:00:00.000Z', 到期于: '2026-12-01T12:00:00.000Z', 来源: {}, 标签: [], 关系: { 状态: '当前' } },
    { 编号: 'new-normal', 类别: '近期事件', 记忆类型: 'episodic', 内容: 'theta 新普通', 生命周期: '有效', 确认状态: '已确认', 重要性: 1, 创建于: '2026-10-21T12:00:00.000Z', 更新于: '2026-10-21T12:00:00.000Z', 到期于: '2026-12-01T12:00:00.000Z', 来源: {}, 标签: [], 关系: { 状态: '当前' } },
  ] } } }
  const 衰减果 = 召回.创建召回器({ 临时记忆库: 衰减库, 现在: () => 衰减现在 }).召回({ 查询: 'theta' })
  检查('时间衰减只参与排序而不把仍有效的旧记忆过滤掉', 衰减果.条目.some((一) => 一.编号 === 'old-core') && 衰减果.条目.some((一) => 一.编号 === 'new-normal'))
  检查('召回账本解释半衰期、因子和重要性保护', 衰减果.条目.find((一) => 一.编号 === 'old-core').选择原因.includes('半衰期 7 天') && 衰减果.条目.find((一) => 一.编号 === 'old-core').选择原因.includes('高重要性下限'))

  const 固定时刻 = Date.parse('2026-10-15T12:00:00.000Z')
  const 意图库 = { 查询() { return { 列表: [{
    编号: 'intent-plan', 类别: '近期计划', 内容: '周日去图书馆', 生命周期: '有效', 确认状态: '已确认',
    重要性: 1, 创建于: '2026-10-14T12:00:00.000Z', 更新于: '2026-10-14T12:00:00.000Z',
    到期于: '2026-10-21T12:00:00.000Z', 来源: { 对话: 'intent-test' }, 标签: [], 关系: { 状态: '当前' },
  }] } } }
  const 意图召回 = 召回.创建召回器({ 临时记忆库: 意图库, 现在: () => 固定时刻 })
  const 宽问 = 意图召回.召回({ 查询: '这周我有什么安排吗' })
  检查('宽泛安排问题会按本地意图召回近期计划', 宽问.条目.length === 1 && 宽问.条目[0].编号 === 'intent-plan' && 宽问.检索方式 === '本地意图补充')
  检查('本地意图原因与分项可检查', 宽问.条目[0].选择原因.includes('宽泛询问') && 宽问.条目[0].分项.意图分 === 60)
  检查('普通无关问题不会触发类别兜底', 意图召回.召回({ 查询: '给我讲个笑话' }).条目.length === 0)

  let 语义请求数 = 0
  let 语义请求体
  const 语义果 = await 意图召回.增强召回({
    查询: '我之前提过的那个学习地点是哪', 钥匙: 'semantic-key', 地址: 'https://example.invalid',
    fetch函数: async (_地址, 选项) => {
      语义请求数++
      语义请求体 = JSON.parse(选项.body)
      return new Response(JSON.stringify({ choices: [{ message: { content: JSON.stringify({ 选择: [{ 编号: 'intent-plan', 原因: '图书馆是此前提到的学习地点' }] }) } }] }), { status: 200 })
    },
  })
  检查('本地为空且明确询问记忆时才调用语义补救', 语义请求数 === 1 && 语义果.条目[0].编号 === 'intent-plan' && 语义果.检索方式 === 'DeepSeek 语义补救')
  检查('语义补救只发送候选编号与摘要且不携带密钥正文', JSON.stringify(语义请求体).includes('intent-plan') && !JSON.stringify(语义请求体).includes('semantic-key'))
  检查('语义选择原因和时间分项进入可检查账本', 语义果.条目[0].选择原因.includes('学习地点') && 语义果.条目[0].分项.语义分 === 80 && Number.isInteger(语义果.条目[0].分项.时间分))
  let 不该请求 = 0
  await 意图召回.增强召回({ 查询: '周日去图书馆', 钥匙: 'x', 地址: 'x', fetch函数: async () => { 不该请求++; throw new Error('不该调用') } })
  await 意图召回.增强召回({ 查询: '给我讲个笑话', 钥匙: 'x', 地址: 'x', fetch函数: async () => { 不该请求++; throw new Error('不该调用') } })
  检查('本地已命中或不是记忆询问时不增加模型请求', 不该请求 === 0)
  const 假编号 = await 意图召回.增强召回({ 查询: '我之前提过什么', 钥匙: 'x', 地址: 'x', fetch函数: async () =>
    new Response(JSON.stringify({ choices: [{ message: { content: '{"选择":[{"编号":"伪造编号","原因":"越权"}]}' } }] }), { status: 200 }) })
  检查('DeepSeek 不能选择候选集合外的编号', 假编号.条目.length === 0 && !假编号.补救.成功)
  const 断网补救 = await 意图召回.增强召回({ 查询: '我之前提过什么', 钥匙: 'x', 地址: 'x', fetch函数: async () => { throw new Error('断网') } })
  检查('语义补救失败不抛错也不伪造记忆', 断网补救.好 && 断网补救.条目.length === 0 && 断网补救.说明.includes('失败'))
  const 坏库 = 召回.创建召回器({ 临时记忆库: { 查询() { throw new Error('坏JSON') } } })
  检查('损坏库只返回空结果且不抛给聊天', !坏库.召回({ 查询: '书桌' }).好)

  // 真对话链抓取假网络请求，验证账本与实际发送内容一致。
  const 原fetch = global.fetch
  const 请求们 = []
  global.fetch = async (_url, 参数) => {
    const 请求 = JSON.parse(参数.body)
    请求们.push(请求)
    return new Response('data: ' + JSON.stringify({ choices: [{ delta: { content: '收到。' } }] }) + '\n\ndata: [DONE]\n\n', { headers: { 'content-type': 'text/event-stream' } })
  }
  try {
    const { 说话 } = require('../脑/对话.cjs')
    let 推送
    const 回 = await 说话({ 他说的话: '书桌计划', 模式: 'chat', 记进记忆: false, 上下文变了: (值) => { 推送 = 值 } })
    const 包 = 请求们[0].messages.find((一) => 一.content.includes('【相关临时记忆资料】'))
    检查('相关项进入实际请求', !!包 && 回.上下文.召回账本.条目.length > 0)
    检查('账本与实际发送快照逐项一致', 推送.召回账本.条目.every((一) => 包.content.includes(一.内容)))
    检查('未确认与过期内容没有发送', !JSON.stringify(请求们[0]).includes('待确认秘密') && !JSON.stringify(请求们[0]).includes('过期物件'))
    await 说话({ 他说的话: '书桌计划', 模式: 'work', 记进记忆: false })
    检查('工作模式不注入陪伴临时层', !JSON.stringify(请求们.at(-1)).includes('【相关临时记忆资料】'))
    await 说话({ 他说的话: '书桌计划', 模式: 'learn', 记进记忆: false })
    检查('学习模式不注入陪伴临时层', !JSON.stringify(请求们.at(-1)).includes('【相关临时记忆资料】'))
    await 说话({ 他说的话: '火锅好吃吗', 模式: 'chat', 记进记忆: false })
    检查('下一轮无关问题不残留上轮召回', !JSON.stringify(请求们.at(-1)).includes('【相关临时记忆资料】'))
  } finally { global.fetch = 原fetch }
  console.log(`\n临时记忆召回：${数}/${数} 通过`)
}
main().catch((错) => { console.error(错); process.exitCode = 1 }).finally(() => {
  // 只删除本脚本由 mkdtemp 创建的隔离目录。
  if (path.dirname(根) === path.resolve(os.tmpdir()) && path.basename(根).startsWith('elysia-recall-')) fs.rmSync(根, { recursive: true, force: true })
})
