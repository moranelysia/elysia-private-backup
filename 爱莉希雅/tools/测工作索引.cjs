/** 工作索引：使用系统临时目录，不调用模型，不碰真实记忆。 */
'use strict'

const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')

const 项目根 = path.resolve(__dirname, '..')
const 临时根 = fs.mkdtempSync(path.join(os.tmpdir(), 'elysia-work-index-'))
process.env.ELYSIA_DATA_DIR = path.join(临时根, '记忆')
process.env.ELYSIA_CACHE_DIR = path.join(临时根, '缓存')

let 总数 = 0
let 通过 = 0
function 检查(说明, 条件, 细节 = '') {
  总数++
  if (!条件) throw new Error('✗ ' + 说明 + (细节 ? '：' + 细节 : ''))
  通过++
  console.log('✓ ' + 说明)
}

async function main() {
  const 工作索引 = require(path.join(项目根, '脑', '工作索引.cjs'))
  const 提示词 = require(path.join(项目根, '脑', '提示词.cjs'))
  const 成功工具 = { 名字: '写', 参数: '不该保存的参数', 结果: { 好: true, 路径: 'F:\\成果.txt', 内容: '不该保存的文件正文' } }
  const 失败工具 = { 名字: '跑', 参数: '不该保存的命令', 结果: { 好: false, 说明: '命令失败详情不该保存' } }
  const 未验证工具 = { 名字: '跑', 参数: 'node build.js', 结果: { 好: true, 退出码: 0 } }

  检查('没有工具的可核对结论算已完成', 工作索引.从工具判断状态([]) === '已完成')
  检查('工具全部成功算已完成', 工作索引.从工具判断状态([成功工具]) === '已完成')
  检查('成功和失败并存算部分完成', 工作索引.从工具判断状态([成功工具, 失败工具]) === '部分完成')
  检查('工具全部失败算失败', 工作索引.从工具判断状态([失败工具]) === '失败')
  检查('只有未验证命令时算部分完成', 工作索引.从工具判断状态([未验证工具]) === '部分完成')

  const 一 = 工作索引.登记({
    对话: 'chat-1',
    目标: '生成一份成果文件',
    工作区: 'F:\\工作区',
    结果摘要: '文件已经写好，可以在右侧查看。',
    工具们: [成功工具],
    产物们: ['F:\\成果.txt', 'F:\\成果.txt'],
  })
  检查('成功登记一条工作', 一.好 && 一.条.状态 === '已完成')
  检查('工作记录带稳定编号和会话', /^work-/.test(一.条.编号) && 一.条.对话 === 'chat-1')
  检查('重复产物路径会去重', 一.条.产物.length === 1 && 一.条.产物[0] === 'F:\\成果.txt')
  检查('工具索引保存三层短状态', 一.条.工具[0].名字 === '写' && 一.条.工具[0].成功 === true && 一.条.工具[0].执行状态 === '成功' && 一.条.工具[0].目标完成 === '是')
  const 原文 = fs.readFileSync(工作索引.索引文件, 'utf8')
  检查('不保存命令参数和工具结果正文', !原文.includes('不该保存的参数') && !原文.includes('不该保存的文件正文'))
  检查('原子写入不留下临时文件', !fs.existsSync(工作索引.索引文件 + '.tmp'))

  工作索引.登记({ 目标: '混合结果', 工具们: [成功工具, 失败工具], 结果摘要: '只完成了一部分' })
  工作索引.登记({ 目标: '全部失败', 工具们: [失败工具], 结果摘要: '没有完成' })
  const 列表 = 工作索引.列()
  检查('列表新的工作排在前面', 列表.列表[0].目标 === '全部失败' && 列表.列表[2].目标 === '生成一份成果文件')
  检查('搜索目标能命中', 工作索引.列({ 搜索: '混合结果' }).总数 === 1)
  检查('搜索产物路径能命中', 工作索引.列({ 搜索: '成果.txt' }).总数 === 1)
  检查('给她看的索引明确保留失败状态', /\[失败\] 全部失败/.test(工作索引.给她看()))
  检查('给她看的索引明确不是陪伴记忆', /不是陪伴记忆/.test(工作索引.给她看()))

  const 工作提示 = 提示词.拼({ 模式: 'work', 工作索引: 工作索引.给她看(), 工具说明: '测试工具' })
  const 聊天提示 = 提示词.拼({ 模式: 'chat' })
  const 学习提示 = 提示词.拼({ 模式: 'learn', 工具说明: '测试工具' })
  检查('工作模式能看到工作索引', 工作提示.includes('最近的工作索引') && 工作提示.includes('全部失败'))
  检查('聊天模式不带工作索引', !聊天提示.includes('最近的工作索引'))
  检查('学习模式不带工作索引', !学习提示.includes('最近的工作索引'))

  const 旧们 = Array.from({ length: 501 }, (_, i) => ({ 编号: 'old-' + i, 目标: '旧任务 ' + i }))
  fs.writeFileSync(工作索引.索引文件, JSON.stringify(旧们), 'utf8')
  工作索引.登记({ 目标: '最新任务', 工具们: [] })
  检查('索引最多保留 500 条', JSON.parse(fs.readFileSync(工作索引.索引文件, 'utf8')).length === 500)
  检查('超限时保留最新任务', 工作索引.列({ 搜索: '最新任务' }).总数 === 1)

  fs.writeFileSync(工作索引.索引文件, '{坏掉', 'utf8')
  const 坏前 = fs.readFileSync(工作索引.索引文件, 'utf8')
  let 坏错 = ''
  try { 工作索引.登记({ 目标: '不能覆盖坏文件' }) } catch (错误) { 坏错 = 错误.message }
  检查('损坏索引时拒绝新增', /已取消写入/.test(坏错))
  检查('拒绝后损坏文件原样保留', fs.readFileSync(工作索引.索引文件, 'utf8') === 坏前)

  const 主进程 = fs.readFileSync(path.join(项目根, 'main.js'), 'utf8')
  const 预载 = fs.readFileSync(path.join(项目根, 'preload.js'), 'utf8')
  const 前端 = fs.readFileSync(path.join(项目根, 'renderer', 'chat.js'), 'utf8')
  检查(
    '主进程冻结本轮模式，任务卡确认或确定的只读工作才登记',
    主进程.includes('const 这轮模式 = 当前模式()') &&
      主进程.includes("const 自动只读工作 = 这轮模式 === 'work' && 工作请求.判断(文字).只读") &&
      主进程.includes("if ((已确认工作 || 自动只读工作) && 这轮模式 === 'work' && !这轮是临时)"),
  )
  检查('预载只传布尔确认标记', 预载.includes('已确认工作: !!选项.已确认工作'))
  检查('任务卡按真实工作状态显示', 前端.includes("回执.工作状态 || '已完成'") && 前端.includes("最终状态 === '部分完成'"))
  检查('纯读取与搜索会先由主进程判断并绕过任务卡', 预载.includes("ipcRenderer.invoke('判断只读工作'") && 前端.includes("当前模式 === 'work' && !自动只读工作"))

  console.log(`\n工作索引：${通过}/${总数} 通过`)
}

main()
  .catch((错误) => {
    console.error(错误.stack || 错误.message)
    process.exitCode = 1
  })
  .finally(() => {
    try { fs.rmSync(临时根, { recursive: true, force: true }) } catch { /* 测试结果更重要 */ }
  })
