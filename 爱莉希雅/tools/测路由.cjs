/**
 * 测路由.cjs —— 检查"程序自己认表情"认得准不准
 *
 * 【为什么要测这个】
 *   表情路由是从她的话里猜她想做什么。猜错比不猜更糟：
 *   · 猜漏了 → 桌面上那个她不动（就是他报的那个问题）
 *   · 猜多了 → 她说句正经话，桌面上那个她突然脸红（更讨厌）
 *
 *   所以拿真句子来量一遍，两边都要看：该认的认出来，不该认的不许认。
 *
 * 用法: node tools\测路由.cjs
 */
'use strict'

const path = require('node:path')
const { 认表情 } = require(path.resolve(__dirname, '..', '脑', '表情路由.cjs'))

// 【该认出来的】左边是她真会说的话，右边是期望的表情
const 该认的 = [
  ['行，我这就换。', '女仆形态'], // ← 这一句是"上文在说女仆"的情况，单独看认不出来，见下面说明
  ['那就换成女仆形态吧。', '女仆形态'],
  ['好呀，这就给你看看女仆装的我♪', '女仆形态'],
  ['我最初那个样子，你还记得吗。', '人律形态'],
  ['好，收起来了。', '人律形态'],
  ['笑一个给你看——', '眯眯眼'],
  ['别这样了，变回来。', '人律形态'],
  ['你居然记得，我有点不好意思了。', '脸红'],
  ['……这个嘛，不告诉你♪', null],
  ['行吧行吧，我这就给你表演一下，看好了哦。', null],
]

// 【不许乱认的】这些句子都是正经话，一个表情都不该做
const 不该认的 = [
  '你明天不是还要军训吗？站了一天累不累。',
  '这个报错的意思是变量没定义，你在第 12 行看一下。',
  '昨天说的那道题，我想到一个更简单的写法。',
  '早点睡吧，明天还要早起。',
  '嗯，我在听，你慢慢说。',
]

console.log('')
console.log('════════ 该认出来的 ════════')
let 对 = 0
for (const [句子, 期望] of 该认的) {
  const 结果 = 认表情(句子, {})
  const 得到 = 结果.表情[0] || null
  const 好 = 得到 === 期望
  if (好) 对++
  console.log(`${好 ? '✓' : '✗'} ${句子}`)
  console.log(`    期望: ${期望 || '（不做）'}   得到: ${得到 || '（不做）'}`)
}

console.log('')
console.log('════════ 不许乱认的 ════════')
let 也对 = 0
for (const 句子 of 不该认的) {
  const 结果 = 认表情(句子, {})
  const 好 = 结果.表情.length === 0
  if (好) 也对++
  console.log(`${好 ? '✓' : '✗'} ${句子}`)
  if (!好) console.log(`    结果认成了: ${结果.表情.join('、')}`)
}

console.log('')
console.log('════════ 结果 ════════')
console.log(`  该认的: ${对} / ${该认的.length}`)
console.log(`  不该认的: ${也对} / ${不该认的.length}`)
console.log('')
console.log('（第一句「行，我这就换。」单独看是认不出来的 —— 它靠上文。')
console.log('  真实对话里有上文，所以她的回话往往带着"女仆"两个字；')
console.log('  真要是只回一句"行，我这就换"，那这一下不会动 —— 这是规矩的边界，')
console.log('  不能为了它去乱猜，猜错了更糟。）')
console.log('')
