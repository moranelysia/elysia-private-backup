/** 语音专名参考：验证不改 ASR 原文，只向大模型提供审核过的语境。 */
'use strict'

const fs = require('node:fs')
const path = require('node:path')
const 根 = path.resolve(__dirname, '..')
const 专名 = require(path.join(根, '脑', 'ASR专名.cjs'))
let 总数 = 0
let 通过 = 0
function 检查(说明, 条件) {
  总数++
  if (!条件) throw new Error('✗ ' + 说明)
  通过++
  console.log('✓ ' + 说明)
}

const 正式表 = JSON.parse(fs.readFileSync(专名.词表路径, 'utf8'))
检查('精确自动纠错默认关闭', 正式表.启用 === false)
检查('大模型语境参考已启用并经人工审核', 正式表.用于大模型理解 === true && 正式表.审核状态 === '已审核')
检查('梅比乌斯使用正确标准写法', 正式表.词条.some(x => x.标准写法 === '梅比乌斯') && !正式表.词条.some(x => x.标准写法 === '美比乌斯'))

const 词们 = 专名.标准词们()
检查('标准词去重并包含核心专名', new Set(词们).size === 词们.length && ['爱莉希雅', '芽衣', '梅比乌斯', '逐火十三英桀'].every(x => 词们.includes(x)))
const 提示 = 专名.拼给模型()
检查('明确告诉模型这是近似听写', /语音识别.*近似听写/.test(提示))
检查('要求结合上下文而不是照字面', /结合当前对话/.test(提示) && /不要纠结转写字面/.test(提示))
检查('有歧义时要求追问', /两种以上合理理解.*追问/.test(提示))
检查('禁止擅自编造专名', /不要擅自编造专名/.test(提示))
检查('关闭语境参考后不再发送专名列表', 专名.标准词们({ ...正式表, 用于大模型理解: false }).length === 0)
检查('未审核词表不进入模型语境', 专名.标准词们({ ...正式表, 审核状态: '待审核' }).length === 0)
检查('坏配置不产生模型专名', 专名.标准词们(null).length === 0)

console.log(`\nASR 专名语境：${通过}/${总数} 通过`)
