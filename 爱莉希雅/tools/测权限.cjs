/**
 * 测权限.cjs —— "要不要问他"这件事，分得清吗
 *
 * 【它治什么】
 *   2026-10-07 他提的："明明就是写一个文件却还要我同意。"
 *   于是加了"放行的目录"：他点过一次"以后别问"，那个文件夹里的写就不再弹卡片。
 *
 *   这个东西坏起来的方式很讨厌 —— **它只会往松的方向坏**：
 *     · 把"记忆\"也放行了 → 她能把他的记忆覆盖坏，而且**不问了**
 *     · 把"能不能写"和"要不要问"混在一起 → 将来想调规矩就得动安全边界
 *   松了不会报错、不会崩，只会有一天她安静地改掉了不该改的东西。
 *   所以每一格都得钉死，尤其是"该问的还得问"那几格。
 *
 * 【不花钱】全程本地，一个模型请求都不发（"问"是拿假函数替的）。
 *
 * 用法: node tools\测权限.cjs
 */
'use strict'

const fs = require('node:fs')
const path = require('node:path')

const 项目根 = path.resolve(__dirname, '..')
const 脑 = path.join(项目根, '脑')
// 放在项目自己的测试区里，复制到任意盘符、任意目录都能跑。
const 试目录 = path.join(项目根, '_测试', '权限')
const 放行的那个 = path.join(试目录, '放行的')

let 过了 = 0
let 总数 = 0
function 检查(说明, 条件, 细节 = '') {
  总数++
  if (条件) {
    过了++
    console.log(`  ✓ ${说明}`)
  } else {
    console.log(`  ✗ ${说明}${细节 ? '   → ' + 细节 : ''}`)
  }
}

async function 主() {
  fs.rmSync(试目录, { recursive: true, force: true })
  fs.mkdirSync(放行的那个, { recursive: true })

  console.log('')
  console.log('  ════════════════════════════════════════════')
  console.log('   要不要问他 —— 放行归放行，免检归免检')
  console.log('  ════════════════════════════════════════════')
  console.log('')

  const 路径安全 = require(path.join(脑, '路径安全.cjs'))
  const 假桌面 = path.join(试目录, 'Desktop')
  fs.mkdirSync(假桌面, { recursive: true })
  fs.writeFileSync(path.join(假桌面, '桌面已有.txt'), '桌面测试', 'utf8')
  路径安全.注册({ 项目根, 工作区根: path.join(项目根, '..'), 桌面目录: 假桌面 })
  const 确认 = require(path.join(脑, '确认.cjs'))
  const 文件工具 = require(path.join(脑, '工具', '文件工具.cjs'))
  文件工具.注册({ 项目根, 工作区根: path.join(项目根, '..') })

  // -------------------------------------------------------------
  console.log('  ── 一、要问他吗()：三种情况 ──')

  路径安全.设放行的目录([])
  检查('★ 桌面文件可以读', 路径安全.查(path.join(假桌面, '桌面已有.txt'), '读').好 === true)
  检查(
    '★ 桌面可以新建文件',
    路径安全.查(path.join(假桌面, '她写的.md'), '写', { 要新建: true }).好 === true,
  )
  检查('  桌面新建默认仍要问', 路径安全.要问他吗(path.join(假桌面, '她写的.md')) === true)
  检查('没放行过任何地方时：要问', 路径安全.要问他吗(path.join(试目录, 'a.md')) === true)

  路径安全.设放行的目录([放行的那个])
  检查('★ 放行过的目录里：不问', 路径安全.要问他吗(path.join(放行的那个, '笔记.md')) === false)
  检查('  子文件夹也算（放行是整棵树）', 路径安全.要问他吗(path.join(放行的那个, '子', '深', 'x.md')) === false)
  检查('  没放行的兄弟目录：照样问', 路径安全.要问他吗(path.join(试目录, '没放行', 'x.md')) === true)

  // 【最要紧的一格】他就算手滑点过"记住"，记忆那儿也得问
  const 记忆里 = path.join(项目根, '记忆', '事实.json')
  检查('★ 记忆里的文件：永远要问（哪怕放行清单覆盖到它）', 路径安全.要问他吗(记忆里) === true)
  路径安全.设放行的目录([path.join(项目根, '记忆')])
  检查('★ 就算把"记忆"整个放行了，它还是问', 路径安全.要问他吗(记忆里) === true)
  路径安全.设放行的目录([放行的那个])

  // 前缀相近的别误判（"放行的" vs "放行的别的"）
  检查('  "放行的别的"不算在"放行的"里面', 路径安全.要问他吗(放行的那个 + '别的' + path.sep + 'x.md') === true)

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 一点二、junction / 符号链接不能绕过边界 ──')

  const 链接目标 = path.join(项目根, '.cache', '_测权限链接目标')
  const 链接入口 = path.join(试目录, '看起来安全')
  fs.mkdirSync(链接目标, { recursive: true })
  fs.writeFileSync(path.join(链接目标, 'secret.txt'), 'secret', 'utf8')
  fs.symlinkSync(链接目标, 链接入口, 'junction')

  const 借链接读 = 路径安全.查(path.join(链接入口, 'secret.txt'), '读')
  检查('★ junction 指进 .cache：读被拒绝', 借链接读.好 === false, JSON.stringify(借链接读))

  const 借链接写 = 路径安全.查(path.join(链接入口, 'new.txt'), '写', { 要新建: true })
  检查('★ junction 指进 .cache：新建也被拒绝', 借链接写.好 === false, JSON.stringify(借链接写))

  const 正常真实路径 = 路径安全.真实路径(path.join(放行的那个, '还不存在', 'x.md'))
  检查('普通的新文件路径仍能正确解析', 正常真实路径 === path.join(放行的那个, '还不存在', 'x.md'))

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 一点五、默认就放行的那几处（2026-10-07 他说"放开吧"）──')

  路径安全.设放行的目录([])
  const 工作区 = path.join(项目根, '..')
  const 学习 = path.join(工作区, '学习')

  检查(
    '★ 学习\\笔记 里：默认就不问',
    路径安全.要问他吗(path.join(学习, '笔记', 'C语言', '第一课.md')) === false,
  )
 检查('★ 学习\\练习 里：默认就不问', 路径安全.要问他吗(path.join(学习, '练习', '错题.md')) === false)
 检查(
    '★ 进度.md：默认就不问 —— 不然每记一次进度都要弹一张卡片，那功能就废了',
    路径安全.要问他吗(path.join(学习, '进度.md')) === false,
  )
 检查('★ C语言\\ 里：默认就不问', 路径安全.要问他吗(path.join(工作区, 'C语言', 'hello.c')) === false)

  // 【这几格是"故意不放开"的】—— 放开的是"写坏了损失小"的地方，
  //   他的原件不算。写坏了笔记再写一篇就行，课件没了是真没了。
  检查(
    '★★ 学习\\材料 里：照样问（那是他的原件，不能让她随手覆盖）',
    路径安全.要问他吗(path.join(学习, '材料', '第一章.pdf')) === true,
  )
  检查(
    '  学习\\说明.md：也问（那是给他看的说明，不是她的笔记）',
    路径安全.要问他吗(path.join(学习, '说明.md')) === true,
  )
  检查(
    '  跟"笔记"名字像、但不在它底下的目录：问',
    路径安全.要问他吗(path.join(学习, '笔记备份', 'x.md')) === true,
  )

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 二、确认.问() 现在回的是个对象 ──')

  let 收到请求 = null
  确认.注册({
    问窗口: async (请求) => {
      收到请求 = 请求
      return { 同意: true, 记住: true }
    },
    记住这个: () => {},
  })
  const 甲 = await 确认.问({ 类型: '新建', 路径: 'x.md', 绝对路径: path.join(试目录, 'x.md') })
  检查('★ 返回的是 { 同意, 记住 }，不是 true', 甲 && 甲.同意 === true && 甲.记住 === true, JSON.stringify(甲))
  检查('  请求原样递出去了', !!(收到请求 && 收到请求.类型 === '新建'))

  // 老的那种"直接返 boolean"还得认 —— 别把别的调用方弄坏
  确认.注册({ 问窗口: async () => false, 记住这个: () => {} })
  const 乙 = await 确认.问({ 类型: '新建' })
  检查('窗口返 boolean 的老写法仍然认（返 false）', 乙 && 乙.同意 === false && 乙.记住 === false, JSON.stringify(乙))

  // 没人可问 → 拒绝，不是默许
  确认.注册({})
  const 丙 = await 确认.问({ 类型: '新建' })
  检查('★ 没人可问 → 拒绝（不是默认允许）', 丙 && 丙.同意 === false, JSON.stringify(丙))

  // 结算时"记住"要能传出去
  let 记住过什么 = null
  确认.注册({ 问窗口: async () => undefined, 记住这个: (请求) => (记住过什么 = 请求) })
  const 等它 = 确认.问({ 类型: '新建', 绝对路径: path.join(试目录, 'y.md') })
  // 等一拍，让它把编号挂上
  await new Promise((事情) => setTimeout(事情, 10))
  const 号 = 确认.在等的编号()[0]
  确认.结算(号, true, true)
  const 丁 = await 等它
  检查('★ 结算时说"记住"，一路传回来了', 丁.同意 === true && 丁.记住 === true, JSON.stringify(丁))
  检查('★ 而且调了"记住这个"回调（落盘那一步在 main.js）', !!(记住过什么 && 记住过什么.绝对路径))
  检查('  作废的时候不带"记住"（程序要退不是他的决定）', 确认.作废() >= 0 && true)

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 三、★ 端到端：写文件到底问不问 ──')

  let 问了几次 = 0
  const 假问 = async () => {
    问了几次++
    return { 同意: true, 记住: false }
  }

  async function 写一个(全路径) {
    问了几次 = 0
    return await 文件工具.写(全路径, '测试内容\n', { 问: 假问, 他说的: '' })
  }

  路径安全.设放行的目录([放行的那个])

  const 甲果 = await 写一个(path.join(放行的那个, '第一课.md'))
  检查('放行过的目录里新建：写成了', 甲果.好 === true, 甲果.说明)
  检查('★ 而且**一次都没问**', 问了几次 === 0, '问了 ' + 问了几次 + ' 次')

  const 乙果 = await 写一个(path.join(试目录, '没放行的.md'))
  检查('没放行的地方新建：也写成了', 乙果.好 === true, 乙果.说明)
  检查('★ 这一次问了', 问了几次 === 1, '问了 ' + 问了几次 + ' 次')

  // 记忆里 —— 哪怕"记住"清单里写了它，也必须问
  路径安全.设放行的目录([放行的那个, path.join(项目根, '记忆')])
  问了几次 = 0
  const 丙果 = await 文件工具.写(path.join(项目根, '记忆', '_测权限临时.md'), 'x\n', {
    问: 假问,
    他说的: '',
  })
  检查('★ 往记忆里写：还是问了', 问了几次 === 1, '问了 ' + 问了几次 + ' 次')
  if (丙果.好) fs.rmSync(path.join(项目根, '记忆', '_测权限临时.md'), { force: true })

  // 追加还是不问（这是原来就有的规矩，别被这次改坏了）
  路径安全.设放行的目录([])
  问了几次 = 0
  const 追加果 = await 文件工具.写(path.join(试目录, '没放行的.md'), '又一行\n', { 问: 假问, 他说的: '' })
  检查('追加到已有文件：还是不问（老规矩没被改坏）', 追加果.好 === true && 问了几次 === 0, '问了 ' + 问了几次 + ' 次')

  // 禁地根本写不了（硬边界没被动过）
  路径安全.设放行的目录([项目根])
  问了几次 = 0
  const 禁地果 = await 文件工具.写(path.join(项目根, '脑', '_不该写进来.cjs'), 'x\n', { 问: 假问, 他说的: '' })
  检查('★ 她的代码（脑\\）：放行了也写不进去（硬边界没松）', 禁地果.好 === false, JSON.stringify(禁地果))
  检查('  而且没白问他一趟', 问了几次 === 0)

  路径安全.设放行的目录([])
  问了几次 = 0
  const 设置果 = await 文件工具.写(path.join(项目根, '.cache', '_不该写.json'), '{}', { 问: 假问, 他说的: '' })
  检查('★ .cache（设置文件在那儿）：写不进去 —— 不然她能给自己改权限', 设置果.好 === false, JSON.stringify(设置果))

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 四、收尾 ──')

  路径安全.设放行的目录([])
  fs.rmSync(试目录, { recursive: true, force: true })
  fs.rmSync(链接目标, { recursive: true, force: true })
  检查('测试目录擦掉了', !fs.existsSync(试目录))

  console.log('')
  console.log('  ════════════════════════════════════════════')
  console.log(`   ${过了} / ${总数}`)
  console.log('  ════════════════════════════════════════════')
  console.log('')
  process.exit(过了 === 总数 ? 0 : 1)
}

主().catch((错误) => {
  console.log('  ✗ 测试自己炸了：' + (错误 && 错误.stack))
  process.exit(1)
})
