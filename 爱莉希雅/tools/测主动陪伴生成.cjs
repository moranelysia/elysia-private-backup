/** P1-C 受限生成测试：假模型、假记忆，不联网、不读写真实数据。 */
'use strict'
const assert = require('node:assert/strict')
const { 创建生成器, 少量临时资料, 清理正文 } = require('../脑/主动陪伴生成.cjs')

let 数量 = 0
function 检查(说明, 条件) { assert.ok(条件, 说明); 数量++; console.log('✓ ' + 说明) }

async function main() {
  const 假库 = { 查询: () => ({ 列表: [
    { 类别: '近期计划', 内容: '周末去图书馆', 确认状态: '已确认', 生命周期: '有效', 更新于: '2026-10-16' },
    { 类别: '近期状态', 内容: '最近有些累', 确认状态: '已确认', 生命周期: '有效', 更新于: '2026-10-15' },
    { 类别: '候选偏好', 内容: '喜欢草莓', 确认状态: '已确认', 生命周期: '有效', 更新于: '2026-10-17' },
    { 类别: '未完话题', 内容: '不该进来', 确认状态: '待确认', 生命周期: '有效', 更新于: '2026-10-18' },
  ] }) }
  const 资料 = 少量临时资料(假库)
  检查('只选适合主动陪伴的已确认有效资料', 资料.length === 2 && 资料.every((一) => ['近期计划', '近期状态'].includes(一.类别)))
  检查('临时资料最多两条且单条受长度限制', 资料.every((一) => 一.内容.length <= 180))

  let 收到 = null
  let 记账参数 = null
  const 生成器 = 创建生成器({
    取钥匙: () => ({ 钥匙: 'fake' }), 临时记忆: 假库,
    现在: () => new Date('2026-10-16T15:20:00+08:00'),
    提示词: {
      拼主动陪伴: (选项) => `人格和边界\n${选项.模式}\n${选项.临时记忆}`,
      拼时间: () => '当前时间 2026-10-16 15:20',
    },
    要一轮: async (选项) => { 收到 = 选项; return { 全文: '忙了这么久，要不要稍微歇一下呀♪[记住:内部]', 用了: { total_tokens: 12 } } },
    记账: (...参数) => { 记账参数 = 参数 },
  })
  const 结果 = await 生成器.生成({ 模式: 'learn', 模型: 'fake-model', 原因: '空闲五分钟' })
  检查('受限生成成功返回干净正文', 结果.好 && 结果.正文 === '忙了这么久，要不要稍微歇一下呀♪')
  检查('请求只有人格时间和触发原因三条', 收到.消息们.length === 3 && 收到.消息们[0].role === 'system' && 收到.消息们[2].content.includes('触发原因'))
  检查('请求限制短输出且不开放工具', 收到.最多多少字 === 220 && !('工具' in 收到))
  检查('真实模型用量按主动陪伴单独记账', 记账参数 && 记账参数[2] === '主动陪伴' && 记账参数[3] === 'learn')
  检查('只注入两条裁剪后的临时资料', 收到.消息们[0].content.includes('周末去图书馆') && !收到.消息们[0].content.includes('喜欢草莓'))

  let 调用数 = 0
  const 无钥匙 = 创建生成器({ 取钥匙: () => ({ 钥匙: '' }), 要一轮: async () => { 调用数++; return {} } })
  检查('没有 API Key 时不发网络请求', !(await 无钥匙.生成()).好 && 调用数 === 0)
  检查('空文和超长输出拒绝交付', !清理正文('') && !清理正文('好'.repeat(501)))
  console.log(`\n主动陪伴生成：${数量}/${数量} 通过`)
}

main().catch((错误) => { console.error(错误.stack || 错误.message); process.exitCode = 1 })
