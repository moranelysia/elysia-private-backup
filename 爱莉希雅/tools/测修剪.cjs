/**
 * 测修剪.cjs —— 量"收拾桌子"这件事做得对不对
 *
 * 【为什么这个要测得这么细】
 *   它会在**她说话的中途**动她的上下文 —— 悄悄改掉她看到的东西。
 *   这种"替她做主"的动作最危险：做对了没人知道，做错了她就开始胡言乱语，
 *   而且**没有任何报错**，只会表现为"她今天怎么不太对"。
 *
 *   所以每一条边界都要打一遍，尤其是那一条：
 *   **没超线的时候，一个字都不许动。**
 *
 * 【它不花钱】
 *   全是纯函数，不调模型。留档会写文件，跑完自己清掉。
 *
 * 用法: node tools\测修剪.cjs
 */
'use strict'

const fs = require('node:fs')
const path = require('node:path')

const 项目根 = path.resolve(__dirname, '..')
const 修 = require(path.join(项目根, '脑', '修剪工具结果.cjs'))
const 尺 = require(path.join(项目根, '脑', '量长度.cjs'))

let 过了 = 0
let 总数 = 0
function 检查(说明, 条件, 细节 = '') {
  总数++
  if (条件) {
    过了++
    console.log(`  ✓ ${说明}`)
  } else {
    console.log(`  ✗ ${说明}${细节 ? '   → ' + 细节 : ''}`)
  }
}

/** 造一段指定字数的正文 */
function 长文(n, 头 = '开头') {
  return 头 + '甲'.repeat(Math.max(0, n - 头.length))
}

/** 造一条"工具结果消息" */
function 造一条(块们, 交代 = '讲的时候像平时说话那样。') {
  const 条 = { role: 'user', content: 修.拼一条(块们, 交代) }
  return 修.挂块(条, 块们, 交代)
}

/** 造一个"块" */
function 造块(工具, 参数, 正文) {
  return { 工具, 标签: `${工具}：${参数}`, 正文 }
}

function main() {
  console.log('')
  console.log('  ════════════════════════════════════════════')
  console.log('   收拾桌子：只裁该裁的，别的一个字不动')
  console.log('  ════════════════════════════════════════════')
  console.log('')

  尺.忘掉锚()
  尺.忘掉修正()

  // -------------------------------------------------------------
  console.log('  ── 一、拼一条 ──')

  const 甲块 = [造块('读', 'a.md', '文件内容在这里'), 造块('跑', 'dir', '文件名列表')]
  const 甲 = 修.拼一条(甲块, '别报步骤。')
  检查('开头是那句"他看不见这段"', 甲.startsWith('【内部】他看不见这段'))
  检查('每块都有自己的标签', 甲.includes('【读：a.md】') && 甲.includes('【跑：dir】'))
  检查('正文都在', 甲.includes('文件内容在这里') && 甲.includes('文件名列表'))
  检查('交代挂在最后', 甲.trimEnd().endsWith('别报步骤。'))
  检查('空块也不崩', typeof 修.拼一条([], '') === 'string')

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 二、那块记录不能跟着请求发出去 ──')
  //
  // 这是最要紧的一条：那个记录要是可枚举的，JSON.stringify 就会把它
  // 一起发到模型那边 —— 每轮白烧一大段 token 去说"我这里有几块"。

  const 乙 = 造一条([造块('读', 'x.md', '东西')], '交代')
  const 发出去的 = JSON.parse(JSON.stringify(乙))
  检查('挂上去的块读得回来', Array.isArray(修.拿块(乙)) && 修.拿块(乙).length === 1)
  检查(
    '序列化之后**看不见**块记录（不会发给模型）',
    !('__块们' in 发出去的) && !('__交代' in 发出去的),
    JSON.stringify(Object.keys(发出去的)),
  )
  检查('发出去的只有 role 和 content', Object.keys(发出去的).sort().join(',') === 'content,role')

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 三、裁一块的边界 ──')

  const 短 = 造块('读', '小.md', 长文(1000))
  检查('1000 字 → 不裁', 修.裁一块(短).改过 === false)

  const 正好 = 造块('读', '正好.md', 长文(修.单条上限))
  检查(`正好 ${修.单条上限} 字 → 不裁（不多不少不算超）`, 修.裁一块(正好).改过 === false)

  const 超一字 = 造块('读', '超.md', 长文(修.单条上限 + 1))
  检查('超一个字 → 裁', 修.裁一块(超一字).改过 === true)

  const 巨 = 造块('跑', '大输出', 长文(30000))
  const 果 = 修.裁一块(巨)
  检查('30000 字被裁了', 果.改过 === true)
  检查('裁完长度 = 头 + 尾 + 标记', 果.正文.length < 30000 && 果.正文.includes('中间省掉了'))
  检查('留下了开头', 果.正文.startsWith('开头'))
  检查('省掉的数字算得对', 果.正文.includes(String(30000 - 修.留头 - 修.留尾)), `该是 ${30000 - 修.留头 - 修.留尾}`)
  检查('头尾都在（尾也留了）', 果.正文.indexOf('开头') === 0 && 果.正文.endsWith('甲'))
  console.log(`     30000 字 → ${果.正文.length} 字（省 ${果.省了}）`)
  检查('省了 0 字的说法不成立', 果.省了 > 20000, String(果.省了))

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 四、没超线就一个字都不许动（这条最要紧）──')

  const 小会话 = [
    { role: 'system', content: '你是爱莉希雅。' },
    造一条([造块('读', '小.md', 长文(2000))], '交代'),
  ]
  const 前 = JSON.stringify(小会话)
  const 果2 = 修.收拾(小会话, { 线: 100000 }) // 线设得高高的
  检查('没超线 → 什么都不裁', 果2.裁了 === 0, JSON.stringify(果2))
  检查('没超线 → 一个字没变', JSON.stringify(小会话) === 前)
  检查('它还会说清楚为什么没动', 果2.说明.includes('没到线'), 果2.说明)

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 五、超线了：只裁老的、大的，最近一轮不碰 ──')

  const 老回合 = [造块('跑', '老的大输出', 长文(30000))]
  const 新回合 = [造块('读', '新的大文件', 长文(30000))]
  const 会话 = [
    { role: 'system', content: '系统提示' },
    造一条(老回合, '交代' + '乙'.repeat(1000)), // 交代也做长一点，验证它没被弄丢
    { role: 'assistant', content: '我看看……' },
    造一条(新回合, '新的交代'),
  ]

  const 果3 = 修.收拾(会话, { 线: 1000 }) // 线压到很低，逼它裁
  检查('裁了老的那一轮', 果3.裁了 === 1, JSON.stringify(果3))
  检查('省下了一大截', 果3.省了字 > 20000, String(果3.省了字))
  检查('老回合的正文被换了', 会话[1].content.includes('中间省掉了'))
  检查('新回合的正文原样没动', 会话[3].content.includes('甲'.repeat(100)), '最近一轮不该碰')
  检查(
    '交代还挂着（没被整条换掉）',
    会话[1].content.includes('乙'.repeat(100)),
    '交代丢了 —— 她就不知道怎么讲了',
  )
  检查('交代在新回合里也在', 会话[3].content.includes('新的交代'))
  检查('留档留了一份', 果3.留档.length === 1, JSON.stringify(果3.留档))

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 六、只有一轮工具结果的时候，不动它 ──')

  const 只有一轮 = [
    { role: 'system', content: '系统提示' },
    造一条([造块('跑', '唯一一次', 长文(30000))], '交代'),
  ]
  const 果4 = 修.收拾(只有一轮, { 线: 1000 })
  检查('只有一轮 → 不裁（那是她正在看的）', 果4.裁了 === 0)
  检查('它说清楚了为什么不动', 果4.说明.includes('只有一轮'), 果4.说明)

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 七、全是零碎的，裁了也省不下 ──')

  const 碎的 = [
    { role: 'system', content: '系统提示' },
    造一条([造块('读', 'a', 长文(100)), 造块('读', 'b', 长文(200))], '交代'),
    造一条([造块('读', 'c', 长文(300))], '交代2'),
  ]
  const 果5 = 修.收拾(碎的, { 线: 1 })
  检查('没有单条超标的 → 不裁', 果5.裁了 === 0)
  检查('说清楚了是"都是零碎的"', 果5.说明.includes('零碎'), 果5.说明)

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 八、裁完锚要失效 ──')
  //
  // 真数锚假定"数组只往后接、前面一个字没变"。裁过就不成立了。
  // 还留着的话估出来的数会偏高 —— 偏高安全，但那是错的。

  尺.忘掉锚()
  const 锚会话 = [
    { role: 'system', content: '系统' },
    造一条([造块('跑', '老的', 长文(30000))], '交代'),
    造一条([造块('读', '新的', 长文(30000))], '交代'),
  ]
  尺.记真数(锚会话, 99999)
  检查('裁之前有锚', 尺.有锚吗() === true)
  修.收拾(锚会话, { 线: 1000 })
  检查('裁完之后锚没了', 尺.有锚吗() === false)

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 九、不出事 ──')

  检查('空数组不崩', 修.收拾([]).裁了 === 0)
  检查('undefined 不崩', 修.收拾(undefined).裁了 === 0)
  检查('没块的消息不崩', 修.收拾([{ role: 'user', content: '普通一句话' }], { 线: 1 }).裁了 === 0)
  检查('拿块(null) 不崩', 修.拿块(null) === null)
  检查('裁一块(空) 不崩', 修.裁一块(null).改过 === false)
  检查('要不要动手() 算得出来', typeof 修.要不要动手(小会话).要 === 'boolean')

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 十、留档真的能查（不是写了个空文件）──')

  const 留档们 = fs.existsSync(修.留档目录)
    ? fs.readdirSync(修.留档目录).filter((名) => 名.endsWith('.txt'))
    : []
  检查('留档目录里有东西', 留档们.length > 0, String(留档们.length))
  if (留档们.length) {
    const 最新 = path.join(修.留档目录, 留档们.sort().pop())
    const 文 = fs.readFileSync(最新, 'utf8')
    检查('留档里有头部说明', 文.includes('这一份是修剪时裁掉的原文'))
    检查('留档里记了是哪个工具', /工具：/.test(文))
    检查('留档里存的是**完整原文**（比裁完的长得多）', 文.length > 20000, String(文.length))
    console.log(`     ${留档们.length} 份，最新那份 ${文.length} 字`)
  }

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 十一、清场 ──')
  // 测试写进去的留档清掉，别占他的地方
  try {
    for (const 名 of fs.readdirSync(修.留档目录)) {
      if (名.endsWith('.txt')) fs.rmSync(path.join(修.留档目录, 名), { force: true })
    }
    fs.rmSync(修.留档目录, { recursive: true, force: true })
  } catch {
    /* 清不掉就算了 */
  }
  检查('测试留下的留档清干净了', !fs.existsSync(修.留档目录))

  console.log('')
  console.log('  ════════════════════════════════════════════')
  console.log(`   ${过了} / ${总数}` + (过了 === 总数 ? '   ✓ 全过' : '   ✗ 有没过的'))
  console.log('  ════════════════════════════════════════════')
  console.log('')
  process.exit(过了 === 总数 ? 0 : 1)
}

main()
