/**
 * 测尺子.cjs —— 量"估长度"这把尺子准不准、锚对不对
 *
 * 【为什么这把尺子值得单独一测】
 *   它现在是"只看不做"，错了也不会有症状。
 *   可下一步所有决定（该不该压、压多少）都要建在它上面 ——
 *   那才是它真正危险的时候。**建在沙子上的决定，出事的时候已经晚了。**
 *
 *   所以趁它还没有决定权，先把它量透：
 *     · 估得对不对（中文和英文差多少）
 *     · 锚用得对不对（同一次请求往后接，该用真数；换个请求，该失效）
 *     · 对账记得对不对（比值必须永远对着"没修过的"那个数）
 *     · 修正系数会不会被一两个极端值带跑
 *
 * 【它为什么要动真的对账文件】
 *   修正系数是拿真文件算的，没法假装。所以先备份、跑完还原，
 *   写在 finally 里，中途出错也还原。
 *
 * 用法: node tools\测尺子.cjs
 */
'use strict'

const fs = require('node:fs')
const path = require('node:path')

const 项目根 = path.resolve(__dirname, '..')
const 尺 = require(path.join(项目根, '脑', '量长度.cjs'))

let 过了 = 0
let 总数 = 0
function 检查(说明, 条件, 细节 = '') {
  总数++
  if (条件) {
    过了++
    console.log(`  ✓ ${说明}`)
  } else {
    console.log(`  ✗ ${说明}${细节 ? '   → ' + 细节 : ''}`)
  }
}

/** 造一段指定字数的中文（不真的打印它） */
function 中文(n) {
  return '汉'.repeat(n)
}
function 英文(n) {
  return 'a'.repeat(n)
}

function main() {
  console.log('')
  console.log('  ════════════════════════════════════════════')
  console.log('   尺子：估得准不准，锚用得对不对')
  console.log('  ════════════════════════════════════════════')
  console.log('')

  // 备份对账文件（修正系数是拿它算的，测的时候得从零开始）
  const 原对账 = fs.existsSync(尺.对账文件) ? fs.readFileSync(尺.对账文件, 'utf8') : null
  const 原条数 = 原对账 ? 原对账.split('\n').filter((l) => l.trim()).length : 0

  // 【为什么要在开头就把账本清空，而不是等到第五组】
  //   第一版是等到第五组才清的。可尺子读的是**真文件** ——
  //   他那天已经聊出 10 条对账，修正系数当场上线，
  //   于是前面几组"应该纯估"的地方全变成了"修正系数"，一次红四格。
  //   教训：测试要动全局状态，就得**在碰它之前**先摆成自己假设的样子，
  //   不能指望它恰好是干净的。
  fs.mkdirSync(path.dirname(尺.对账文件), { recursive: true })
  fs.writeFileSync(尺.对账文件, '', 'utf8')
  尺.忘掉修正()
  尺.忘掉锚()
      尺.忘掉修正()

  try {
    // ---------------------------------------------------------------
    console.log('  ── 一、估得对不对 ──')

    检查('空字符串 → 0', 尺.估('') === 0)
    检查('null → 0', 尺.估(null) === 0)

    // 中文：一个字 0.6 token，1000 字 → 600
    const 中 = 尺.估(中文(1000))
    检查('1000 个汉字 ≈ 600 token', 中 === 600, String(中))

    // 英文：四字符一个，1000 字符 → 250
    const 英 = 尺.估(英文(1000))
    检查('1000 个英文字母 ≈ 250 token', 英 === 250, String(英))

    检查('同样字符数，中文估出来比英文贵（这是关键）', 中 > 英 * 2, `中 ${中} vs 英 ${英}`)

    // 混排：一半一半
    const 混 = 尺.估(中文(500) + 英文(500))
    检查('中英各一半 → 落在两者中间', 混 > 英 / 2 && 混 < 中, String(混))

    // 表情（代理对）：不能被劈成两半算错
    const 带表情 = 尺.估('😀😀😀')
    检查('表情不会把估算算崩（不许是 NaN）', Number.isFinite(带表情), String(带表情))

    // ---------------------------------------------------------------
    console.log('')
    console.log('  ── 二、每条消息的固定开销 ──')

    const 一条 = 尺.估消息们([{ role: 'user', content: '你好' }])
    检查('一条消息 = 正文 + 4', 一条.总 === 尺.估('你好') + 4, JSON.stringify(一条))

    const 两条 = 尺.估消息们([
      { role: 'user', content: '你好' },
      { role: 'assistant', content: '在的' },
    ])
    检查('两条 = 两条正文 + 8', 两条.总 === 尺.估('你好') + 尺.估('在的') + 8, JSON.stringify(两条))
    检查('空数组 → 0', 尺.估消息们([]).总 === 0)
    检查('undefined 也不崩', 尺.估消息们(undefined).总 === 0)

    // ---------------------------------------------------------------
    console.log('')
    console.log('  ── 三、锚：同一次请求往后接，该用真数 ──')
    //
    // 这是干活那一轮的真实形状：一回合一次请求，每次都在前面基础上往后接。

    尺.忘掉锚()
      尺.忘掉修正()
    检查('一开始没有锚', 尺.有锚吗() === false)

    const 消息们 = [
      { role: 'system', content: 中文(1000) }, // 系统提示
      { role: 'user', content: '帮我写个程序' },
    ]
    const 第一次 = 尺.估请求(消息们)
    检查('第一次只能纯估', 第一次.靠 === '纯估', 第一次.靠)

    // 假装模型报了个真数回来
    尺.记真数(消息们, 800)
    检查('记完就有锚了', 尺.有锚吗() === true)

    // 往后接两条（她的话 + 工具结果）—— 同一个数组，push
    消息们.push({ role: 'assistant', content: 中文(200) })
    消息们.push({ role: 'user', content: '【内部】这是你要的东西' })

    const 第二次 = 尺.估请求(消息们)
    检查('第二次用上了真数锚', 第二次.靠 === '真数锚', 第二次.靠)
    // 估出来应该 = 800 + 新增那两条的估算
    const 增量 = 尺.估消息们([
      { role: 'assistant', content: 中文(200) },
      { role: 'user', content: '【内部】这是你要的东西' },
    ]).总
    检查('第二次 = 上次真数 + 增量', 第二次.tok === 800 + 增量, `拿到 ${第二次.tok}，该是 ${800 + 增量}`)
    检查('第二次比纯估更贴近真数', 第二次.靠 === '真数锚')

    // ---------------------------------------------------------------
    console.log('')
    console.log('  ── 四、换个请求，锚必须失效（不能张冠李戴）──')

    const 另一批 = [{ role: 'user', content: '完全不相干的一句话' }]
    const 换过 = 尺.估请求(另一批)
    检查('新数组不会沿用上一个锚', 换过.靠 !== '真数锚', 换过.靠)
    检查('新数组是纯估（数据太少，修正还没启用）', 换过.靠 === '纯估', 换过.靠)

    // 同样的内容、但**是另一个数组对象** —— 也不该认
    const 长得一样 = [
      { role: 'system', content: 中文(1000) },
      { role: 'user', content: '帮我写个程序' },
    ]
    尺.记真数(长得一样, 800)
    const 同内容不同对象 = [{ role: 'system', content: 中文(1000) }]
    检查('内容一样但是新数组 → 不认锚', 尺.估请求(同内容不同对象).靠 !== '真数锚')

    尺.忘掉锚()
      尺.忘掉修正()
    检查('忘掉锚之后就没有了', 尺.有锚吗() === false)

    // ---------------------------------------------------------------
    console.log('')
    console.log('  ── 五、对账：比值永远对着"没修过的"那个数 ──')

    // 清空对账，从零开始（开头已经清过一次，这里再确认一遍）
    fs.mkdirSync(path.dirname(尺.对账文件), { recursive: true })
    fs.writeFileSync(尺.对账文件, '', 'utf8')
    尺.忘掉修正()

    检查('清空之后修正系数是 null（数据太少，不敢修）', 尺.修正系数() === null)

    // 故意让"实际"是估算的 2 倍 —— 看看它记下来的是几
    const 比值 = 尺.对账(1000, 2000, '测试用', '纯估')
    检查('比值记的是 实际/纯估 = 2', 比值 === 2, String(比值))

    const 记下的 = 尺.读对账()
    检查('确实写进文件了', 记下的.length === 1, String(记下的.length))
    检查('记的纯估是 1000（不是修过的数）', 记下的[0].纯估 === 1000, JSON.stringify(记下的[0]))
    检查('记的实际是 2000', 记下的[0].实际 === 2000)
    检查('备注和"靠"也记下了', 记下的[0].备注 === '测试用' && 记下的[0].靠 === '纯估')

    // ---------------------------------------------------------------
    console.log('')
    console.log('  ── 六、修正系数：少了不敢用，有了也不被极端值带跑 ──')

    // 再来 8 条，凑够 10（最少几条才敢修 = 10）
    for (let i = 0; i < 8; i++) 尺.对账(1000, 2000)
    检查('9 条还是不敢修', 尺.修正系数() === null, String(尺.修正系数()))

    // 第 10 条，全是 2 倍 → 中位数还是 2
    尺.对账(1000, 2000)
    const 修 = 尺.修正系数()
    检查('10 条就敢修了', 修 !== null, String(修))
    检查('10 条全是 2 倍 → 修正系数 2', 修 === 2, String(修))

    // 塞一个极端值进去，中位数不该被带跑
    尺.对账(1000, 90000) // 比值 90，脏数据
    const 修2 = 尺.修正系数()
    检查('来一个 90 倍的脏数据，中位数不动', 修2 === 2, `变成 ${修2} 了`)
    console.log('     （这就是为什么用中位数不用平均数 —— 平均数这会儿已经被带到 10 倍了）')

    // 修正系数夹在合理范围内
    for (let i = 0; i < 20; i++) 尺.对账(1000, 90000)
    const 修3 = 尺.修正系数()
    检查('脏数据太多被夹住，不会飞掉', 修3 <= 2.5, `修正是 ${修3}`)

    // ---------------------------------------------------------------
    console.log('')
    console.log('  ── 七、修正在估算里真的起作用了 ──')

    // 现在中位数是 90（刚塞了一堆），但被夹到 2.5
    const 修过 = 尺.估请求([{ role: 'user', content: 中文(1000) }])
    检查('没锚的时候用修正系数', 修过.靠 === '修正系数', 修过.靠)
    检查('估出来的数被放大了', 修过.tok > 修过.纯, `${修过.纯} → ${修过.tok}`)
    检查('纯估那个数一直没被修（对账要用它）', 修过.纯 === 尺.估消息们([{ role: 'user', content: 中文(1000) }]).总)

    // ---------------------------------------------------------------
    console.log('')
    console.log('  ── 八、不出事 ──')

    检查('对账传 0 不崩（也不会记进去）', 尺.对账(0, 100) === null)
    检查('对账传 undefined 不崩', 尺.对账(undefined, 100) === null)
    检查('估请求传 undefined 不崩', Number.isFinite(尺.估请求(undefined).tok))
    检查('记真数传 0 不会把锚弄坏', (() => { 尺.记真数([], 0); return true })())
  } finally {
    // ---------------------------------------------------------------
    console.log('')
    console.log('  ── 九、还原 ──')
    try {
      if (原对账 === null) fs.rmSync(尺.对账文件, { force: true })
      else fs.writeFileSync(尺.对账文件, 原对账, 'utf8')
      尺.忘掉锚()
      尺.忘掉修正()
    } catch (错误) {
      console.log('  ✗ 还原失败：' + 错误.message)
      process.exit(1)
    }
    const 现在条数 = fs.existsSync(尺.对账文件)
      ? fs.readFileSync(尺.对账文件, 'utf8').split('\n').filter((l) => l.trim()).length
      : 0
    检查('对账文件回到原来的样子', 现在条数 === 原条数, `${原条数} → ${现在条数}`)
  }

  console.log('')
  console.log('  ════════════════════════════════════════════')
  console.log(`   ${过了} / ${总数}` + (过了 === 总数 ? '   ✓ 全过' : '   ✗ 有没过的'))
  console.log('  ════════════════════════════════════════════')
  console.log('')
  process.exit(过了 === 总数 ? 0 : 1)
}

main()
