/**
 * 测并发确认.cjs —— 她一轮里要写好几个东西的时候，确认那条路通不通
 *
 * 【为什么专门测这个】
 *   2026-10-01 出的现场：她在干活模式里一轮要点两个文件，
 *   日志里是这样 ——
 *     ⏸ 等他对「新建：D:\elysia测试\hello.py」点头
 *       ✓ 他同意了（请求 1）
 *       ↳ 动手：…（hello.py）—— 没成：他不同意这次写入。
 *   **他明明点了同意，第二个却报"他不同意"。**
 *
 *   根因：确认那一层原来是"一次只准一个待答复"，
 *   第二个请求撞上"有人在等"就**直接返回 false**，
 *   而工具收到 false 会理解成"他不同意"。
 *   他没看见那次请求，却被当成了拒绝。
 *
 *   这个测试就是量这件事：同时发好几个请求，看它们是不是各答各的。
 *
 * 【2026-10-08 补的账】
 *   答复的形状那天从 `true/false` 变成了 `{同意, 记住}`（多了"以后别再问"那一票）。
 *   程序改完了，这个测试没跟着改 —— 于是它 8/15 红着。
 *   **更糟的是它当时还退 0**，所以混在"跑全套"里跟通过的一模一样，
 *   红了整整一天没人发现。两件事都在这儿修掉了：
 *     · 断言改成认两种形状（见下面的 同意了吗 / 拒了吗）
 *     · 结尾 process.exit 说实话
 *   教训连着上一条：**替身和断言都得跟着真身走**，
 *   不然量出来的"全过"和"全红"都是假的。
 *
 * 用法: node tools\测并发确认.cjs
 */
'use strict'

const path = require('node:path')
const 确认 = require(path.resolve(__dirname, '..', '脑', '确认.cjs'))

let 过了 = 0
let 总数 = 0
function 检查(说明, 条件, 细节 = '') {
  总数++
  if (条件) {
    过了++
    console.log(`  ✓ ${说明}`)
  } else {
    console.log(`  ✗ ${说明}${细节 ? '   → ' + 细节 : ''}`)
  }
}

/**
 * 这一票是不是"同意"。
 *
 * 【为什么要写成小助手，而不是每处 `x === true`】
 *   答复的形状变过一次（布尔 → {同意, 记住}），而当时就是靠
 *   "每一处都自己写了一遍 === true"漏掉的：改程序的人不知道有 15 处要改。
 *   收成一个函数，以后形状再变只改这两行。
 *   两种形状都认 —— 是为了让"有人把返回值改回去"这件事也能被测出来。
 */
const 同意了吗 = (答复) => 答复 === true || (答复 && 答复.同意 === true)
const 拒了吗 = (答复) => !同意了吗(答复)

async function main() {
  console.log('')
  console.log('  ════════════════════════════════════════════')
  console.log('   同时来好几个"要他点头"，会不会互相踩')
  console.log('  ════════════════════════════════════════════')
  console.log('')

  // ---------------------------------------------------------------
  console.log('  ── 一、两个请求同时在等，各答各的 ──')

  const 收到的 = []
  确认.注册({
    问窗口: async (请求) => {
      收到的.push(请求)
      // 注意：这里**不立刻结算** —— 模拟"两个请求同时挂起"的局面
    },
  })

  const 甲 = 确认.问({ 类型: '新建', 路径: '甲.txt' })
  const 乙 = 确认.问({ 类型: '新建', 路径: '乙.txt' })

  // 给它们一点时间挂上去
  await new Promise((停) => setTimeout(停, 50))

  检查('两个请求都送到他那儿了', 收到的.length === 2, `收到 ${收到的.length} 个`)
  检查('编号是两个不同的', 收到的[0] && 收到的[1] && 收到的[0].编号 !== 收到的[1].编号)

  // 先答第二个（故意不按顺序）—— 看它会不会答错人
  确认.结算(收到的[1].编号, true)
  const 乙的答复 = await 乙
  检查('先答第二个：第二个拿到"同意"', 同意了吗(乙的答复), JSON.stringify(乙的答复))

  确认.结算(收到的[0].编号, false)
  const 甲的答复 = await 甲
  检查('再答第一个：第一个拿到"不同意"', 拒了吗(甲的答复), JSON.stringify(甲的答复))
  检查('顺序乱了也不会答错人', 同意了吗(乙的答复) && 拒了吗(甲的答复))

  // ---------------------------------------------------------------
  console.log('')
  console.log('  ── 二、三个同时来，全同意 ──')

  const 第二批 = []
  确认.注册({
    问窗口: async (请求) => {
      第二批.push(请求)
    },
  })

  const 三个 = [
    确认.问({ 类型: '新建', 路径: '一号.txt' }),
    确认.问({ 类型: '新建', 路径: '二号.txt' }),
    确认.问({ 类型: '跑命令', 命令: 'python x.py' }),
  ]
  await new Promise((停) => setTimeout(停, 50))
  检查('三个都送到了', 第二批.length === 3, `送到 ${第二批.length} 个`)

  for (const 请求 of 第二批) 确认.结算(请求.编号, true)
  const 结果们 = await Promise.all(三个)
  检查('三个都拿到"同意"（没有谁被误判成拒绝）', 结果们.every(同意了吗), JSON.stringify(结果们))

  // ---------------------------------------------------------------
  console.log('')
  console.log('  ── 二点五、★ "记住"这一票有没有带回来 ──')
  //
  // 【为什么单独量它 —— 2026-10-08】
  //   他点"同意"的时候还能顺手勾一句"以后这类别再问我"。
  //   那一票要是丢了，表现是**他勾了、也不报错、但下次照样弹卡片** ——
  //   他会以为是自己没点中，然后再点一遍，一直点。
  //   所以"同意"和"记住"是两票，得分开量。
  const 第五批 = []
  确认.注册({
    问窗口: async (请求) => {
      第五批.push(请求)
    },
  })

  const 丙 = 确认.问({ 类型: '新建', 路径: '丙.txt' })
  const 丁 = 确认.问({ 类型: '新建', 路径: '丁.txt' })
  await new Promise((停) => setTimeout(停, 50))

  确认.结算(第五批[0].编号, true, true)
  确认.结算(第五批[1].编号, true, false)
  const [丙答, 丁答] = await Promise.all([丙, 丁])
  检查('★ 他勾了"记住"：这一票带得回来', 同意了吗(丙答) && 丙答.记住 === true, JSON.stringify(丙答))
  检查(
    '★ 他没勾：记住是 false（不是"同意就等于记住"）',
    同意了吗(丁答) && 丁答.记住 === false,
    JSON.stringify(丁答),
  )

  // ---------------------------------------------------------------
  console.log('')
  console.log('  ── 三点五、窗口把答复 return 回来的时候（真身就是这么干的）──')
  //
  // 【这一格是补票的 —— 2026-10-01 晚上他真卡住了一次】
  //
  //   上面几关的问窗口都是 `async (请求) => { 收到.push(请求) }` ——
  //   它 resolve 出来的是 **undefined**，走的是"等你回头调 结算()"那条路。
  //   于是 11/11 全过，可**真身走的根本不是这条路**。
  //
  //   真身（main.js）是这样：
  //     return await new Promise((完成) => { 等答复的.set(编号, 完成); ... })
  //   他一点卡片，这个 promise 就 resolve 成 **true / false** ——
  //   是布尔值，于是 确认.问 里那句
  //       if (typeof 答复 === 'boolean') 结算(编号, 答复)
  //   就真的跑起来了，而它当时用的是**模块级的 编号**（还在变的那个）。
  //
  //   两个请求同时在等的时候，甲的答复回来时 编号 已经变成乙的号了 ——
  //   于是甲的"同意"结算到了乙头上，甲永远等不到。
  //   他看到的：点了同意，界面还挂着"等你点头"，消息也发不出去。
  //
  //   测试漏掉它，是因为**喂给它的形状跟真身不一样**。
  //   教训：替身要照着真身的形状做，不然量出来的"全过"是假的。
  //
  // 【2026-10-08】真身现在 resolve 的是 `{同意, 记住}` 了。
  //   所以这一关**两条路都走一遍**（一个 resolve 布尔、一个 resolve 对象）——
  //   确认.问 里那两个分支都得有人踩过，不然又是"看着全过"。
  const 第四批 = []
  确认.注册({
    问窗口: (请求) =>
      new Promise((完成) => {
        第四批.push(请求)
        // 学 main.js：把"兑现承诺"的函数存起来，等他点的时候再调
        请求.__完成 = 完成
      }),
  })

  const 甲2 = 确认.问({ 类型: '跑命令', 命令: 'gcc guess.c -o guess.exe' })
  const 乙2 = 确认.问({ 类型: '新建', 路径: 'guess.c' })
  await new Promise((停) => setTimeout(停, 50))

  检查('两个都挂上了', 第四批.length === 2, `挂上 ${第四批.length} 个`)

  // 他点了第一张卡片 —— 老形状：resolve 成布尔值
  第四批[0].__完成(true)
  await new Promise((停) => setTimeout(停, 50))

  // 第一张点完之后，还剩几个在等？
  // 【为什么用 在等的编号() 而不是 在等吗()】要看清楚**剩的是哪一个**。
  const 还剩 = 确认.在等的编号()
  检查('点完第一张，还剩第二个在等（第一个不该被留下）', 还剩.length === 1, `还剩 ${JSON.stringify(还剩)}`)
  检查(
    '剩下的那个是乙，不是甲（甲的答复没算到乙头上）',
    还剩.length === 1 && 还剩[0] === 第四批[1].编号,
    `剩的是 ${JSON.stringify(还剩)}，乙的编号是 ${第四批[1].编号}`,
  )

  // 再点第二张 —— 新形状：resolve 成 {同意, 记住}
  第四批[1].__完成({ 同意: true, 记住: false })
  const [甲2答, 乙2答] = await Promise.all([甲2, 乙2])
  检查(
    '两张都点了同意 → 两个都拿到"同意"',
    同意了吗(甲2答) && 同意了吗(乙2答),
    JSON.stringify([甲2答, 乙2答]),
  )

  // ---------------------------------------------------------------
  console.log('')
  console.log('  ── 三、作废：程序退出时不能留等不到的承诺 ──')

  const 第三批 = []
  确认.注册({
    问窗口: async (请求) => {
      第三批.push(请求)
    },
  })

  const 挂着的 = [确认.问({ 类型: '新建', 路径: '甲.txt' }), 确认.问({ 类型: '新建', 路径: '乙.txt' })]
  await new Promise((停) => setTimeout(停, 50))

  const 作废了几个 = 确认.作废()
  检查('作废了两个', 作废了几个 === 2, `作废了 ${作废了几个} 个`)

  const 作废后 = await Promise.all(挂着的)
  检查('作废 = 当作不同意（不是永远等）', 作废后.every(拒了吗), JSON.stringify(作废后))
  检查(
    '★ 作废不带"记住"（程序要退了，不是他点的放行）',
    作废后.every((x) => !x.记住),
    JSON.stringify(作废后),
  )
  检查('作废之后没有残留', 确认.在等吗() === false)

  // ---------------------------------------------------------------
  console.log('')
  console.log('  ── 四、没人可问的时候 ──')

  确认.注册({}) // 把窗口撤掉
  const 没窗口 = await 确认.问({ 类型: '新建', 路径: 'x.txt' })
  检查('没人可问 → 拒绝（不是默许）', 拒了吗(没窗口), JSON.stringify(没窗口))

  console.log('')
  console.log('  ════════════════════════════════════════════')
  console.log(`   ${过了} / ${总数}` + (过了 === 总数 ? '   ✓ 全过' : '   ✗ 有不对的'))
  console.log('  ════════════════════════════════════════════')
  console.log('')

  // 【退出码要说实话】这个脚本原来跑出 8/15 也退 0，
  //   于是在"跑全套"里跟通过的一模一样 —— 红了整整一天没人发现。
  process.exit(过了 === 总数 ? 0 : 1)
}

main().catch((错误) => {
  console.log('✗ 测试自己出错了: ' + 错误.message)
  console.log(错误.stack.split('\n').slice(0, 4).join('\n'))
  process.exit(1)
})
