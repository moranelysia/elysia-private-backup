/**
 * 测学习进度.cjs —— 那本"学到哪儿了"的账，读得出来吗、只在该出现的地方出现吗
 *
 * 【为什么值得单写】
 *   账本这东西坏了**不报错**：读不出来就是空字符串，
 *   她照样能说话，只是每次开口都以为"我们什么都没学过"——
 *   表现是"她怎么又问一遍我学到哪了"，而这看着像她记性差，
 *   没人会想到是文件读失败。
 *
 * 【默认不花钱】"学习模式才带账本"是拿假网截请求看的。
 * 只有显式传 `--真跑` 才会跑最后那次真实记账请求。
 *
 * 【不动真的进度文件】用 ELYSIA_进度文件 指到测试目录里。
 *
 * 用法: node tools\测学习进度.cjs
 */
'use strict'

const fs = require('node:fs')
const path = require('node:path')

const 项目根 = path.resolve(__dirname, '..')
const 脑 = path.join(项目根, '脑')
const 测试目录 = path.join(项目根, '.cache', '_测学习进度')
const 测试账本 = path.join(测试目录, '进度.md')
const 真跑 = process.argv.includes('--真跑')

// 【必须在 require 之前设】不然会去动真的 学习\进度.md
process.env.ELYSIA_进度文件 = 测试账本
// 对话层即使用假网，也会按正常流程落一次记忆。把整套运行数据隔离到测试目录，
// 不能再像旧测试那样把真实记忆文件“内容不变地重写一遍”。
process.env.ELYSIA_DATA_DIR = path.join(测试目录, '记忆')
process.env.ELYSIA_CACHE_DIR = path.join(测试目录, '缓存')

// 真的那个账本的路径（收尾时要确认它没被碰）
const 配置 = require(path.join(脑, '配置.cjs'))
const 真账本路径 = path.join(配置.学习区根, '进度.md')
const 真账本原来存在 = fs.existsSync(真账本路径)
const 真账本原文 = 真账本原来存在 ? fs.readFileSync(真账本路径, 'utf8') : null

let 过了 = 0
let 总数 = 0
function 检查(说明, 条件, 细节 = '') {
  总数++
  if (条件) {
    过了++
    console.log(`  ✓ ${说明}`)
  } else {
    console.log(`  ✗ ${说明}${细节 ? '   → ' + 细节 : ''}`)
  }
}

const 编码器 = new TextEncoder()
function 编码(文字) {
  return 编码器.encode(文字)
}

function 装假网(抓到) {
  const 真网 = globalThis.fetch
  globalThis.fetch = async (_地址, 选项) => {
    try {
      抓到.push(JSON.parse(选项.body))
    } catch {
      抓到.push(null)
    }
    const 段 = [
      编码('data: ' + JSON.stringify({ choices: [{ delta: { content: '嗯嗯' } }] }) + '\n\n'),
      编码('data: [DONE]\n\n'),
    ]
    let 号 = 0
    return {
      ok: true,
      status: 200,
      text: async () => '',
      body: {
        getReader: () => ({
          read: async () => (号 < 段.length ? { done: false, value: 段[号++] } : { done: true }),
        }),
      },
    }
  }
  return () => {
    globalThis.fetch = 真网
  }
}

function 系统提示(体) {
  const 们 = (体 && 体.messages) || []
  const 条 = 们.find((m) => m.role === 'system')
  return (条 && typeof 条.content === 'string' && 条.content) || ''
}

const 暗号 = '### 这是测试用的假账本 SEKRIT ###'

async function 主() {
  fs.rmSync(测试目录, { recursive: true, force: true })
  fs.mkdirSync(测试目录, { recursive: true })

  console.log('')
  console.log('  ════════════════════════════════════════════')
  console.log('   学习进度账本 —— 读得到吗、只在学习模式出现吗')
  console.log('  ════════════════════════════════════════════')
  console.log('')

  const 学习进度 = require(path.join(脑, '学习进度.cjs'))
  const 对话 = require(path.join(脑, '对话.cjs'))

  // -------------------------------------------------------------
  console.log('  ── 一、文件这一层 ──')

  检查('路径落在测试目录里（没跑到真的学习区去）', 学习进度.路径() === 测试账本, 学习进度.路径())
  检查('刚开始没有这个文件', 学习进度.有吗() === false)
  检查('读不出来时给空字符串，不报错', 学习进度.读() === '')

  检查('建了一个空的', 学习进度.建空的() === true)
  检查('  建完就在了', 学习进度.有吗() === true)
  检查('  空壳里写着"还没有记过东西"', 学习进度.读().includes('还没有记过东西'))
  检查('  再建一次不会覆盖（返回 false）', 学习进度.建空的() === false)

  学习进度.写('# 学习进度\n\n## C语言程序设计\n\n- 现在到：讲了 C 的来历\n')
  检查('写得进去', 学习进度.读().includes('讲了 C 的来历'))

  // 他自己手写的别的东西也要原样留着 —— 这是我们"不解析"的理由
  学习进度.写(暗号 + '\n\n随便他写点什么\n')
  检查('★ 他自己写进账本的内容原样读得回来（不解析、不重排）', 学习进度.读().includes(暗号))

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 二、给她看的那一段 ──')

  const 话 = 学习进度.拼给她()
  检查('拼出来的话里带着账本原文', 话.includes(暗号))
  检查('  也写清楚了账本文件在哪', 话.includes(测试账本))
  检查('  提醒了她"接着讲之前先看一眼"', 话.includes('先看一眼'))

  学习进度.写('') // 空文件
  检查('账本是空的时候，干脆不拼（省得她以为学过）', 学习进度.拼给她() === '')

  学习进度.写(暗号)

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 三、★ 只该在学习模式里出现（假网截请求）──')

  async function 跑一轮(模式) {
    const 抓到 = []
    const 收网 = 装假网(抓到)
    try {
      await 对话.说话({ 他说的话: '在吗', 历史: [], 模式 })
    } finally {
      收网()
    }
    return 系统提示(抓到[0])
  }

  const 学习的 = await 跑一轮('learn')
  const 聊天的 = await 跑一轮('chat')
  const 干活的 = await 跑一轮('work')

  检查('★ 学习模式带上了账本', 学习的.includes(暗号))
  检查('★ 聊天模式没带', !聊天的.includes(暗号))
  检查('★ 干活模式也没带（干活是干活，别把学习那套塞给它）', !干活的.includes(暗号))

  检查('  账本排在提示词的靠后位置', 学习的.indexOf(暗号) > 学习的.length * 0.8, `位置 ${学习的.indexOf(暗号)} / 总长 ${学习的.length}`)

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 四、账本文件不在的时候，学习模式会不会自己补一个 ──')

  fs.rmSync(测试账本, { force: true })
  const 学习的那份 = await 跑一轮('learn')
  检查('★ 账本不在 → 自己建了一个空的', fs.existsSync(测试账本))
  检查('  这一轮照样能说话（没崩）', 学习的那份.includes('陪他学'))
  检查('  没把"空账本"当成"我们什么都没学过"塞给她', !学习的那份.includes(暗号))

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 五、并进账本（纯文本活，不花钱）──')

  const 底稿 =
    '# 学习进度\n\n' +
    '## 高数A-1\n\n' +
    '- 现在到：第一章极限\n' +
    '- 已经弄明白的：\n' +
    '- 还没弄明白的：\n' +
    '- 下一步：\n' +
    '- 复习时间：2026-10-12 20:00\n' +
    '- 上次动过：2026-10-01\n\n' +
    '我自己的记号：极限这块要再看一遍\n\n' +
    '## 我自己写的一节\n\n' +
    '这里是我手写的笔记，格式跟程序那套不一样\n'

  学习进度.写(底稿)
  检查('认得账本里有哪几门课', 学习进度.课程们().join('、') === '高数A-1、我自己写的一节', 学习进度.课程们().join('、'))

  const 甲 = 学习进度.并进去({
    有进展: true,
    课程: '高数A-1',
    现在到: '讲完极限，开始导数',
    已经弄明白的: '极限的定义',
    还没弄明白的: '无穷小到底算不算 0',
    下一步: '导数的几何意义',
  })
  检查('改已有的那一门：改成了', 甲.改了 === true)
  检查('  "现在到"换成了新的', 学习进度.读().includes('讲完极限，开始导数'))
  检查('  旧的"第一章极限"没了', !学习进度.读().includes('第一章极限'))
  检查('  ★同一节里他自己加的记号还在', 学习进度.读().includes('我自己的记号：极限这块要再看一遍'))
  检查('  ★他自己手写的那一节一个字没动', 学习进度.读().includes('这里是我手写的笔记，格式跟程序那套不一样'))
  检查('  ★没给新的复习时间时保留他手定的时间', 学习进度.读().includes('- 复习时间：2026-10-12 20:00'))

  const 四项 = 学习进度.四项状态()
  检查('四项状态认得课程', 四项.课程 === '高数A-1', JSON.stringify(四项))
  检查('  认得当前章节（兼容旧增量字段）', 四项.当前章节 === '讲完极限，开始导数')
  检查('  认得下一步', 四项.下一步 === '导数的几何意义')
  检查('  认得复习时间', 四项.复习时间 === '2026-10-12 20:00')

  const 空四项 = 学习进度.四项状态('# 学习进度\n\n他手写：下一步也许复习高数，但还没定。\n')
  检查('★ 自由文字里出现“下一步”也不误读', Object.values(空四项).every((x) => x === ''))

  const 多门 = 学习进度.四项状态(
    '## 较早的课\n- 当前章节：第一章\n- 上次动过：2026-10-01 10:00\n\n' +
      '## 最近的课\n- 现在到：第二章\n- 下一步：第三章\n- 上次动过：2026-10-03 10:00\n',
  )
  检查('★ 多门课取“上次动过”最新的一门', 多门.课程 === '最近的课')
  检查('  旧字段“现在到”仍能读成当前章节', 多门.当前章节 === '第二章')

  const 乙 = 学习进度.并进去({
    有进展: true,
    课程: 'C语言程序设计',
    现在到: '讲了 C 的来历',
    已经弄明白的: '',
    还没弄明白的: '',
    下一步: '动手写第一个程序',
  })
  检查('新的一门课：接在最后', 乙.改了 === true)
  检查('  它成了一个二级标题', 学习进度.读().includes('## C语言程序设计'))
  检查('  排在原有课程后面', 学习进度.读().indexOf('C语言程序设计') > 学习进度.读().indexOf('我自己写的一节'))

  // 他手写的那一节：我们只能往后追加，不许动他的字
  const 丙 = 学习进度.并进去({ 有进展: true, 课程: '我自己写的一节', 现在到: '她插了一笔' })
  检查('碰他手写的节：也记上了', 丙.改了 === true)
  检查('  ★他那句话还在', 学习进度.读().includes('这里是我手写的笔记，格式跟程序那套不一样'))
  检查('  我们的字段追加在后面', 学习进度.读().indexOf('她插了一笔') > 学习进度.读().indexOf('这里是我手写的笔记'))

  const 丁 = 学习进度.并进去({ 有进展: false })
  检查('闲聊那一种：什么都不改', 丁.改了 === false && 丁.说明.includes('没什么可记'))

  const 戊 = 学习进度.并进去({ 有进展: true })
  检查('说"有进展"却没说是哪门课：也不改，但要说清为什么', 戊.改了 === false && !!戊.说明)

  检查('★ 每两节之间有空行（不然 markdown 会粘在一起）', !/上次动过：[^\n]*\n##/.test(学习进度.读()))

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 六、从模型嘴里抠 JSON ──')

  检查('光秃秃的 JSON 抠得出来', 学习进度.抠JSON('{"有进展":true}').有进展 === true)
  检查('套着 ```json 壳的也抠得出来', 学习进度.抠JSON('```json\n{"有进展":false}\n```').有进展 === false)
  检查('前后带废话的也抠得出来', 学习进度.抠JSON('好的，这是结果：{"有进展":true} 完毕').有进展 === true)
  检查('根本不是 JSON → null，不抛错', 学习进度.抠JSON('我不会') === null)
  检查('空的 → null', 学习进度.抠JSON('') === null)

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 七、★ 真跑一次记账（只有 --真跑 才执行）──')

  if (真跑) {
    学习进度.写(底稿)
    let 真果 = null
    try {
      真果 = await 学习进度.记一笔({
        他说的: '这一段我没看懂，为什么 C 语言的数组下标要从 0 开始？',
        她回的:
          '因为下标说的其实是"离开头有多远"。第一个元素离开头是 0 个位置，' +
          '所以它是 0 —— 不是"第一个"，是"偏移了 0 个"。',
      })
    } catch (错误) {
      真果 = { 改了: false, 说明: '抛异常了：' + 错误.message }
    }

    检查('★ 真跑了一次，没崩在异常上', !!(真果 && typeof 真果.改了 === 'boolean'), JSON.stringify(真果))
    console.log('      它说：' + JSON.stringify(真果))
    if (真果 && 真果.改了) {
      const 记完的 = 学习进度.读()
      console.log('      账本里现在有：' + 学习进度.课程们().join('、'))
      检查('  记进去之后，账本还是能读的', 记完的.length > 0)
      检查('  原来那门课没被弄丢', 记完的.includes('高数A-1'))
    } else {
      console.log('      （这次它判断"没什么可记的"—— 那也是一种正确的回答，不算失败）')
    }
  } else {
    console.log('      跳过：默认离线；需要付费真测时显式加 --真跑')
  }

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 八、收尾 ──')

  fs.rmSync(测试目录, { recursive: true, force: true })
  检查('测试目录擦掉了（没往真的学习区里丢垃圾）', !fs.existsSync(测试目录))
  const 现在存在 = fs.existsSync(真账本路径)
  const 现在原文 = 现在存在 ? fs.readFileSync(真账本路径, 'utf8') : null
  检查(
    '真的那个账本没被这次测试碰过',
    现在存在 === 真账本原来存在 && 现在原文 === 真账本原文,
  )

  console.log('')
  console.log('  ════════════════════════════════════════════')
  console.log(`   ${过了} / ${总数}`)
  console.log('  ════════════════════════════════════════════')
  console.log('')
  process.exit(过了 === 总数 ? 0 : 1)
}

主().catch((错误) => {
  console.log('  ✗ 测试自己炸了：' + (错误 && 错误.stack))
  process.exit(1)
})
