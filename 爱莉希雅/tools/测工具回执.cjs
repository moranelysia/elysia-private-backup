/** T1：统一工具回执与本地完成闸门。全程本地，不调用模型、不碰真实记忆。 */
'use strict'

const path = require('node:path')
const { spawnSync } = require('node:child_process')
const 根 = path.resolve(__dirname, '..')
const 回执 = require(path.join(根, '脑', '工具回执.cjs'))
const 对话 = require(path.join(根, '脑', '对话.cjs'))
const 工作索引 = require(path.join(根, '脑', '工作索引.cjs'))

let 总数 = 0
let 通过 = 0
function 检查(说明, 条件, 细节 = '') {
  总数++
  if (!条件) throw new Error('✗ ' + 说明 + (细节 ? '：' + 细节 : ''))
  通过++
  console.log('✓ ' + 说明)
}

// S01：天气搜回无关材料，已经被工具拒绝时，不能再变成完成。
const 天气 = { 名字: '查', 参数: '天津今天天气', 结果: { 好: false, 原因: '天气结果不可靠', 说明: '没有有效气象来源' } }
const 天气回执 = 回执.取(天气)
检查('S01 无关天气结果是失败', 天气回执.执行状态 === '失败' && 天气回执.目标完成 === '否')
检查('S01 错误类别保留为结果不可靠', 天气回执.错误.类别 === '结果不可靠')
检查('S01 工作状态不能完成', 工作索引.从工具判断状态([天气]) === '失败')

// F03：即使系统调用本身成功，只要后验明确不符，目标就不能完成。
const 写错 = {
  名字: '写', 参数: '成果.txt',
  结果: { 好: true, 路径: 'F:\\成果.txt', 验证状态: '未验证', 目标完成: '否', 错误类别: '写后内容不符' },
}
检查('F03 写入执行成功与目标失败能同时表达', 回执.取(写错).执行状态 === '成功' && 回执.取(写错).目标完成 === '否')
检查('F03 空口说写好会被完成闸门拦住', 对话.判断空转补救({
  能动手: true, 工具们: [写错], 他说的话: '写一份成果', 回答: '已经写好了。',
}).原因 === '目标未验证')

// C01：退出码为零只证明命令结束，不证明目标产物存在。
const 缺产物 = {
  名字: '跑', 参数: 'node build.js',
  结果: { 好: true, 退出码: 0, 验证状态: '未验证', 目标完成: '否', 错误类别: '目标产物缺失' },
}
检查('C01 退出零但缺产物不能算完成', 回执.取(缺产物).目标完成 === '否')
检查('C01 工作状态只能部分完成', 工作索引.从工具判断状态([缺产物]) === '部分完成')

// A01：子代理交来非空文字，但没有目标证据。
const 无证据纸条 = { 名字: '派', 参数: '查清版本', 结果: { 好: true, 内容: '应该已经处理好了。' } }
检查('A01 无证据子代理默认为未验证未知', 回执.取(无证据纸条).验证状态 === '未验证' && 回执.取(无证据纸条).目标完成 === '未知')
检查('A01 子代理纸条不能替代完成证据', 对话.判断空转补救({
  能动手: true, 工具们: [无证据纸条], 他说的话: '把它处理好', 回答: '已经做好了。',
}).要补救 === true)

// 兼容：旧工具无需一次重写，确定性的写/任务仍可通过归一层。
const 旧写 = { 名字: '写', 结果: { 好: true, 路径: 'F:\\成果.txt', 内容: '新建了成果.txt' } }
检查('旧写工具自动补齐三层回执', 回执.取(旧写).执行状态 === '成功' && 回执.取(旧写).验证状态 === '部分验证' && 回执.取(旧写).目标完成 === '是')
检查('旧写工具自动补文件证据、来源和时间', 回执.取(旧写).证据[0].类型 === '文件' && 回执.取(旧写).来源[0] === 'F:\\成果.txt' && !!回执.取(旧写).时间)
检查('确有完成证据时不误触发补救', 对话.判断空转补救({
  能动手: true, 工具们: [旧写], 他说的话: '写一份成果', 回答: '已经写好了。',
}).要补救 === false)
const 只读 = { 名字: '读', 结果: { 好: true, 内容: '读到了材料' } }
检查('只读材料不能替代写入完成证据', 对话.判断空转补救({
  能动手: true, 工具们: [只读], 他说的话: '写一份成果', 回答: '已经写好了。',
}).原因 === '目标未验证')
检查('真实失败仍能证明“试过但没成”', 对话.判断空转补救({
  能动手: true, 工具们: [天气], 他说的话: '查一下天气', 回答: '我试过了，但没成。',
}).要补救 === false)

// T01：测试自己报失败时必须非零；当前固定样本应真实通过并返回零。
const 动手测试 = spawnSync(process.execPath, [path.join(根, 'tools', '测动手.cjs')], { encoding: 'utf8' })
检查('T01 测动手当前样本真实通过', 动手测试.status === 0, (动手测试.stdout || '') + (动手测试.stderr || ''))
const 动手源码 = require('node:fs').readFileSync(path.join(根, 'tools', '测动手.cjs'), 'utf8')
检查('T01 测动手失败分支设置非零退出码', 动手源码.includes('process.exitCode = 1'))

console.log(`\n工具回执：${通过}/${总数} 通过`)
