/**
 * 测解析.cjs —— 量"她的话"能不能被读懂
 *
 * 【为什么这个值得一测再测】
 *   她是在**生成文字**，不是在查说明书。同一个意思，她可能写成：
 *     [列:记忆]  [列出 记忆]  [列出：记忆]  [帮我列一下 记忆]
 *   我们这边每漏一种写法，她那边的表现就是"我说了，但什么都没发生"——
 *   而且**不报错**，只是安静地不干活。这种错最难查。
 *
 *   更坏的一种是**认错**：她本来想做表情，却被认成"列目录"，
 *   然后去列一个叫"情:超级爱莉"的目录。这种错会让她干错事。
 *   所以两边都要量：**该认的认出来，不该认的绝不许认。**
 *
 * 用法: node tools\测解析.cjs
 */
'use strict'

const path = require('node:path')
const 解析 = require(path.resolve(__dirname, '..', '脑', '解析工具调用.cjs'))
const 工具表 = require(path.resolve(__dirname, '..', '脑', '工具表.cjs'))
// 流式遮蔽也在这条链上，一起验（它和最终清理必须给出一致的结果）
const 对话 = require(path.resolve(__dirname, '..', '脑', '对话.cjs'))

let 过了 = 0
let 总数 = 0

function 检查(说明, 条件, 细节 = '') {
  总数++
  if (条件) {
    过了++
    console.log(`  ✓ ${说明}`)
  } else {
    console.log(`  ✗ ${说明}${细节 ? '   → ' + 细节 : ''}`)
  }
}

/** 拆一句话，返回 [{名字, 参数, 内容}] */
function 拆(文本) {
  const r = 解析.拆(文本, 工具表.认工具)
  return r.要做.map((x) => ({ 名字: x.名字, 参数: x.参数, 内容: x.内容 }))
}

