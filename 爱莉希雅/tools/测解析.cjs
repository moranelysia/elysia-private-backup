console.log('  ── 六、边吐边掐：说到她动手就停住 ──')
//
// 【他在 2026-10-01 晚上提的】
//   "她的请求是晚于她的输出的，导致她根本不知道自己干了什么。"
//   屏幕上原来是这个顺序：她的话先哗哗流完（里面常常已经在说
//   "写好了""编出来了"），**然后**确认卡片才弹出来问他准不准。
//   人是先读结论、再批准动作的 —— 顺序反了。
//   所以干活模式下，第一轮只吐到"第一个工具标记"为止。

/** 切一刀，看看留下的是什么 */
function 掐(文本) {
  return 解析.切到动手之前(文本, 工具表.认工具)
}

{
  // 最常见的：起手话 + 写文件（代码块很长，本来会先刷一屏）
  const 长 = '好呀，我这就去写。\n\n[写:guess.c]\n```c\nint main(void){ return 0; }\n```\n写好了，你双击就能玩。'
  const 掐后 = 掐(长)
  检查('起手话留下，动手之后的都掐掉', 掐后 === '好呀，我这就去写。', JSON.stringify(掐后))
  检查('代码块没被先刷出来', !掐后.includes('int main'))
  检查('她"写好了"那句没提前露出来', !掐后.includes('写好了'))
}

{
  // [表情:] [记住:] 不算动手 —— 它们在句尾，掐了会把话截没
  const 带表情 = '好呀♪[表情:开心] 你先猜，我去看看记录。\n\n[列:D:\\elysia测试]'
  const 掐后 = 掐(带表情)
  检查('表情标记不当作动手的点', 掐后.includes('你先猜'), JSON.stringify(掐后))
  检查('真正的工具标记才掐', !掐后.includes('列:D'))
}

{
  // 一上来就动手 → 掐完是空的，调用方就不吐字（留着"在打字"三个点）
  const 直接动手 = '[跑:gcc guess.c -o guess.exe]\n编给你看。'
  检查('一上来就动手 → 掐成空的，一个字都不吐', 掐(直接动手) === '', JSON.stringify(掐(直接动手)))
}

{
  // 纯聊天，没有任何标记 → 一个字都不该动
  const 纯话 = '嗯……这个我得想想。你觉得呢？'
  检查('没有标记的话，原样不动', 掐(纯话) === 纯话, JSON.stringify(掐(纯话)))
}

{
  // 认不出的方括号不算动手
  const 认不出 = '他管这个叫[翻个跟头:随便]，我不认识。\n\n[读:共同经历.md]'
  const 掐后 = 掐(认不出)
  检查('认不出的方括号不当动手的点', 掐后.includes('翻个跟头'), JSON.stringify(掐后))
  检查('后面认得出来的还是掐得住', !掐后.includes('读:'))
}

