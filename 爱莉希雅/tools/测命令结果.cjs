/**
 * 测命令结果.cjs —— 量"命令失败的时候，她能不能看见原因"
 *
 * 【为什么专门给这个写测试】
 *   2026-10-01 晚上跑整条线（tools\测整条线.cjs），抓到一个很闷的 bug：
 *
 *     她让 gcc 编一份自己刚写的 C，编不过。然后她说：
 *       "文件是写好了，可是编译没过去 —— **报的是 undefined**，
 *        具体哪一行我也没看清，得再跑一次才知道。"
 *
 *   她不是没看，是那句话里真的什么都没有。
 *   跑命令这个工具**只在成功时填 内容，从来不填 说明**；
 *   而对话层把失败的结果拼成 `没成 —— ${结果.说明}` 递给她 ——
 *   于是 gcc 的原文被整个吞掉，她只拿到一个 undefined。
 *
 *   后果不是"难看"，是**她会开始猜**。那晚她的原话是
 *   "我猜八成是 Windows 那边的事，unistd.h 在 MinGW 上不一定有" ——
 *   一路猜下去，越改越远。有原文的话一眼就知道改哪儿。
 *
 *   所以这一关量三件事：
 *     一、失败时 说明 必须有东西（不能再是 undefined）
 *     二、说明 里要带着命令自己的输出，不是一句干巴巴的"失败了"
 *     三、对话层拼给她的那句话，不许出现 undefined
 *
 * 用法: node tools\测命令结果.cjs
 */
'use strict'

const path = require('node:path')

const 项目根 = path.resolve(__dirname, '..')
const 命令工具 = require(path.join(项目根, '脑', '工具', '命令工具.cjs'))

let 过了 = 0
let 总数 = 0
function 检查(说明, 条件, 细节 = '') {
  总数++
  if (条件) {
    过了++
    console.log(`  ✓ ${说明}`)
  } else {
    console.log(`  ✗ ${说明}${细节 ? '   → ' + 细节 : ''}`)
  }
}

/** 跟 脑\对话.cjs 里拼给她看的那句话一模一样 —— 要测就测同一句 */
function 她会看到的那句(项, 结果) {
  return 结果.好
    ? `【${项.名字}：${项.参数}】\n${结果.内容}`
    : `【${项.名字}：${项.参数}】没成 —— ` +
        (结果.说明 || 结果.内容 || '（工具没给出原因，别猜，换个做法再试）')
}

const 点头 = async () => true

async function main() {
  console.log('')
  console.log('  ════════════════════════════════════════════')
  console.log('   命令失败时：她到底能不能看见原因')
  console.log('  ════════════════════════════════════════════')

  // ---------------------------------------------------------------
  console.log('')
  console.log('  ── 一、一条必然失败的命令 ──')

  // 用 cmd 自己稳定造一个退出码 7。原先的 node -e 在 Node 26 + cmd 下会被
  // 改写引号，实际变成 JavaScript 语法错误和退出码 1，测试虽然红得起来，
  // 却没有测到注释声称的分支。
  const 失败命令 = 'echo intentional failure 1>&2 & exit /b 7'
  const 果 = await 命令工具.跑(失败命令, { 问: 点头 })

  console.log(`     好 = ${果.好}`)
  console.log(`     说明 = ${JSON.stringify(果.说明)}`)
  console.log(`     内容 = ${JSON.stringify(String(果.内容).slice(0, 160))}`)

  检查('失败的时候 说明 不是 undefined', 果.说明 !== undefined, '说明 是 undefined —— 她又要看见"没成 —— undefined"了')
  检查('失败的时候 说明 是有内容的字符串', typeof 果.说明 === 'string' && 果.说明.trim().length > 0)
  检查('内容 也还在（成功/失败两条路都得有正文）', typeof 果.内容 === 'string' && 果.内容.trim().length > 0)
  检查('稳定拿到预期退出码 7', 果.退出码 === 7, String(果.退出码))

  // ---------------------------------------------------------------
  console.log('')
  console.log('  ── 二、说明 里得带着命令自己的话 ──')

  // 失败原因千奇百怪，这里只要求"不是一句空话"：
  // 至少要交代 用时 / 在哪儿跑的 / 它吐了什么。
  检查('说了用时', /用时/.test(果.说明))
  检查('说了在哪个目录里跑的', /在 .+ 里跑的/.test(果.说明))
  检查('带了命令自己的输出（或者明说没有输出）', /没有任何输出|错误输出|EPERM|error|Error|error/i.test(果.说明), String(果.说明).slice(0, 120))

  // ---------------------------------------------------------------
  console.log('')
  console.log('  ── 三、拼给她看的那句话 ──')

  const 那句 = 她会看到的那句({ 名字: '跑', 参数: 失败命令 }, 果)
  console.log('     ' + 那句.split('\n').slice(0, 3).join('\n     '))

  检查('没有出现 undefined', !/undefined/.test(那句), 那句.slice(0, 160))
  检查('也没有出现 null', !/\bnull\b/.test(那句))
  检查('她看得见"没成"这件事', /没成/.test(那句))

  // ---------------------------------------------------------------
  console.log('')
  console.log('  ── 四、成功那条路不许被改坏 ──')

  // 造一个"成功"的返回，走一遍同一句拼接 —— 成功时用的是 内容，不是 说明
  const 装成功 = { 好: true, 内容: '命令跑完了（用时 0.1s，在 爱莉希雅 里跑的）：\n\nhello' }
  const 成功那句 = 她会看到的那句({ 名字: '跑', 参数: 'echo hello' }, 装成功)
  检查('成功时用 内容', /hello/.test(成功那句))
  检查('成功时不带"没成"', !/没成/.test(成功那句))
  检查('成功时没有 undefined', !/undefined/.test(成功那句))

  // ---------------------------------------------------------------
  console.log('')
  console.log('  ── 五、失败但一个字都没吐的时候 ──')

  // 空命令 = 工具自己挡下来，这条路压根没跑，说明 是必需字段
  const 空 = await 命令工具.跑('', { 问: 点头 })
  检查('空命令被挡下', 空.好 === false)
  检查('空命令有说明', typeof 空.说明 === 'string' && 空.说明.length > 0, JSON.stringify(空.说明))

  // ---------------------------------------------------------------
  console.log('')
  console.log('  ── 六、跑命令时主进程不能被堵住 ──')

  let 定时器响了 = false
  const 慢命令 = 命令工具.跑('node -e "setTimeout(()=>{},250)"', { 问: 点头 })
  setTimeout(() => { 定时器响了 = true }, 30)
  const 慢果 = await 慢命令
  检查('慢命令本身跑完了', 慢果.好 === true, 慢果.说明 || 慢果.内容)
  检查('★ 命令没堵住事件循环（30ms 定时器能先响）', 定时器响了 === true)

  console.log('')
  console.log('  ════════════════════════════════════════════')
  console.log(`   ${过了} / ${总数}` + (过了 === 总数 ? '   ✓ 全过' : '   ✗ 有没过的'))
  console.log('  ════════════════════════════════════════════')
  console.log('')
  process.exit(过了 === 总数 ? 0 : 1)
}

main().catch((错误) => {
  console.log('✗ 测试自己出错了: ' + 错误.message)
  console.log(错误.stack.split('\n').slice(0, 4).join('\n'))
  process.exit(1)
})
