/** 记忆日记 J1：全部使用隔离临时目录与假模型，不读取或改写真正记忆。 */
'use strict'

const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { 创建日记系统, 周期间, 规范日记可见性, 共享日记投影 } = require('../脑/记忆日记.cjs')

const 临时根 = fs.mkdtempSync(path.join(os.tmpdir(), 'elysia-diary-'))
let 总数 = 0
let 通过 = 0
function 检查(说明, 条件) {
  总数++
  if (!条件) throw new Error('✗ ' + 说明)
  通过++
  console.log('✓ ' + 说明)
}
function 读JSON(文件) { return JSON.parse(fs.readFileSync(文件, 'utf8').replace(/^\uFEFF/, '')) }
function 日(年, 月, 号, 时 = 9) { return new Date(年, 月 - 1, 号, 时, 0, 0) }

async function main() {
  let 现在 = 日(2026, 10, 15)
  let 模型次数 = 0
  const 空系统 = 创建日记系统({
    数据目录: path.join(临时根, '空'),
    现在: () => new Date(现在),
    取来源: () => [],
    生成: async () => { 模型次数++; throw new Error('无来源时不该调用模型') },
  })
  const 首次 = 空系统.安排()
  检查('首次调度只建立昨天和上一个自然周', 首次.待处理 === 2)
  检查('日任务使用稳定编号', 空系统.读索引().任务.some((一) => 一.编号 === '日:2026-10-14'))
  检查('周任务使用 ISO 自然周编号', 空系统.读索引().任务.some((一) => 一.编号 === '周:2026-W41'))
  空系统.安排()
  检查('同一天重复启动不重复建任务', 空系统.读索引().任务.length === 2)
  const 空结果 = await 空系统.执行待办({}, 8)
  检查('没有材料的周期明确记为无内容', 空结果.状态.任务.every((一) => 一.状态 === '无内容'))
  检查('没有材料时完全不调用模型', 模型次数 === 0)

  现在 = 日(2026, 10, 18)
  空系统.安排()
  const 补写编号 = 空系统.读索引().任务.map((一) => 一.编号)
  检查('跨数日重启会补齐中间漏掉的每日任务', ['日:2026-10-15', '日:2026-10-16', '日:2026-10-17'].every((一) => 补写编号.includes(一)))
  检查('仍在同一自然周时不重复生成周任务', 补写编号.filter((一) => 一.startsWith('周:')).length === 1)

  现在 = 日(2026, 10, 15)
  const 来源 = [{ 编号: '聊天:abc', 类型: '聊天', 时间: '2026-10-14 20:00', 标题: '他说', 摘要: '完成了 C 语言练习。' }]
  let 生成版本 = 1
  const 正常系统 = 创建日记系统({
    数据目录: path.join(临时根, '正常'),
    现在: () => new Date(现在),
    取来源: () => 来源,
    生成: async ({ 来源们 }) => ({
      标题: `第 ${生成版本} 版`,
      模块: [{ 名字: '学习', 正文: `完成练习 ${生成版本}`, 来源: [来源们[0].编号] }],
    }),
  })
  正常系统.安排()
  const 正常结果 = await 正常系统.执行待办({}, 8)
  检查('有来源的日和周任务都能完成', 正常结果.状态.任务.every((一) => 一.状态 === '已完成'))
  const 日文件 = 正常系统.日记路径('日', '2026-10-14')
  const 日记 = 读JSON(日文件)
  检查('日记保留模块正文和真实来源编号', 日记.模块[0].正文 === '完成练习 1' && 日记.模块[0].来源[0] === '聊天:abc')
  检查('日记来源清单保存可核对的真实摘要', 日记.来源.length === 1 && 日记.来源[0].编号 === '聊天:abc' && 日记.来源[0].摘要 === 来源[0].摘要)
  检查('日记默认不标为用户修改', 日记.用户修改 === false)
  检查('新生成日记明确写为共享可见性', 日记.可见性 === 'shared')
  检查('旧日记缺少可见性字段时只读兼容为共享', 规范日记可见性(undefined) === 'shared')
  let 非法可见性拒绝 = false
  try { 规范日记可见性('secret') } catch (错误) { 非法可见性拒绝 = 错误.message.includes('可见性无效') }
  检查('显式非法可见性不会降级成共享', 非法可见性拒绝)
  let 空可见性拒绝 = false
  try { 规范日记可见性('') } catch (错误) { 空可见性拒绝 = 错误.message.includes('可见性无效') }
  检查('显式空可见性同样被拒绝', 空可见性拒绝)

  日记.用户修改 = true
  日记.标题 = '我自己改的标题'
  fs.writeFileSync(日文件, JSON.stringify(日记, null, 2), 'utf8')
  const 索引 = 正常系统.读索引()
  const 日任务 = 索引.任务.find((一) => 一.编号 === '日:2026-10-14')
  日任务.状态 = '待处理'
  fs.writeFileSync(正常系统.索引文件, JSON.stringify(索引, null, 2), 'utf8')
  生成版本 = 2
  await 正常系统.执行待办({}, 1)
  检查('重新处理不会覆盖用户改过的日记', 读JSON(日文件).标题 === '我自己改的标题')
  const 界面全部 = 正常系统.给界面()
  检查('只读时间轴按最近周期排在前面', 界面全部.列表.length === 2 && 界面全部.列表[0].编号 === '日:2026-10-14')
  检查('界面能只筛选周记', 正常系统.给界面({ 类型: '周' }).列表.every((一) => 一.类型 === '周'))
  检查('界面能搜索模块正文和来源摘要', 正常系统.给界面({ 搜索: 'C 语言练习' }).总数 === 2)
  检查('界面保留模块到来源的可核对链', 界面全部.列表[0].模块[0].来源[0] === '聊天:abc' && 界面全部.列表[0].来源[0].摘要 === 来源[0].摘要)
  检查('界面不暴露日记文件绝对路径', !Object.prototype.hasOwnProperty.call(界面全部.列表[0], '文件'))

  const 周界面 = 界面全部.列表.find((一) => 一.类型 === '周')
  const 编辑结果 = 正常系统.修改日记({
    编号: 周界面.编号, 版本标记: 周界面.版本标记, 标题: '我改过的周记',
    模块: [{ 名字: '学习', 正文: '第一行\n第二行\n本地材料 F:\\private\\notes.txt', 来源: 周界面.模块[0].来源 }],
  })
  const 改后 = 正常系统.给界面().列表.find((一) => 一.编号 === 周界面.编号)
  检查('人工编辑保留换行并标记修改时间', 编辑结果.好 && 改后.模块[0].正文.startsWith('第一行\n第二行') && 改后.用户修改 && !!改后.修改于)
  检查('人工编辑保留原始来源链', 改后.模块[0].来源[0] === '聊天:abc' && 改后.来源[0].摘要 === 来源[0].摘要)
  let 旧版本拒绝 = false
  try { 正常系统.修改日记({ 编号: 周界面.编号, 版本标记: 周界面.版本标记, 标题: '过期编辑', 模块: 周界面.模块 }) } catch (错误) { 旧版本拒绝 = 错误.message.includes('刷新') }
  检查('并发变化后拒绝旧界面覆盖新日记', 旧版本拒绝)
  let 假来源拒绝 = false
  try { 正常系统.修改日记({ 编号: 改后.编号, 版本标记: 改后.版本标记, 标题: '假来源', 模块: [{ 名字: '学习', 正文: '内容', 来源: ['伪造来源'] }] }) } catch (错误) { 假来源拒绝 = 错误.message.includes('来源链无效') }
  检查('编辑不能伪造日记来源编号', 假来源拒绝)

  const 导出文件 = path.join(临时根, '导出', '记忆日记.md')
  const 导出结果 = 正常系统.导出Markdown(导出文件)
  const 导出正文 = fs.readFileSync(导出文件, 'utf8')
  检查('Markdown 导出包含全部日记正文与来源摘要', 导出结果.条数 === 2 && 导出正文.includes('我改过的周记') && 导出正文.includes('第一行\n第二行') && 导出正文.includes(来源[0].摘要))
  检查('Markdown 导出不夹带本机路径或聊天全文字段', 导出正文.includes('[本机路径已省略]') && !导出正文.includes('F:\\private') && !导出正文.includes(临时根) && !导出正文.includes('消息们'))

  const 私密日记 = 读JSON(日文件)
  私密日记.可见性 = 'private'
  私密日记.标题 = '只留在本地的私密日记'
  fs.writeFileSync(日文件, JSON.stringify(私密日记, null, 2), 'utf8')
  检查('共享投影明确拒绝私密日记', 共享日记投影(私密日记) === null)
  检查('默认界面完全不返回私密日记', !正常系统.给界面().列表.some((一) => 一.编号 === 私密日记.编号))
  const 私密后导出文件 = path.join(临时根, '导出', '私密过滤.md')
  const 私密后导出 = 正常系统.导出Markdown(私密后导出文件)
  const 私密后正文 = fs.readFileSync(私密后导出文件, 'utf8')
  检查('默认导出只包含共享日记', 私密后导出.条数 === 1 && !私密后正文.includes('只留在本地的私密日记'))

  delete 私密日记.可见性
  const 旧格式原文 = JSON.stringify(私密日记, null, 2)
  fs.writeFileSync(日文件, 旧格式原文, 'utf8')
  正常系统.给界面()
  检查('读取旧格式日记不会顺手重写正式数据结构', fs.readFileSync(日文件, 'utf8') === 旧格式原文)
  私密日记.可见性 = 'not-allowed'
  fs.writeFileSync(日文件, JSON.stringify(私密日记, null, 2), 'utf8')
  const 非法界面项 = 正常系统.给界面().列表.find((一) => 一.编号 === 私密日记.编号)
  const 非法导出文件 = path.join(临时根, '导出', '非法过滤.md')
  const 非法导出 = 正常系统.导出Markdown(非法导出文件)
  检查('非法可见性只显示读取失败且不会进入导出', 非法界面项 && 非法界面项.状态 === '读取失败' && 非法导出.条数 === 1)

  私密日记.可见性 = 'shared'
  fs.writeFileSync(日文件, JSON.stringify(私密日记, null, 2), 'utf8')

  const 删除结果 = 正常系统.删除日记({ 编号: 改后.编号, 版本标记: 改后.版本标记 })
  const 删除任务 = 正常系统.读索引().任务.find((一) => 一.编号 === 改后.编号)
  检查('删除后文件消失且索引留下防重建标记', 删除结果.好 && 删除任务.状态 === '已删除' && !fs.existsSync(正常系统.日记路径('周', 改后.周期)))
  正常系统.安排()
  检查('重新调度不会重建已删除周期', 正常系统.读索引().任务.filter((一) => 一.编号 === 改后.编号).length === 1 && !正常系统.给界面().列表.some((一) => 一.编号 === 改后.编号))
  const 删除后导出 = path.join(临时根, '导出', '删除后.md')
  检查('已删除日记不进入后续导出', 正常系统.导出Markdown(删除后导出).条数 === 1 && !fs.readFileSync(删除后导出, 'utf8').includes('我改过的周记'))

  const 坏引用系统 = 创建日记系统({
    数据目录: path.join(临时根, '坏引用'),
    现在: () => new Date(现在),
    取来源: () => 来源,
    生成: async () => ({ 标题: '不可信', 模块: [{ 名字: '回顾', 正文: '编出来的', 来源: ['不存在'] }] }),
  })
  坏引用系统.安排()
  const 失败 = await 坏引用系统.执行待办({}, 1)
  const 失败任务 = 失败.状态.任务.find((一) => 一.编号 === '日:2026-10-14')
  检查('引用不存在时不写日记并进入失败重试', 失败任务.状态 === '失败待重试' && !fs.existsSync(坏引用系统.日记路径('日', '2026-10-14')))
  检查('失败任务记录短错误与下次重试时间', 失败任务.错误.includes('不存在的来源') && !!失败任务.下次尝试)

  const 坏索引系统 = 创建日记系统({ 数据目录: path.join(临时根, '坏索引'), 现在: () => new Date(现在) })
  fs.mkdirSync(path.dirname(坏索引系统.索引文件), { recursive: true })
  fs.writeFileSync(坏索引系统.索引文件, '{坏了', 'utf8')
  let 拒绝覆盖 = false
  try { 坏索引系统.安排() } catch (错误) { 拒绝覆盖 = 错误.message.includes('已停止写入') }
  检查('索引损坏时拒绝拿空数据覆盖原文件', 拒绝覆盖 && fs.readFileSync(坏索引系统.索引文件, 'utf8') === '{坏了')

  const 跨年 = 周期间(日(2027, 1, 1))
  检查('跨年日期仍按 ISO 周归属', 跨年.周期 === '2026-W53' && 跨年.开始.getDay() === 1)

  const 主进程 = fs.readFileSync(path.join(__dirname, '..', 'main.js'), 'utf8')
  const 预载 = fs.readFileSync(path.join(__dirname, '..', 'preload.js'), 'utf8')
  const 页面 = fs.readFileSync(path.join(__dirname, '..', 'renderer', 'index.html'), 'utf8')
  const 前端 = fs.readFileSync(path.join(__dirname, '..', 'renderer', 'chat.js'), 'utf8')
  const 样式 = fs.readFileSync(path.join(__dirname, '..', 'renderer', 'style.css'), 'utf8')
  检查('主进程分别暴露日记查询、修改、删除和导出入口', ['问记忆日记', '修改记忆日记', '删除记忆日记', '导出记忆日记'].every((名) => 主进程.includes(`ipcMain.handle('${名}'`)))
  检查('预载裁剪日记编辑字段且不接受导出路径', 预载.includes('修改记忆日记:') && 预载.includes("正文: String((一 && 一.正文)") && 预载.includes("导出记忆日记: () => ipcRenderer.invoke('导出记忆日记')"))
  检查('记忆库增加独立日记页签与筛选', 页面.includes('data-记忆层="日记"') && 页面.includes('id="日记筛选"'))
  检查('日记模块和来源都使用 textContent 绘制', 前端.includes('正文.textContent = 模块.正文') && 前端.includes('来源摘要.textContent = 来源.摘要'))
  检查('日记页明确不进入聊天上下文', 前端.includes('日记不会自动进入聊天上下文'))
  检查('日记卡提供编辑删除且日记页可导出', 前端.includes('开始编辑日记(卡, 一)') && 前端.includes('删除一篇日记(卡, 一, 删除)') && 前端.includes('导出全部记忆日记'))
  检查('日记使用轻量时间轴样式', 样式.includes('.日记卡::before') && 样式.includes('.日记来源详情'))

  console.log(`\n记忆日记：${通过}/${总数} 通过`)
}

main().catch((错误) => { console.error(错误.stack || 错误.message); process.exitCode = 1 }).finally(() => {
  try { fs.rmSync(临时根, { recursive: true, force: true }) } catch { /* 测试结果更重要 */ }
})
