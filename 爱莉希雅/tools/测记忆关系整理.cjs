/** 自动关系整理：隔离记忆目录，验证高置信写入、人工边界、抑制与低频调度。 */
'use strict'

const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')

const 项目根 = path.resolve(__dirname, '..')
const 临时根 = fs.mkdtempSync(path.join(os.tmpdir(), 'elysia-auto-relations-'))
process.env.ELYSIA_DATA_DIR = path.join(临时根, '记忆')
process.env.ELYSIA_CACHE_DIR = path.join(临时根, '缓存')

let 总数 = 0, 通过 = 0
function 检查(说明, 条件) {
  总数++
  if (!条件) throw new Error('✗ ' + 说明)
  通过++
  console.log('✓ ' + 说明)
}

async function main() {
  const 记忆 = require(path.join(项目根, '脑', '记忆.cjs'))
  const 关系模块 = require(path.join(项目根, '脑', '记忆关系图.cjs'))
  const 整理模块 = require(path.join(项目根, '脑', '记忆关系整理.cjs'))
  const 甲 = 记忆.记一条('经历', '2026年10月1日完成记忆关系图', '她')
  const 乙 = 记忆.记一条('经历', '2026年10月5日后来继续完成记忆关系图', '她')
  记忆.记一条('事实', '2026年10月1日喜欢喝咖啡', '她')
  记忆.记一条('事实', '2026年10月2日不喜欢喝咖啡', '她')
  const 关系文件 = path.join(临时根, '记忆', '关系图.json')
  const 状态文件 = path.join(临时根, '缓存', '关系整理状态.json')
  const 图 = 关系模块.创建关系图库({
    关系文件, 布局文件: path.join(临时根, '缓存', '布局.json'), 长期记忆库: 记忆,
    现在: () => new Date('2026-10-22T08:00:00.000Z'),
  })
  const 整理 = 整理模块.创建整理器({
    长期记忆库: 记忆, 关系图库: 图, 状态文件,
    现在: () => new Date('2026-10-22T08:00:00.000Z'), 防抖毫秒: 100, 最小间隔毫秒: 1000,
  })

  const 低分 = 整理模块.挑安全候选([
    { 编号: 'low', 类型: '同一主题', 从编号: 'a', 到编号: 'b', 置信度: 0.91, 依据: '低于阈值' },
    { 编号: 'conflict', 类型: '矛盾', 从编号: 'a', 到编号: 'b', 置信度: 1, 依据: '有冲突' },
  ], new Map([['a', { 类别: '事实', 编号: 'a' }], ['b', { 类别: '事实', 编号: 'b' }]]))
  检查('低置信与矛盾候选不会自动落图', 低分.length === 0)

  const 首次 = 整理.整理一次({ 原因: '隔离测试' })
  检查('高置信后续关系会自动写入', 首次.好 && 首次.新增数 === 2)
  const 已写 = 图.查询().关系
  检查('只写后续发展和单向先于，不写冗余后于', 已写.some((一) => 一.类型 === '后续发展') && 已写.some((一) => 一.类型 === '先于') && !已写.some((一) => 一.类型 === '后于'))
  检查('自动关系保留规则、置信度和文字依据', 已写.every((一) => 一.来源 === '自动整理' && 一.自动依据 && 一.自动依据.规则版本 === 整理模块.规则版本 && 一.自动依据.依据))
  检查('冲突记忆仍只作为候选而不自动确认', !已写.some((一) => 一.类型 === '矛盾' || 一.类型 === '更新'))
  检查('状态缓存记录输入指纹和候选统计', fs.existsSync(状态文件) && JSON.parse(fs.readFileSync(状态文件, 'utf8')).输入指纹 === 首次.输入指纹)
  检查('关系文件不复制记忆正文', !fs.readFileSync(关系文件, 'utf8').includes('完成记忆关系图'))

  const 重复 = 整理.整理一次({ 原因: '重复检查' })
  检查('输入没有变化时直接跳过', 重复.好 && 重复.跳过 && 图.查询().关系.length === 2)

  const 自动语义 = 图.查询().关系.find((一) => 一.类型 === '后续发展')
  检查('用户可以删除自动关系', 图.删除(自动语义.编号).好 && !图.查询().关系.some((一) => 一.编号 === 自动语义.编号))
  const 再跑 = 整理.整理一次({ 原因: '强制复查', 强制: true })
  检查('用户删掉的关系进入抑制记录且不会复活', 再跑.好 && 再跑.新增数 === 0 && !图.查询().关系.some((一) => 一.类型 === '后续发展'))
  const 人工重建 = 图.新增({ 类型: '后续发展', 从: 甲, 到: 乙 })
  检查('用户明确重建后可解除抑制并改为人工确认', 人工重建.好 && 图.查询().关系.find((一) => 一.类型 === '后续发展').来源 === '人工确认')

  const 禁止写 = 图.应用自动候选({ 候选们: [{ 类型: '更新', 从: 甲, 到: 乙, 置信度: 1, 关联置信度: 1, 依据: '不应自动' }] })
  检查('写层再次拒绝自动更新和矛盾关系', 禁止写.好 && 禁止写.新增数 === 0)

  const 排队一 = 整理.排队({ 原因: '变化一' })
  const 排队二 = 整理.排队({ 原因: '变化二' })
  检查('防抖与最小间隔把连续请求合并为单次计划', 排队一.已排队 && 排队二.已排队 && 整理.状态().已安排 && 排队二.等待毫秒 >= 1000)
  整理.取消()
  检查('退出时可以取消尚未执行的整理', !整理.状态().已安排)

  const main源 = fs.readFileSync(path.join(项目根, 'main.js'), 'utf8')
  const 对话源 = fs.readFileSync(path.join(项目根, '脑', '对话.cjs'), 'utf8')
  const 临时源 = fs.readFileSync(path.join(项目根, '脑', '临时记忆提取.cjs'), 'utf8')
  const 前端源 = fs.readFileSync(path.join(项目根, 'renderer', 'chat.js'), 'utf8')
  检查('新增修改遗忘与晋升都会排队关系整理', 对话源.includes('长期记忆发生变化') && main源.includes("原因: '用户修改长期记忆'") && main源.includes("原因: '用户遗忘长期记忆'") && main源.includes("原因: '用户将临时记忆晋升到长期层'"))
  检查('自主晋升也会触发关系整理', 临时源.includes("原因: '临时记忆自主晋升到长期层'"))
  检查('启动检查和三十分钟自我检索已接入单实例主进程', main源.includes("原因: '启动后检查'") && main源.includes("原因: '定期自我检索'") && main源.includes('30 * 60 * 1000'))
  检查('界面区分自动关系并展示置信依据', 前端源.includes('自动整理的关系') && 前端源.includes('确认并保存') && 前端源.includes('自动.置信度'))

  console.log(`\n自动记忆关系整理：${通过}/${总数} 通过`)
}

main()
  .catch((错误) => { console.error(错误.stack || 错误.message); process.exitCode = 1 })
  .finally(() => { try { fs.rmSync(临时根, { recursive: true, force: true }) } catch { /* 测试结果更重要 */ } })
