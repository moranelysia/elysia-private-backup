/** P2 第二层最小版：全部使用假记忆库和系统临时目录，不触碰真实记忆。 */
'use strict'

const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const crypto = require('node:crypto')
const 模块 = require('../脑/记忆聚类候选.cjs')

let 总数 = 0
let 通过 = 0
function 检查(名称, 条件) {
  总数++
  if (!条件) throw new Error('未通过：' + 名称)
  通过++
  console.log('✓ ' + 名称)
}
function 哈希(文件) {
  return crypto.createHash('sha256').update(fs.readFileSync(文件)).digest('hex')
}
function 记录(编号, 内容, 改 = {}) {
  return {
    键: `测试:${编号}`,
    来源层: '长期记忆', 编号, 类别: '事实', 记忆类型: 'semantic',
    person: '用户本人', relationship: '本人', 内容, 时间: '2026-10-21T00:00:00.000Z',
    ...改,
  }
}

const 同主题 = [
  记录('a', '用户喜欢下雨天在窗边读书'),
  记录('b', '用户喜欢下雨天坐在窗边读书'),
  记录('c', '用户很喜欢下雨天在窗边安静读书'),
]
const 组 = 模块.聚类(同主题)
检查('三条高度相似记忆形成一组', 组.length === 1 && 组[0].条数 === 3)
检查('候选保留全部原文与稳定编号', 组[0].依据.length === 3 && 组[0].依据.map((一) => 一.编号).join('') === 'abc')
检查('抽取式摘要明确给出共同线索与代表内容', 组[0].摘要候选.includes('代表内容：') && 组[0].共同线索.length > 0)
检查('组内最低相似度确实达到明示阈值', 组[0].最低相似度 >= 模块.默认相似阈值)

检查('不足三条不会形成候选', 模块.聚类(同主题.slice(0, 2)).length === 0)
检查('不同记忆类型不能混组', 模块.聚类([...同主题.slice(0, 2), 记录('d', 同主题[2].内容, { 记忆类型: 'episodic' })]).length === 0)
检查('不同人物不能混组', 模块.聚类([...同主题.slice(0, 2), 记录('e', 同主题[2].内容, { person: '妈妈', relationship: '家人' })]).length === 0)

const 链 = [
  记录('chain-a', 'alpha beta gamma delta'),
  记录('chain-b', 'alpha beta gamma delta epsilon zeta'),
  记录('chain-c', 'gamma delta epsilon zeta'),
]
const 链分 = [模块.相似度(链[0].内容, 链[1].内容), 模块.相似度(链[1].内容, 链[2].内容), 模块.相似度(链[0].内容, 链[2].内容)]
检查('相似度计算可解释且范围正确', 链分.every((分) => 分 >= 0 && 分 <= 1))
检查('完全链接阻止首尾不足阈值的链式误并', 链分[0] >= 0.55 && 链分[1] >= 0.55 && 链分[2] < 0.55 && 模块.聚类(链).length === 0)

const 临时条 = [
  { 编号: 't-ok', 类别: '候选偏好', 内容: '有效', 生命周期: '有效', 确认状态: '已确认', 到期于: '2026-11-01T00:00:00.000Z', 更新于: '2026-10-20T00:00:00.000Z', 记忆类型: 'semantic', 元数据: { person: '用户本人', relationship: '本人' }, 关系: { 状态: '当前' } },
  { 编号: 't-pending', 类别: '候选偏好', 内容: '待确认', 生命周期: '有效', 确认状态: '待确认', 到期于: '2026-11-01T00:00:00.000Z', 记忆类型: 'semantic', 元数据: { person: '用户本人', relationship: '本人' } },
  { 编号: 't-old', 类别: '候选偏好', 内容: '过期', 生命周期: '有效', 确认状态: '已确认', 到期于: '2026-10-01T00:00:00.000Z', 记忆类型: 'semantic', 元数据: { person: '用户本人', relationship: '本人' } },
  { 编号: 't-replaced', 类别: '候选偏好', 内容: '被替代', 生命周期: '有效', 确认状态: '已确认', 到期于: '2026-11-01T00:00:00.000Z', 记忆类型: 'semantic', 元数据: { person: '用户本人', relationship: '本人' }, 关系: { 状态: '已被替代' } },
]
const 读 = 模块.读取可聚类记忆({
  临时记忆库: { 查询: () => ({ 列表: 临时条 }) },
  长期记忆库: { 全部长期记忆: () => [] },
  现在: () => new Date('2026-10-21T00:00:00.000Z'),
})
检查('只读取有效、已确认、未过期且当前版本的临时记忆', 读.记录.length === 1 && 读.记录[0].编号 === 't-ok')

const 临时根 = fs.mkdtempSync(path.join(os.tmpdir(), 'elysia-cluster-'))
try {
  const 原始文件 = path.join(临时根, '原始记忆.json')
  const 输出文件 = path.join(临时根, 'cache', '候选.json')
  fs.writeFileSync(原始文件, JSON.stringify(同主题, null, 2), 'utf8')
  const 前 = 哈希(原始文件)
  const 假临时库 = { 查询: () => ({ 列表: [] }) }
  const 假长期库 = { 全部长期记忆: () => JSON.parse(fs.readFileSync(原始文件, 'utf8')) }
  const 甲 = 模块.生成并保存({ 输出文件, 临时记忆库: 假临时库, 长期记忆库: 假长期库, 现在: () => new Date('2026-10-21T01:00:00.000Z') })
  const 乙 = 模块.生成并保存({ 输出文件, 临时记忆库: 假临时库, 长期记忆库: 假长期库, 现在: () => new Date('2026-10-21T02:00:00.000Z') })
  const 盘 = JSON.parse(fs.readFileSync(输出文件, 'utf8'))
  检查('候选单独原子写入指定缓存文件', fs.existsSync(输出文件) && 盘.用途.includes('不参与召回'))
  检查('重复生成保持输入指纹、候选编号和候选数量稳定', 甲.报告.输入指纹 === 乙.报告.输入指纹 && 甲.报告.候选[0].编号 === 乙.报告.候选[0].编号 && 乙.报告.候选数量 === 1)
  检查('输出候选不重复', new Set(盘.候选.map((一) => 一.编号)).size === 盘.候选.length)
  检查('生成候选不会改写原始记忆文件', 哈希(原始文件) === 前)
  检查('报告公开阈值、最小组数、硬边界和截断统计', 盘.规则.相似阈值 === 0.55 && 盘.规则.最小组数 === 3 && 盘.规则.硬边界.length === 4 && 盘.来源统计.截断数量 === 0)
} finally {
  fs.rmSync(临时根, { recursive: true, force: true })
}

let 报错 = false
try { 模块.聚类(同主题, { 相似阈值: 0 }) } catch { 报错 = true }
检查('非法阈值被拒绝', 报错)

console.log(`\n记忆聚类候选：${通过}/${总数} 通过`)
