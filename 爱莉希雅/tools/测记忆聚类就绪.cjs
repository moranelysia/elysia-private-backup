/** 只读聚类就绪门控：用假候选模块和假时钟验证调度，不读取或写入真实记忆。 */
'use strict'

const fs = require('node:fs')
const path = require('node:path')
const 模块 = require('../脑/记忆聚类就绪.cjs')

let 总数 = 0, 通过 = 0
function 检查(说明, 条件) {
  总数++
  if (!条件) throw new Error('✗ ' + 说明)
  通过++
  console.log('✓ ' + 说明)
}

let 当前毫秒 = Date.parse('2026-10-24T01:00:00.000Z')
let 生成次数 = 0
let 候选数 = 0
const 计时器们 = []
const 假候选模块 = {
  生成并保存({ 强制 }) {
    生成次数++
    return {
      好: true, 跳过: 生成次数 > 1 && !强制,
      报告: {
        候选数量: 候选数,
        就绪门控: {
          状态: 候选数 ? '待人工审核' : '等待真实候选',
          可进入候选审核: 候选数 > 0,
          可进入生产闭环: false,
        },
      },
    }
  },
}

const 检查器 = 模块.创建检查器({
  候选模块: 假候选模块,
  现在: () => new Date(当前毫秒),
  防抖毫秒: 100,
  最小间隔毫秒: 1000,
  设定时器: (函数, 毫秒) => {
    const 条 = { 函数, 毫秒, 已取消: false, unref() {} }
    计时器们.push(条)
    return 条
  },
  清定时器: (条) => { 条.已取消 = true },
})

const 首次 = 检查器.检查一次({ 原因: '隔离测试' })
检查('空候选返回等待状态且生产闭环保持关闭', 首次.好 && 首次.报告.就绪门控.状态 === '等待真实候选' && !首次.报告.就绪门控.可进入生产闭环)

const 排队一 = 检查器.排队({ 原因: '变化一' })
const 排队二 = 检查器.排队({ 原因: '变化二' })
检查('连续变化由单实例防抖合并', 排队一.已排队 && 排队二.已排队 && 计时器们[0].已取消 && 检查器.状态().已安排)
检查('最小运行间隔不会被连续变化绕过', 排队二.等待毫秒 >= 1000)

当前毫秒 += 2000
候选数 = 1
计时器们.at(-1).函数()
检查('真实候选出现后只进入待审核状态', 检查器.状态().最近结果.报告.就绪门控.状态 === '待人工审核' && 检查器.状态().最近结果.报告.就绪门控.可进入候选审核)
检查('候选出现仍不会自动开放生产闭环', 检查器.状态().最近结果.报告.就绪门控.可进入生产闭环 === false)

检查器.排队({ 原因: '退出前待执行' })
检查器.取消()
检查('退出时可以取消尚未执行的检查', !检查器.状态().已安排)

const 项目根 = path.resolve(__dirname, '..')
const main源 = fs.readFileSync(path.join(项目根, 'main.js'), 'utf8')
const 对话源 = fs.readFileSync(path.join(项目根, '脑', '对话.cjs'), 'utf8')
const 临时源 = fs.readFileSync(path.join(项目根, '脑', '临时记忆提取.cjs'), 'utf8')
const 整理源 = fs.readFileSync(path.join(项目根, '脑', '记忆整理.cjs'), 'utf8')
检查('启动与三十分钟定期检查已接入主进程', main源.includes("记忆聚类就绪.排队({ 原因: '启动后检查'") && main源.includes("原因: '定期聚类就绪检查'") && main源.includes('30 * 60 * 1000'))
检查('主进程退出会取消聚类检查', main源.includes('记忆聚类就绪.取消()'))
检查('长期记忆与临时记忆变化都会刷新门控', main源.includes("原因: '用户修改长期记忆'") && main源.includes("原因: '用户修改临时记忆'") && 对话源.includes('记忆聚类就绪.排队'))
检查('自主评估与后台合并也会刷新门控', 临时源.includes("原因: '后台临时记忆提取或自主评估'") && 整理源.includes("原因: '后台事实合并后重新评估聚类就绪'"))

console.log(`\n记忆聚类就绪门控：${通过}/${总数} 通过`)
