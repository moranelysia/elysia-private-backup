const 源模型根 = path.join(根, '美术', 'Live2D', '拆分工作', 'SeeThrough-v13-原生头饰', '模型')
const 模型 = JSON.parse(fs.readFileSync(path.join(运行模型根, 'seethrough_blink.model3.json'), 'utf8'))
const 显示信息 = JSON.parse(fs.readFileSync(path.join(运行模型根, 模型.FileReferences.DisplayInfo), 'utf8'))

for (const 相对 of [
  模型.FileReferences.Moc,
  ...模型.FileReferences.Textures,
  模型.FileReferences.Physics,
  模型.FileReferences.DisplayInfo,
]) {
  const 运行文件 = path.join(运行模型根, 相对)
  const 源文件 = path.join(源模型根, 相对)
  assert.ok(fs.existsSync(运行文件), '缺少运行模型资源：' + 相对)
  assert.ok(fs.existsSync(源文件), '缺少 v12 源模型资源：' + 相对)
  const 摘要 = (文件) => crypto.createHash('sha256').update(fs.readFileSync(文件)).digest('hex')
  assert.equal(摘要(运行文件), 摘要(源文件), '运行资源不是正式项目的最新版 v13：' + 相对)
}

