<#
  build-folder-icon.ps1 -- make an Elysia icon on your Desktop

  WHAT IT DOES
    Creates a Desktop shortcut named "Elysia" that starts everything:
    her voice, DSH, the desktop pet, and the tray flower. It uses the
    pink flower icon (icon.ico) that sits next to the project folder.

  WHY THIS FILE IS PURE ASCII (no Chinese anywhere, not even a path)
    Windows PowerShell 5.1 decodes .ps1 files with the system ANSI
    codepage (936/GBK on this machine). A UTF-8 Chinese character would
    be decoded into garbage -- and if it is inside a file PATH, the path
    stops existing and the script fails for a reason nobody can read.
    So: Chinese file names are fine, Chinese inside this file is not.
    The icon itself is generated by Node (tools\make-ico.cjs), which reads
    UTF-8 properly.

  USAGE
    Double-click tools\make-icon.cmd, or run:
      powershell -NoProfile -ExecutionPolicy Bypass -File tools\build-folder-icon.ps1
#>

$ErrorActionPreference = 'Stop'

# tools\ -> project folder -> workspace root (two levels up)
$Here = $PSScriptRoot
$ProjectRoot = Split-Path -Parent $Here
$Workspace = Split-Path -Parent $ProjectRoot

$Icon = Join-Path $ProjectRoot 'desktop-icon.ico'
$Launcher = Join-Path $Workspace 'start-all.cmd'
$Desktop = [Environment]::GetFolderPath('Desktop')
$ShortcutPath = Join-Path $Desktop 'Elysia.lnk'

Write-Host ""
Write-Host "  workspace : $Workspace"
Write-Host "  launcher  : $Launcher"
Write-Host "  icon      : $Icon"
Write-Host ""

if (-not (Test-Path $Launcher)) {
  Write-Host "  [ERROR] start-all.cmd not found. Expected it in the workspace root." -ForegroundColor Red
  exit 1
}

if (-not (Test-Path $Icon)) {
  Write-Host "  [!!] icon.ico is missing -- the shortcut will use a default icon." -ForegroundColor Yellow
  Write-Host "       To rebuild it, run tools\repair-icon.cmd first."
  Write-Host ""
}

$shell = New-Object -ComObject WScript.Shell
$sc = $shell.CreateShortcut($ShortcutPath)
$sc.TargetPath = $Launcher
$sc.WorkingDirectory = $Workspace
$sc.Description = 'Start Elysia: voice, DSH, the desktop pet, and the tray flower'
$sc.WindowStyle = 1
if (Test-Path $Icon) { $sc.IconLocation = "$Icon,0" }

$saved = $false
try {
  $sc.Save()
  $saved = Test-Path $ShortcutPath
} catch {
  $saved = $false
  Write-Host "  [FAIL] Windows would not let me write to the Desktop." -ForegroundColor Red
  Write-Host "         $($_.Exception.Message)"
  Write-Host ""
  Write-Host "         Easiest fix: a shortcut is already sitting in the project"
  Write-Host "         folder (its name is the Chinese word for Elysia). Just drag"
  Write-Host "         that one onto your Desktop."
}

Write-Host ""
if ($saved) {
  Write-Host "  [OK] Desktop icon created:" -ForegroundColor Green
  Write-Host "       $ShortcutPath"
  Write-Host ""
  Write-Host "  Double-click it to wake her up. If you do not see it, click once"
  Write-Host "  on the Desktop and press F5."
} else {
  Write-Host "  [FAIL] No shortcut was created -- see the message above." -ForegroundColor Red
}
Write-Host ""
