/** 自主重要性评估：全部使用隔离目录与假模型，不读取或修改真实记忆。 */
'use strict'

const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const 根 = fs.mkdtempSync(path.join(os.tmpdir(), 'elysia-memory-auto-'))
process.env.ELYSIA_DATA_DIR = path.join(根, '记忆')
process.env.ELYSIA_CACHE_DIR = path.join(根, '缓存')

let 数 = 0
function 检查(说明, 条件) { if (!条件) throw new Error('✗ ' + 说明); 数++; console.log('✓ ' + 说明) }
function 回应(候选) {
  return new Response(JSON.stringify({ choices: [{ message: { content: JSON.stringify({ 候选 }) } }] }), { status: 200 })
}

async function main() {
  const 项目 = path.resolve(__dirname, '..')
  const 临时模块 = require(path.join(项目, '脑', '临时记忆.cjs'))
  const 长期库 = require(path.join(项目, '脑', '记忆.cjs'))
  const 提取模块 = require(path.join(项目, '脑', '临时记忆提取.cjs'))
  const 评估模块 = require(path.join(项目, '脑', '临时记忆自主评估.cjs'))
  let id = 0
  const 临时库 = 临时模块.创建临时记忆库({ 数据目录: path.join(根, '短期'), 新编号: () => 'auto-' + (++id) })
  const 提取器 = 提取模块.创建提取器({ 临时记忆库: 临时库, 长期记忆库: 长期库 })
  const 公共 = { 钥匙: 'fake', 地址: 'https://example.invalid', 她的回复: '知道了' }

  const 普通 = await 提取器.提取一次({ ...公共, 对话: 'dialog-ledger', 消息时间: '2026-10-22T01:00:00.000Z', 用户原话: '我喜欢蓝色', fetch函数: async () => 回应([{
    类别: '候选偏好', 记忆类型: 'semantic', 内容: '喜欢蓝色', 依据原文: '喜欢蓝色',
  }]) })
  检查('普通单次偏好仍保持待确认', 普通.自主处理数 === 0 && 临时库.取一条('auto-1').确认状态 === '待确认')
  const 普通账本 = 临时库.取一条('auto-1').评估账本
  检查('低分评估也保存逐字依据和来源', 普通账本 && 普通账本.当前分数 < 70 && 普通账本.提及次数 === 1 && 普通账本.证据[0].依据原文 === '喜欢蓝色' && 普通账本.证据[0].对话 === 'dialog-ledger')
  const 重开库 = 临时模块.创建临时记忆库({ 数据目录: path.join(根, '短期') })
  检查('重启后低分证据账本仍可读取', 重开库.取一条('auto-1').评估账本.证据[0].依据原文 === '喜欢蓝色')
  await 提取器.提取一次({ ...公共, 对话: 'dialog-ledger', 消息时间: '2026-10-22T01:00:00.000Z', 用户原话: '我喜欢蓝色', fetch函数: async () => 回应([]) })
  检查('重复消费同一条消息不会虚增提及次数', 临时库.取一条('auto-1').评估账本.提及次数 === 1)
  const 敏感评估 = 评估模块.评估({ 候选: { 内容: '喜欢蓝色', 记忆类型: 'semantic' }, 对话轮次: [{ 用户原话: '我喜欢蓝色，token=绝不能进入账本' }] })
  检查('含密钥或内部标记的原话不会进入证据账本', 敏感评估.新增提及次数 === 0)

  const 重复 = await 提取器.提取批次({ ...公共, 对话轮次: [
    { 用户原话: '我喜欢草莓蛋糕', 她的回复: '嗯' },
    { 用户原话: '再说一次，我喜欢草莓蛋糕', 她的回复: '记下了' },
  ], fetch函数: async () => 回应([{
    依据轮次: 1, 类别: '候选偏好', 记忆类型: 'semantic', 内容: '喜欢草莓蛋糕', 依据原文: '喜欢草莓蛋糕',
  }]) })
  检查('同批重复提及会自主晋升', 重复.自主处理数 === 1 && 临时库.取一条('auto-2').生命周期 === '已晋升')
  检查('重复偏好进入事实层并保留评分', 长期库.全部长期记忆().some((一) => 一.内容 === '喜欢草莓蛋糕' && 一.类别 === '事实' && 一.自主评估.分数 >= 70))

  const 情感 = await 提取器.提取一次({ ...公共, 用户原话: '我特别讨厌别人迟到', fetch函数: async () => 回应([{
    类别: '候选偏好', 记忆类型: 'semantic', 内容: '特别讨厌别人迟到', 依据原文: '特别讨厌别人迟到',
  }]) })
  检查('强烈且稳定的情感偏好可自主晋升', 情感.自主处理数 === 1 && 长期库.全部长期记忆().some((一) => 一.内容 === '特别讨厌别人迟到'))

  const 明说 = await 提取器.提取一次({ ...公共, 用户原话: '请记住我明年想去看极光', fetch函数: async () => 回应([{
    类别: '近期计划', 记忆类型: 'episodic', 内容: '明年想去看极光', 依据原文: '请记住我明年想去看极光',
  }]) })
  检查('明确要求记住可自主晋升', 明说.自主处理数 === 1 && 长期库.全部长期记忆().some((一) => 一.内容 === '明年想去看极光' && 一.类别 === '经历'))

  const 待重复 = 临时库.新增('候选偏好', '喜欢安静的音乐', { 提取方式: '模型提取', 记忆类型: 'semantic' })
  const 后续 = await 提取器.提取一次({ ...公共, 用户原话: '我还是喜欢安静的音乐', fetch函数: async () => 回应([]) })
  检查('模型不重复返回候选时，后续再次提及仍能推动旧候选晋升', 后续.自主处理数 === 1 && 临时库.取一条(待重复.编号).生命周期 === '已晋升')

  const 旧条 = 临时库.新增('候选偏好', '喜欢甜咖啡', { 提取方式: '手动', 记忆类型: 'semantic' })
  const 冲突 = await 提取器.提取一次({ ...公共, 用户原话: '更正一下，我现在特别讨厌甜咖啡', fetch函数: async () => 回应([{
    类别: '候选偏好', 记忆类型: 'semantic', 内容: '特别讨厌甜咖啡', 依据原文: '更正一下，我现在特别讨厌甜咖啡', 替代编号: 旧条.编号,
  }]) })
  const 冲突条 = 冲突.新增[0] && 临时库.取一条(冲突.新增[0].编号)
  检查('涉及替代旧记忆的强烈候选仍不自动决定', 冲突.自主处理数 === 0 && 冲突条.确认状态 === '待确认' && 冲突条.关系.状态 === '待处理')

  const 低分 = 评估模块.评估({ 候选: { 内容: '偶尔散步', 记忆类型: 'episodic', 关系: { 状态: '当前' } }, 对话轮次: [{ 用户原话: '偶尔散步' }] })
  检查('评估结果包含分数、依据和目标层且低分不自主', !低分.可自主 && 低分.去向 === '经历' && Number.isInteger(低分.分数))

  let 复活时刻 = new Date('2026-10-01T00:00:00.000Z')
  let 复活编号 = 0
  const 复活库 = 临时模块.创建临时记忆库({
    数据目录: path.join(根, '复活短期'), 现在: () => new Date(复活时刻), 新编号: () => 'revive-' + (++复活编号),
  })
  const 复活长期 = []
  const 复活长期库 = {
    全部长期记忆: () => [...复活长期],
    记一条: (类别, 内容, 来源, 上下文) => {
      const 条 = { 编号: 'revive-long-' + (复活长期.length + 1), 类别, 内容, 来源, 临时记忆: 上下文.临时记忆, 自主评估: 上下文.自主评估 }
      复活长期.push(条); return 条
    },
  }
  const 复活提取器 = 提取模块.创建提取器({ 临时记忆库: 复活库, 长期记忆库: 复活长期库 })
  await 复活提取器.提取一次({ ...公共, 对话: 'dialog-old', 消息时间: '2026-10-01T00:00:00.000Z', 用户原话: '我喜欢收集明信片', fetch函数: async () => 回应([{
    类别: '候选偏好', 记忆类型: 'semantic', 内容: '喜欢收集明信片', 依据原文: '喜欢收集明信片',
  }]) })
  复活时刻 = new Date('2026-10-09T00:00:00.000Z')
  复活库.归档到期()
  检查('低分候选到期后只归档且保留评估账本', 复活库.取一条('revive-1').生命周期 === '已归档' && 复活库.取一条('revive-1').评估账本.提及次数 === 1)
  const 复活结果 = await 复活提取器.提取一次({ ...公共, 对话: 'dialog-new', 消息时间: '2026-10-09T00:00:00.000Z', 用户原话: '我还是喜欢收集明信片', fetch函数: async () => 回应([{
    类别: '候选偏好', 记忆类型: 'semantic', 内容: '喜欢收集明信片', 依据原文: '喜欢收集明信片',
  }]) })
  const 复活条 = 复活库.取一条('revive-1')
  检查('再次提及时复用原编号并自主晋升且不新建副本', 复活结果.复活数 === 1 && 复活结果.新增数 === 0 && 复活结果.自主处理数 === 1 && 复活条.生命周期 === '已晋升' && 复活编号 === 1 && 复活长期.length === 1)
  检查('复活后保留跨会话证据、时间和历史最高分', 复活条.评估账本.提及次数 === 2 && 复活条.评估账本.证据.length === 2 && 复活条.评估账本.证据[1].对话 === 'dialog-new' && 复活条.评估账本.历史最高分 >= 70)

  const 续做库 = 临时模块.创建临时记忆库({ 数据目录: path.join(根, '续做短期'), 新编号: () => 'retry-1' })
  const 长期记录 = []
  let 首次失败 = true
  const 故障长期库 = {
    全部长期记忆: () => [...长期记录],
    记一条: (类别, 内容, 来源, 上下文) => {
      if (首次失败) { 首次失败 = false; return null }
      const 条 = { 编号: 'long-retry', 类别, 内容, 来源, 临时记忆: 上下文.临时记忆 }
      长期记录.push(条); return 条
    },
  }
  const 续做提取器 = 提取模块.创建提取器({ 临时记忆库: 续做库, 长期记忆库: 故障长期库 })
  const 首次 = await 续做提取器.提取一次({ ...公共, 用户原话: '请记住我喜欢晨跑', fetch函数: async () => 回应([{
    类别: '候选偏好', 记忆类型: 'semantic', 内容: '喜欢晨跑', 依据原文: '请记住我喜欢晨跑',
  }]) })
  检查('长期写入失败时保留已确认评估而不伪报完成', 首次.自主处理数 === 0 && 续做库.取一条('retry-1').确认状态 === '已确认' && 续做库.取一条('retry-1').生命周期 === '有效')
  const 重试 = await 续做提取器.提取一次({ ...公共, 用户原话: '普通后续', fetch函数: async () => 回应([]) })
  检查('后续批次会幂等续做中断的自主晋升', 重试.自主处理数 === 1 && 续做库.取一条('retry-1').生命周期 === '已晋升' && 长期记录.length === 1)

  console.log(`\n记忆自主评估：${数}/${数} 通过`)
}

main().catch((错误) => { console.error(错误.stack || 错误.message); process.exitCode = 1 }).finally(() => {
  try { fs.rmSync(根, { recursive: true, force: true }) } catch {}
})
