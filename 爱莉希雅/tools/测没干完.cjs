/**
 * 测没干完.cjs —— 她干活干到一半断了，那半截还捡得回来吗
 *
 * 【为什么这个值得单写一个测试】
 *   这个功能**平时永远不跑**。只有程序崩了、或者他把窗口关了的时候才用得上。
 *   也就是说：如果它写错了，你不会在日常使用中发现 ——
 *   你会在**唯一需要它的那一次**发现，而那时候活儿已经丢了。
 *   所以它必须有一组专门的测试，包括"真崩一次"。
 *
 * 【怎么造一次真的崩】
 *   起一个子进程，让它在纸上写完"我要写文件了"之后直接 process.exit(1)。
 *   在文件系统看来，这跟断电、跟 Electron 崩掉长得一模一样 ——
 *   纸还在，没人撕它。然后看主进程能不能把它捡回来。
 *   （这比在同一个进程里假装"我不调干完了()"要真：那样测的是我自己记不记得，
 *     不是崩溃这个事实。）
 *
 * 用法: node tools\测没干完.cjs
 */
'use strict'

const fs = require('node:fs')
const path = require('node:path')
const { spawnSync } = require('node:child_process')

const 项目根 = path.resolve(__dirname, '..')
const 测试目录 = path.join(项目根, '.cache', '_测没干完')

// 【必须在 require 没干完.cjs 之前设】—— 不然测试会往真的 .cache 里丢假纸条
process.env.ELYSIA_纸条目录 = 测试目录

/** 拿一个全新的模块（模块里有 手上这份 / 这次是我铺的 这些状态，测试之间必须隔开） */
function 新的() {
  const 路径 = require.resolve('../脑/没干完.cjs')
  delete require.cache[路径]
  return require(路径)
}

let 过了 = 0
let 总数 = 0
function 检查(说明, 条件, 细节 = '') {
  总数++
  if (条件) {
    过了++
    console.log(`  ✓ ${说明}`)
  } else {
    console.log(`  ✗ ${说明}${细节 ? '   → ' + 细节 : ''}`)
  }
}

function 洗牌() {
  fs.rmSync(测试目录, { recursive: true, force: true })
  fs.mkdirSync(测试目录, { recursive: true })
}

function 主() {
  fs.rmSync(测试目录, { recursive: true, force: true })
  fs.mkdirSync(测试目录, { recursive: true })

  console.log('')
  console.log('  ════════════════════════════════════════════')
  console.log('   干活干到一半断了 —— 那半截还捡得回来吗')
  console.log('  ════════════════════════════════════════════')
  console.log('')

  // -------------------------------------------------------------
  console.log('  ── 一、顺顺利利干完一趟 ──')

  洗牌()
  {
    const M = 新的()
    M.盯住('甲')
    M.开始({ 他说的: '改一下那个 C 程序' })
    检查('开始干活就铺好了纸', M.有草稿吗('甲'))

    M.要动手了({ 名字: '读', 参数: 'main.c', 危险度: 'safe' })
    检查('纯读的事不记（崩了重读一遍就行）', M.手上有吗().不知道的.length === 0)

    M.要动手了({ 名字: '写', 参数: 'main.c', 危险度: 'write' })
    检查('要写文件的时候，先记一笔"结果不知道"', M.手上有吗().不知道的.length === 1)

    M.动完了({ 名字: '写', 参数: 'main.c', 危险度: 'write', 好: true, 说明: '写好了' })
    const 纸 = M.手上有吗()
    检查('做完了就挪到"确定"那一栏', 纸.不知道的.length === 0 && 纸.确定的.length === 1)

    M.干完了()
    检查('正常收工 → 纸撕了', !M.有草稿吗('甲'))
    检查('也没留下便条', !M.有便条吗('甲'))
  }

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 二、★ 正写文件的时候断了（这个功能存在的全部理由）──')

  洗牌()
  let 便条 = null
  {
    const M = 新的()
    M.盯住('乙')
    M.开始({ 他说的: '把那个程序改成能算平方的' })
    M.要动手了({ 名字: '读', 参数: 'main.c', 危险度: 'safe' })
    M.动完了({ 名字: '读', 参数: 'main.c', 危险度: 'safe', 好: true, 说明: '' })
    M.要动手了({ 名字: '写', 参数: 'main.c', 危险度: 'write' })
    M.动完了({ 名字: '写', 参数: 'main.c', 危险度: 'write', 好: true, 说明: '写好了' })
    M.要动手了({ 名字: '跑', 参数: 'gcc main.c -o guess.exe', 危险度: 'shell' })

    // ← 就在这儿断了。没有 动完了，没有 干完了。
    检查('草稿还躺在盘上（这就是崩溃现场）', M.有草稿吗('乙'))

    const N = 新的() // 重启
    便条 = N.认领('乙')
    检查('重启之后认得出来', !!便条)
    检查('  还知道他要的是什么', !!(便条 && /算平方/.test(便条.他说的)))
    检查('  "写 main.c"记成确定做完了', !!(便条 && 便条.确定的.some((x) => x.名字 === '写')))
    检查('  ★"跑 gcc"记成结果不知道', !!(便条 && 便条.不知道的.some((x) => x.名字 === '跑')))
    检查(
      '  纯读的那条两边都不进（重读一遍不花钱）',
      !!(便条 && !便条.确定的.concat(便条.不知道的).some((x) => x.名字 === '读')),
    )
  }

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 三、★ 给她看的那段话 ──')

  {
    const N = 新的()
    const 文字 = N.变成便条(便条)
    检查('开头就说明白了是上次没干完的', /上次没干完的活儿/.test(文字))
    检查('  说出了他要她做的是什么', /算平方/.test(文字))
    检查('  ★写死了"不许自己重做"', /不许自己重做/.test(文字))
    检查('  ★点明了"结果不知道"', /结果不知道/.test(文字))
    检查('  要她先问问他', /先问问他/.test(文字))
    检查('  把那件不确定的事列出来了', /gcc/.test(文字))
    检查('  交代了别把这段话抄出来', /别把这段话抄/.test(文字))
    检查('  说了这是程序写的、不是他说的', /不是他说的/.test(文字))
  }

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 四、她看过之后就不念第二遍 ──')

  {
    const N = 新的()
    N.看过了('乙')
    const P = 新的()
    检查('再看就没有了', P.认领('乙') === null)
    检查('  便条文件也删干净了', !P.有便条吗('乙'))
  }

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 五、啥也没干成的那种，不生成便条 ──')

  洗牌()
  {
    const M = 新的()
    M.盯住('丙')
    M.开始({ 他说的: '随便问一句' })
    // 一件危险的事都没动过就断了
    const N = 新的()
    检查('没动过手 → 不生成便条', N.认领('丙') === null)
    检查('  顺手把空壳收掉了', !N.有草稿吗('丙') && !N.有便条吗('丙'))
  }

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 六、按对话分段：别串台 ──')

  洗牌()
  {
    const M = 新的()
    M.盯住('甲')
    M.开始({ 他说的: '甲这段的事' })
    M.要动手了({ 名字: '写', 参数: 'a.txt', 危险度: 'write' })

    const N = 新的()
    检查('乙段问不到甲段的便条', N.认领('乙') === null)
    检查('  甲段问得到', !!N.认领('甲'))
  }

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 七、★ 收工的时候不许顺手撕了别人的纸 ──')

  洗牌()
  {
    const M = 新的()
    // 甲段断在半路
    M.盯住('甲')
    M.开始({ 他说的: '甲的事' })
    M.要动手了({ 名字: '写', 参数: 'a.txt', 危险度: 'write' })

    // 他跑到乙段干了个新活，顺顺利利干完了
    M.盯住('乙')
    M.开始({ 他说的: '乙的事' })
    检查('乙这段正常收工，撕的是乙的纸', M.干完了() === true)
    检查('  ★甲的纸还在（没被顺手撕掉）', M.有草稿吗('甲'))
    检查('  乙的纸撕了', !M.有草稿吗('乙'))

    // 没铺过纸就调收工 —— 什么都不该动
    const N = 新的()
    检查('这一轮压根没铺过纸的话，收工是无动作', N.干完了() === false)
    检查('  甲那张照样还在', N.有草稿吗('甲'))
  }

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 八、坏掉的纸（半截的 JSON / 过期的）──')

  洗牌()
  {
    const M = 新的()
    // 写到一半断电，留下半截 JSON
    fs.mkdirSync(测试目录, { recursive: true })
    fs.writeFileSync(M.干活路径('丁'), '{ "他说的": "半截', 'utf8')

    const N = 新的()
    检查('半截的读不出来 → 当没有', N.认领('丁') === null)
    检查('  并且清掉（不然每次开机都报一次错）', !N.有草稿吗('丁'))

    // 四天前断的活儿
    const 老的 = {
      对话: '戊',
      他说的: '四天前那件事',
      开始: '2020-01-01 10:00:00',
      断在: '2020-01-01 10:00:05',
      确定的: [],
      不知道的: [{ 名字: '写', 参数: 'old.txt', 什么时候: '2020-01-01 10:00:05' }],
    }
    fs.writeFileSync(N.干活路径('戊'), JSON.stringify(老的), 'utf8')

    const P = 新的()
    检查('三天前断的活儿不再提（他早忘了）', P.认领('戊') === null)
    检查('  也清掉了', !P.有便条吗('戊'))
  }

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 九、★ 真崩一次（起个子进程，写完纸就 process.exit）──')

  洗牌()
  {
    const 崩脚本 = path.join(测试目录, '崩给你看.cjs')
    fs.writeFileSync(
      崩脚本,
      [
        '// 这个文件是测试当场写出来的，跑完就跟着测试目录一起删掉',
        `process.env.ELYSIA_纸条目录 = ${JSON.stringify(测试目录)}`,
        `const 没干完 = require(${JSON.stringify(path.join(项目根, '脑', '没干完.cjs'))})`,
        "没干完.盯住('崩')",
        "没干完.开始({ 他说的: '崩给你看的那件事' })",
        "没干完.要动手了({ 名字: '写', 参数: '崩.txt', 危险度: 'write' })",
        "process.stdout.write('我把纸写好了，现在假装断电\\n')",
        'process.exit(1)',
      ].join('\n'),
      'utf8',
    )

    // 【stdio 全给 ignore】不开管道 —— 沙箱不让进程开命名管道，
    // 用管道接子进程输出会一律 EPERM，报出来的错还特别容易让人以为
    // 是"这个功能坏了"。见 tools\试命令.cjs 开头那段量测记录。
    const 果 = spawnSync(process.execPath, [崩脚本], { stdio: ['ignore', 'ignore', 'ignore'] })
    if (果.error) {
      console.log('  ⚠ 这个环境不让起子进程（' + 果.error.code + '）—— 这一组跳过。')
      console.log('    在你自己的终端里跑这个脚本就能测到。')
    } else {
      检查('子进程真的死透了（退出码 1）', 果.status === 1, String(果.status))

      const N = 新的()
      const 捡回来 = N.认领('崩')
      检查('★ 从一个真崩掉的进程手里把纸条捡回来了', !!捡回来)
      检查('  知道它正要写哪个文件', !!(捡回来 && 捡回来.不知道的.some((x) => x.参数 === '崩.txt')))
      检查('  知道那件事是什么', !!(捡回来 && /崩给你看/.test(捡回来.他说的)))
      const 文字 = N.变成便条(捡回来)
      检查('  生成的便条里带着"不许自己重做"', /不许自己重做/.test(文字))
    }
  }

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 十、收尾 ──')
  fs.rmSync(测试目录, { recursive: true, force: true })
  检查('测试目录擦掉了（没在 .cache 里留垃圾）', !fs.existsSync(测试目录))

  console.log('')
  console.log('  ════════════════════════════════════════════')
  console.log(`   ${过了} / ${总数}`)
  console.log('  ════════════════════════════════════════════')
  console.log('')
  process.exit(过了 === 总数 ? 0 : 1)
}

