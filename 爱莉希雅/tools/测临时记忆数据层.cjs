  检查('逐层删除替代者会依次恢复旧版本', 关系库.删除(更新条.编号) && 关系库.取一条(新条.编号).关系.状态 === '当前' && 关系库.删除(新条.编号) && 关系库.取一条(旧条.编号).关系.状态 === '当前')
