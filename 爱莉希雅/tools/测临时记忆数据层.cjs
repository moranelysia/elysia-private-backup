  检查('人工决定会原子确认新条并替代旧条', 替代决定.好 && 关系库.取一条(新条.编号).确认状态 === '已确认' && 关系库.取一条(旧条.编号).关系.状态 === '已被替代')
  检查('新旧双方保存可追溯稳定编号', 关系库.取一条(新条.编号).关系.替代编号[0] === 旧条.编号 && 关系库.取一条(旧条.编号).关系.由编号 === 新条.编号)
  检查('已被替代旧版本不能直接修改或晋升', !关系库.修改(旧条.编号, { 内容: '不该改' }).好 && !关系库.提议晋升(旧条.编号, '事实').好)
  检查('查询能读到规范化关系且不改写旧格式', 关系库.查询({ 生命周期: '有效' }).列表.some((一) => 一.编号 === 旧条.编号 && 一.关系.状态 === '已被替代'))
