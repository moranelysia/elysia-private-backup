  关系库.提议替代(并存新条.编号, 旧条.编号)
  const 并存决定 = 关系库.决定替代(并存新条.编号, '两条并存')
  检查('人工可选择两条并存', 并存决定.好 && 关系库.取一条(并存新条.编号).关系.状态 === '当前' && 关系库.取一条(旧条.编号).关系.状态 === '当前')
  const 过时候选 = 关系库.新增('候选偏好', '最近喜欢喝乌龙茶', { 提取方式: '模型提取' })
  关系库.提议替代(过时候选.编号, 旧条.编号)
  关系库.修改(旧条.编号, { 内容: '最近喜欢喝手冲咖啡' })
  检查('旧条在提议后变化会拒绝过时决定', !关系库.决定替代(过时候选.编号, '替代旧条').好 && 关系库.取一条(旧条.编号).关系.状态 === '当前')

  const 坏文件 = path.join(临时根, '坏库.json')
