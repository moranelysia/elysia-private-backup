  const 手动 = 库.新增('近期计划', '  周五前完成高数作业  ', {
    来源对话: 'dialog-1', 来源消息时间: '2026-10-14 10:00', 标签: ['学习', '学习'],
  })
  检查('手动新增会清理正文并默认确认', 手动.内容 === '周五前完成高数作业' && 手动.确认状态 === '已确认')
  检查('新记录默认使用普通重要性', 手动.重要性 === 1)
  检查('计划默认归为事件记忆并保存完整元数据', 手动.记忆类型 === 'episodic' && handMeta(手动))
  检查('保存来源和去重后的标签', 手动.来源.对话 === 'dialog-1' && 手动.标签.length === 1)
  检查('近期计划默认保留五天以减少临时层堆积', handDays(手动) === 5)
  检查('写入使用版本化对象而非裸数组', JSON.parse(原文(文件)).版本 === 1 && Array.isArray(JSON.parse(原文(文件)).记录))
  检查('原子写入没有遗留临时文件', !fs.existsSync(文件 + '.tmp'))

  const 模型候选 = 库.新增('候选偏好', '可能喜欢轻音乐', {
    提取方式: '模型提取', 来源对话: 'dialog-2', 保留天数: 2, 标签: ['音乐'],
    记忆类型: 'semantic', 元数据: { backstory: '用户提到音乐偏好', person: '用户本人', relationship: '本人' },
  })
  检查('非手动提取默认待确认', 模型候选.确认状态 === '待确认')
  检查('显式记忆类型和元数据原样保存', 模型候选.记忆类型 === 'semantic' && 模型候选.元数据.backstory === '用户提到音乐偏好')
  const 取到 = 库.取一条(模型候选.编号)
  取到.内容 = '外部乱改'
  检查('按编号读取返回副本且不会绕过写入口', 库.取一条(模型候选.编号).内容 === '可能喜欢轻音乐')
  检查('可自定义一到三十天保留期', handDays(模型候选) === 2)
  检查('模型提取不能伪装成已确认', 会抛错(() => 库.新增('近期状态', '状态', { 提取方式: '模型提取', 确认状态: '已确认' })))
  检查('拒绝未知分类', 会抛错(() => 库.新增('随便一类', '内容')))
  检查('拒绝空内容和超长内容', 会抛错(() => 库.新增('近期事件', '  ')) && 会抛错(() => 库.新增('近期事件', 'a'.repeat(4001))))
  检查('拒绝越界保留期', 会抛错(() => 库.新增('近期事件', '内容', { 保留天数: 31 })))
  检查('拒绝越界或小数重要性', 会抛错(() => 库.新增('近期事件', '内容', { 重要性: 4 })) && 会抛错(() => 库.新增('近期事件', '内容', { 重要性: 1.5 })))
  检查('拒绝未知记忆类型和超长元数据', 会抛错(() => 库.新增('近期事件', '内容', { 记忆类型: 'random' })) && 会抛错(() => 库.新增('近期事件', '内容', { 元数据: { backstory: 'x'.repeat(241) } })))

  检查('默认查询只返回有效记录', 库.查询().总数 === 2)
  检查('可按分类查询', 库.查询({ 类别: '候选偏好' }).列表[0].编号 === 模型候选.编号)
  检查('可按记忆类型筛选并搜索人物元数据', 库.查询({ 记忆类型: 'semantic' }).总数 === 1 && 库.查询({ 搜索: '用户本人' }).总数 === 2)
  检查('可搜索正文、标签和来源对话', 库.查询({ 搜索: '高数' }).总数 === 1 && 库.查询({ 搜索: '音乐' }).总数 === 1 && 库.查询({ 搜索: 'dialog-2' }).总数 === 1)
  检查('查询限量会报告截断', 库.查询({ 限量: 1 }).列表.length === 1 && 库.查询({ 限量: 1 }).截断)

  当前 = new Date('2026-10-14T03:00:00.000Z')
  const 改果 = 库.修改(手动.编号, { 内容: '周六前完成高数作业', 类别: '未完话题', 重要性: 3, 标签: ['高数', '作业'] })
  检查('能按稳定编号修改正文、分类、重要性和标签', 改果.好 && 改果.条.内容.includes('周六') && 改果.条.类别 === '未完话题' && 改果.条.重要性 === 3 && 改果.条.标签.length === 2)
  检查('修改保留创建时间并更新修改时间', 改果.条.创建于 === 手动.创建于 && 改果.条.更新于 === 当前.toISOString())
  const 修改后原文 = 原文(文件)
  const 没变化 = 库.修改(手动.编号, { 内容: '周六前完成高数作业' })
  检查('相同内容不重写文件', 没变化.好 && 没变化.没变化 && 原文(文件) === 修改后原文)
  检查('不存在编号修改明确失败', !库.修改('missing', { 内容: 'x' }).好)
  检查('修改入口拒绝非法重要性', 会抛错(() => 库.修改(手动.编号, { 重要性: -1 })))

  const 未确认提议 = 库.提议晋升(模型候选.编号, '事实')
  检查('待确认内容不能提议晋升', !未确认提议.好)
  const 确认 = 库.修改(模型候选.编号, { 确认状态: '已确认' })
  检查('可以人工确认模型候选', 确认.好 && 确认.条.确认状态 === '已确认')
  const 提议 = 库.提议晋升(模型候选.编号, '事实')
  检查('晋升先进入待确认而不直接写长期库', 提议.好 && 提议.条.晋升.状态 === '待确认' && 提议.条.生命周期 === '有效')
  检查('未批准不能完成晋升', !库.完成晋升(模型候选.编号, 'fact-1').好)
  const 批准 = 库.决定晋升(模型候选.编号, true)
  检查('晋升决定被单独记录', 批准.好 && 批准.条.晋升.状态 === '已批准')
  const 完成 = 库.完成晋升(模型候选.编号, 'fact-1')
  检查('完成晋升后保留目标编号并退出有效层', 完成.好 && 完成.条.生命周期 === '已晋升' && 完成.条.晋升.目标编号 === 'fact-1')
  检查('默认查询不返回已晋升记录', 库.查询().总数 === 1)
  检查('可显式查询已晋升记录', 库.查询({ 生命周期: '已晋升' }).总数 === 1)

  当前 = new Date('2026-10-22T02:00:00.000Z')
  const 归档 = 库.归档到期()
  检查('到期记录会归档而不是删除', 归档.数量 === 1 && 库.查询({ 生命周期: '已归档' }).总数 === 1)
  const 归档条 = 库.查询({ 生命周期: '已归档' }).列表[0]
  检查('归档保存时间和原因', 归档条.归档于 === 当前.toISOString() && 归档条.归档原因 === '到期')
  检查('重复归档不会重复修改', 库.归档到期().数量 === 0)
  检查('归档记录不能修改或提议晋升', !库.修改(归档条.编号, { 内容: '不该改' }).好 && !库.提议晋升(归档条.编号, '事实').好)
  const 恢复 = 库.恢复(归档条.编号, 5)
  检查('归档记录可以恢复并获得新到期日', 恢复.好 && 恢复.条.生命周期 === '有效' && handDaysFrom(恢复.条, 当前) === 5)
  检查('恢复会清掉旧归档标记', !('归档于' in 恢复.条) && !('归档原因' in 恢复.条))

  库 = 建库()
  检查('重新创建实例后仍能读到记录', 库.查询({ 包括归档: true }).总数 === 1)
  检查('跨重启后已晋升记录仍可查询', 库.查询({ 生命周期: '已晋升' }).总数 === 1)
  检查('能精准删除且不误伤其他记录', 库.删除(恢复.条.编号) && 库.查询({ 包括归档: true }).总数 === 0 && 库.查询({ 生命周期: '已晋升' }).总数 === 1)
  检查('重复删除返回失败', 库.删除(恢复.条.编号) === false)

  const 关系文件 = path.join(临时根, '关系库.json')
  let 关系序号 = 0
  const 关系库 = 模块.创建临时记忆库({ 文件: 关系文件, 现在: () => new Date(当前), 新编号: () => 'rel-' + (++关系序号) })
  const 旧条 = 关系库.新增('候选偏好', '最近喜欢喝咖啡')
  const 新条 = 关系库.新增('候选偏好', '最近改成喜欢喝红茶', { 提取方式: '模型提取' })
  const 提议替代 = 关系库.提议替代(新条.编号, 旧条.编号)
  检查('模型只能提出待处理替代关系', 提议替代.好 && 提议替代.条.关系.状态 === '待处理' && 提议替代.条.确认状态 === '待确认')
  检查('提议阶段旧记忆仍保持当前', 关系库.取一条(旧条.编号).关系.状态 === '当前')
  检查('待处理关系不能绕过人工决定直接确认', !关系库.修改(新条.编号, { 确认状态: '已确认' }).好)
  检查('不能跨分类建立自动替代', !关系库.提议替代(关系库.新增('近期状态', '最近精神不错', { 提取方式: '模型提取' }).编号, 旧条.编号).好)
