function handDays(条) {
  return Math.round((new Date(条.到期于) - new Date(条.创建于)) / 86400000)
}
function handDaysFrom(条, 从) {
  return Math.round((new Date(条.到期于) - new Date(从)) / 86400000)
}
function handMeta(条) {
  return !!(条 && 条.元数据 && 条.元数据.backstory && 条.元数据.person && 条.元数据.relationship)
}


