'use strict'
const assert = require('node:assert/strict')
const { 查询要求, 检查门槛, 补搜查询, 合并结果 } = require('../脑/搜索验证.cjs')
const { 查 } = require('../脑/动手.cjs')

let 数 = 0
function 测(名字, 条件) { assert.ok(条件, 名字); 数++; console.log('✓ ' + 名字) }

测('普通知识查询不增加双来源要求', !查询要求('C语言指针原理').需要加强)
测('今天和最新触发高时效要求', 查询要求('天津今天天气').高时效 && 查询要求('Node.js 最新版本').高时效)
测('医疗法律金融触发高影响要求', ['这种药副作用', '合同是否违法', '股票投资建议'].every((一) => 查询要求(一).高影响))
测('高时效要求两个来源和至少一条日期', 查询要求('最新版本').最少来源数 === 2 && 查询要求('最新版本').需要日期)
测('同一来源且无日期判材料不足', !检查门槛('最新版本', { 不同来源数: 1, 有日期数: 0 }).通过)
测('不足原因分别列出来源和日期', 检查门槛('最新版本', { 不同来源数: 1, 有日期数: 0 }).缺少.length === 2)
测('两个来源加日期达到最低门槛', 检查门槛('最新版本', { 不同来源数: 2, 有日期数: 1 }).通过)
测('高影响非时效查询仍要两个来源', !检查门槛('药物副作用', { 不同来源数: 1, 有日期数: 0 }).通过)
测('普通查询一个来源即可作为待核验材料', 检查门槛('C语言指针原理', { 不同来源数: 1, 有日期数: 0 }).通过)
测('补搜词要求官方或原始来源', 补搜查询('最新版本').includes('官方来源') && 补搜查询('药物副作用').includes('原始来源'))
测('补搜查询不会超过搜索入口上限', 补搜查询('甲'.repeat(220)).length <= 220)
const 合并 = 合并结果([{ 链接: 'https://a.test/1' }], [{ 链接: 'https://a.test/1' }, { 链接: 'https://b.test/2' }])
测('合并补搜结果时按链接去重', 合并.length === 2)

const 条 = (标题, 链接, 摘要, 日期 = '') => ({ title: 标题, link: 链接, snippet: 摘要, date: 日期 })
const 回应 = (结果) => new Response(JSON.stringify({ organic_results: 结果, search_metadata: { status: 'Success' } }), { headers: { 'content-type': 'application/json' } })

async function 集成() {
  let 次 = 0
  const 恢复 = await 查('Node.js 最新版本', {
    钥匙: 'serp-test',
    fetch函数: async () => 回应(++次 === 1
      ? [条('Node.js', 'https://nodejs.org/a', 'v24')]
      : [条('Release note', 'https://example.org/b', 'v24 released', '2026-10-15')]),
  })
  测('高时效材料不足时只补搜一次', 次 === 2 && 恢复.已重试)
  测('补搜取得第二来源和日期后达到门槛', 恢复.材料门槛.通过 && 恢复.来源审查.不同来源数 === 2)
  测('达到门槛仍只标部分验证', 恢复.验证状态 === '部分验证' && 恢复.目标完成 === '未知')

  次 = 0
  const 仍不足 = await 查('某软件最新版本', {
    钥匙: 'serp-test',
    fetch函数: async () => { 次++; return 回应([条('同站材料', `https://${次 === 1 ? 'docs' : 'support'}.example.com/${次}`, '版本说明')]) },
  })
  测('同一来源的不同子域不能凑成双来源', 仍不足.来源审查.不同来源数 === 1)
  测('补搜后仍不足时保留材料但降级验证', 仍不足.好 && 仍不足.材料门槛.状态 === '材料不足' && 仍不足.验证状态 === '未验证' && 仍不足.目标完成 === '部分')
  测('材料不足不会无限补搜', 次 === 2 && 仍不足.可重试 === false)
  测('给模型的材料明确列出缺口', 仍不足.内容.includes('材料门槛：不足') && 仍不足.内容.includes('不能把下面材料表述成已经核实'))

  次 = 0
  const 普通 = await 查('C语言指针原理', {
    钥匙: 'serp-test',
    fetch函数: async () => { 次++; return 回应([条('教程', 'https://example.com/c', 'pointer')]) },
  })
  测('普通知识查询保持一次请求', 普通.好 && 次 === 1 && !普通.已重试)

  console.log(`搜索验证：${数}/${数} 通过`)
}

集成().catch((错误) => { console.error(错误); process.exitCode = 1 })
