/** 流式语音句段队列：纯假合成与假播放，不启动声音服务。 */
'use strict'

const fs = require('node:fs')
const path = require('node:path')
const 根 = path.join(__dirname, '..')
const { 完整句截止, 拆出完整句们, 创建流式语音队列 } = require(path.join(根, 'renderer', '流式语音.js'))

let 总数 = 0
let 通过 = 0
function 检查(说明, 条件) {
  总数++
  if (!条件) throw new Error('✗ ' + 说明)
  通过++
  console.log('✓ ' + 说明)
}

async function main() {
  const 页面 = fs.readFileSync(path.join(根, 'renderer', 'index.html'), 'utf8')
  const 界面 = fs.readFileSync(path.join(根, 'renderer', 'chat.js'), 'utf8')
  const 样式 = fs.readFileSync(path.join(根, 'renderer', 'style.css'), 'utf8')
  检查('句段模块在聊天脚本之前加载', 页面.indexOf('<script src="流式语音.js"') >= 0 && 页面.indexOf('<script src="流式语音.js"') < 页面.indexOf('<script src="chat.js"'))
  检查('新回复开始时建立新的语音轮次', 界面.includes('if (要出声) 流式朗读.开始()'))
  检查('文字流持续送入句段队列', 界面.includes('流式朗读.收到(到现在)'))
  检查('最终稿负责补齐尾句', 界面.includes('流式朗读.完成(结果.她说的话)'))
  检查('静音会取消当前队列', /要出声 = false\s+流式朗读\.取消\(\)/.test(界面))
  检查('她的每条回复带有重播入口', 界面.includes("谁的 === '她的'") && 界面.includes("className = '重播声音'"))
  检查('重播前确认声音已开启且服务在线', 界面.includes('async function 重播回复') && 界面.includes('if (!要出声)') && 界面.includes('await window.爱莉.声音状态()'))
  检查('重播复用可取消的句段队列', 界面.includes('正在重播按钮 === 按钮') && 界面.includes('流式朗读.开始()') && 界面.includes('流式朗读.完成(文字)'))
  检查('重播入口平时淡出且播放时显示停止', 样式.includes('.重播声音.播放中') && 样式.includes('opacity: 0') && 界面.includes("按钮.textContent = '■'"))

  检查('没有完整句号时不提前截断', 完整句截止('让我想想') === 0)
  检查('识别中文句号和问号', 完整句截止('你好。可以吗？尾巴') === 7)
  检查('连续破折号作为一句结束', 完整句截止('好呀——下一句') === 4)
  检查('句末引号随前一句一起交付', 完整句截止('“好呀。”下一句') === 5)
  检查('同一批到达的多句话会分别切开', 拆出完整句们('第一句。第二句！尾巴').句子们.join('|') === '第一句。|第二句！')

  const 合成过 = []
  const 播放过 = []
  const 首声们 = []
  const 队列 = 创建流式语音队列({
    合成: async (文字) => { 合成过.push(文字); return { 成功: true, 文字 } },
    播放: async (结果, 开始) => { 开始(); 播放过.push(结果.文字) },
    首声: (毫秒) => 首声们.push(毫秒),
  })
  队列.开始()
  队列.收到('第一句。第')
  队列.收到('第一句。第二句！没有')
  队列.完成('第一句。第二句！没有句号')
  await 队列.等空闲()
  检查('完整句生成时立即进入合成', 合成过[0] === '第一句。')
  检查('多句严格按原顺序合成', 合成过.join('|') === '第一句。|第二句！|没有句号')
  检查('多句严格按原顺序播放', 播放过.join('|') === 合成过.join('|'))
  检查('未结束的尾句在最终稿到达后补播', 播放过.at(-1) === '没有句号')
  检查('每轮只记录一次首声延迟', 首声们.length === 1 && 首声们[0] >= 0)

  let 放完第一句
  const 第一句播放完 = new Promise((好) => { 放完第一句 = 好 })
  const 预合成记录 = []
  const 预播放记录 = []
  const 可预取 = 创建流式语音队列({
    合成: async (文字) => { 预合成记录.push(文字); return { 成功: true, 文字 } },
    播放: async (结果) => {
      预播放记录.push(结果.文字)
      if (结果.文字 === '第一句。') await 第一句播放完
    },
  })
  可预取.开始()
  可预取.完成('第一句。第二句。第三句。')
  await new Promise((好) => setImmediate(好))
  检查('播放第一句时已在后台预合成后续句子', 预播放记录.join('|') === '第一句。' && 预合成记录.join('|') === '第一句。|第二句。|第三句。')
  放完第一句()
  await 可预取.等空闲()
  检查('预合成后仍严格按句子顺序播放', 预播放记录.join('|') === '第一句。|第二句。|第三句。')

  let 停止次数 = 0
  let 失败说明 = ''
  const 防回退 = 创建流式语音队列({
    合成: async (文字) => ({ 成功: true, 文字 }),
    播放: async () => {},
    停止: () => { 停止次数++ },
    失败: (错误) => { 失败说明 = 错误.说明 || '' },
  })
  防回退.开始()
  防回退.收到('她先这样说。')
  const 回退 = 防回退.收到('她改口了。')
  检查('累计文字回退时拒绝继续朗读', !回退.接受 && 回退.回退)
  检查('文字回退会停止当前声音', 停止次数 >= 2)
  检查('文字回退给出明确原因', /回退/.test(失败说明))

  let 放行合成
  const 慢合成 = new Promise((好) => { 放行合成 = 好 })
  const 取消后播放 = []
  const 可取消 = 创建流式语音队列({
    合成: async () => 慢合成,
    播放: async (结果) => 取消后播放.push(结果),
  })
  可取消.开始()
  可取消.收到('不要念这句。')
  可取消.取消()
  放行合成({ 成功: true })
  await new Promise((好) => setImmediate(好))
  检查('取消后丢弃晚到的合成结果', 取消后播放.length === 0)

  let 放行旧轮
  const 旧轮合成 = new Promise((好) => { 放行旧轮 = 好 })
  const 跨轮播放 = []
  let 合成序号 = 0
  const 可立即重开 = 创建流式语音队列({
    合成: async (文字) => {
      合成序号++
      if (合成序号 === 1) return 旧轮合成
      return { 成功: true, 文字 }
    },
    播放: async (结果) => { 跨轮播放.push(结果.文字) },
  })
  可立即重开.开始()
  可立即重开.收到('旧的一句。')
 可立即重开.取消()
  可立即重开.开始()
  可立即重开.完成('新的一句。')
  await 可立即重开.等空闲()
  检查('旧合成未返回时新一轮仍能立即播放', 跨轮播放.join('') === '新的一句。')
  放行旧轮({ 成功: true, 文字: '旧的一句。' })
  await new Promise((好) => setImmediate(好))
  检查('旧轮晚到后不会插入新轮', 跨轮播放.join('') === '新的一句。')

  let 抛错 = ''
  const 失败队列 = 创建流式语音队列({
    合成: async () => ({ 成功: false, 说明: '假服务失败' }),
    播放: async () => {},
    失败: (错误) => { 抛错 = 错误.说明 },
  })
  失败队列.开始()
  失败队列.完成('测试。')
  await 失败队列.等空闲()
  检查('单句合成失败后停止本轮队列', 抛错 === '假服务失败' && !失败队列.忙吗())

  console.log(`\n流式语音：${通过}/${总数} 通过`)
}

main().catch((错误) => {
  console.error(错误.stack || 错误.message)
  process.exitCode = 1
})
