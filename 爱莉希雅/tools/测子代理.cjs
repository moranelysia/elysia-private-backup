/**
 * 测子代理.cjs —— 量"派个小助手去干活"这件事办得对不对
 *
 * 【它治什么】
 *   她读一个文件就吞 12000 token，搜一次网页六条摘要全赖在上下文里。
 *   而她要的往往只是"里面说了什么"。所以派个助手去干，只把纸条带回来。
 *
 * 【三条要量的硬规矩】
 *   一、**小助手不许看见【派】** —— 看见了它就能一层层派下去，没底
 *   二、**它没有人设** —— 它是去干活的，不是爱莉希雅。
 *       它要是学着爱莉希雅的口吻汇报，那些语气会顺着纸条爬回她的上下文
 *   三、**纸条上必须写明"这是别人替你跑的"** ——
 *       不写的话，她会把纸条上的事讲得跟自己亲眼翻过一样
 *
 * 【最后一组会真花钱】派一个真实的小任务（一两次请求，一分多钱）。
 *   前面几组都是纯函数，不花钱。
 *
 * 用法: node tools\测子代理.cjs
 */
'use strict'

const path = require('node:path')

const 项目根 = path.resolve(__dirname, '..')
const 子 = require(path.join(项目根, '脑', '子代理.cjs'))
const 工具表 = require(path.join(项目根, '脑', '工具表.cjs'))
const 记忆 = require(path.join(项目根, '脑', '记忆.cjs'))

let 过了 = 0
let 总数 = 0
function 检查(说明, 条件, 细节 = '') {
  总数++
  if (条件) {
    过了++
    console.log(`  ✓ ${说明}`)
  } else {
    console.log(`  ✗ ${说明}${细节 ? '   → ' + 细节 : ''}`)
  }
}

async function main() {
  console.log('')
  console.log('  ════════════════════════════════════════════')
  console.log('   子代理：派个小助手去干活，只带纸条回来')
  console.log('  ════════════════════════════════════════════')
  console.log('')

  const 提示 = 子.助手提示()

  // -------------------------------------------------------------
  console.log('  ── 一、它不许看见【派】（不然能无限套娃）──')
  //
  // 【注意查什么】不能查"派"这个字 —— 提示词正文里就有
  // （"你是爱莉希雅**派**出去办事的助手"）。第一版就是这么查的，
  // 结果误报。要查的是**工具标记**和**工具说明的样子**。
  检查('提示里没有 [派:  这种标记', !/\[派[:：]/.test(提示))
  检查('提示里没有【派】这种工具说明', !提示.includes('【派】'))
  检查('它看得见别的工具（读）', 提示.includes('读'))
  检查('它看得见别的工具（跑）', 提示.includes('跑'))
  const 看得见的 = 工具表.表.filter((t) => t.名字 !== '派' && 提示.includes(t.名字)).map((t) => t.名字)
  console.log('     它看得见：' + 看得见的.join('、'))

  // 光看提示词不够 —— 得确认"认工具"那一层也挡住了
  // （提示里没写，但它要是认得出 [派:xxx]，一样能派）
  const 认 = (写法) => {
    const 工具 = 工具表.认工具(写法)
    return 工具 && 工具.名字 !== '派' ? 工具 : null
  }
  检查('认工具那一层也挡住【派】了', 认('派') === null, String(认('派')))
  检查('别的工具照样认得出', 认('读') !== null && 认('读').名字 === '读')

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 二、它是干活的，不是爱莉希雅 ──')

  检查('提示很短（这是它的价值）', 提示.length < 900, `${提示.length} 字`)
  检查('里面没有人设守则', !提示.includes('守则') && !提示.includes('英桀'))
  检查('里面没有她的语气符号', !/[♪～]/.test(提示))
  检查('明确说了"你不是爱莉希雅"', 提示.includes('你不是爱莉希雅'))
  检查('明确要求别编', 提示.includes('别编'))
  检查('明确要求交纸条不报过程', 提示.includes('别写'))
  console.log(`     主代理的说明书 14256 字，它这份 ${提示.length} 字`)

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 三、入参挡住不该派的 ──')

  const 空 = await 子.派('')
  检查('没说要干什么 → 不派，而且不花钱', 空.好 === false)
  检查('它说清楚了原因', String(空.说明).includes('没说要它干什么'))

  const 太长 = await 子.派('甲'.repeat(600))
  检查('任务说得太长 → 不派', 太长.好 === false)
  检查('它提示"一句话说清"', String(太长.说明).includes('一句话'), String(太长.说明))

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 四、工具表那边的口子 ──')

  检查('工具表里有【派】', 工具表.表.some((t) => t.名字 === '派'))
  const 派工具 = 工具表.表.find((t) => t.名字 === '派')
  检查('它的危险度是 safe（它自己不碰硬盘）', 派工具.危险度 === 'safe')
  检查(
    '但它的"做"声明了三个参数（不然"怎么问他"传不下去）',
    派工具.做.length >= 3,
    `只声明了 ${派工具.做.length} 个`,
  )
  检查('自检没意见', 工具表.自检().length === 0, JSON.stringify(工具表.自检()))
  检查('拼给她看的说明里有【派】', 工具表.拼工具说明().includes('【派】'))
  检查('拼给小助手看的说明里没有', !工具表.拼工具说明({ 除了: ['派'] }).includes('【派】'))

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 五、真派一次（会花钱，一分多）──')
  console.log('')

  const 账本前 = 记忆.读聊天记录(0).length // 只是确认文件读得动
  const 开始 = Date.now()
  const 果 = await 子.派('读一下 D:\\新建文件夹\\爱莉希雅\\测试清单.md 的开头部分，告诉我它一共分了几组，每组是干嘛的', {
    问: async () => true,
  })
  const 用时 = ((Date.now() - 开始) / 1000).toFixed(1)

  if (!果.好) {
    console.log('  ✗ 派失败了：' + 果.说明)
    process.exit(1)
  }

  console.log(`  转了几轮：${果.用了几轮}`)
  console.log(`  它动过的手：${(果.用过的工具 || []).map((t) => `${t.名字}(${t.参数})`).join('、') || '（没动手）'}`)
  console.log(`  用了 ${用时}s`)
  if (果.用了) console.log(`  token：输入 ${果.用了.prompt_tokens}，输出 ${果.用了.completion_tokens}`)
  console.log('')
  console.log('  ── 它交回来的纸条 ──')
  console.log(果.内容)

  const 纸条 = 果.内容

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 六、纸条本身对不对 ──')

  检查('它真的动手了（去读了）', (果.用过的工具 || []).length > 0, '一次手都没动')
  检查('它读的是那份文件', (果.用过的工具 || []).some((t) => String(t.参数).includes('测试清单')))

  检查('交回来的是一段话', 纸条.length > 20, `${纸条.length} 字`)
  检查('纸条不太长（这是派它的意义）', 纸条.length < 2500, `${纸条.length} 字`)
  检查('**纸条上没有残留的工具标记**', !/\[[^\]]{1,40}[:：][^\]]{0,80}\]/.test(纸条), 纸条.slice(-120))

  // 这一条最要紧：纸条上必须写明"这是别人替你跑的"
  // 不写的话，她会把纸条上的事讲得跟自己亲眼翻过一样
  检查('纸条上写清了"这是小助手跑的"', 纸条.includes('小助手'))
  检查('纸条上提醒了"你没亲眼看过"', 纸条.includes('没有亲眼看过'), '缺这句她就会讲得跟自己翻过一样')

  // -------------------------------------------------------------
  console.log('')
  console.log('  ── 七、它的上下文比主代理小得多（派它的理由）──')

  const 它的输入 = (果.用了 && 果.用了.prompt_tokens) || 0
  console.log(`     它那一发的输入：${它的输入} token`)
  console.log(`     主代理平时一发：7700 ~ 11500 token`)
  检查('它比主代理省（说明短提示词起作用了）', 它的输入 > 0 && 它的输入 < 7700, `${它的输入}`)
  if (果.用过的工具 && 果.用过的工具.length) {
    const 读过 = 果.用过的工具.find((t) => t.名字 === '读')
    if (读过 && 读过.结果 && 读过.结果.内容) {
      const 原文 = String(读过.结果.内容).length
      console.log(`     它读回来 ${原文} 字，交出去的纸条 ${纸条.length} 字 —— 压缩了 ${Math.round(原文 / 纸条.length)} 倍`)
      检查('确实"读很多、交很少"', 原文 > 纸条.length * 2, `读了 ${原文} 字只交了 ${纸条.length} 字`)
    }
  }

  console.log('')
  console.log('  ════════════════════════════════════════════')
  console.log(`   ${过了} / ${总数}` + (过了 === 总数 ? '   ✓ 全过' : '   ✗ 有没过的'))
  console.log('  ════════════════════════════════════════════')
  console.log('')
  process.exit(过了 === 总数 ? 0 : 1)
}

main().catch((错误) => {
  console.log('✗ 测试自己出错了: ' + 错误.message)
  console.log(错误.stack.split('\n').slice(0, 4).join('\n'))
  process.exit(1)
})
