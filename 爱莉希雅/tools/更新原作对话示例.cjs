function 原作示例文本() {
  return 原作组.map(({ 标题, 行 }) => {
    const 对话 = 行.map(([角色, 台词]) => `${角色}：${台词}`).join('\n')
    return `【${标题}】\n${对话}`
  }).join('\n\n')
}

function 时间戳() {
  const d = new Date()
  const 两位 = n => String(n).padStart(2, '0')
  return `${d.getFullYear()}${两位(d.getMonth() + 1)}${两位(d.getDate())}-${两位(d.getHours())}${两位(d.getMinutes())}${两位(d.getSeconds())}`
}

function 精确替换字符串(原文, 旧值, 新值, 字段名) {
  const 旧片段 = JSON.stringify(旧值)
  const 新片段 = JSON.stringify(新值)
  const 位置 = 原文.indexOf(旧片段)
  if (位置 < 0) throw new Error(`找不到 ${字段名} 的原始字符串，未写入`)
  if (原文.indexOf(旧片段, 位置 + 1) >= 0) throw new Error(`${字段名} 原始字符串出现多次，未写入`)
  return 原文.slice(0, 位置) + 新片段 + 原文.slice(位置 + 旧片段.length)
}

function 主() {
  const 角色卡原文 = fs.readFileSync(角色卡路径, 'utf8')
  const 卡 = JSON.parse(角色卡原文)
  const 数据 = 卡.data
  if (数据.mes_example.includes(完成记号) && 数据.character_version === '1.10') {
    console.log('· 原作对话示例已经安装，没有重复写入')
    return
  }

  const 语料 = fs.readFileSync(原作路径, 'utf8').replace(/\r\n/g, '\n')
  let 核对数 = 0
  for (const 组 of 原作组) {
    for (const [角色, 台词] of 组.行) {
      const 原句 = `**${角色}**：${台词}`
      if (!语料.includes(原句)) throw new Error(`原作中找不到这句，未写入：${原句}`)
      核对数 += 1
    }
  }

  const 原作 = 原作示例文本()
  const 新示例 = `以下六段是游戏内原作对话，只学习其中的语气、节奏与反应方式；人物和事件属于原作上下文，不是当前记忆，也不要逐字复述。\n\n${原作}\n\n${本项目纠偏}`
  const 原作占比 = 原作.length / 新示例.length
  if (原作占比 < 0.75) throw new Error(`原作占比不足：${(原作占比 * 100).toFixed(1)}%`)

  const 版本说明 = `v1.10（2026-10-21，原作示例重构）：按用户要求，mes_example 改为六段 D 盘游戏内原作对话为主体，仅保留三条很短的本项目纠偏示范。脚本逐句核对 zhuiyi.md，原作部分占示例区 ${(原作占比 * 100).toFixed(1)}%，避免继续用大量 DeepSeek 生成对白定义她的口吻。`
  const 新说明 = 数据.creator_notes.includes('原作示例重构')
    ? 数据.creator_notes
    : `${版本说明}\n\n${数据.creator_notes}`

  let 改后 = 角色卡原文
  改后 = 精确替换字符串(改后, 数据.mes_example, 新示例, 'mes_example')
  改后 = 精确替换字符串(改后, 数据.creator_notes, 新说明, 'creator_notes')
  改后 = 精确替换字符串(改后, 数据.character_version, '1.10', 'character_version')

  const 验 = JSON.parse(改后)
  if (!验.data.mes_example.includes(完成记号)) throw new Error('原作示例写入校验失败')
  if (验.data.character_version !== '1.10') throw new Error('版本写入校验失败')
  if (验.data.extensions.dshCosplay.rules !== 数据.extensions.dshCosplay.rules) {
    throw new Error('非目标守则字段发生变化，未写入')
  }

  fs.mkdirSync(备份目录, { recursive: true })
  const 备份 = path.join(备份目录, `角色卡.json.原作示例之前-${时间戳()}`)
  fs.writeFileSync(备份, 角色卡原文, 'utf8')
  fs.writeFileSync(角色卡路径, 改后, 'utf8')

  console.log(`✓ 原作对话示例已安装：${原作组.length} 段，核对 ${核对数} 句`)
  console.log(`  原作占示例区：${(原作占比 * 100).toFixed(1)}%`)
  console.log('  角色卡版本：1.10')
  console.log('  备份：' + 备份)
}

主()
