// 生成对齐表.cjs —— 算出 25 张手部素材该在页面上摆哪儿
//
// 【核心换算】
//   素材图是 1400x1400，它里面的"25 个键位"（爱心+手）分布在
//   x 约 640~1090、y 约 850~1250 这一块（实测）。
//
//   她的 Live2D 键盘在贴图里的位置是 x 1307~1720, y 1590~1830。
//
//   两边的"一格键"宽度：
//     素材：25 个键占 5 列 → 每列约 (1090-640)/5.7 ≈ 79 像素
//     她键盘：每列约 (1720-1307)/9 ≈ 46 像素
//   所以素材要缩小到 46/79 ≈ 0.58
//
// 用法: node tools/生成对齐表.cjs

const fs = require("fs")

// 素材里每个键（爱心）的中心 —— 实测数据里爱心位置是固定的
const 爱心固定 = { x: 48, y: 255, 宽: 278, 高: 240 }

// 素材里 25 个键的中心（从上一步测量.json 里能拿到手的位置，
// 爱心的中心则是固定的：48+139 = 187, 255+120 = 375）
const 爱心中心 = { x: 爱心固定.x + 爱心固定.宽 / 2, y: 爱心固定.y + 爱心固定.高 / 2 }

// 素材网格：5 列 × 5 行（和她的键盘布局一致）
// 素材里相邻两列的中心距（实测：爱心都在同一位置，所以间距要靠她的手推算）
// 从测量数据看：编号 0~4 在左列，5~9 第二列…… 手的位置随列变化
// 这里用一个保守估计：素材里每个键占约 79 像素
const 素材格宽 = 79

// 她键盘：每列约 46 像素
const 她键盘格宽 = 46

const 缩放 = 她键盘格宽 / 素材格宽

console.log(`素材格宽 ${素材格宽}px → 她键盘格宽 ${她键盘格宽}px`)
console.log(`所以手部素材要缩放到 ${缩放.toFixed(3)} 倍\n`)

// 每个键在素材图里的中心位置 = 爱心中心 + (列偏移, 行偏移)
// 注意素材是"倒着"的（Bongo Cat 的设计：她在键盘后面）
const 键序 = [
  ["Shift", 0, 0], ["Ctrl", 1, 0], ["Alt", 2, 0], ["Space", 3, 0], ["Enter", 4, 0],
  ["Z", 0, 1], ["X", 1, 1], ["C", 2, 1], ["V", 3, 1], ["B", 4, 1],
  ["A", 0, 2], ["S", 1, 2], ["D", 2, 2], ["F", 3, 2], ["G", 4, 2],
  ["Q", 0, 3], ["W", 1, 3], ["E", 2, 3], ["R", 3, 3], ["T", 4, 3],
  ["Digit1", 0, 4], ["Digit2", 1, 4], ["Digit3", 2, 4], ["Digit4", 3, 4], ["Digit5", 4, 4],
]

const 表 = {}
for (const [键, 列, 行] of 键序) {
  表[键] = {
    列,
    行,
    缩放: Number(缩放.toFixed(4)),
    // 这个键的爱心在素材图里的中心
    素材中心X: Math.round(爱心中心.x + (列 - 2) * 素材格宽),
    素材中心Y: Math.round(爱心中心.y + (行 - 2) * 素材格宽),
  }
}

fs.writeFileSync(
  "renderer/assets/keyboard/对齐表.json",
  JSON.stringify({
    说明: "手部素材每张图该缩放到多少、它里面的键中心在图的哪个位置",
    素材尺寸: 1400,
    缩放: Number(缩放.toFixed(4)),
    表,
  }, null, 2),
  "utf8"
)

console.log("对齐表:")
for (const [键, v] of Object.entries(表).slice(0, 8)) {
  console.log(`  ${键.padEnd(7)} 列${v.列} 行${v.行}  素材里的键中心 (${v.素材中心X}, ${v.素材中心Y})`)
}
console.log("\n存到: renderer/assets/keyboard/对齐表.json")
