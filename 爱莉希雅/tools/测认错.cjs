/**
 * 测认错.cjs —— 出错的时候，它认得出是哪一种吗
 *
 * 【为什么值得单写一个测试】
 *   这段逻辑只有一句话："碰巧的错再试，必然的错别试"。
 *   可它判错的时候**你看不出来** ——
 *     · 把"欠费"当成"网抖" → 她会连着试三次，白等十几秒，
 *       最后报的还是"连不上"，你会去查网线。
 *     · 把"超时"当成"你按了停" → 一声不吭就算了，屏幕上什么都不说。
 *   这两种我都差点写出来（第二种真写出来了，改的时候才发现）。
 *   所以每一条"应该分到哪一类"都钉在这儿。
 *
 * 用法: node tools\测认错.cjs
 */
'use strict'

const 认错 = require('../脑/认错.cjs')

let 过了 = 0
let 总数 = 0
function 检查(说明, 条件, 细节 = '') {
  总数++
  if (条件) {
    过了++
    console.log(`  ✓ ${说明}`)
  } else {
    console.log(`  ✗ ${说明}${细节 ? '   → ' + 细节 : ''}`)
  }
}

/** 造一个"像 fetch 报出来的"网络错 */
function 网错(码) {
  const 里 = new Error('read ' + 码)
  里.code = 码
  const 外 = new TypeError('fetch failed')
  外.cause = 里
  return 外
}

function 主() {
  console.log('')
  console.log('  ════════════════════════════════════════════')
  console.log('   认错 —— 这个错该不该再试一次')
  console.log('  ════════════════════════════════════════════')
  console.log('')

  // ---------------------------------------------------------------
  console.log('  ── 一、路上出的事：该重试 ──')

  const 甲 = 认错.分类(网错('ECONNRESET'), 0)
  检查('ECONNRESET → 网', 甲.种类 === '网', 甲.种类)
  检查('  ……而且能重来', 甲.能重来 === true)

  // 【这一条是"挖到底"的意义】外层只有"fetch failed"四个字，
  // 真病根在 cause 里。不挖，就分不清网断了和对面挂了。
  const 乙 = 认错.分类(网错('ENOTFOUND'), 0)
  检查('错埋在 cause 里也挖得到（ENOTFOUND）', 乙.种类 === '网', 乙.种类)

  const 丙 = 认错.分类(new TypeError('fetch failed'), 0)
  检查('只有一句 fetch failed → 网', 丙.种类 === '网', 丙.种类)

  const 丁 = 认错.分类(new Error('socket hang up'), 0)
  检查('socket hang up → 网', 丁.种类 === '网', 丁.种类)

  // ---------------------------------------------------------------
  console.log('')
  console.log('  ── 二、等太久了：也算路上出的事，但**不能**当成"他按了停" ──')

  const 超时错 = new Error('This operation was aborted')
  超时错.name = 'AbortError'
  超时错.是超时 = true
  超时错.等了 = 30000

  const 戊 = 认错.分类(超时错, 0)
  检查('超时 → 归到"网"，能重来', 戊.种类 === '网' && 戊.能重来 === true, 戊.种类)
  检查('  说法里说出了等了多少秒', /30 秒/.test(戊.说法), 戊.说法)

  // 这一格是钉"我差点写错的那个 bug"：
  // 超时报错和"用户按停"长得**一模一样**（都是 AbortError + 同一句话），
  // 第一版判"喊停"的时候没把超时摘出去，于是超时会被当成他自己按的停，
  // 然后一声不吭地算了 —— 屏幕上什么都不说，他会以为是卡住了。
  const 真喊停 = new Error('This operation was aborted')
  真喊停.name = 'AbortError'
  const 己 = 认错.分类(真喊停, 0)
  检查('真的按停 → 中止（两件事长得一样，得靠记号分开）', 己.种类 === '中止', 己.种类)
  检查('  按停不重来', 己.能重来 === false)
  检查('  按停不该报错吓他', !/HTTP|失败|出错/.test(己.说法), 己.说法)

  // ---------------------------------------------------------------
  console.log('')
  console.log('  ── 三、钱和钥匙：不重试，而且得说清楚 ──')

  const 庚 = 认错.分类(new Error('HTTP 401：Authentication Fails'), 401)
  检查('401 → 钥匙', 庚.种类 === '钥匙' && !庚.能重来, 庚.种类)
  检查('  说法会引导去设置检查', /设置/.test(庚.说法), 庚.说法)

  const 辛 = 认错.分类(new Error('HTTP 402：Insufficient Balance'), 402)
  检查('402 → 欠费', 辛.种类 === '欠费' && !辛.能重来, 辛.种类)
  检查('  说法里说了要充值', /充值/.test(辛.说法), 辛.说法)

  // 有些情况状态码丢了，只能靠正文认
  const 壬 = 认错.分类(new Error('Insufficient Balance'), 0)
  检查('状态码丢了，从正文也能认出欠费', 壬.种类 === '欠费', 壬.种类)

  // ---------------------------------------------------------------
  console.log('')
  console.log('  ── 四、对面忙 / 对面抽风：该重试，但等久一点 ──')

  const 癸 = 认错.分类(new Error('HTTP 429'), 429)
  检查('429 → 忙，能重来', 癸.种类 === '忙' && 癸.能重来 === true, 癸.种类)
  检查('  忙的时候等得比网抖久', 癸.基础等待 > 甲.基础等待, `${癸.基础等待} vs ${甲.基础等待}`)

  const 子 = 认错.分类(new Error('HTTP 503'), 503)
  检查('5xx → 对面，能重来', 子.种类 === '对面' && 子.能重来 === true, 子.种类)

  // ---------------------------------------------------------------
  console.log('')
  console.log('  ── 五、请求本身写错了：再试一万次也一样 ──')

  const 丑 = 认错.分类(new Error('HTTP 400：bad request'), 400)
  检查('400 → 请求，不重来', 丑.种类 === '请求' && !丑.能重来, 丑.种类)

  const 寅 = 认错.分类(new Error('不知道哪儿冒出来的'), 0)
  检查('没见过的错 → 说不清，不重来（别装懂）', 寅.种类 === '说不清' && !寅.能重来, 寅.种类)
  检查('  原文留在说法里，能查', /不知道哪儿冒出来的/.test(寅.说法), 寅.说法)

  // ---------------------------------------------------------------
  console.log('')
  console.log('  ── 六、越试等得越久 ──')

  检查('第一次等 基础等待×1', 认错.等多久(癸, 1) === 癸.基础等待)
  检查('第二次等 基础等待×2', 认错.等多久(癸, 2) === 癸.基础等待 * 2)
  检查('不重试的那种，等 0', 认错.等多久(庚, 1) === 0)

  // ---------------------------------------------------------------
  console.log('')
  console.log('  ── 七、包装之后，他看到的是一句中国话 ──')

  const 卯 = 认错.包装(网错('ECONNRESET'), 甲, 3)
  检查('试了 3 次才放弃，会说出来', /试了 3 次/.test(卯.message), 卯.message)
  检查('  说法本身是中文，不是 fetch failed', !/fetch failed/.test(卯.message), 卯.message)
  检查('  原文没丢（挂在 .原文 上）', /fetch failed/.test(卯.原文), 卯.原文)
  检查('  种类传下去了', 卯.种类 === '网')

  const 辰 = 认错.包装(网错('ECONNRESET'), 甲, 1)
  检查('第一次就放弃，不啰嗦"试了 1 次"', !/试了/.test(辰.message), 辰.message)

  console.log('')
  console.log('  ════════════════════════════════════════════')
  console.log(`   ${过了} / ${总数}`)
  console.log('  ════════════════════════════════════════════')
  console.log('')
  process.exit(过了 === 总数 ? 0 : 1)
}

主()
