/** E1-C 统一表现事件：纯内存、假时间，不驱动真实桌宠。 */
'use strict'
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { 创建表现层, 类型们 } = require('../脑/表现事件.cjs')

let 数量 = 0
function 检查(说明, 条件) { assert.ok(条件, 说明); 数量++; console.log('✓ ' + 说明) }
const 层 = 创建表现层({ 现在: () => new Date('2026-10-16T14:00:00+08:00') })
const 状态 = { 情绪: '开心', 强度: 0.72, 温度: 0.9, 活跃度: 0.78, 触发于: '2026-10-16T06:00:00.000Z' }
const 慢 = { 情绪: '明快', 强度: 0.16 }

检查('事件类型是有限集合', ['待机', '思考', '执行', '说话', '开心', '关心', '认真', '疑惑', '惊讶'].every((一) => 类型们.includes(一)))
检查('思考阶段使用统一结构', 层.阶段('a', '思考', { 即时: 状态, 缓慢: 慢 }).类型 === '思考')
检查('明确开心能驱动现有桌宠的眯眯眼', 层.回复('a', { 即时: 状态, 缓慢: 慢 }).表情 === '眯眯眼')
检查('同一触发衰减期间不重复按表情', 层.回复('a', { 即时: { ...状态, 强度: 0.6 }, 缓慢: 慢 }).表情 === '')
检查('新的情绪触发可以再次表现', 层.回复('a', { 即时: { ...状态, 触发于: '2026-10-16T06:01:00.000Z' }, 缓慢: 慢 }).表情 === '眯眯眼')
检查('模型显式表情优先于自动情绪', 层.回复('b', { 即时: 状态, 显式表情: ['脸红'], 文本表情: ['星星眼'] }).表情 === '脸红')
检查('回复内容路由优先于自动情绪', 层.回复('c', { 即时: 状态, 文本表情: ['星星眼'] }).表情 === '星星眼')
检查('关心事件不硬套流泪表情', 层.回复('d', { 即时: { 情绪: '关心', 强度: 0.82, 温度: 0.94, 活跃度: 0.3, 触发于: 'x' } }).表情 === '')
检查('认真事件不硬套脸黑表情', 层.回复('e', { 即时: { 情绪: '认真', 强度: 0.68, 温度: 0.64, 活跃度: 0.54, 触发于: 'y' } }).表情 === '')
const 安全 = 层.回复('f', { 即时: 状态, 缓慢: 慢, 回复: '不该进入事件的正文' })
检查('事件不携带聊天正文', !Object.values(安全).some((值) => String(值).includes('不该进入事件')))

const 根 = path.resolve(__dirname, '..')
const 主进程 = fs.readFileSync(path.join(根, 'main.js'), 'utf8')
const 预载 = fs.readFileSync(path.join(根, 'preload.js'), 'utf8')
检查('主进程四个阶段都走统一事件', ['思考', '执行', '说话'].every((一) => 主进程.includes(`表现层.阶段(这`) && 主进程.includes(`'${一}'`)) && 主进程.includes('表现层.回复('))
检查('预载只开放只读事件监听', 预载.includes('表现事件: (回调)') && !预载.includes("invoke('表现事件'"))

console.log(`\n表现事件：${数量}/${数量} 通过`)
