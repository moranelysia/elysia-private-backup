/**
 * Cyrene 的"写文件"是怎么做的 —— 扒它的源码记下来的（2026-10-01）
 *
 * 放在这儿是因为：**这些决定我不想凭印象重造一遍**。
 * 它的值是实打实调出来的（注释里写着踩过什么坑、为什么选这个数），
 * 我们要做同一件事，照着它的判断走比自己拍脑袋强。
 * （许可查过：源码 MIT。）
 *
 * ────────────────────────────────────────────────────────────
 * 一、权限分四档，不是"能写/不能写"
 * ────────────────────────────────────────────────────────────
 *   完全只读 / 只读 / 指定目录 / 每次审批 / 完全访问
 *
 *   moran 机器上现在是「指定目录」（scoped）：
 *     读 ✓   写 ✓   联网 ✓   跑命令 → 交给沙箱兜
 *
 *   **注意这里有个反直觉的地方**：scoped 档把"写"放行了。
 *   因为"只能写某个目录"这层限制不是靠"工具准入"实现的，
 *   是靠**底下那个沙箱**（buildFilesystemConfigForLevel + wrapWithSandbox）
 *   强制出来的。准入表只回答"这类操作允不允许"。
 *
 *   这一条对我们有启发：**"允许写"和"只能写到哪儿"是两件事，分两层管。**
 *
 * ────────────────────────────────────────────────────────────
 * 二、相对路径怎么处理（resolveWritePath）
 * ────────────────────────────────────────────────────────────
 *   1. 相对路径的根固定是"可信工作区"，没绑定就退到桌面
 *   2. **禁止 .. 穿越** —— 看到 ".." 直接拒
 *   3. 拼完之后再算一次 path.relative，确认还在根目录下面
 *      （注释里特意写了"不能靠前缀碰撞绕过" —— 比如
 *        根是 D:\a，路径是 D:\ab\x，光看字符串前缀会误判）
 *
 *   这三步跟我们 脑\动手.cjs 里那个 查路径() 是同一个思路：
 *   **规范化 → 算相对位置 → 确认没跑出去**。
 *
 * ────────────────────────────────────────────────────────────
 * 三、写之前的"骤降检查"（overwrite-guard.ts）——最值钱的一条
 * ────────────────────────────────────────────────────────────
 *   背景（它的原话）："弱模型在长上下文 + 多工具场景下，
 *   可能生成被截断的 content 后仍然发起覆盖写，把既有大文件毁成半篇。"
 *
 *   规则（纯函数，可调）：
 *     原文件 ≥ 50 行  且  新内容行数 < 原来的 50%  →  拒绝写
 *   小文件不拦 —— 10 行的笔记整理成 4 行是正常的。
 *
 *   拒绝时文件**保持原样**（检查在落盘之前）。
 *   而且拒绝文案会引导模型改走"局部替换"，不是让它原样重试。
 *
 *   这条我们要原样照搬。它治的正是我们最怕的那件事：
 *   她一句话说错，把你的文件改坏。
 *
 * ────────────────────────────────────────────────────────────
 * 四、几个小细节，都是踩出来的
 * ────────────────────────────────────────────────────────────
 *   · 写前**现读**原文件，不用"本次修改前的基线"
 *     （基线可能已经过时，同一轮里改过好几次的话，diff 和骤降口径都会算错）
 *   · 读原文件失败 → **拒绝覆盖写**，不硬写
 *   · 追加写时：原文件末尾没有换行就先补一个
 *     （不然两段内容会粘在同一行）
 *   · append（追加）和覆盖是同一个工具的两个参数，不是两个工具
 *
 * ────────────────────────────────────────────────────────────
 * 五、审批怎么弹（它的做法，我们要简化）
 * ────────────────────────────────────────────────────────────
 *   主进程把审批请求广播给所有窗口 → 渲染端弹一张卡片 → 你点同意/拒绝
 *   之后：
 *     · **不设超时** —— 等你回应，或那次任务被取消
 *     · 没有窗口可以审批 → 直接拒绝（应用正在退出那种边缘情况）
 *     · 每 10 秒**幂等重播**一次请求，防止窗口刚重载时把请求丢了
 *     · 任何一侧结算都会广播一个"已结算"事件，渲染端据此清卡
 *       （注释里写着：杜绝"点了没反应的僵尸卡"）
 *
 *   这整套（广播、重播、结算事件）是为"多窗口 + 会话切换"设计的。
 *   我们只有一个窗口，用不着这么多机制。
 *
 * ────────────────────────────────────────────────────────────
 * 六、我打算怎么做（跟它的取舍不同，理由写在下面）
 * ────────────────────────────────────────────────────────────
 *
 *   工具：加一个「写」，跟「查/读/列」并列。
 *
 *   写法（跟已有的标记风格一致）：
 *     [写:记忆\小本子.md]
 *     ```要写的内容```
 *
 *   三种情况的规矩不一样 —— 关键在这儿：
 *
 *     新建文件      →  弹确认（你能看见写在哪儿、写什么）
 *     覆盖已有文件  →  弹确认 + 骤降检查（照搬它那套 50 行/50%）
 *     追加到末尾    →  直接写，不弹
 *
 *   为什么"追加"可以不弹：追加**不会毁掉已有内容**，这是它和覆盖的
 *   本质差别。而"把今天这件事记进去"正是最常用的那种写。
 *   每次都要点一下确认，这个功能就会没人用。
 *
 *   （这个取舍跟它不一样：它是 scoped 档直接放行写、靠沙箱兜边界。
 *     我们的"沙箱"就是白名单，所以白名单要写得更严一点：
 *     写只允许落在她自己的记忆目录和工作区根，别的地方一律拒。）
 *
 *   还有三条照搬它：
 *     · 写前现读原文件（为了骤降检查和 diff）
 *     · 骤降检查不过 → 文件保持原样，并告诉她"改用追加或者问我"
 *     · 追加时补换行
 */

