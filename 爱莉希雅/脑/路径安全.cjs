/**
 * 路径安全.cjs —— 她能动硬盘上的哪些地方（唯一的关口）
 *
 * 【为什么必须是唯一一份】
 *   读、写、搜、跑命令，每一处都要问"这个路径她能不能碰"。
 *   要是各写一份，早晚会有一处松了 —— 而松的那一处就是漏洞。
 *   所以判断只在这里，别处一律调它。
 *
 * 【规矩：白名单 + 禁地，两层】
 *   第一层 白名单：只有这几个目录下面才认。
 *   第二层 禁地：就算在白名单里，某些名字也不给看/不给写
 *                （她的 API 钥匙、依赖目录、别人的仓库……）。
 *
 * 【读写分开】
 *   **能读的地方不等于能写。** 她能读工作区那一层（角色卡、共同经历都在那儿），
 *   但不该让她随手改角色卡 —— 那是他和她一起定的东西。
 *   所以写有单独一份更窄的白名单。
 *
 * 用法:
 *   const 路径安全 = require("./路径安全.cjs")
 *   路径安全.注册({ 项目根, 工作区根 })
 *   const 结果 = 路径安全.查(她写的路径, "读")   // "读" | "写"
 */
'use strict'

const fs = require('node:fs')
const path = require('node:path')
const 配置 = require('./配置.cjs')

let 项目根 = 配置.项目根
let 工作区根 = 配置.工作区根
let 桌面目录 = null

/**
 * 他这次选的"干活目录"。
 *
 * 【为什么它是单独一个变量，不塞进工作区根】
 *   工作区根是**她的家** —— 角色卡、学习资料和运行数据，
 *   她的一切都在那儿。而"干活目录"是他在界面上选的一个地方，
 *   可能是一个完全无关的项目文件夹。
 *
 *   两者都要能写，但含义不同：家里那一层是"她自己的东西"，
 *   干活目录是"他让她去动的东西"。分开存，将来想收紧哪个都方便。
 */
let 干活目录 = null

function 注册(选项 = {}) {
  if (选项.项目根) 项目根 = 选项.项目根
  if (选项.工作区根) 工作区根 = 选项.工作区根
  if (选项.桌面目录) 桌面目录 = path.resolve(选项.桌面目录)
}

/**
 * 设他这次选的干活目录。传 null 就是取消（退回只有家里那两个地方能写）。
 */
function 设工作区(目录) {
  干活目录 = 目录 ? path.resolve(目录) : null
  return 干活目录
}

function 拿工作区() {
  return 干活目录
}

/**
 * 读：这几个目录下面都认
 *
 * 【2026-10-01 晚上补了 干活目录 —— 这是个"反过来"的错】
 *   原来读白名单里**没有**他选的那个干活目录，只有写白名单里有。
 *   于是她在 D:\elysia测试 里：能写、能在那儿跑命令，**却读不了、列不了**。
 *   听着像小事，实际是致命的 —— 她写完 guess.c，想回头看一眼自己写了什么、
 *   想列一下目录确认 exe 到底出来没有，全被挡住，回一句
 *   "找不到这个地方，或者不在她能看的范围里"。
 *   **她根本没法核对自己在干什么。**
 *
 *   他那晚的日志（一字不改）：
 *     ↳ 动手：跑(cd /d D:\elysia测试 && gcc guess.c -o guess.exe) —— 成功
 *     ↳ 动手：列(D:\elysia测试) —— 没成：找不到这个地方，或者不在她能看的范围里
 *     ↳ 动手：读(D:\elysia测试\guess.c) —— 没成：找不到这个地方……
 *   编是编出来了，可她看不见自己编的是什么，只好干说。
 *
 *   为什么原来会漏：写白名单那段专门写了"他明确让她去动的地方"，
 *   加得很仔细；而读白名单是更早写的，那时候还没有"干活目录"这个概念。
 *   **后加的东西只加了一半** —— 这种漏法不报错，只会在某天突然咬人。
 *
 *   安全上没问题：那是他亲手挑的目录，本来就是让她干活的；
 *   "能读"比"能写"窄，能写的地方当然能读。
 */
function 读白名单() {
  const 名单 = [
    配置.数据目录,
    path.join(项目根, '脑'),
    path.join(项目根, 'renderer'),
    path.join(项目根, 'tools'),
    path.join(项目根, '工具研究'),
    path.join(项目根, 'icon-source'),
    工作区根,
  ]
  // 桌面是他明确要求加入的日常交换区。真实路径由 Electron 的
  // app.getPath('desktop') 传进来，兼容 OneDrive 重定向和非英文用户名。
  if (桌面目录) 名单.push(桌面目录)
  // 他这次选的干活目录 —— 能在那儿干活，就得能看见那儿
  if (干活目录) 名单.push(干活目录)
  return 名单
}

/**
 * 写：比读窄得多。
 *
 * 【为什么这么严】
 *   写是"会毁掉东西"的那个动作。她能写的地方只有三类：
 *     · 她自己的记忆目录 —— 她的本子，本来就该她自己写
 *     · 工作区根 —— 她的家那一层（放角色卡、共同经历的地方）
 *     · **他这次选的干活目录** —— 他让她去动的东西
 *   项目代码（脑、renderer、tools）**不在写白名单里**：
 *   那是她和我们一起在写的东西，让她自己改风险太大，
 *   真要改，走"她写出来给你看、你来落盘"那条路。
 */
function 写白名单() {
  const 名单 = [配置.数据目录, 工作区根]
  // 能写不等于静默写：桌面不在默认放行清单里，新建和覆盖仍会问他。
  if (桌面目录) 名单.push(桌面目录)
  // 他自己选的那个干活目录也算 —— 那是他明确让她去动的地方
  if (干活目录) 名单.push(干活目录)
  return 名单
}

