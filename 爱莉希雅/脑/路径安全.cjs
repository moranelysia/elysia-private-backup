/**
 * 放行的目录：他点过"以后这个文件夹不用问了"的那些（**额外的**）。
 *
 * 由外面灌进来（main.js 启动时从设置里读）——
 * 这个模块**不自己读设置文件**：那样它就得知道设置存在哪，
 * 而"谁知道设置在哪"这件事只能有一个地方负责，两处各存一份早晚对不上。
 */
let 放行的目录 = []

/** 灌放行清单（main.js 启动时、以及他每点一次"记住"之后调） */
function 设放行的目录(名单) {
  放行的目录 = (Array.isArray(名单) ? 名单 : [])
    .map((一个) => {
      try {
        return path.resolve(String(一个))
      } catch {
        return ''
      }
    })
    .filter(Boolean)
  return 放行的目录
}

function 拿放行的目录() {
  return [...放行的目录]
}

/**
 * 把路径换成文件系统真正指向的位置。
 *
 * `path.resolve()` 只能消掉 `..`，看不穿 Windows junction 和符号链接。
 * 新文件还不存在时，从最近一个存在的父目录开始 realpath，再把剩余部分接回去。
 */
function 真实路径(输入) {
  const 原路径 = path.resolve(输入)
  let 已存在的 = 原路径
  const 尾巴 = []

  while (!fs.existsSync(已存在的)) {
    const 父 = path.dirname(已存在的)
    if (父 === 已存在的) return 原路径
    尾巴.unshift(path.basename(已存在的))
    已存在的 = 父
  }

  try {
    const 真父 = fs.realpathSync.native ? fs.realpathSync.native(已存在的) : fs.realpathSync(已存在的)
    return path.resolve(真父, ...尾巴)
  } catch {
    // 读不到真实路径时保持保守：后续仍要经过白名单，不能因为探测失败直接放行。
    return 原路径
  }
}

/** 甲的绝对路径在不在乙这个目录底下（等于乙也算） */
function 在底下吗(甲路径, 乙目录) {
  const 甲 = 真实路径(甲路径)
  const 乙 = 真实路径(乙目录)
  if (甲 === 乙) return true
  const 相对 = path.relative(乙, 甲)
  return !!相对 && !相对.startsWith('..') && !path.isAbsolute(相对)
}

/**
 * 这次写要不要问他。
 *
 * 【顺序要紧，别调换】
 *   一、先看是不是在"永远要问"的地方 —— 是就问，
 *       **别管放行清单里写了什么**。放行清单再长也压不过它：
 *       他就算手滑点过一次"记住"，记忆那儿照样问。
 *   二、再看在不在放行清单里 —— 在就不问。
 *   三、剩下的都问。
 *
 * 【为什么单独一个函数，不写进 查()】
 *   查() 管的是"能不能碰"——**硬边界**，越权直接拒，没有商量。
 *   这个管的是"要不要打招呼"——**软规矩**，可以放宽。
 *   两件事混在一起的话，将来想调"什么情况可以不问"，
 *   就得去动安全边界，那是很危险的改法。
 *
 * @param {string} 绝对路径
 * @returns {boolean} true = 要问他
 */
function 要问他吗(绝对路径) {
  if (!绝对路径) return true

  // 运行数据目录即使改了名字，也仍然属于不可永久放行的记忆范围。
  if (在底下吗(绝对路径, 配置.数据目录)) return true

  const 节 = path.resolve(绝对路径).split(path.sep)
  for (const 名 of 永远要问) {
    // 按"路径里有一层叫这个名字"来判断 —— 跟 写禁地 一个路子
    if (节.includes(名)) return true
  }

  // 默认放行的 + 他后来放行的，一起看。
  // 【顺序】永远要问 那一关在上面 —— 先过了它才轮到这儿，
  //   所以默认清单里就算哪天误加了 `记忆`，也压不过上面那一关。
  for (const 目录 of [...默认放行的目录(), ...放行的目录]) {
    if (在底下吗(绝对路径, 目录)) return false
  }

  return true
}

/** 单个文件最多读这么大 */
const 读的上限 = 200 * 1024

/** 单个文件最多写这么大（防止她一口气写个几百兆的东西） */
const 写的上限 = 2 * 1024 * 1024

/**
 * 查一个路径能不能碰。
 *
 * @param {string} 她写的   她写的路径（相对或绝对）
 * @param {'读'|'写'} 干什么
 * @param {object} [选项]  { 要新建: true } —— 写一个新文件时它还不存在，别按"不存在"拒掉
 * @returns {{好:true, 绝对路径:string} | {好:false, 原因:string}}
 */
function 查(她写的, 干什么 = '读', 选项 = {}) {
  const 原文 = String(她写的 || '').trim()
  if (!原文) return { 好: false, 原因: '路径是空的' }

  // 绝对路径直接用；相对路径按"项目根 → 工作区根"依次试
  const 候选 = path.isAbsolute(原文)
    ? [原文]
    : [path.resolve(项目根, 原文), path.resolve(工作区根, 原文)]

  const 白名单 = 干什么 === '写' ? 写白名单() : 读白名单()

  for (const 候选路径 of 候选) {
    // 规范化：把 ".." "." 都算掉，这样 "记忆\..\..\C盘" 这种会自己露馅
    const 规范 = path.resolve(候选路径)
    // 再看文件系统真正指到哪里。junction / symlink 不能靠字符串发现。
    const 真正位置 = 真实路径(规范)

    // 【第一关】必须在白名单里的某个目录下面。
    //   用 path.relative 算，不是比字符串前缀 ——
    //   前缀会误判：根是 D:\a，而 D:\ab\x 的字符串前缀也是 "D:\a"。
    //   （Cyrene 的 resolveWritePath 里也专门写了这一条。）
    const 在名单 = 白名单.some((目录) => {
      const 相对 = path.relative(真实路径(目录), 真正位置)
      return 相对 === '' || (!相对.startsWith('..') && !path.isAbsolute(相对))
    })
    if (!在名单) continue

    // 【第二关】路径里不能撞上禁地
    // 两份都查：表面路径可能写着禁地，真实路径也可能经链接落进禁地。
    const 分段 = [...规范.split(path.sep), ...真正位置.split(path.sep)].map((x) => x.toLowerCase())
    const 撞禁地 = 禁地.find((禁) => 分段.includes(禁.toLowerCase()))
    if (撞禁地) return { 好: false, 原因: `那个地方不能碰（${撞禁地}）` }

    // 【第二关半】写的时候还要多躲一层 —— 见 写禁地 的注释
    if (干什么 === '写') {
      const 基本名 = path.basename(真正位置).toLowerCase()
      const 撞写禁地 = 写禁地.find((禁) => {
        const 小写 = 禁.toLowerCase()
        // 目录名（路径里有一段叫这个）或者就是这个文件本身
        return 分段.includes(小写) || 基本名 === 小写
      })
      if (撞写禁地) {
        return {
          好: false,
          原因: `那个地方只能读不能写（${撞写禁地}）—— 他和我一起做的东西，改之前得跟他说`,
        }
      }
    }

    // 【第三关】得真的存在（写新文件的时候例外）
    if (!fs.existsSync(规范)) {
      if (干什么 === '写' && 选项.要新建) return { 好: true, 绝对路径: 真正位置 }
      continue
    }

    return { 好: true, 绝对路径: 真正位置 }
  }

  const 说法 = 干什么 === '写' ? '不能往那儿写' : '不在她能看的范围里'
  return { 好: false, 原因: `找不到这个地方，或者${说法}：${原文}` }
}

/** 给她看的一句话：她到底能碰哪儿（写进提示词） */
function 拼范围说明() {
  const 短 = (p) => {
    const 相对 = path.relative(工作区根, p)
    return 相对 && !相对.startsWith('..') ? 相对 : p
  }
  return [
    '**只能读**：' + 读白名单().map(短).join('、'),
    '**能读也能写**：' + 写白名单().map(短).join('、'),
    '**碰不到**（问也白问）：' + 禁地.join('、'),
    '（她的代码那些地方只能读不能写 —— 要改由他说了算）',
  ].join('\n')
}

