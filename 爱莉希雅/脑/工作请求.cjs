'use strict'

// 这只决定工作模式要不要先弹“整项任务确认”。真正的写入和命令仍由底层逐项确认。
// 判定刻意保守：必须明确是在查资料或读现有内容，并且不能同时出现改变电脑状态的意图。
const 改变意图 = [
  /写入|写个|写一(?:份|篇|个)|帮我写|撰写|保存|追加|覆盖|替换/,
  /新建|创建|生成|制作|导出|下载|上传|复制|移动|重命名/,
  /删除|清空|卸载|安装|更新|部署|发布|提交|发送|发给/,
  /修改|改写|改成|改一下|优化(?:这个|代码|文件|项目)|修复|调整/,
  /运行|执行|启动|关闭|编译|跑(?:一下|命令|脚本|程序)|测试(?:代码|程序|项目)/,
]

const 搜索意图 = /联网|上网|搜索|搜一下|查询|查一下|检索|查资料|天气|新闻|价格|报价|官网|最新|当前版本/
const 读取意图 = /读取|读一下|查看|看看|浏览|分析|总结|检查|审查|列出|目录|有哪些|找出|定位|对比|比较|解释|内容是什么|写了什么/

function 判断(原文) {
  const 文字 = String(原文 || '').replace(/\s+/g, ' ').trim()
  if (!文字) return { 只读: false, 类型: '', 理由: '没有明确文字目标' }
  const 改变 = 改变意图.find((规则) => 规则.test(文字))
  if (改变) return { 只读: false, 类型: '', 理由: '包含可能改变文件或系统状态的意图' }
  if (搜索意图.test(文字)) return { 只读: true, 类型: '搜索', 理由: '明确的联网或资料搜索请求' }
  if (读取意图.test(文字)) return { 只读: true, 类型: '读取', 理由: '明确的读取或分析请求' }
  return { 只读: false, 类型: '', 理由: '无法确定为纯读取或搜索' }
}

module.exports = { 判断 }
