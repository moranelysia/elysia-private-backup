/**
 * 学习进度.cjs —— 你们那本"学到哪儿了"的账
 *
 * 【它治什么】
 *   聊天和干活的记忆是"你们说过什么"；学习要的是另一件事：
 *   **他学到哪儿了**。这两样不一样 ——
 *   同一门课聊过十次，不等于他懂了十次。
 *
 *   没有这个账本的话，每开一段新对话她都得从头问一遍
 *   "你学到哪儿了"，问完还是记不住，下次再问。
 *
 * 【它长什么样】
 *   配置中学习区的 `进度.md` —— 一份**给他和她都能读**的 markdown，
 *   按课程分节。为什么不存成 json：他随时该能打开看一眼、改两笔，
 *   而 json 一改就坏。markdown 改坏了顶多是她读不懂那一段。
 *
 * 【谁在写】
 *   主要是她（每学完一段，程序让她自己记一笔，见下面 记一笔()）。
 *   他手改也完全可以 —— 她下次记的时候以文件为准，不会跟他打架。
 *
 * 【为什么这个文件是"唯一真相"】
 *   进度只存在这一个地方，不往别处抄。抄两份的话迟早对不上，
 *   而对不上的时候没人知道该信哪个。
 */
'use strict'

const fs = require('node:fs')
const path = require('node:path')

// 学习区在哪儿，只有 提示词.cjs 说了算 —— 别在这儿重写一遍路径，
// 那样将来想换地方就得改两处，而漏一处是不会报错的。
const 提示词 = require('./提示词.cjs')

const 进度文件 = path.join(提示词.学习区根, '进度.md')

/** 环境变量那个口子只给测试用 */
function 路径() {
  return process.env.ELYSIA_进度文件 || 进度文件
}

/** 文件还没有的时候，先给它一个能读的壳 */
const 空壳 = `# 学习进度

> 这份是爱莉希雅自己维护的账本。你随时可以打开看，也可以自己改两笔 ——
> 她下次记的时候以这份文件为准，不会跟你打架。

（还没有记过东西。等你们学过一段，这儿就会长出内容来。）
`

/**
 * 读进度（原始 markdown，不解析）。
 *
 * 【为什么不解析成对象再拼回去】
 *   他可能自己在这个文件里写别的东西（表格、清单、自己的记号）。
 *   解析一遍再吐出来，等于把他写的东西重排了 —— 那很讨厌。
 *   原样读、原样拼给她看，他写什么都不会被动。
 */
function 读() {
  try {
    const 内容 = fs.readFileSync(路径(), 'utf8').replace(/^\uFEFF/, '')
    return 内容.trim() ? 内容.trim() : ''
  } catch {
    return ''
  }
}

/** 文件在不在 */
function 有吗() {
  return fs.existsSync(路径())
}

/** 建一个空的（已经在了就什么都不做） */
function 建空的() {
  const 一个 = 路径()
  if (fs.existsSync(一个)) return false
  fs.mkdirSync(path.dirname(一个), { recursive: true })
  fs.writeFileSync(一个, 空壳, 'utf8')
  return true
}

/** 整个覆盖着写（记一笔的时候用） */
function 写(内容) {
  const 一个 = 路径()
  fs.mkdirSync(path.dirname(一个), { recursive: true })
  // 先写临时文件再改名 —— 写到一半断电的话，进度文件不至于变成半截的。
  // （跟 脑\没干完.cjs 里那个纸条是一个道理。）
  const 临时 = 一个 + '.正在写'
  fs.writeFileSync(临时, String(内容 || ''), 'utf8')
  fs.renameSync(临时, 一个)
  return true
}

/**
 * 拼一段"你们学到哪儿了"给她看。
 *
 * 【为什么原样贴进去，不加任何加工】
 *   她需要的是**事实**：这门课讲到哪、哪些懂了、哪些还卡着。
 *   我要是替她总结一遍，总结出来的东西就成了"程序对进度的理解"，
 *   而那玩意儿一旦跟文件不一致，她就会开始说胡话。
 *
 * 【为什么放在提示词最末尾】
 *   它比记忆变得还勤（每学一段就动一次）。放最后的话，
 *   它一动，前面那一大叠（她是谁、规矩）的缓存照样能用。
 */
function 拼给她() {
  const 内容 = 读()
  if (!内容) return ''
  return [
    '===== 你们的学习进度（她自己维护的账本）=====',
    '',
    内容,
    '',
    '上面这些是**你们已经走过的路**：他学到哪儿了、哪些懂了、哪些还卡着。',
    '接着往下讲之前先看一眼 —— 别把讲过的当没讲过，',
    '也别从他还没弄明白的地方往前跳。',
    '',
    '这份账本在：' + 路径(),
    '（学完一段该记的时候，程序会提醒你更新它。）',
    '',
  ].join('\n')
}

// ============================================================
// 认账本的"节"（每一门课是一个 ## 标题）
// ============================================================

/** 账本里已经有哪些课（就是所有二级标题） */
function 课程们(内容) {
  const 原文 = 内容 === undefined ? 读() : String(内容 || '')
  const 名们 = []
  for (const 行 of 原文.split('\n')) {
    if (/^##\s+/.test(行)) {
      const 名 = 行.replace(/^##\s+/, '').trim()
      if (名 && !名们.includes(名)) 名们.push(名)
    }
  }
  return 名们
}

/**
 * 找到某一门课那一节在原文里的起止位置（字符下标）。
 * 一节 = 从它的 `## 名字` 开始，到下一个 `## ` 或者文件结尾。
 * @returns {{起:number, 止:number}|null}
 */
function 找一节(内容, 课程名) {
  const 原文 = String(内容 || '')
  const 名 = String(课程名 || '').trim()
  if (!名) return null

  const 行们 = 原文.split('\n')
  let 起 = -1
  let 止 = -1
  let 位置 = 0

  for (const 行 of 行们) {
    if (/^##\s+/.test(行)) {
      if (起 >= 0) {
        止 = 位置 // 撞见下一个二级标题了，上一节到这儿为止
        break
      }
      if (行.replace(/^##\s+/, '').trim() === 名) 起 = 位置
    }
    位置 += 行.length + 1 // +1 是那个换行符
  }

  if (起 < 0) return null
  if (止 < 0) 止 = 原文.length
  return { 起, 止 }
}

/**
 * 只有这种完整的项目符号行才算结构化字段。
 * 自由 markdown 里哪怕写了“下一步我想……”，也不会被界面误当成状态。
 * `现在到` 是旧名字，只读兼容；以后写回统一使用更清楚的 `当前章节`。
 */
const 字段别名 = {
  当前章节: '当前章节',
  现在到: '当前章节',
  已经弄明白的: '已经弄明白的',
  还没弄明白的: '还没弄明白的',
  下一步: '下一步',
  复习时间: '复习时间',
  上次动过: '上次动过',
}

function 认字段行(行) {
  const 命中 = String(行 || '').match(/^\s*[-*]\s*([^：:]+?)\s*[：:]\s*(.*?)\s*$/)
  if (!命中) return null
  const 名 = 字段别名[命中[1].trim()]
  return 名 ? { 名, 值: 命中[2].trim() } : null
}

/** 只从固定字段行取值；其余 markdown 一个字都不解释。后写的同名字段优先。 */
function 读一节的字段(一节) {
  const 字段 = {}
  let 有固定字段 = false
  for (const 行 of String(一节 || '').split('\n')) {
    const 一个 = 认字段行(行)
    if (!一个) continue
    有固定字段 = true
    字段[一个.名] = 一个.值
  }
  return { 字段, 有固定字段 }
}

/**
 * 给界面用的四项状态。
 * 多门课时先选 `上次动过` 最新的一节；都没有时间就选文件里靠后的结构化课程。
 * 没有结构化课程时四项全空，界面显示“还没定”，绝不从自由文字猜。
 */
function 四项状态(内容) {
  const 原文 = 内容 === undefined ? 读() : String(内容 || '')
  let 当前 = null

  for (const 课程 of 课程们(原文)) {
    const 位置 = 找一节(原文, 课程)
    if (!位置) continue
    const 读到的 = 读一节的字段(原文.slice(位置.起, 位置.止))
    if (!读到的.有固定字段) continue

    const 候选 = { 课程, ...读到的.字段 }
    if (!当前) {
      当前 = 候选
      continue
    }

    const 候选时间 = 候选.上次动过 || ''
    const 当前时间 = 当前.上次动过 || ''
    if ((候选时间 && !当前时间) || (候选时间 && 当前时间 && 候选时间 >= 当前时间)) 当前 = 候选
    else if (!候选时间 && !当前时间) 当前 = 候选
  }

  return {
    课程: (当前 && 当前.课程) || '',
    当前章节: (当前 && 当前.当前章节) || '',
    下一步: (当前 && 当前.下一步) || '',
    复习时间: (当前 && 当前.复习时间) || '',
  }
}

/**
 * 把一次记账的结果并进账本。
 *
 * 【为什么只并"那一门课"，不让她重写整个文件】
 *   她自己手写的东西（表格、清单、自己的记号、别的课）一个字都不该被动。
 *   所以已有课程不再整节替换，只改固定字段行；缺的字段追加在这一节末尾。
 *
 * @param {{有进展:boolean, 课程:string, 当前章节?:string, 现在到?:string,
 *          已经弄明白的:string, 还没弄明白的:string, 下一步:string, 复习时间?:string}} 增量
 * @returns {{改了:boolean, 课程?:string, 说明?:string}}
 */
function 并进去(增量) {
  if (!增量 || !增量.有进展) return { 改了: false, 说明: '这一轮没什么可记的' }

  const 课程 = String(增量.课程 || '').trim()
  if (!课程) return { 改了: false, 说明: '她没说这是哪门课' }

  const 现在 = 读() || 空壳
  const 日期 = 现在几点()
  const 新值 = {
    当前章节: 一行(增量['当前章节'] || 增量['现在到']),
    已经弄明白的: 一行(增量['已经弄明白的']),
    还没弄明白的: 一行(增量['还没弄明白的']),
    下一步: 一行(增量['下一步']),
    复习时间: 一行(增量['复习时间']),
    上次动过: 日期,
  }
  const 顺序 = ['当前章节', '已经弄明白的', '还没弄明白的', '下一步', '复习时间', '上次动过']

  const 一节 = 找一节(现在, 课程)

  if (!一节) {
    // 账本里还没有这门课 —— 新起一节，接在最后
    // 末尾那两个空字符串是故意的：join 完会得到 "……上次动过：xxx\n\n"，
    // 也就是**跟下一节之间留一个空行**。少写一个的话，
    // 我们那行会直接顶着下一个 `##`，markdown 读起来是粘的。
    const 我们那几行 = 顺序.map((名) => `- ${名}：${新值[名]}`)
    const 新节 = [`## ${课程}`, '', ...我们那几行, '', ''].join('\n')
    return { 改了: 写(现在.replace(/\s*$/, '') + '\n\n' + 新节), 课程 }
  }

  const 旧的 = 现在.slice(一节.起, 一节.止)
  const 旧字段 = 读一节的字段(旧的).字段
  // 复习时间经常是他手定的。模型这次没明确给，就保留原值，不能顺手清空。
  if (!新值.复习时间) 新值.复习时间 = 旧字段.复习时间 || ''

  const 已写 = new Set()
  const 保留下来的行 = []
  for (const 行 of 旧的.split('\n')) {
    const 一个 = 认字段行(行)
    if (!一个) {
      保留下来的行.push(行)
      continue
    }
    if (已写.has(一个.名)) continue
    保留下来的行.push(`- ${一个.名}：${新值[一个.名]}`)
    已写.add(一个.名)
  }

  const 缺的 = 顺序.filter((名) => !已写.has(名)).map((名) => `- ${名}：${新值[名]}`)
  let 新节 = 保留下来的行.join('\n').replace(/\s*$/, '')
  if (缺的.length) 新节 += '\n\n' + 缺的.join('\n')
  新节 += '\n\n'

  return { 改了: 写(现在.slice(0, 一节.起) + 新节 + 现在.slice(一节.止)), 课程 }
}

/** 去掉换行、两头空白，再砍到 200 字 —— 账本不是聊天记录，一行就得说完 */
function 一行(东西) {
  const 字 = String(东西 == null ? '' : 东西).replace(/\s+/g, ' ').trim()
  return 字.length > 200 ? 字.slice(0, 200) + '…' : 字
}

function 现在几点() {
  const d = new Date()
  const 补 = (n) => String(n).padStart(2, '0')
  return `${d.getFullYear()}-${补(d.getMonth() + 1)}-${补(d.getDate())} ${补(d.getHours())}:${补(d.getMinutes())}`
}

