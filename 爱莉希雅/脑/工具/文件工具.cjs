async function 读(路径) {
  const 查过 = 路径安全.查(路径, '读')
  if (!查过.好) return { 好: false, 说明: 查过.原因 }

  let 状态
  try {
    状态 = fs.statSync(查过.绝对路径)
  } catch (错误) {
    return { 好: false, 说明: '读不到：' + 错误.message }
  }

  if (状态.isDirectory()) {
    return { 好: false, 说明: '那是个目录，不是文件。想看里面有什么就用 [列:那个目录]' }
  }

  if (状态.size > 路径安全.读的上限) {
    return {
      好: false,
      说明:
        `那个文件太大了（${Math.round(状态.size / 1024)} KB，上限 ` +
        `${路径安全.读的上限 / 1024} KB）—— 换个小的，或者跟我说你要看哪一段`,
    }
  }

  let 内容
  try {
    内容 = fs.readFileSync(查过.绝对路径, 'utf8')
  } catch (错误) {
    return { 好: false, 说明: '读不出来（可能是二进制文件）：' + 错误.message }
  }

  // 太长的话头尾各留一段，中间省掉 —— 全塞进去会烧掉一大堆 token
  const 封顶 = 读取字符上限
  let 给 = 内容
  const 已截断 = 内容.length > 封顶
  if (已截断) {
    const 头 = 内容.slice(0, 封顶 * 0.7)
    const 尾 = 内容.slice(-封顶 * 0.3)
    给 = `${头}\n\n……（中间省掉 ${内容.length - 封顶} 个字）……\n\n${尾}`
  }

  const 时间 = new Date().toISOString()
  const 范围说明 = 已截断
    ? `只返回头部 ${Math.round(封顶 * 0.7)} 字和尾部 ${Math.round(封顶 * 0.3)} 字，中间省略 ${内容.length - 封顶} 字`
    : `完整读取 ${内容.length} 字`

  return {
    好: true,
    内容:
      `文件 ${说路径(查过.绝对路径)} 的内容：\n\n` +
      (已截断 ? `⚠ 这不是全文：${范围说明}。不要对省略部分下结论。\n\n` : '') +
      给,
    说明: 范围说明,
    字节: 状态.size,
    路径: 查过.绝对路径,
    读取范围: { 类型: 已截断 ? '头尾摘取' : '全文', 原始字符: 内容.length, 返回字符: 已截断 ? 封顶 : 内容.length },
    执行状态: '成功',
    验证状态: 已截断 ? '部分验证' : '已验证',
    目标完成: 已截断 ? '部分' : '是',
    截断: { 有: 已截断, 原始量: 内容.length, 保留量: 已截断 ? 封顶 : 内容.length },
    证据: [{ 类型: '文件读取', 目标: 查过.绝对路径, 说明: `${范围说明}；${状态.size} 字节`, 来源: 查过.绝对路径, 时间 }],
    来源: [查过.绝对路径],
  }
}

