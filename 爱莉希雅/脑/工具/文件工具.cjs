/**
 * 在一个目录里搜文字。
 *
 * 【为什么这个工具很重要】
 *   她的记忆散在好几个文件里（事实、经历、小本子、聊天记录、共同经历……）。
 *   要回答"我第一次编程序是哪天"，她得先知道"这事记在哪个文件里"。
 *   [读:] 只能读她猜中的那个；[找:] 是让程序替她翻。
 *
 * 参数写法：[找:要搜的话]  或  [找:要搜的话|目录]
 */
async function 找(参数) {
  const 原文 = String(参数 || '').trim()
  if (!原文) return { 好: false, 说明: '没给要搜的话' }

  const [要找的, 目录参数] = 原文.split('|').map((x) => x.trim())
  if (!要找的) return { 好: false, 说明: '没给要搜的话' }
  const 目录 = 目录参数 || '.'
  const 查过 = 路径安全.查(目录, '读')
  if (!查过.好) return { 好: false, 说明: 查过.原因 }

  const 结果 = []
  let 看过 = 0
  let 跳过大文件 = 0
  let 读失败 = 0
  let 文件上限触发 = false
  let 命中上限触发 = false

  /** 递归翻 */
  function 翻(当前) {
    if (看过 >= 搜索文件上限) {
      文件上限触发 = true
      return
    }
    if (结果.length >= 搜索命中上限) {
      命中上限触发 = true
      return
    }
    let 项们
    try {
      项们 = fs.readdirSync(当前, { withFileTypes: true })
    } catch {
      return
    }
    for (const 项 of 项们) {
      if (结果.length >= 搜索命中上限) {
        命中上限触发 = true
        return
      }
      if (看过 >= 搜索文件上限) {
        文件上限触发 = true
        return
      }
      if (路径安全.禁地.includes(项.name)) continue
      const 全 = path.join(当前, 项.name)

      if (项.isDirectory()) {
        翻(全)
        continue
      }
      // 只看文本类的文件
      if (!/\.(md|json|jsonl|txt|js|cjs|mjs|ts|html|css|yml|yaml|log)$/i.test(项.name)) continue
      try {
        if (fs.statSync(全).size > 搜索单文件上限) {
          跳过大文件++
          continue
        }
      } catch {
        读失败++
        continue
      }

      看过++
      let 内容
      try {
        内容 = fs.readFileSync(全, 'utf8')
      } catch {
        读失败++
        continue
      }
      const 行们 = 内容.split('\n')
      for (const [i, 行] of 行们.entries()) {
        if (行.includes(要找的)) {
          结果.push(`${说路径(全)}:${i + 1}  ${行.trim().slice(0, 100)}`)
          if (结果.length >= 搜索命中上限) {
            命中上限触发 = true
            break
          }
        }
      }
    }
  }

  let 状态
  try {
    状态 = fs.statSync(查过.绝对路径)
  } catch (错误) {
    return { 好: false, 说明: '搜索前无法读取目标状态：' + 错误.message }
  }
  if (状态.isDirectory()) 翻(查过.绝对路径)
  else {
    // 直接给的是文件，就在它里面搜
    if (状态.size > 搜索单文件上限) {
      return {
        好: false,
        说明: `目标文件太大，未搜索（${Math.round(状态.size / 1024)} KB，上限 ${搜索单文件上限 / 1024} KB）`,
      }
    }
    let 内容
    try {
      内容 = fs.readFileSync(查过.绝对路径, 'utf8')
    } catch (错误) {
      return { 好: false, 说明: '目标文件读不出来：' + 错误.message }
    }
    看过 = 1
    for (const [i, 行] of 内容.split('\n').entries()) {
      if (行.includes(要找的)) {
        结果.push(`${说路径(查过.绝对路径)}:${i + 1}  ${行.trim().slice(0, 100)}`)
        if (结果.length >= 搜索命中上限) {
          命中上限触发 = true
          break
        }
      }
    }
  }

  const 截断原因 = []
  if (命中上限触发) 截断原因.push(`命中达到 ${搜索命中上限} 条上限`)
  if (文件上限触发) 截断原因.push(`已检查文件达到 ${搜索文件上限} 个上限`)
  if (跳过大文件) 截断原因.push(`跳过 ${跳过大文件} 个超过 ${搜索单文件上限 / 1024} KB 的文件`)
  if (读失败) 截断原因.push(`${读失败} 个文件无法读取`)
  const 已截断 = 截断原因.length > 0
  const 范围说明 = 已截断
    ? `搜索不完整：${截断原因.join('；')}`
    : `已完整搜索支持的文本范围，共检查 ${看过} 个文件`
  const 时间 = new Date().toISOString()
  const 共同 = {
    好: true,
    说明: 范围说明,
    路径: 查过.绝对路径,
    处数: 结果.length,
    看过文件: 看过,
    执行状态: '成功',
    验证状态: 已截断 ? '部分验证' : '已验证',
    目标完成: 已截断 ? '部分' : '是',
    截断: { 有: 已截断, 原始量: 已截断 ? Math.max(结果.length, 搜索命中上限) : 结果.length, 保留量: 结果.length },
    证据: [{ 类型: '文件搜索', 目标: 查过.绝对路径, 说明: `${范围说明}；找到 ${结果.length} 处`, 来源: 查过.绝对路径, 时间 }],
    来源: [查过.绝对路径],
  }

  if (!结果.length) {
    return {
      ...共同,
      内容: 已截断
        ? `在已检查范围内没找到「${要找的}」。（${范围说明}）不能断言其余范围也没有。`
        : `完整搜索后没找到「${要找的}」。（看过 ${看过} 个文件）`,
    }
  }
  return {
    ...共同,
    内容:
      `找到 ${结果.length} 处提到「${要找的}」：\n\n${结果.join('\n')}` +
      (已截断 ? `\n\n⚠ ${范围说明}，这些不是全部结果。` : ''),
  }
}

