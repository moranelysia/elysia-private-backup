/** 覆盖写之前的"骤降检查"（照搬 Cyrene 的判定） */
const 骤降_最少行数 = 50
const 骤降_比例下限 = 0.5

function 数行数(文本) {
  if (!文本) return 0
  const 行们 = String(文本).replace(/\r\n/g, '\n').split('\n')
  return 行们[行们.length - 1] === '' ? 行们.length - 1 : 行们.length
}

function 查骤降(原内容, 新内容) {
  const 原行 = 数行数(原内容)
  const 新行 = 数行数(新内容)
  const 比例 = 原行 > 0 ? 新行 / 原行 : 1
  return {
    拦: 原行 >= 骤降_最少行数 && 比例 < 骤降_比例下限,
    原行,
    新行,
    比例,
  }
}

function 指纹(字节) {
  return crypto.createHash('sha256').update(字节).digest('hex')
}

/** 写完后从磁盘重新读取，逐字节确认实际文件就是预期结果。 */
function 核对写入(绝对路径, 预期内容, 选项 = {}) {
  const 读文件 = typeof 选项.读文件 === 'function' ? 选项.读文件 : (路径) => fs.readFileSync(路径)
  const 预期 = Buffer.from(String(预期内容 == null ? '' : 预期内容), 'utf8')
  const 时间 = new Date().toISOString()
  let 实际
  try {
    const 读到的 = 读文件(绝对路径)
    实际 = Buffer.isBuffer(读到的) ? 读到的 : Buffer.from(读到的)
  } catch (错误) {
    return {
      通过: false,
      验证状态: '未验证',
      目标完成: '未知',
      错误类别: '写后验证失败',
      验证说明: '文件已经执行写入，但重新读取失败：' + 错误.message,
      证据: [{ 类型: '写后重读', 目标: 绝对路径, 说明: '重新读取失败，无法确认磁盘内容', 来源: 绝对路径, 时间 }],
      来源: [绝对路径],
      可重试: true,
    }
  }

  const 预期指纹 = 指纹(预期)
  const 实际指纹 = 指纹(实际)
  const 一致 = 预期.length === 实际.length && 预期.equals(实际)
  const 说明 = 一致
    ? `重新读取 ${实际.length} 字节并逐字节核对一致；SHA-256 ${实际指纹}`
    : `写后内容不一致：预期 ${预期.length} 字节，实际 ${实际.length} 字节；` +
      `预期 SHA-256 ${预期指纹}，实际 SHA-256 ${实际指纹}`
  return {
    通过: 一致,
    验证状态: 一致 ? '已验证' : '未验证',
    目标完成: 一致 ? '是' : '否',
    错误类别: 一致 ? '' : '写后内容不符',
    验证说明: 说明,
    证据: [{ 类型: '写后重读', 目标: 绝对路径, 说明, 来源: 绝对路径, 时间 }],
    来源: [绝对路径],
    可重试: !一致,
    实际大小: 实际.length,
    SHA256: 实际指纹,
  }
}

/**
 * 写一个文件。
 *
 * @param {string} 路径参数  她写的路径；末尾带 ! 表示覆盖，否则追加
 * @param {string} 内容
 * @param {object} [选项]  { 允许覆盖: true } —— 用户已经在界面上点过确认了
 */
async function 写(路径参数, 内容, 选项 = {}) {
  const 原文 = String(路径参数 || '').trim()
  if (!原文) return { 好: false, 说明: '没给路径' }

  // 末尾的 ! 表示"整个替换掉"
  const 要覆盖 = 原文.endsWith('!')
  const 干净路径 = 要覆盖 ? 原文.slice(0, -1).trim() : 原文

  let 文本 = typeof 内容 === 'string' ? 内容 : ''
  if (!文本) return { 好: false, 说明: '没给要写的内容（内容要放在标记下面的代码块里）' }

  let 字节 = Buffer.byteLength(文本, 'utf8')
  if (字节 > 路径安全.写的上限) {
    return {
      好: false,
      说明: `写的东西太大了（${Math.round(字节 / 1024)} KB，上限 ${路径安全.写的上限 / 1024} KB）`,
    }
  }

  const 查过 = 路径安全.查(干净路径, '写', { 要新建: true })
  if (!查过.好) return { 好: false, 说明: 查过.原因 }

  const 存在 = fs.existsSync(查过.绝对路径)
  const 显示路径 = 说路径(查过.绝对路径)

  // ---- 工程活儿：先让"工程师"过一遍 ----
  //
  // 【为什么要多这一道手（2026-10-01 深夜想通的）】
  //   "工作就是工作，把回答和工作内容分开算"落地时漏了一半：
  //   低温那一层（脑\生成内容.cjs）**写好了，却没有任何人调它** ——
  //   真正干活时走的是她回复里的代码块，那是**说话的温度（0.8）**，
  //   而她那时候脑子里还在想着怎么跟他讲话。
  //
  //   所以草稿往往思路对、细节毛糙：缺个 #include、把窗口尺寸写成 80x25、
  //   留一句"这里以后再补"。这些跟"像不像她"没关系，是纯工程问题。
  //
  // 【为什么只放代码过去，不放散文】
  //   日记、笔记、写给他的信 —— 那些**就该**是她的口吻，
  //   扔给一个低温工程师去"修正"是糟蹋东西。界线见 生成内容.是代码文件()。
  //
  // 【为什么追加到已有文件时不过手】
  //   追加的常常是一个片段（往配置里补几行），没有"整份文件"可言，
  //   重写反而会把上下文搞丢。
  //
  // 【为什么失败也得往下走】
  //   连不上模型就退回草稿 —— 宁可交一份毛糙但完整的，也不要因为
  //   "润色失败"害她白写一遍。
  let 过手说明 = ''
  if (选项.过工程师 && 生成内容.是代码文件(查过.绝对路径) && (要覆盖 || !存在)) {
    let 机器情况 = ''
    try {
      机器情况 = 命令工具.环境说明()
    } catch {
      /* 问不到就算了，不是必须的 */
    }

    const 过手 = await 生成内容.过工程师的手({
      要写什么: 选项.他说的话 || `把这份草稿整理成能用的最终版：${显示路径}`,
      路径: 查过.绝对路径,
      草稿: 文本,
      要求: 选项.要求 || '',
      机器情况,
    })

    if (过手.过手了 && 过手.内容 && 过手.内容.trim()) {
      文本 = 过手.内容
      字节 = Buffer.byteLength(文本, 'utf8')
      过手说明 = 过手.说明
    } else {
      // 润色没成 —— 用草稿照写，但把原因留个底，别让人以为是"本来就该这样"
      过手说明 = 过手.说明 || '工程师那一趟没走通'
      console.log('  ⚠ ' + 过手说明)
    }
  }

  // 工程师可能写长了，得再量一次
  if (字节 > 路径安全.写的上限) {
    return {
      好: false,
      说明: `写的东西太大了（${Math.round(字节 / 1024)} KB，上限 ${路径安全.写的上限 / 1024} KB）`,
    }
  }

  // ---- 已有的文件：走覆盖的那套检查 ----
  let 原内容 = null
  if (存在) {
    try {
      原内容 = fs.readFileSync(查过.绝对路径, 'utf8')
    } catch (错误) {
      // 照搬 Cyrene：读不出来就**拒绝覆盖**，不硬写
      return { 好: false, 说明: '那个文件读不出来，为了不弄坏它，这次不写了：' + 错误.message }
    }

    if (要覆盖) {
      const 骤降 = 查骤降(原内容, 文本)
      if (骤降.拦) {
        return {
          好: false,
          说明:
            `覆盖被拦下来了：原来 ${骤降.原行} 行，你现在只写了 ${骤降.新行} 行` +
            `（${Math.round(骤降.比例 * 100)}%），像是不小心截断了。\n` +
            '要是真想整个重写，把整篇内容都给全；要是只想改一处，' +
            '先 [读:] 出来、改好、再整篇覆盖。',
        }
      }
    }
  }

  // ---- 要不要问他 ----
  //
  // 【三段判断，2026-10-07 改过】
  //   1. 追加到已有文件 → **不问**（追加毁不掉已有内容，这是原来就有的规矩）
  //   2. 新建 / 覆盖 → 交给 路径安全.要问他吗()：
  //        · 在"永远要问"的地方（`记忆\`）→ 问
  //        · 在他放行过的目录里           → 不问
  //        · 其余                         → 问
  //   3. 调用方说"他已经同意了"（选项.允许覆盖）→ 一律不问
  //
  //   【为什么第 2 步要交给 路径安全】
  //     "要不要打招呼"和"能不能写"是两件事，理由见那边 要问他吗() 上面那段。
  //
  //   【为什么原来那行必须改】
  //     原来是 `要覆盖 || !存在` —— 等于"除了追加，一律问"。
  //     于是她写五个文件他得点五次。他的原话是
  //     "明明就是写一个文件却还要我同意"。
  const 本来要问 = 要覆盖 || !存在
  const 因为放行而不问 = 本来要问 && !路径安全.要问他吗(查过.绝对路径)
  const 要问 = !选项.允许覆盖 && 本来要问 && !因为放行而不问

  if (因为放行而不问 && !选项.允许覆盖) {
    // 【为什么不吭声也要留个痕】"不用问了"是他要的，但"她悄悄改了什么"
    //   不该是完全看不见的。至少终端里得有这一行 ——
    //   哪天真出了事，回头能查"那次到底是谁批的"。
    console.log(`  · 直接写了（这个目录他放行过）：${显示路径}`)
  }

  if (要问 && typeof 选项.问 === 'function') {
    const 答复 = await 选项.问({
      类型: 要覆盖 ? '覆盖' : '新建',
      路径: 显示路径,
      绝对路径: 查过.绝对路径, // ← "记住这个文件夹"要用它，别删
      内容: 文本,
      原内容,
      字节,
    })
    // 【答复可能是对象，也可能是 true / false】
    //   确认.cjs 现在给的是 { 同意, 记住 }（2026-10-07 改的），
    //   但测试脚本、以及将来别的调用方可能还是直接给 true / false。
    //   **两种都认** —— 不认的话，一个"返 true"的调用方会被当成"他不同意"，
    //   而那种错看起来就像他真的点了拒绝，查起来要命。
    //
    //   （这一条是踩出来的：改完当天，测写文件 / 测整条线 / 测工程师过手
    //     三套全在报"他不同意这次写入"，而他压根没被问过。）
    const 同意了 = 答复 === true || (答复 && 答复.同意 === true)
    if (!同意了) return { 好: false, 说明: '他不同意这次写入。', 被拒绝: true }
  } else if (要问 && 选项.问 === undefined) {
    // 没给他问的机会 —— 这种情况宁可不错
    return {
      好: false,
      说明: `${要覆盖 ? '覆盖' : '新建'}文件要经过他同意，但现在没有问他的办法，所以这次不写了。`,
      需要确认: { 类型: 要覆盖 ? '覆盖' : '新建', 路径: 显示路径, 内容: 文本 },
    }
  }

  // ---- 落盘 ----
  // 先算出写完以后整个文件应当长什么样。验证时比较的是最终文件，
  // 不是只看这次追加的片段是否出现，避免重复、错位或漏换行也被算成功。
  let 预期内容 = 文本
  if (!要覆盖 && 存在 && 原内容 !== null) {
    预期内容 = 原内容 + (原内容.length > 0 && !原内容.endsWith('\n') ? '\n' : '') + 文本
  }
  try {
    // 追加的时候：原文件末尾没有换行就先补一个，免得两段内容粘在一行
    if (!要覆盖 && 存在 && 原内容 !== null && 原内容.length > 0 && !原内容.endsWith('\n')) {
      fs.appendFileSync(查过.绝对路径, '\n' + 文本, 'utf8')
    } else if (!要覆盖 && 存在) {
      fs.appendFileSync(查过.绝对路径, 文本, 'utf8')
    } else {
      fs.mkdirSync(path.dirname(查过.绝对路径), { recursive: true })
      fs.writeFileSync(查过.绝对路径, 文本, 'utf8')
    }
  } catch (错误) {
    return { 好: false, 说明: '写不进去：' + 错误.message }
  }

  const 动作 = !存在 ? '新建了' : 要覆盖 ? '整个重写了' : '追加到末尾了'
  const 核对 = 核对写入(查过.绝对路径, 预期内容)
  const 新大小 = Number(核对.实际大小) || Buffer.byteLength(预期内容, 'utf8')
  const 基本说明 =
    `${动作} ${显示路径}（写了 ${字节} 个字节，现在整个文件 ${Math.round(新大小 / 1024)} KB）` +
    (过手说明 ? `\n（${过手说明}）` : '')

  if (!核对.通过) {
    return {
      好: true,
      执行状态: '成功',
      内容: `${基本说明}\n⚠ 写入后核对没有通过：${核对.验证说明}`,
      说明: 核对.验证说明,
      路径: 查过.绝对路径,
      动作,
      ...核对,
    }
  }
  return {
    好: true,
    内容: `${基本说明}\n（已重新读取并逐字节核对；该文件会自动进入右侧“文件”栏，无需再交付）`,
    路径: 查过.绝对路径,
    动作,
    ...核对,
  }
}

/**
 * 把已经存在的最终文件登记成“交付物”。
 *
 * Word / PPT / Excel 往往由脚本生成：写工具只看得到脚本，真正的文档是跑命令后才出现。
 * 这一步不改文件，只验明它确实存在且在可读范围内，再把绝对路径交给文件侧栏。
 */
function 交付(路径参数) {
  const 查过 = 路径安全.查(String(路径参数 || '').trim(), '读')
  if (!查过.好) return { 好: false, 说明: 查过.原因 }
  try {
    const 状态 = fs.statSync(查过.绝对路径)
    if (!状态.isFile()) return { 好: false, 说明: '要交付的是文件，不是目录' }
    return {
      好: true,
      内容: `已把 ${说路径(查过.绝对路径)} 放进右侧文件栏（${Math.round(状态.size / 1024)} KB）`,
      路径: 查过.绝对路径,
      动作: '交付',
    }
  } catch (错误) {
    return { 好: false, 说明: '交付文件不存在或读不到：' + 错误.message }
  }
}

