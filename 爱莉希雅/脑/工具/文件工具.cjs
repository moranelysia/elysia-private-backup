/**
 * 文件工具.cjs —— 读、列、找、写
 *
 * 【写的部分最要紧，说清楚】
 *   她写文件有两种：
 *     追加（默认）  [写:记忆\小本子.md]  —— 加在末尾，**不会毁掉原来的内容**
 *     覆盖          [写:路径!]          —— 整个替换掉（路径后面加感叹号）
 *
 *   覆盖之前会做一道"骤降检查"，这条是照搬 Cyrene 的：
 *     原文件 ≥ 50 行 且 新内容不到原来的一半  →  拒绝写，文件保持原样
 *   它的原话是这么说的：「弱模型在长上下文 + 多工具场景下，可能生成被截断的
 *   content 后仍然发起覆盖写，把既有大文件毁成半篇。」
 *   小文件不拦 —— 10 行的笔记整理成 4 行是正常的。
 *
 * 【还有一个细节也是照搬的】
 *   追加的时候，原文件末尾没有换行就先补一个 —— 不然两段内容会粘在同一行。
 */
