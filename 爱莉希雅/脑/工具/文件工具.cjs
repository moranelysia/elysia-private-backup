async function 列(路径) {
  const 查过 = 路径安全.查(路径, '读')
  if (!查过.好) return { 好: false, 说明: 查过.原因 }

  let 项们
  try {
    项们 = fs.readdirSync(查过.绝对路径, { withFileTypes: true })
  } catch (错误) {
    return { 好: false, 说明: '列不出来：' + 错误.message }
  }

  const 行 = []
  let 藏了几个 = 0
  const 显示项们 = 项们.slice(0, 目录显示上限)
  for (const 项 of 显示项们) {
    let 尾巴 = ''
    if (项.isFile()) {
      try {
        尾巴 = `  ${Math.round(fs.statSync(path.join(查过.绝对路径, 项.name)).size / 1024)} KB`
      } catch {
        /* 读不到大小就算了 */
      }
    }

    // 【禁地里的东西要**列出来**，只是标一句"碰不到" —— 2026-10-04 改的】
    //
    //   原来这一行是 `if (禁地.includes(项.name)) continue` —— 直接跳过。
    //   看着挺谨慎，实际闯了祸：他让她去看 cyrene-源码 是什么，
    //   小助手 [列:] 了工作区根，**清单里没有那个目录**，
    //   于是它回去报"那儿压根没有这个文件夹" —— 她就这么跟他说的。
    //
    //   而那个目录一直都在。**清单说自己在列目录，却没列全，还不打招呼。**
    //   一张缺了东西的清单比没有清单更坏：没有清单她会去问，
    //   缺了东西的清单她会**据此下结论**。
    //
    //   所以改成：名字照列，后面挂一句它为什么碰不到。
    //   这样她至少知道"那儿有这个东西，只是我够不着"，
    //   而不是"那儿什么都没有"。名字本身不是秘密（钥匙文件的内容才是）。
    const 碰不到 = 路径安全.禁地.includes(项.name)
    if (碰不到) 藏了几个++

    行.push(
      (项.isDirectory() ? '[目录] ' : '       ') +
        项.name +
        尾巴 +
        (碰不到 ? '   ← 这个她碰不到（要看得问他）' : ''),
    )
  }

  const 已截断 = 项们.length > 显示项们.length
  const 范围说明 = 已截断
    ? `目录共有 ${项们.length} 项，只显示前 ${显示项们.length} 项`
    : `完整列出 ${项们.length} 项`
  const 时间 = new Date().toISOString()

  return {
    好: true,
    内容:
      `${说路径(查过.绝对路径)} 里有这些：\n\n${行.join('\n')}` +
      (藏了几个 ? `\n\n（显示范围内有 ${藏了几个} 样她碰不到，已经标出来了 —— **别当成"没有"**。）` : '') +
      (已截断 ? `\n\n⚠ ${范围说明}，不能据此断言未显示的项目不存在。` : ''),
    说明: 范围说明,
    个数: 项们.length,
    显示个数: 行.length,
    路径: 查过.绝对路径,
    执行状态: '成功',
    验证状态: 已截断 ? '部分验证' : '已验证',
    目标完成: 已截断 ? '部分' : '是',
    截断: { 有: 已截断, 原始量: 项们.length, 保留量: 行.length },
    证据: [{ 类型: '目录清单', 目标: 查过.绝对路径, 说明: 范围说明, 来源: 查过.绝对路径, 时间 }],
    来源: [查过.绝对路径],
  }
}

