/**
 * 命令工具.cjs —— 跑命令（最大的那个口子，所以要最小心）
 *
 * 【为什么它最危险】
 *   一条命令能干任何事：删文件、改注册表、下载东西、发邮件。
 *   别的工具再怎么出格，也只在"读/写某个文件"这个范围里；
 *   run_shell 没有范围。
 *
 *   所以这个工具的设计原则跟别的不一样：
 *     · **永远要问他**，不给"一直允许"这个选项
 *     · 有超时（跑飞了的命令不能一直挂着）
 *     · 有输出上限（防止一条命令吐几百兆把对话撑爆）
 *     · 工作目录固定在她自己的文件夹（不是随便是哪儿）
 *
 *   （Cyrene 那边所有档位都放行 shell，因为底下有沙箱兜。
 *     我们没有沙箱 —— 所以这里就用"每次都问"当那道网。）
 *
 * 【她拿它干什么】
 *   做 PPT / Word / Excel 就是走这条路：
 *     先 [写:工作区\做个PPT.py] 写一个 python 脚本，
 *     再 [跑:python 做个PPT.py]，脚本里用 python-pptx 生成 .pptx。
 *   （他机器上 python-pptx 和 Pillow 已经装好了。）
 */
'use strict'

const { execFile } = require('node:child_process')
const fs = require('node:fs')
const path = require('node:path')
const 配置 = require('../配置.cjs')
const 路径安全 = require('../路径安全.cjs')

let 项目根 = 配置.项目根
let 工作区根 = 配置.工作区根

/**
 * 命令默认在哪儿跑。
 *
 * 【原来是 项目根（她自己的文件夹），2026-10-01 晚上改掉的】
 *   他在界面上选了"干活目录"（比如工作区里的 `_onepass-test`），
 *   她也确实把文件写在那儿了 —— 可 `[跑:...]` 一执行，人还站在
 *   `爱莉希雅\` 里。于是 `gcc stars.c` 找不到 stars.c，她只好去写
 *   一长串绝对路径，而**绝对路径正好踩中 gcc 那个中文的坑**。
 *
 *   把默认目录挪到他选的那个，她就自然写 `gcc stars.c -o stars.exe` ——
 *   又短，又正好避开那个坑。等于顺手治了两个毛病。
 */
let 干活目录 = 项目根

function 注册(选项 = {}) {
  if (选项.项目根) 项目根 = 选项.项目根
  if (选项.工作区根) 工作区根 = 选项.工作区根
  if (选项.干活目录) 干活目录 = 选项.干活目录
}

/** 一条命令最多跑这么久 */
const 超时毫秒 = 60 * 1000

/** 最多回多少输出（超了截断，免得撑爆对话） */
const 输出上限 = 30000

/** 一条命令最长多少字（防止她写一篇论文当命令） */
const 命令上限 = 2000

/** 命令和预期产物之间的保留分隔符。Windows 文件名不能含竖线，所以产物清单可安全用 | 分隔。 */
const 产物分隔符 = '::产物::'
const 产物上限 = 8

function 拆产物声明(输入) {
  const 原文 = String(输入 || '').trim()
  const 位置 = 原文.indexOf(产物分隔符)
  if (位置 < 0) return { 好: true, 命令: 原文, 产物参数: [] }
  if (原文.indexOf(产物分隔符, 位置 + 产物分隔符.length) >= 0) {
    return { 好: false, 说明: `一条命令只能写一个 ${产物分隔符}` }
  }

  const 命令 = 原文.slice(0, 位置).trim()
  const 后半 = 原文.slice(位置 + 产物分隔符.length).trim()
  if (!命令) return { 好: false, 说明: '声明了产物，但前面没有要运行的命令' }
  if (!后半) return { 好: false, 说明: `声明了 ${产物分隔符}，但没有填写目标文件` }

  const 产物参数 = 后半.split('|').map((一) => 一.trim()).filter(Boolean)
  if (!产物参数.length) return { 好: false, 说明: '产物清单是空的' }
  if (产物参数.length > 产物上限) return { 好: false, 说明: `一条命令最多核对 ${产物上限} 个产物` }
  return { 好: true, 命令, 产物参数 }
}

function 看文件状态(绝对路径) {
  try {
    const 状态 = fs.statSync(绝对路径)
    if (!状态.isFile()) return { 存在: true, 是文件: false, 大小: 0, 修改时间: 状态.mtimeMs }
    return { 存在: true, 是文件: true, 大小: 状态.size, 修改时间: 状态.mtimeMs }
  } catch {
    return { 存在: false, 是文件: false, 大小: 0, 修改时间: 0 }
  }
}

function 核对产物(声明们, 之前们, 开始时间) {
  const 时间 = new Date().toISOString()
  const 结果们 = 声明们.map((绝对路径, 下标) => {
    const 前 = 之前们[下标]
    const 后 = 看文件状态(绝对路径)
    let 通过 = false
    let 说明 = ''
    if (!后.存在) 说明 = '命令结束后文件不存在'
    else if (!后.是文件) 说明 = '目标存在，但不是文件'
    else if (!前.存在) {
      通过 = 后.修改时间 >= 开始时间 - 2000
      说明 = 通过 ? `本轮新建，${后.大小} 字节` : '文件新出现了，但修改时间早于本轮，无法证明由本轮生成'
    } else {
      const 有变化 = 后.修改时间 > 前.修改时间 || 后.大小 !== 前.大小
      const 时间属于本轮 = 后.修改时间 >= 开始时间 - 2000
      通过 = 有变化 && 时间属于本轮
      说明 = 通过
        ? `本轮更新，${前.大小} → ${后.大小} 字节`
        : '文件原本就存在，本轮没有检测到大小或修改时间变化'
    }
    return {
      通过,
      路径: 绝对路径,
      说明,
      证据: { 类型: '命令产物', 目标: 绝对路径, 说明, 来源: 绝对路径, 时间 },
    }
  })
  const 通过数 = 结果们.filter((一) => 一.通过).length
  return { 结果们, 通过数, 总数: 结果们.length }
}

/**
 * 明令禁止的东西。
 *
 * 【说清楚：这不是安全边界】
 *   真想绕，办法多的是（写进脚本里、用变量拼、换个写法）。
 *   **真正的边界是"每次都问他"** —— 这一层只是把最明显的几种
 *   挡在前面，让他点确认的时候少看见几次恶心东西。
 *   把拦不住的希望寄托在这张名单上，是自欺欺人。
 */
const 明令禁止 = [
  { 模式: /\brm\s+-rf\s+[\\/]\s*$/i, 说明: '删根目录' },
  { 模式: /\bformat\s+[a-z]:/i, 说明: '格式化磁盘' },
  { 模式: /\bdiskpart\b/i, 说明: '磁盘分区工具' },
  { 模式: /\bshutdown\b/i, 说明: '关机/重启' },
  { 模式: /\breg\s+delete\b/i, 说明: '删注册表项' },
  { 模式: /\bcipher\s+\/w/i, 说明: '擦除磁盘空闲空间' },
  { 模式: /\bvssadmin\b/i, 说明: '卷影副本（常被勒索软件用来删备份）' },
  { 模式: /Remove-Item.*-Recurse.*-Force.*[\\/]\s*$/i, 说明: '递归强删根目录' },
]

/**
 * 跑一条命令。
 *
 * @param {string} 命令
 * @param {object} [选项]  { 工作目录, 超时, 问 }
 * @returns {Promise<{好:boolean, 内容?:string, 说明?:string}>}
 */
async function 跑(命令, 选项 = {}) {
  const 原文 = String(命令 || '').trim()
  if (!原文) return { 好: false, 说明: '没给命令' }
  if (原文.length > 命令上限) return { 好: false, 说明: `命令太长了（上限 ${命令上限} 字）` }

  const 拆的 = 拆产物声明(原文)
  if (!拆的.好) return { 好: false, 说明: 拆的.说明 }
  const 真命令 = 拆的.命令

  // 一、明令禁止的先挡一道
  for (const 禁 of 明令禁止) {
    if (禁.模式.test(真命令)) {
      return { 好: false, 说明: `这条命令不能跑（${禁.说明}）。这一条不问也直接拒。` }
    }
  }

  // 二、工作目录：默认在她这次干活的目录里（不让他点到别处去）
  const 工作目录 = 选项.工作目录 || 干活目录
  if (!fs.existsSync(工作目录)) return { 好: false, 说明: '工作目录不存在：' + 工作目录 }

  // 产物声明只接受当前可写范围内的文件。它不扩大命令权限，只决定哪些目标可以拿来证明完成。
  const 产物们 = []
  for (const 参数 of 拆的.产物参数) {
    const 待核对 = path.isAbsolute(参数) ? 参数 : path.resolve(工作目录, 参数)
    const 查过 = 路径安全.查(待核对, '写', { 要新建: true })
    if (!查过.好) return { 好: false, 说明: `不能核对声明的产物“${参数}”：${查过.原因}` }
    if (产物们.includes(查过.绝对路径)) return { 好: false, 说明: `产物清单里重复了：${参数}` }
    产物们.push(查过.绝对路径)
  }

  // 三、问他 —— **这一层才是真正的关卡**
  if (typeof 选项.问 !== 'function') {
    return {
      好: false,
      说明: '跑命令必须先经过他同意，但现在没有问他的办法，所以这次不跑。',
      需要确认: { 命令: 真命令, 工作目录, 产物们 },
    }
  }

  // 【答复从 true/false 变成了 { 同意, 记住 } —— 2026-10-07】
  //   跑命令**故意不认"记住"**：这条命令他点了"以后别问"也一样要问。
  //   写文件最坏是改坏一个文件；跑命令最坏是干任何事。
  //   （市面上的 agent 也几乎都把执行命令单独拎出来最严。）
  const 答复 = await 选项.问({ 类型: '跑命令', 命令: 真命令, 工作目录, 产物们 })
  // 对象和 true/false 都认 —— 理由（以及踩过的坑）见 文件工具.cjs 里那段
  const 同意了 = 答复 === true || (答复 && 答复.同意 === true)
  if (!同意了) return { 好: false, 说明: '他不同意跑这条命令。', 被拒绝: true }

  // 四、跑
  //
  // 【为什么用 cmd /c 而不是直接 spawn】
  //   她写的是"命令行"（可能带管道、重定向、&&），
  //   直接 spawn 是不认这些的。走 cmd 才跟她在终端里敲一样。
  //
  // 【为什么必须异步】
  //   她仍然会等这一条跑完再决定下一步，但 Electron 主进程不能跟着堵住。
  //   同步调用会让窗口无法重绘、确认卡不能响应、退出也要等命令结束。
  //   execFile 的回调不占住事件循环，原来的超时和输出上限仍然保留。
  const 开始 = Date.now()
  const 产物之前 = 产物们.map(看文件状态)
  let 输出 = ''
  let 成功 = true
  let 退出码 = 0
  const 这次超时 = Number(选项.超时) > 0 ? Number(选项.超时) : 超时毫秒

  await new Promise((完成) => {
    execFile(
      'cmd',
      ['/c', 真命令],
      {
        cwd: 工作目录,
        encoding: 'utf8',
        timeout: 这次超时,
        windowsHide: true,
        maxBuffer: 8 * 1024 * 1024,
        signal: 选项.中止,
      },
      (错误, 标准输出 = '', 错误输出 = '') => {
        输出 = String(标准输出 || '') + (错误输出 ? '\n[错误输出]\n' + 错误输出 : '')
        if (错误) {
          成功 = false
          退出码 =
            typeof 错误.code === 'number' ? 错误.code
            : typeof 错误.status === 'number' ? 错误.status
            : null
          if (错误.killed || 错误.signal === 'SIGTERM') {
            输出 += `\n（跑了超过 ${这次超时 / 1000} 秒，已停止）`
          }
          if (!输出.trim()) 输出 = 错误.message
        }
        完成()
      },
    )
  })

  const 用时 = ((Date.now() - 开始) / 1000).toFixed(1)

  // 五、输出太长就截断
  let 给 = 输出.trim()
  let 截断说明 = ''
  if (给.length > 输出上限) {
    截断说明 = `\n\n……（输出太长，只留了开头 ${Math.round(输出上限 / 1024)} KB，一共 ${Math.round(给.length / 1024)} KB）`
    给 = 给.slice(0, 输出上限)
  }

  // 【失败不等于"没东西给你看"】
  //   编译报错、python 抛异常，这些都是**命令跑成功了、只是它自己失败了** ——
  //   而那份报错恰恰是她下一步要改的依据。
  //   所以措辞上要区分开：不是"这工具坏了"，是"你要看的东西在这儿"。
  let 交代 =
    (成功
      ? '命令跑完了'
      : `命令跑完了，但**它自己是失败退出的**` +
        (typeof 退出码 === 'number' ? `（退出码 ${退出码}）` : '') +
        ' ——\n这很正常：编译器报错、脚本抛异常都长这样。' +
        '**下面就是它说的话，照着它改**，别猜。') +
    `\n（用时 ${用时}s，在 ${path.basename(工作目录)} 里跑的）\n\n` +
    (给 || '（没有任何输出）') +
    截断说明

  const 产物核对 = 成功 && 产物们.length ? 核对产物(产物们, 产物之前, 开始) : null
  let 验证状态 = 成功 ? '部分验证' : '不适用'
  let 目标完成 = 成功 ? '未知' : '否'
  const 证据 = typeof 退出码 === 'number'
    ? [{ 类型: '退出码', 目标: 真命令, 说明: `退出码 ${退出码}`, 来源: '', 时间: new Date().toISOString() }]
    : []

  if (产物核对) {
    证据.push(...产物核对.结果们.map((一) => 一.证据))
    if (产物核对.通过数 === 产物核对.总数) {
      验证状态 = '已验证'
      目标完成 = '是'
      交代 += `\n\n✓ 已核对 ${产物核对.总数} 个声明产物，均由本轮新建或更新。`
    } else {
      验证状态 = 产物核对.通过数 > 0 ? '部分验证' : '未验证'
      目标完成 = 产物核对.通过数 > 0 ? '部分' : '否'
      const 没通过 = 产物核对.结果们.filter((一) => !一.通过)
      交代 += '\n\n⚠ 命令退出码为 0，但声明产物没有全部通过核对：\n' +
        没通过.map((一) => `  · ${path.basename(一.路径)}：${一.说明}`).join('\n') +
        '\n不能据此说目标已经完成，也不要自动重跑命令。'
    }
  }

  return {
    好: 成功,
    执行状态: 成功 ? '成功' : undefined,
    验证状态,
    目标完成,
    内容: 交代,
    // 【为什么失败时也必须填 说明 —— 这一条是血的教训】
    //   调用方（脑\对话.cjs）拿到"没成"的结果时，是这样递给她看的：
    //       `没成 —— ${结果.说明}`
    //   而这里原来只在成功时填 内容、**从来不填 说明**。
    //   于是失败的时候，她看到的那句话是：「没成 —— undefined」。
    //
    //   2026-10-01 晚上跑整条线，她自己的原话是：
    //     "文件是写好了，可是编译没过去 —— 报的是 undefined，
    //       具体哪一行我也没看清，得再跑一次才知道。"
    //   她不是没看，是那句话里真的什么都没有 —— gcc 的原文被吞掉了。
    //   她于是只能猜（"我猜八成是 Windows 那边的事"），越猜越远。
    说明: 成功 ? undefined : 交代,
    用时: Number(用时),
    退出码,
    证据,
    产物们,
  }
}

/** 看看她要用哪些命令（给提示词用的：告诉他这台机器上有什么） */
function 环境说明() {
  const 行 = ['这台机器上现成能用的：']
  try {
    const { execFileSync: 跑一下 } = require('node:child_process')
    const py = 跑一下('python', ['--version'], { encoding: 'utf8', timeout: 10000 }).trim()
    行.push('  · ' + py + '（命令是 python）')
    // 顺便看看那几个做文档的库
    const 库 = 跑一下(
      'python',
      [
        '-c',
        "import importlib.util as u; print(', '.join([n for n in ['pptx','docx','openpyxl','PIL','matplotlib','pandas','numpy','requests'] if u.find_spec(n)]))",
      ],
      { encoding: 'utf8', timeout: 15000 },
    ).trim()
    行.push('  · python 里已经装好的库：' + (库 || '（没有）'))
    if (!库.includes('docx')) 行.push('    （docx 没装 —— 做 Word 要先 pip install python-docx）')
    if (!库.includes('openpyxl')) 行.push('    （openpyxl 没装 —— 做 Excel 要先 pip install openpyxl）')
  } catch {
    行.push('  · python 查不到')
  }
  try {
    const { execFileSync: 跑一下 } = require('node:child_process')
    const n = 跑一下('node', ['--version'], { encoding: 'utf8', timeout: 10000 }).trim()
    行.push('  · node ' + n)
  } catch {
    /* 没有就算了 */
  }

  // ---- C 编译器 ----
  //
  // 【为什么原来漏了它 —— 2026-10-01 晚上补的】
  //   这段"这台机器上有什么"里**从来没有提过 gcc**，只有 python 和 node。
  //   于是她想编一份自己刚写的 C 时，压根不知道有编译器可用，
  //   试了一下没成就说"这台机器上好像没有 gcc"，然后开始猜、
  //   开始绕（"我干脆别耍聪明了，就写 Windows 版"），一晚上绕了三圈。
  //   机器上明明装着 gcc 16.2.0。
  let 有gcc = false
  try {
    const { execFileSync: 跑一下 } = require('node:child_process')
    const g = 跑一下('gcc', ['--version'], { encoding: 'utf8', timeout: 10000 }).trim().split('\n')[0]
    行.push('  · ' + g.replace(/\s+$/, '') + '（命令就是 gcc，C 语言用这个编）')
    有gcc = true
  } catch {
    行.push('  · 没有 gcc（C 语言编不了，得先装 MSYS2）')
  }

  // ---- 一条会坑死她的规矩，必须写在明面上 ----
  //
  // 【2026-10-01 晚上一格一格试出来的。前后写错过两版，这里是第三版。】
  //
  //   第一版我写的是"gcc 不能带中文路径" —— 太粗，会害她白白躲开中文命名。
  //   第二版我写的是"只有 -o 带中文的绝对路径才坏，中文文件名没关系" ——
  //   **还是错的**。真相是中文文件名也坏，只是坏得很安静：
  //
  //     源码 `猜数字.c`、输出 `-o 猜数字.exe`
  //       → gcc 退出码 0，它说成功了
  //       → 可盘上那个文件其实叫 `²ÂÊý×Ö.exe`
  //         （猜数字 的 GBK 字节被当成 Latin-1，一个字节一个字符存了下去）
  //       → 于是 `猜数字.exe` 根本不存在，她去跑就跑不起来，
  //         而且**没有任何报错**，她只会以为是自己哪里写错了
  //
  //   完整的表（同一份 C，七种写法各试一遍）：
  //     -o 带中文的绝对路径              → ld 直接报 cannot open output file
  //                                        （报错里那串中文也是乱的）
  //     -o 带中文的相对名                → **退出码 0，但文件名变成乱码**
  //     -o 纯 ASCII 名，人先 cd 过去      → 成
  //     -o 纯 ASCII 的绝对路径（纯英文目录）→ 成
  //     源码路径带中文                    → 成（gcc 找得到）
  //     源码中文绝对路径 + ASCII 相对输出  → 成
  //     纯英文目录 + 纯 ASCII 绝对路径      → 成
  //
  //   结论一句话：**`-o` 后面整条路径必须是纯英文的。**
  //   源码名随便（中文也行），输出名老老实实用英文。
  //
  //   为什么"先 cd 过去、输出用英文名"就一定行：相对名是 ld 拿当前目录
  //   自己拼的，而当前目录是 Windows 用宽字符传下去的，不会经过那道
  //   字节转换；写成绝对路径就得在命令行里过一遍，那一遍就把中文啃了。
  //
  //   python、node 没这毛病，中文绝对路径随便给。
  //   （gcc 都没装的话这条就没意义了，所以跟着 有gcc 走。）
  if (有gcc) {
    行.push('  · **gcc 有一条要记牢**：`-o` 后面**整条路径必须是纯英文的**。')
    行.push('    源码名随便（`猜数字.c` 没问题），但输出名老老实实用英文。')
    行.push('    两种坏法，第二种最阴：')
    行.push('      1. `-o` 写中文绝对路径 → 直接报 cannot open output file')
    行.push('         （而且**报错里那串中文本身也是乱码的**，你从报错看不出原因）')
    行.push('      2. `-o` 写中文相对名   → **它不报错！退出码 0，说成功了**，')
    行.push('         可盘上那个文件其实叫 `²ÂÊý×Ö.exe` 这种乱码名 ——')
    行.push('         你去找 `猜数字.exe` 是找不到的，也没有任何提示。')
    行.push('    所以编 C 一律这样写：')
    行.push('      cd /d <那个目录> && gcc 猜数字.c -o guess.exe')
    行.push('                                ^^^^^^^ 输出名用英文')
    行.push('    python、node 都没这个毛病，中文路径随便写。')
  }

  return 行.join('\n')
}

