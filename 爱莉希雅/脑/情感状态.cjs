/**
 * 情感状态.cjs —— 轻量即时反应层。
 *
 * 它只根据这一轮用户明确表达出来的线索，给出有限状态和表达提示；不调用模型、
 * 不写磁盘、不把推断当事实。每段对话各有一份，十分钟内自然回到平静。
 */
'use strict'

const 状态名们 = Object.freeze(['平静', '开心', '关心', '认真', '疑惑', '惊讶'])
const 衰减毫秒 = 10 * 60 * 1000
const 情绪衰减毫秒 = 6 * 60 * 60 * 1000
const 基线 = Object.freeze({ 情绪: '平静', 强度: 0, 温度: 0.72, 活跃度: 0.34 })
const 情绪基线 = Object.freeze({ 情绪: '平稳', 强度: 0, 温度: 0.72, 活跃度: 0.34 })
const 情绪目标 = Object.freeze({
  明快: { 温度: 0.88, 活跃度: 0.72 },
  温柔: { 温度: 0.92, 活跃度: 0.28 },
  专注: { 温度: 0.64, 活跃度: 0.48 },
  好奇: { 温度: 0.78, 活跃度: 0.68 },
})

function 限制(数) { return Math.max(0, Math.min(1, Number(数) || 0)) }
function 有效时间(值) {
  const 数 = 值 instanceof Date ? 值.getTime() : new Date(值).getTime()
  return Number.isFinite(数) ? 数 : Date.now()
}

function 识别反应(原文) {
  const 文本 = String(原文 || '').replace(/\s+/g, ' ').trim().slice(0, 4000)
  if (!文本) return null
  // 先拿掉常见的否定和“已经解决”，否则“没有问题”也会被“有问题”命中。
  const 判定文本 = 文本
    .replace(/(没有|没(?:有)?(?:再|那么|这么|怎么|太|很|多么)?|不(?:再|太|怎么)?)(难受|不舒服|焦虑|害怕|疼|累|问题|报错|出错|失败)/g, '')
    .replace(/(不是|并非)不行/g, '')
    .replace(/问题(已经)?解决了|修好了|已修复|恢复正常/g, '')
  const 规则 = [
    { 情绪: '关心', 强度: 0.82, 温度: 0.94, 活跃度: 0.30, 原因: '他明确表达了难受或需要安慰', 正则: /(我.{0,8}(难受|不舒服|害怕|焦虑|崩溃|想哭|生病|疼)|心情不好|睡不着|好累|很累|撑不住)/i },
    { 情绪: '认真', 强度: 0.68, 温度: 0.64, 活跃度: 0.54, 原因: '他报告了需要处理的问题', 正则: /(报错|出错|崩了|坏了|失败|不能用|不工作|不行|有问题|\bbug\b)/i },
    { 情绪: '开心', 强度: 0.72, 温度: 0.90, 活跃度: 0.78, 原因: '他分享了成功、开心或亲近的表达', 正则: /(成功了|通过了|验收成功|搞定了|太好了|开心|高兴|谢谢你|喜欢你|爱你|哈哈+)/i },
    { 情绪: '开心', 强度: 0.46, 温度: 0.84, 活跃度: 0.60, 原因: '他表达了事情正在顺利推进', 正则: /(进展.{0,6}(顺利|不错|很好)|学得?.{0,5}(很顺|挺顺|顺利)|课程.{0,8}(很顺|挺顺|顺利)|比较顺利|一切顺利)/i },
    { 情绪: '惊讶', 强度: 0.62, 温度: 0.78, 活跃度: 0.82, 原因: '他表达了明确的意外', 正则: /(居然|竟然|没想到|真的假的|这么巧)/i },
    { 情绪: '疑惑', 强度: 0.52, 温度: 0.72, 活跃度: 0.48, 原因: '他明确表示没有理解', 正则: /(没看懂|看不明白|不明白|什么意思|为什么会|怎么回事|搞不懂)/i },
  ]
  return 规则.find((一) => 一.正则.test(判定文本)) || null
}

function 创建反应层(选项 = {}) {
  const 取现在 = typeof 选项.现在 === 'function' ? 选项.现在 : () => new Date()
  const 每段 = new Map()
  const 每段情绪 = new Map()

  function 平静状态(对话 = '') {
    return { 对话: String(对话 || ''), ...基线, 原因: '没有明确的即时情绪线索', 触发于: '', 剩余分钟: 0 }
  }

  function 状态(对话) {
    const 编号 = String(对话 || '')
    const 旧 = 每段.get(编号)
    if (!旧) return 平静状态(编号)
    const 已过 = Math.max(0, 有效时间(取现在()) - 旧.时刻)
    const 比例 = Math.max(0, 1 - 已过 / 衰减毫秒)
    const 强度 = 限制(旧.强度 * 比例)
    if (强度 < 0.08) {
      每段.delete(编号)
      return 平静状态(编号)
    }
    return {
      对话: 编号,
      情绪: 旧.情绪,
      强度: Number(强度.toFixed(2)),
      温度: Number((基线.温度 + (旧.温度 - 基线.温度) * 比例).toFixed(2)),
      活跃度: Number((基线.活跃度 + (旧.活跃度 - 基线.活跃度) * 比例).toFixed(2)),
      原因: 旧.原因,
      触发于: new Date(旧.时刻).toISOString(),
      剩余分钟: Math.max(1, Math.ceil((衰减毫秒 - 已过) / 60000)),
    }
  }

  function 衰减后权重(对话) {
    const 编号 = String(对话 || '')
    const 旧 = 每段情绪.get(编号)
    if (!旧) return { 编号, 权重: {}, 比例: 0, 时刻: 0 }
    const 已过 = Math.max(0, 有效时间(取现在()) - 旧.时刻)
    const 比例 = Math.max(0, 1 - 已过 / 情绪衰减毫秒)
    const 权重 = {}
    for (const [名字, 数] of Object.entries(旧.权重 || {})) {
      const 值 = 限制(Number(数) * 比例)
      if (值 >= 0.01) 权重[名字] = 值
    }
    return { 编号, 权重, 比例, 时刻: 旧.时刻 }
  }

  function 情绪状态(对话) {
    const { 编号, 权重, 时刻 } = 衰减后权重(对话)
    const 项们 = Object.entries(权重).filter(([名字]) => Object.prototype.hasOwnProperty.call(情绪目标, 名字))
    const 总强度 = 项们.reduce((和, [, 数]) => 和 + 数, 0)
    if (总强度 < 0.02) {
      每段情绪.delete(编号)
      return { 对话: 编号, ...情绪基线, 原因: '近期反应已经回落', 更新于: '', 剩余小时: 0 }
    }
    项们.sort((a, b) => b[1] - a[1])
    let 温度 = 情绪基线.温度
    let 活跃度 = 情绪基线.活跃度
    for (const [名字, 数] of 项们) {
      温度 += (情绪目标[名字].温度 - 情绪基线.温度) * 数
      活跃度 += (情绪目标[名字].活跃度 - 情绪基线.活跃度) * 数
    }
    const 已过 = Math.max(0, 有效时间(取现在()) - 时刻)
    return {
      对话: 编号,
      情绪: 项们[0][0],
      强度: Number(Math.min(0.45, 总强度).toFixed(2)),
      温度: Number(限制(温度).toFixed(2)),
      活跃度: Number(限制(活跃度).toFixed(2)),
      原因: '由这段对话近期几轮的明确反应缓慢累计',
      更新于: new Date(时刻).toISOString(),
      剩余小时: Math.max(1, Math.ceil((情绪衰减毫秒 - 已过) / 3600000)),
    }
  }

  function 推进情绪(对话, 反应) {
    if (!反应) return 情绪状态(对话)
    const 对应 = { 开心: ['明快', 0.16], 关心: ['温柔', 0.15], 认真: ['专注', 0.13], 疑惑: ['专注', 0.10], 惊讶: ['好奇', 0.11] }[反应.情绪]
    if (!对应) return 情绪状态(对话)
    const 当前 = 衰减后权重(对话)
    // 较轻的“进展顺利”也能让状态动起来，但不能和“验收成功”一样跳得多。
    // 0.72 是原来明确反应的大致强度基准，最低仍保留四成增量以免再次看不见变化。
    const 强度系数 = Math.max(0.4, Math.min(1.15, Number(反应.强度 || 0) / 0.72))
    当前.权重[对应[0]] = Number(当前.权重[对应[0]] || 0) + 对应[1] * 强度系数
    const 总数 = Object.values(当前.权重).reduce((和, 数) => 和 + Number(数 || 0), 0)
    if (总数 > 0.45) {
      const 比例 = 0.45 / 总数
      for (const 名字 of Object.keys(当前.权重)) 当前.权重[名字] *= 比例
    }
    每段情绪.set(当前.编号, { 权重: 当前.权重, 时刻: 有效时间(取现在()) })
    return 情绪状态(当前.编号)
  }

  function 接收用户(对话, 文字) {
    const 编号 = String(对话 || '')
    const 反应 = 识别反应(文字)
    if (!反应) return 状态(编号)
    每段.set(编号, { ...反应, 时刻: 有效时间(取现在()) })
    推进情绪(编号, 反应)
    return 状态(编号)
  }

  function 重置(对话) {
    每段.delete(String(对话 || ''))
    return 平静状态(对话)
  }

  function 重置情绪(对话) {
    每段情绪.delete(String(对话 || ''))
    return 情绪状态(对话)
  }

  function 拼表达提示(当前, 缓慢 = null) {
    const 值 = 当前 && 状态名们.includes(当前.情绪) ? 当前 : 平静状态('')
    const 慢 = 缓慢 && Object.prototype.hasOwnProperty.call(情绪目标, 缓慢.情绪) ? 缓慢 : 情绪基线
    if ((值.情绪 === '平静' || 值.强度 < 0.08) && (慢.情绪 === '平稳' || 慢.强度 < 0.02)) return ''
    const 指引 = {
      开心: '自然地分享他的高兴，可以更轻快；不要连续夸赞或刻意拔高。',
      关心: '先接住他的感受，语气放轻，给具体帮助；不要说教、诊断或制造依赖。',
      认真: '先处理问题，表达清楚、克制；保留她的口吻，但不要用玩笑冲淡故障。',
      疑惑: '耐心确认他卡住的具体位置，再用短句解释；不要假装已经理解全部语境。',
      惊讶: '可以有一句自然的惊讶反应，随后回到事情本身；不要夸张表演。',
    }[值.情绪] || ''
    const 慢指引 = {
      明快: '近期基调略明快，但不能把严肃或难过的话题说得轻浮。',
      温柔: '近期基调略柔和，但不要过度关怀、讨好或制造依赖。',
      专注: '近期基调略沉稳，优先清楚和具体，同时保留自然的角色口吻。',
      好奇: '近期基调略灵动，可以自然追问，但不要擅自补全事实。',
    }[慢.情绪] || ''
    return [
      '【当前即时反应（本地程序计算，不是事实或记忆）】',
      值.情绪 === '平静' ? '' : `即时状态：${值.情绪}；强度：${Math.round(限制(值.强度) * 100)}%；表达温度：${Math.round(限制(值.温度) * 100)}%。`,
      指引,
      慢.情绪 === '平稳' ? '' : `近期基调：${慢.情绪}；强度：${Math.round(限制(慢.强度) * 100)}%。即时状态优先于近期基调。`,
      慢指引,
      '这只调整本轮措辞，不改变身份、事实判断、工具权限或任务完成标准。不要向用户念出状态数值。',
    ].filter(Boolean).join('\n')
  }

  return { 状态, 情绪状态, 接收用户, 重置, 重置情绪, 拼表达提示 }
}

const 默认反应层 = 创建反应层()
module.exports = { 创建反应层, 识别反应, 状态名们, 衰减毫秒, 情绪衰减毫秒, ...默认反应层 }
