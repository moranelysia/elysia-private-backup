/**
 * 确认.cjs —— "这件事要不要先问他"的那个通道
 *
 * 【为什么要单独一层】
 *   她干活的时候会撞上两类事：
 *     · 往硬盘上写东西（新建 / 覆盖）—— 要问他
 *     · 跑命令 —— 每次都要问
 *   而"问她还是问我"这件事，工具的代码不该管 ——
 *   工具只管"我需要人点个头"，谁来点、怎么点，是外面的事。
 *   所以中间放这一层：工具 await 一个承诺，外面负责兑现它。
 *
 * 【它是 Cyrene 那套审批的简化版】
 *   它有：广播给所有窗口、10 秒幂等重播、结算事件、按 run 清理……
 *   那些是为"多窗口 + 会话切换"设计的。我们只有一个窗口，
 *   那套机制是纯负担。所以这里只留最必要的：
 *     · 一次只处理一个请求（她本来就是一条一条干活的）
 *     · 无窗口可问 → 直接拒绝（跟它一样，宁可不错）
 *     · 谁在等它，就结算谁
 *
 * 【为什么"无窗口就拒绝"是对的】
 *   他可能把窗口收起来了（她躲在托盘里）。这时候她在后台想写文件，
 *   没人能点确认 —— 那就别写。**没有批准不等于默许。**
 *
 * 用法:
 *   确认.注册({ 问窗口 })          // 主程序启动时
 *   const 行不行 = await 确认.问({ 类型:"跑命令", 命令:"python x.py" })
 */
'use strict'

/**
 * 待答复的请求们。
 *
 * 【2026-10-01 改过 —— 原来是"一次只准一个"，那是个 bug】
 *   原来的写法：正在等的时候又来一个请求，**直接返回 false**。
 *   而工具那边收到 false 会理解成"他不同意"，于是她看到的是
 *   "他不同意这次写入"——**可他压根没看见那次请求**。
 *
 *   实测现场：她一轮里要写两个文件（两个标记），
 *   程序并行去写 → 第一个挂起等答复 → 第二个撞上"有人在等" → 被拒。
 *   他点了同意，第一个成了，第二个却报"他不同意"。
 *   她那边就懵了，开始说胡话（"刚才那一大段乱七八糟的，不算数"）。
 *
 *   现在改成可以同时挂好几个（Map 按编号存），界面上就出好几张卡片，
 *   互不影响。
 */
const 待答复 = new Map()

/** 用来跟他说话的办法 —— 由主程序注入 */
let 问窗口 = null

/** 请求编号，用来对回执 */
let 编号 = 0

/** 他点"以后这个文件夹别问了"的时候，用来把这件事记下来 —— 由主程序注入 */
let 记住这个 = null

/**
 * 注入"怎么问他"。
 *
 * @param {object} 选项
 * @param {(请求:object)=>Promise<boolean|{同意:boolean,记住:boolean}>} 选项.问窗口
 *        把请求递给他，等他的答复。
 *        【2026-10-07 起它也能返回一个对象了】—— 因为多了一样"记住"要带回来。
 *        老的、直接返 true/false 的那种仍然认（见 问() 里那两个分支）。
 * @param {(请求:object)=>void} [选项.记住这个]
 *        他说"以后这个文件夹别问了"的时候调它。
 *        **落盘是外面的事** —— 这个模块不知道设置文件存在哪，也不该知道：
 *        那样就有两个地方各记一份"设置在哪"，早晚对不上。
 */
function 注册(选项 = {}) {
  // 【注意】这里要**显式**赋值，包括赋成 null。
  //   第一版写的是 `if (选项.问窗口) 问窗口 = 选项.问窗口` ——
  //   于是 `注册({})` 什么也没改，上一个问窗口还留着。
  //   清理的时候（程序要退了、窗口没了）得能真的把它撤掉。
  问窗口 = typeof 选项.问窗口 === 'function' ? 选项.问窗口 : null
  记住这个 = typeof 选项.记住这个 === 'function' ? 选项.记住这个 : null
}

/**
 * 问她该不该做这件事。
 *
 * @param {object} 请求
 * @param {string} 请求.类型     "新建" | "覆盖" | "跑命令"
 * @param {string} [请求.路径]
 * @param {string} [请求.命令]
 * @param {string} [请求.内容]   要写的内容（界面上给他看一眼）
 * @param {string} [请求.原内容] 覆盖前的原内容（用来算"改了多少"）
 * @returns {Promise<{同意:boolean, 记住:boolean}>}
 *   记住 = 他这次点的是"以后这个文件夹别问了"。
 *   调用方**不用管**怎么落盘 —— 这个模块会调 记住这个() 递出去，
 *   干活的工具只管"这次到底让不让做"。
 */
async function 问(请求) {
  // 没人可问 → 拒绝。不是"默认允许"。
  if (typeof 问窗口 !== 'function') return { 同意: false, 记住: false }

  // 【这一行是 2026-10-01 晚上修的一个大 bug —— 别改回去】
  //
  //   原来写的是：
  //     编号++
  //     const 这一件 = { ...请求, 编号 }
  //     ... .then((答复) => { if (typeof 答复 === 'boolean') 结算(编号, 答复) })
  //                                        ↑ 这里读的是**模块级的 编号**
  //
  //   问题出在最后那个 编号 —— 它是个还在变的变量，不是"这次请求的号"。
  //   两个请求同时在等的时候：
  //     请求甲 → 编号 变成 1，待答复里挂上 1
  //     请求乙 → 编号 变成 2，待答复里挂上 2
  //     他点了甲的卡片 → 甲的答复回来了 → `.then` 这时候读到的 编号 已经是 2 了
  //       → **结算到了乙头上**：乙被提前兑现，甲那份承诺再也没人兑现
  //
  //   现场（他那晚的日志，一字不改）：
  //     ⏸ 等他对「跑命令：cd /d D:\elysia测试 && gcc guess.c -o guess.exe」点头
  //     ⏸ 等他对「新建：D:\elysia测试\guess.c」点头
  //     ✓ 他同意了（请求 1）
  //     ✓ 他同意了（请求 2）
  //     ↳ 动手：写(...\guess.c) —— 成功
  //     ↳ 动手：跑(...gcc guess.c -o guess.exe) —— 没成：他不同意跑这条命令。
  //   主程序明明两次都收到了"他同意了"，可跑命令那条拿到的答复是"不同意"。
  //   他那边看到的是：点了同意，界面上还一直挂着"等你点头"，
  //   而且**再也发不出消息**（那一轮还卡在 await 上，发送按钮一直锁着）。
  //
  //   教训：并发的时候"这次是几号"必须**当场定住**，
  //   不能等回调回来再去读那个已经被别人改过的变量。
  const 这号 = ++编号
  const 这一件 = { ...请求, 编号: 这号 }

  return new Promise((完成) => {
    // 【存的是"完成 + 这次问的是什么"】
    //   2026-10-07 之前只存 完成 一个函数。现在多存那份请求，
    //   因为"记住这个文件夹"要用到它里面的 绝对路径 ——
    //   结算的时候只看得到编号，看不到当初问的是什么。
    待答复.set(这号, { 完成, 请求: 这一件 })

    Promise.resolve(问窗口(这一件))
      .then((答复) => {
        // 三种结算方式，都要支持：
        //   1. 窗口自己返 true / false（比如它判断"没法问"，直接回 false）
        //   2. 窗口自己返 { 同意, 记住 }（2026-10-07 加的）
        //   3. 窗口那边异步等用户点，之后调 结算(编号, 同意, 记住)
        // 第 3 种情况下这里返回的是 undefined，那就什么都不做 ——
        // 等 结算 来兑现。**这个分支不能落下**：
        // 第一版忘了处理"窗口直接返回答复"，于是程序要退的时候
        // 那个 promise 永远不兑现，她那边一直挂着。
        if (typeof 答复 === 'boolean') 结算(这号, 答复, false)
        else if (答复 && typeof 答复 === 'object' && typeof 答复.同意 === 'boolean') {
          结算(这号, 答复.同意, !!答复.记住)
        }
      })
      .catch(() => {
        结算(这号, false, false)
      })
  })
}

/**
 * 结算：他点了同意 / 不同意，或者这次请求作废了。
 * 外面（主程序收到窗口回执时）调它。
 *
 * @param {number} 编号
 * @param {boolean} 同意
 * @param {boolean} [记住] 他点的是不是"以后这个文件夹别问了"
 */
function 结算(编号, 同意, 记住 = false) {
  const 一件 = 待答复.get(编号)
  if (!一件) return false
  待答复.delete(编号)
  一件.完成({ 同意: Boolean(同意), 记住: Boolean(记住) })

  // 他说"以后别问了" —— 把这件事递出去让人记下来。
  // 【为什么在这儿调，不在返回里带出去让工具记】
  //   因为工具（文件工具/命令工具）**不知道设置存在哪**，也不该知道。
  //   而且"记住"是审批这件事的一部分，让它跟着审批的结算走最自然：
  //   同意 + 记住 是一个动作，不是两个。
  if (同意 && 记住 && 记住这个) {
    try {
      记住这个(一件.请求)
    } catch (错误) {
      console.log('⚠ 没能记住这次放行：' + 错误.message)
    }
  }
  return true
}

/** 现在有几个在等他点头（界面用它决定要不要显示那行提示） */
function 在等吗() {
  return 待答复.size > 0
}

/** 在等哪几个（主程序退出时要把它们全作废） */
function 在等的编号() {
  return [...待答复.keys()]
}

/**
 * 作废所有还在等的请求（当作"不同意"）。
 * 用在"程序要退了"或者"她自己被叫停了"的时候 ——
 * 不能让一个永远等不到答复的承诺挂着。
 */
function 作废() {
  const 个数 = 待答复.size
  for (const [号, 一件] of [...待答复]) {
    待答复.delete(号)
    // 作废一律按"不同意"算，**不带记住** ——
    // 窗口关掉/程序要退了，不是他做的决定，不能拿它去改权限。
    一件.完成({ 同意: false, 记住: false })
  }
  return 个数
}

module.exports = { 问, 注册, 结算, 在等吗, 在等的编号, 作废 }
