// 二点六、学习任务（2026-10-07 加的）
// ============================================================
//
// 【为什么只给她"加"和"勾"，不给她"删"】
//   删掉一条 = "这件事我们不做了"，那是个**决定**，该他来做。
//   她只能往前推（加一件要做的）、往回记（这件做完了）。
//   少一只手不会出问题；多一只手，哪天她把他排的清单清空了就找不回来了。
//   （跟"只给她 safe 的工具"是同一个思路：能少给就少给。）
//
// 【为什么危险度是 safe】
//   它改的是 `学习\任务.md` 那个清单，改坏了顶多乱一条 ——
//   而且他随时能自己打开改。这跟"往硬盘上写一个文件"不是一回事，
//   不值得每动一次都弹张卡片。真要拦的是 [写:] 那种覆盖。
const 管任务 = {
  名字: '任务',
  别名: ['待办', '任务清单', '加任务', '记一条任务'],
  危险度: 'safe',
  说明:
    '**你们的学习待办清单。** 两个动作：\n' +
    '  [任务:加 看完第一章课件]   ← 加一条要做的\n' +
    '  [任务:勾 看完第一章课件]   ← 做完了一条，勾掉它\n' +
    '\n' +
    '不写动词也行，那就当"加一条"：[任务:第三章那三道题]\n' +
    '\n' +
    '⚠ **「做完 xx」是"勾"的意思，不是"加"**（"做完"本身是个动词）。\n' +
    '   想加一条叫"做完 xx"的，写成 [任务:加 做完 xx] 才不含糊。\n' +
    '\n' +
    '⚠ **勾的时候照抄清单里的原话**（可以只写其中几个字，但要能唯一对上）。\n' +
    '   写歪了它会告诉你"没有这一条" —— 那比乱勾一条好得多。\n' +
    '\n' +
    '⚠ **你删不掉任务。** 他要是说"那条不做了"，跟他说一声让他自己删，\n' +
    '   或者问他"要不要我先划掉" —— **别当成自己已经删了**。\n' +
    '\n' +
    '什么时候该加：他说"下次要……""回头我得……"；或者你们讲完一段，\n' +
    '你看出他下一步该干什么（比如"动手写第一个程序"）。\n' +
    '一次加一条，别一口气排十件 —— 待办清单长了就没人看了。',
  做: (参数) => {
    const 原文 = String(参数 || '').trim()
    if (!原文) return { 好: false, 说明: '没说要加什么、或者勾哪一条' }

    const 命中 = /^(加|添加|新增|记|勾|勾掉|划掉|完成|做完)\s*[:：]?\s*(.+)$/.exec(原文)
    if (!命中) {
      // 没写动词 —— 当"加一条"（那是她最常用的那个）
      const 果 = 学习任务.加(原文)
      return 果.好
        ? { 好: true, 内容: `加上了：${原文}（现在一共 ${学习任务.统计().一共} 条）` }
        : { 好: false, 说明: 果.说明 }
    }

    const 干什么 = 命中[1]
    const 内容 = 命中[2]

    if (/^(加|添加|新增|记)/.test(干什么)) {
      const 果 = 学习任务.加(内容)
      return 果.好
        ? { 好: true, 内容: `加上了：${内容}（现在一共 ${学习任务.统计().一共} 条）` }
        : { 好: false, 说明: 果.说明 }
    }

    // 剩下的是"勾"
    const 果 = 学习任务.勾(内容, true)
    if (!果.好) return { 好: false, 说明: 果.说明 }
    const 数 = 学习任务.统计()
    return { 好: true, 内容: `勾掉了「${果.文字}」—— 现在 ${数.做完}/${数.一共} 条做完了` }
  },
}

