const 表 = [联网查, 看时间, 读文件, 列目录, 找文件, 写文件, 交付文件, 跑命令, 派助手, 管任务]

/**
 * 每种模式真正拿得到的工具。
 * 聊天模式开放联网搜索和本机时间；文件、命令和任务能力仍只属于工作/学习模式。
 */
function 按模式(模式) {
  if (模式 === 'chat') return 表.filter((工具) => 工具.名字 === '查' || 工具.名字 === '时间')
  if (模式 === 'work' || 模式 === 'learn') return 表.slice()
  return []
}

/**
 * 把她写的说法（"列出""读一下"）归一成工具名。
 *
 * 【2026-10-01 收紧过一次 —— 原来那条"双向包含"很危险】
 *   原来最后一步是：只要 `她写的` 和某个说法**互相包含**就算认得。
 *   结果出了这么一桩怪事：她写 `[列:记忆` （没写右括号，跨行了），
 *   正则跳过它，接着把下一行的 `[表情:超级爱莉]` 抓了下来 ——
 *   动词是"表情"，参数是"超级爱莉"。而"表情"这两个字在双向包含里
 *   撞上了某个工具，于是她本来想做表情，程序却去 `列("情:超级爱莉")`，
 *   报了个谁也看不懂的错。
 *
 *   改成**只认前缀**：`她写的` 必须以某个说法开头（"帮我查查" 以"查"开头 → 是它；
 *   "表情" 不以任何工具说法开头 → 认不出）。
 *   宁可认不出（那边会回一句"这个我够不着"），也不要认错（认错会让她干错事）。
 *
 *   认不出不等于白写：调用方会把认不出的方括号从正文里抠掉，
 *   他看不到那些内部标记，她那边也只是"这次没生效"。
 */
function 认工具(她写的) {
  const 原文 = String(她写的 || '').trim()
  if (!原文) return null

  // 把开头的冒号/空格和结尾的标点去掉，"列出：" 也要认
  const 干净 = 原文.replace(/^[:：\s]+/, '').replace(/[:：\s]+$/, '')
  if (!干净) return null

  // 一、一模一样
  for (const 工具 of 表) {
    if (工具.名字 === 干净) return 工具
  }

  // 二、别名里一模一样
  for (const 工具 of 表) {
    if (工具.别名.includes(干净)) return 工具
  }

  // 三、她写的以某个说法**开头**（"帮我查查" → "查"；"搜一下" → "搜"）
  //
  //    【2026-10-01 又收紧了一次 —— "前缀"这条也会放得太宽】
  //      实测：切"写入工作区/x.md"的时候，切法有四种，
  //      而 **"写"、"写入"、"写入工"、"写入工作" 全都"认得出"** ——
  //      因为前缀规则让它们都以别名"写"开头。于是打分要在四个都合格的
  //      候选里选，很容易选错。
  //
  //      正确的判据是：**动词那截不能比它匹配到的别名更长。**
  //      "写入工" 匹配到的最长别名是"写"（1 个字），可它有 3 个字
  //      —— 多出来的"入工"就不是动词的一部分，这个切法不成立。
  //
  //      所以这里改成：**匹配到的别名，必须几乎占满整个"她写的"**
  //      （最多再多一个冒号/空格/标点）。
  const 候选 = []
  for (const 工具 of 表) {
    for (const 说法 of [工具.名字, ...工具.别名]) {
      if (!干净.startsWith(说法)) continue
      const 多出来的 = 干净.slice(说法.length)
      // 多出来的部分只能是标点或者空 —— 不能是别的字
      const 干净的多余 = 多出来的.replace(/^[:：\s、，。．.]+/, '').replace(/[:：\s]+$/, '')
      if (干净的多余.length > 0) continue
      候选.push({ 工具, 说法 })
    }
  }
  if (候选.length) {
    候选.sort((a, b) => b.说法.length - a.说法.length)
    return 候选[0].工具
  }

  return null
}

/** 给提示词用的：把所有本事的说明拼成一段 */
function 拼工具说明(选项 = {}) {
  const 除了 = 选项.除了 || []
  const 只要 = Array.isArray(选项.只要) ? 选项.只要 : null
  const 行 = []
  for (const 工具 of 表) {
    if (除了.includes(工具.名字)) continue
    if (只要 && !只要.includes(工具.名字)) continue
    const 别名 = 工具.别名.length ? `（也可以写成：${工具.别名.slice(0, 4).join('、')}）` : ''
    const 危险 = { safe: '', write: '  ← 要经过他同意', shell: '  ← 每次都要他同意' }[工具.危险度]
    行.push(`【${工具.名字}】${别名}${危险}`)
    行.push(工具.说明)
    行.push('')
  }
  return 行.join('\n')
}

/**
 * 自检：每个工具的"做"是不是把该收的参数都收下了。
 *
 * 【为什么要这么个自检】
 *   2026-10-01 这一天，"第三个参数（怎么问他）被丢掉"这个 bug
 *   一口气出现了两处（写文件、跑命令）。两处的表现都是
 *   "功能静悄悄地不工作" —— 不报错，只是她那边回一句
 *   "这个窗口还缺一只手"。
 *
 *   所以加一道自检：**凡是要问他的工具，它的"做"必须声明三个参数**
 *   （参数、内容、选项）。参数少写了，函数.length 就对不上。
 *   这个检查跑在主程序启动时，未来的工具少写参数会当场被抓住。
 */
function 自检() {
  const 问题 = []
  for (const 工具 of 表) {
    const 个数 = 工具.做.length
    if (工具.危险度 === 'write' || 工具.危险度 === 'shell') {
      if (个数 < 3) {
        问题.push(`【${工具.名字}】要问他，但"做"只声明了 ${个数} 个参数 —— 选项（怎么问他）会被丢掉`)
      }
    } else if (个数 < 1) {
      问题.push(`【${工具.名字}】的"做"没有声明参数`)
    }
  }
  return 问题
}

module.exports = {
  表,
  按模式,
  认工具,
  为模式认工具: (模式) => {
    const 允许 = new Set(按模式(模式).map((工具) => 工具.名字))
    return (写法) => {
      const 工具 = 认工具(写法)
      return 工具 && 允许.has(工具.名字) ? 工具 : null
    }
  },
  注册,
  拼工具说明,
  自检,
  危险度们: ['safe', 'write', 'shell'],
  拿到: (名字) => 表.find((工具) => 工具.名字 === 名字) || null,
}

