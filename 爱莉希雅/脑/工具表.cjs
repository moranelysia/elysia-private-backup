/**
 * 工具表.cjs —— 她能动用的所有本事，一张表
 *
 * 【为什么要单独一张表】
 *   以前"查/读/列"三个工具散在 动手.cjs 里，靠 if 判断。
 *   要长成"像 DSH 一样会干活"的样子，工具会越来越多（写文件、跑命令、
 *   找代码、git、做文档……），散着写很快就乱了。
 *
 *   所以：**每个工具自己声明自己是什么**，主循环只认这张表。
 *   加工具 = 加一个文件 + 在这儿登记一行。
 *
 * 【每一项要写清楚什么】
 *   名字     她写在标记里的名字（[读:...] 里的"读"）
 *   别名     她可能用的别的说法（她会变着法儿说"看一下""读读"）
 *   危险度   决定要不要问你 —— 见下面三档
 *   说明     给**她**看的（她得知道这工具是干嘛的、参数怎么写）
 *   做       真正干活的那个函数
 *
 * 【危险度三档 —— 这是整套东西的安全阀】
 *   safe   自己就能做，不问。查资料、读文件、列目录都算。
 *   write  会改动硬盘上的东西。**默认要问你**（除非你放行过那个目录）。
 *   shell  跑命令。这个是最大的口子 —— 一条命令能干任何事，
 *          所以**永远要问你**，不给"一直允许"。
 *
 *   （Cyrene 那边是四档权限 + 沙箱兜边界。我们没有沙箱，
 *     所以把"能不能做"和"能碰到哪儿"都压在这三档 + 路径白名单里。
 *     它的 scoped 档直接放行写，我们不敢 —— 因为我们底下没有第二层网。）
 */
