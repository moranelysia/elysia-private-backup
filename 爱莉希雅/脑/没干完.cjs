/**
 * 没干完.cjs —— 她干活干到一半，程序断了，别让那一轮白干
 *
 * 【它治的是什么】
 *   她干一件活要来回好几趟：读文件 → 你点头 → 写文件 → 跑一下 → 再看结果。
 *   这一串**只活在内存里**。中间任何一下断了（Electron 崩了、你点了"全部关掉"、
 *   断电、我改代码重启她），那一串就没了：重启之后她只记得你们聊过什么，
 *   完全不记得刚才在干什么。
 *
 *   更麻烦的是"她到底写成没有"没人知道 —— 程序是在她正写文件那一刻断的，
 *   文件是写了一半还是写完了？
 *
 * 【为什么不学 Cyrene 那样自动接着跑】
 *   Cyrene 重启后会恢复状态、接着跑。我们不敢，理由很实在：
 *   它底下有沙箱、有权限层、有"副作用记账"，重放之前能判断安不安全；
 *   我们底下什么都没有。自动接着跑 = 可能把一条已经跑过的命令再跑一遍。
 *
 *   所以我们只留一张便条：下次她开口时，把"上次那个活儿断在半路了、
 *   这几件事结果不知道、别自己重做、先问他"塞给她，让她自己决定。
 *   这跟 Cyrene 提示词里那句话是一个意思：
 *     「以上副作用结果未知，不得自动重放；先向用户查证实际结果后再决定下一步。」
 *
 * 【为什么只记 write / shell 两种】
 *   工具表里每个工具都有危险度：
 *     safe  —— 查、读、列、找、派。纯看，不动任何东西。
 *              这种断了就断了，重来一遍只花几秒钟，不值得记。
 *     write —— 往硬盘上写东西。
 *     shell —— 跑命令，一条命令能干任何事。
 *   只有后两种"做过就有痕迹、重做可能出事"，才需要留纸条。
 *
 * 【为什么"动手前"要单独落一次盘】
 *   要是只在她做完之后才落盘，"正做的时候断了"这一格就永远记不上 ——
 *   而那一格恰恰最要紧（文件写了一半）。所以会改变东西的事都要落两次：
 *   **动手前**记一笔"我要做这个了"，**做完了**再挪到"确定做过的"里去。
 *   中间断了的话，纸上就留着一条"要动手、没下文" —— 那就是"结果不知道"。
 *   （数据库管这个叫 write-ahead log，我们这个是它的迷你版。）
 *
 * 【为什么是两张纸，不是一个文件】
 *   一开始我用一个文件同时干两件事，结果它们互相踩：
 *     · 他重启后在别的对话里干了个新活 → 覆盖掉旧纸，旧纸没了
 *     · 他重启后只聊天 → 那张纸没被"用掉"，于是每次开口都念一遍
 *     · 这轮的活干完了要撕纸 → 顺手把"还没告诉他的旧纸"也撕了
 *   所以拆成两张，各管各的：
 *     没做完的-<段号>.json    这一轮正在干的活。干活时铺，正常走完就撕，
 *                              **异常/崩溃时留着** —— 留着的那张就是线索。
 *     要告诉她的-<段号>.json  上一轮没干完、还没跟她交代过的。
 *                              开机第一次有人问的时候，上一张"转正"成这一张
 *                              （改名，原子操作），她看过之后才撕。
 *
 * 【为什么按对话分段】
 *   他有好几段对话。A 段断在半路的活儿，跑到 B 段去提就是串台。
 *   文件名里带段号，各段互不干扰。
 *
 * 【存在哪、为什么不进备份】
 *   .cache\ 是临时目录，备份脚本本来就跳过它。这是对的 ——
 *   这个文件要么被消费掉（她看到便条），要么过期作废，
 *   不该跟着备份搬到另一台电脑上去。
 *
 * 用法（当模块）:
 *   const 没干完 = require('./没干完.cjs')
 *   没干完.盯住('dmusffxjd')                                  // 后面几步都作用于这一段
 *   没干完.开始({ 他说的: '帮我把那个 C 程序改一下' })          // 铺纸
 *   没干完.要动手了({ 名字: '写', 参数: 'main.c', 危险度: 'write' })
 *   没干完.动完了({ 名字: '写', 参数: 'main.c', 危险度: 'write', 好: true, 说明: '写好了' })
 *   没干完.干完了()                                           // 正常收工，撕纸
 *   const 便条 = 没干完.认领('dmusffxjd')                      // 开机问一次
 *   没干完.变成便条(便条)                                      // 生成给她看的那段话
 *   没干完.看过了('dmusffxjd')                                 // 她看过了，撕掉
 */
'use strict'

const fs = require('node:fs')
const path = require('node:path')
const 配置 = require('./配置.cjs')

const 项目根 = 配置.项目根
// 平时就放 .cache。环境变量那个口子只给测试用 —— 不然测一次就往真的
// .cache 里丢几张假纸条，还得记得擦，早晚会忘。
const 存放目录 = process.env.ELYSIA_纸条目录 || 配置.缓存目录

/** 超过这个岁数的纸条就别留了 —— 三天前断的活儿，他早忘了 */
const 保质期 = 3 * 24 * 60 * 60 * 1000

/** 两边各留这么多条，免得她一口气动了几十次手把纸条撑爆 */
const 最多几条 = 50

/** 参数和说明都要截短 —— 纸条是给她看的，不是把整个文件搬进去 */
const 参数上限 = 300
const 说明上限 = 200

// ---------------------------------------------------------------
//  状态
// ---------------------------------------------------------------

/** 正在盯哪一段对话（干活时由 对话.cjs 设好） */
let 盯着哪一段 = ''

/** 这一轮正在干的活（内存里那份，避免每动一次手都读一遍盘） */
let 手上这份 = null

/** 这张是不是**这一轮**铺的。不是的话，"干完了"不许撕它 —— 见 干完了() */
let 这次是我铺的 = false

/** 认领过的便条（同一次运行里别重复认领同一段） */
let 认领存着 = null

// ---------------------------------------------------------------
//  路径
// ---------------------------------------------------------------

/** 段号要变成安全的文件名（理论上不会有事，但文件名里不能有 \ / : * ? " < > |） */
function 洗(段号) {
  const 干净 = String(段号 || '默认').replace(/[\\/:*?"<>|]/g, '_').trim()
  return 干净.slice(0, 60) || '默认'
}

/** 这一轮正在干的活 */
function 干活路径(段号 = 盯着哪一段) {
  return path.join(存放目录, `没做完的-${洗(段号)}.json`)
}

/** 还没告诉过她的那张便条 */
function 便条路径(段号 = 盯着哪一段) {
  return path.join(存放目录, `要告诉她的-${洗(段号)}.json`)
}

function 现在() {
  return new Date().toLocaleString('zh-CN', { hour12: false })
}

function 短(东西, 上限) {
  const 字 = String(东西 == null ? '' : 东西)
  return 字.length > 上限 ? 字.slice(0, 上限) + '…' : 字
}

/**
 * 往盘上写。
 *
 * 【为什么要先写 .正在写 再改名】
 *   正在写的那一刻断电，会留下半截 JSON。半截 JSON 比没有更坏 ——
 *   开机读的时候解析失败，那一条线索就白留了。
 *   先写临时文件、写完整了再改名，改名在文件系统层面是原子的：
 *   要么是旧的完整版，要么是新的完整版，不会有半截。
 *
 * 【失败了为什么只打一行日志】
 *   记进度这件事本身坏了，大不了这次没有纸条。它不能耽误她干活 ——
 *   跟 脑\修剪工具结果.cjs 里"桌子收拾不成也要让她说话"是一个道理。
 */
function 落盘(路径, 内容) {
  try {
    fs.mkdirSync(存放目录, { recursive: true })
    const 临时 = 路径 + '.正在写'
    fs.writeFileSync(临时, JSON.stringify(内容, null, 2), 'utf8')
    fs.renameSync(临时, 路径)
    return true
  } catch (错误) {
    console.log('⚠ 没干完的活儿记不下来: ' + 错误.message)
    return false
  }
}

function 悄悄删(路径) {
  try {
    fs.rmSync(路径, { force: true })
  } catch {
    /* 删不掉也不耽误事 */
  }
}

// ---------------------------------------------------------------
//  干活这一路
