/** 从这一刻起，后面几步都作用于这一段对话 */
function 盯住(段号) {
  盯着哪一段 = String(段号 || '')
  return 盯着哪一段
}

/**
 * 她现在开始干一件活了。
 * 只有干活模式才会调 —— 聊天一轮就完了，中间没有"半路"可言。
 */
function 开始(选项 = {}) {
  if (选项.对话 !== undefined) 盯住(选项.对话)
  手上这份 = {
    对话: 盯着哪一段,
    他说的: 短(选项.他说的, 500),
    开始: 现在(),
    断在: 现在(),
    确定的: [],
    不知道的: [],
  }
  这次是我铺的 = true
  落盘(干活路径(), 手上这份)
  return 手上这份
}

/**
 * 她要动手了 —— 在**做之前**记一笔。
 * 做完之后要用 动完了() 把它挪走；没挪走就说明当时断了。
 */
function 要动手了(选项 = {}) {
  if (!手上这份) return
  if (选项.危险度 === 'safe') return // 纯看的，断了重来一遍没事，不值得记
  try {
    const 参数 = 短(选项.参数, 参数上限)
    // 同一样事情连着记两次就别记了（她有时候会重复写同一个标记）
    const 已有 = 手上这份.不知道的.some((x) => x.名字 === 选项.名字 && x.参数 === 参数)
    if (!已有) {
      手上这份.不知道的.push({ 名字: 选项.名字, 参数, 什么时候: 现在() })
      if (手上这份.不知道的.length > 最多几条) 手上这份.不知道的.shift()
    }
    手上这份.断在 = 现在()
    落盘(干活路径(), 手上这份)
  } catch (错误) {
    console.log('⚠ 没干完的活儿记不下来: ' + 错误.message)
  }
}

/** 这件事做完了（成功或失败都算做完）—— 从"不知道"挪到"确定" */
function 动完了(选项 = {}) {
  if (!手上这份) return
  if (选项.危险度 === 'safe') return
  try {
    const 参数 = 短(选项.参数, 参数上限)
    const 位置 = 手上这份.不知道的.findIndex((x) => x.名字 === 选项.名字 && x.参数 === 参数)
    if (位置 >= 0) 手上这份.不知道的.splice(位置, 1)

    手上这份.确定的.push({
      名字: 选项.名字,
      参数,
      好: !!选项.好,
      说明: 短(选项.说明, 说明上限),
    })
    if (手上这份.确定的.length > 最多几条) 手上这份.确定的.shift()

    手上这份.断在 = 现在()
    落盘(干活路径(), 手上这份)
  } catch (错误) {
    console.log('⚠ 没干完的活儿记不下来: ' + 错误.message)
  }
}

/**
 * 正常收工 —— 把干活的纸撕掉。
 *
 * 【什么时候算"正常收工"】
 *   整轮说话走完了（不管她最后答得怎么样）就算这一轮结束。
 *   注意：**这一轮里有工具失败不算没干完** —— 失败了她是知道的，
 *   她会在这一轮里自己处理（重试、换办法、或者老实说没成）。
 *   只有"程序没走到终点就没了"才算没干完。
 *
 * 【为什么必须先看"这次是不是我铺的"】
 *   要是无条件删，会出这种事：他重启后在**别的**对话里随口聊两句，
 *   而那一段的半路活儿是另一段留下的 —— 一张纸都不该被碰，
 *   结果被这句话顺手撕了。
 */
function 干完了() {
  if (!这次是我铺的) return false
  手上这份 = null
  这次是我铺的 = false
  悄悄删(干活路径())
  悄悄删(干活路径() + '.正在写')
  return true
}

