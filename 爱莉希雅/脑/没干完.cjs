/** 读一个 JSON 文件，读不出来就返回 null（顺带把坏的清掉） */
function 读一份(路径) {
  let 内容
  try {
    内容 = fs.readFileSync(路径, 'utf8').replace(/^\uFEFF/, '')
  } catch {
    return null
  }
  try {
    const 那份 = JSON.parse(内容)
    return 那份 && typeof 那份 === 'object' ? 那份 : null
  } catch {
    // 半截的 JSON（写的时候断电了，理论上不会 —— 但真坏了就清掉，
    // 留着只会每次开机都报一次错）
    console.log('⚠ 上次的进度纸条读不出来（半截的），清掉')
    悄悄删(路径)
    return null
  }
}

/** 这张纸还有没有值得说的东西 */
function 有内容吗(那份) {
  return !!那份 && (那份.不知道的 || []).length + (那份.确定的 || []).length > 0
}

/** 过期没有 */
function 过期了吗(那份) {
  const 断在 = Date.parse(那份.断在) || Date.parse(那份.开始) || 0
  return 断在 > 0 && Date.now() - 断在 > 保质期
}

/**
 * 开机认领：上次没走完的那张纸，转正成"要告诉她的便条"，然后读出来。
 *
 * 【为什么是"改名"而不是"读出来再删"】
 *   改名是原子的。要是读出来再删，中间那一下崩了，纸就没了 ——
 *   而那正是最可能崩的时候（刚开完机）。
 *   改名之后，纸还在盘上，只是换了个名字，叫"要告诉她的"。
 *
 * @param {string} 段号 哪一段对话
 * @returns {object|null} 有便条就返回，没有返回 null
 */
function 认领(段号) {
  const 这段 = String(段号 || '')
  if (认领存着 && 认领存着.段号 === 这段) return 认领存着.那份

  const 干活 = 干活路径(这段)
  const 便条 = 便条路径(这段)

  // 上次没走完的 → 转正
  try {
    if (fs.existsSync(干活)) {
      if (fs.existsSync(便条)) 悄悄删(便条) // 理论上不该同时有；真有就以"没走完的"为准
      fs.renameSync(干活, 便条)
      console.log('  · 上次有个活儿没干完，捡回来了')
    }
  } catch (错误) {
    console.log('⚠ 上次没干完的活儿捡不回来: ' + 错误.message)
  }

  let 那份 = 读一份(便条)

  if (那份 && 过期了吗(那份)) {
    console.log('  （上次的进度纸条过期了，清掉）')
    悄悄删(便条)
    那份 = null
  }

  // 什么手都没动过 —— 那多半是刚开始就断了，没什么可交代的
  if (那份 && !有内容吗(那份)) {
    悄悄删(便条)
    那份 = null
  }

  // 转正后要是没用，把空壳收掉，别在 .cache 里存一堆空文件
  if (!那份) 悄悄删(便条)

  认领存着 = { 段号: 这段, 那份 }
  return 那份
}

/** 她看过了 —— 把便条撕掉，免得她每次开口都念一遍 */
function 看过了(段号) {
  const 这段 = String(段号 || '')
  悄悄删(便条路径(这段))
  悄悄删(便条路径(这段) + '.正在写')
  if (认领存着 && 认领存着.段号 === 这段) 认领存着 = null
  return true
}

/**
 * 把便条变成给**她**看的一段话。
 *
 * 【为什么放在最后一条消息里】
 *   前面那一大段（她是谁）要每次一模一样才缓存得住。
 *   往前面插东西 = 缓存全废 = 每句都多花钱。放最后就只影响它自己。
 *   见 脑\对话.cjs 里拼消息那一段。
 *
 * 【为什么非要写"不许自己重做"】
 *   不写的话，她看到"我正要跑 gcc"，最自然的反应就是再跑一遍 ——
 *   万一下面那一下本来已经成功了，这就是重复动手。
 *   模型是很听话的：**你不明说，它就会自己补全**。所以这句必须写死。
 */
function 变成便条(那份) {
  if (!那份) return ''

  const 行 = []
  行.push('【上次没干完的活儿】')
  行.push(`上次你正在替他做这件事：「${那份.他说的 || '（没记下来）'}」`)
  行.push(`干到一半程序断了（${那份.断在 || '时间不详'}）。下面是你断之前的情况：`)
  行.push('')

  const 确定的 = 那份.确定的 || []
  if (确定的.length) {
    行.push('已经确定做完的：')
    for (const 一件 of 确定的) {
      行.push(`  · ${一件.名字} ${一件.参数} —— ${一件.好 ? '' : '没成：'}${一件.说明 || ''}`)
    }
    行.push('')
  }

  const 不知道的 = 那份.不知道的 || []
  if (不知道的.length) {
    行.push('⚠ **结果不知道的**（正做这件事的时候断的，做没做成没人知道）：')
    for (const 一件 of 不知道的) {
      行.push(`  · ${一件.名字} ${一件.参数}`)
    }
    行.push('')
    行.push(
      '那几件"结果不知道"的事，**不许自己重做一遍** —— ' +
        '它们可能已经做成了，再动一次就是重复动手。' +
        '先问问他那边现在是什么情况（文件长什么样、命令跑出什么了），' +
        '弄清楚之后再说下一步。',
    )
    行.push('')
  }

  行.push(
    '（这段话是程序写在便条上给你看的，不是他说的。' +
      '跟他提这件事的时候，用你自己的话说，别把这段话抄出来。）',
  )

  return 行.join('\n')
}

