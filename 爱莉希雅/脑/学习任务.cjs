/**
 * 学习任务.cjs —— "接下来要做什么"那张清单
 *
 * 【它跟 学习进度.cjs 不是一回事】
 *   进度记的是**已经走过的路**：学到哪了、哪些懂了、还卡在哪儿 —— 回头看。
 *   任务记的是**接下来要做的**：看完这份课件、做三道题、把上次那道错题重做 —— 往前看。
 *   两个都围着课程转，但一个是账本、一个是待办。别合并：
 *   合并之后"完成情况"就说不清了（学了一半算完成吗？）。
 *
 * 【为什么存成 markdown 的勾选框】
 *     - [ ] 看完第一章
 *     - [x] 装好环境
 *   这一行格式**他改得动、她改得动、界面读得懂**。
 *   存成 json 的话他自己打开就改不动了（手改一个标点就整篇坏掉）。
 *   而且 Obsidian、VS Code、GitHub 都认这个语法 —— 他将来换工具也不吃亏。
 *
 * 【谁在写】
 *   三边都写：他在界面上勾、她在对话里加、他也可以直接改那个文件。
 *   所以每次操作都**重新读一遍文件**再改 —— 不缓存。
 *   缓存的话，他手改完界面上还显示旧的，而且没人知道为什么。
 */
'use strict'

const fs = require('node:fs')
const path = require('node:path')

const 提示词 = require('./提示词.cjs')

const 任务文件 = path.join(提示词.学习区根, '任务.md')

/** 环境变量那个口子只给测试用 */
function 路径() {
  return process.env.ELYSIA_任务文件 || 任务文件
}

/** 新清单顶上那三行说明 —— 写() 和 空壳 共用一份，免得改一处忘另一处 */
const 说明行 = [
  '> 这是你们的学习待办。',
  '> 你随时可以自己改（就是普通的 markdown 勾选框，把 ` ` 换成 `x` 就算做完了），',
  '> 爱莉希雅也能往上加、能替你勾 —— 她动完会跟你说一声。',
]

const 空壳 = ['# 学习任务', '', ...说明行, '', '（还没有任务。）', ''].join('\n')

/** 一行任务长这样：  - [ ] 看完第一章   /   - [x] 装好环境 */
const 行长相 = /^\s*[-*]\s*\[([ xX])\]\s*(.+?)\s*$/

/** 空清单时占位的那一行。它不是任务（读的时候要跳过），写的时候按有没有任务决定留不留 */
const 占位行 = /^\s*（还没有任务。）\s*$/

/**
 * 读任务清单。
 * @returns {Array<{文字:string, 完成:boolean}>}
 */
function 读() {
  let 内容
  try {
    内容 = fs.readFileSync(路径(), 'utf8').replace(/^\uFEFF/, '')
  } catch {
    return []
  }

  const 任务们 = []
  for (const 行 of 内容.split('\n')) {
    const 命中 = 行长相.exec(行)
    if (!命中) continue
    const 文字 = 命中[2]
    // 空勾选框不算任务（"- [ ] " 后面啥也没有，多半是手滑）
    if (!文字 || 文字 === '（还没有任务。）') continue
    任务们.push({ 文字, 完成: 命中[1].toLowerCase() === 'x' })
  }
  return 任务们
}

/** 文件在不在 */
function 有吗() {
  return fs.existsSync(路径())
}

/** 建一个空的（已经在了就什么都不做） */
function 建空的() {
  const 一个 = 路径()
  if (fs.existsSync(一个)) return false
  fs.mkdirSync(path.dirname(一个), { recursive: true })
  fs.writeFileSync(一个, 空壳, 'utf8')
  return true
}

/**
 * 把清单写回去。
 *
 * 【写的是"任务行"，不是"整个文件"】
 *   这儿是**就地改**：读原文，一行一行过，碰到任务行就换成新的状态，
 *   别的行 —— 他自己写的标题、说明、随手记的话 —— 原样留着。
 *
 *   ⚠️ 这儿踩过一次，记着：最早写的是"整篇重写"（生成一份标准清单覆盖掉原文件），
 *   看着更干净，实际上**会把他手写的行全部抹掉**。
 *   他在清单里记一句"老师说期中会考第三章"，下一次她随手勾个任务，那句话就没了，
 *   而且谁都不会发现。是 测学习任务.cjs 里"他手写的那句还在吗"这一格抓出来的。
 *
 * 【为什么不用"第几行"去改】
 *   因为清单是**他自己也能改**的：他可能删了一行、加了三个字、或者换了顺序。
 *   按行号定位的做法在他手改过之后就对不上了 ——
 *   那种错最恶心：勾的是第 3 条，动的是第 4 条，而且不报错。
 *   所以每次重新读全，再按"读出来的顺序"依次对上文件里的任务行。
 *
 * 【代价，说清楚】他要是拿 `*` 当项目符号、或者给任务加了缩进，
 *   重写之后会被拍平成 `- [ ]`。只丢样式不丢内容。
 *   （`1. [ ] xxx` 这种有序列表读的时候就不认，会被当成"他自己的文字"原样留着，不会消失。）
 */
function 写(任务们) {
  const 一个 = 路径()
  const 成行 = (任务) => `- [${任务.完成 ? 'x' : ' '}] ${任务.文字}`

  let 原文 = null
  try {
    原文 = fs.readFileSync(一个, 'utf8').replace(/^\uFEFF/, '')
  } catch {
    原文 = null
  }

  let 行们
  if (原文 === null) {
    // 文件还不存在：给一份带说明的标准清单
    行们 = ['# 学习任务', '', ...说明行, '']
    for (const 任务 of 任务们) 行们.push(成行(任务))
    行们.push('')
  } else {
    行们 = []
    let 用掉 = 0
    for (const 行 of 原文.split('\n')) {
      if (占位行.test(行)) continue // 先摘掉，末尾按"到底有没有任务"再决定补不补
      if (行长相.test(行)) {
        // 任务行：按读出来的顺序换成新的；数组比它短，这一行就是被删掉的
        if (用掉 < 任务们.length) {
          行们.push(成行(任务们[用掉]))
          用掉++
        }
        continue
      }
      行们.push(行)
    }

    // 新加的任务（数组比原文的任务行多）挂到末尾
    const 多出来 = 任务们.slice(用掉)
    if (多出来.length) {
      补空行(行们)
      for (const 任务 of 多出来) 行们.push(成行(任务))
    }

    if (!任务们.length) {
      补空行(行们)
      行们.push('（还没有任务。）')
    }
  }

  // 收尾：以换行结束，且不堆一长串空行
  while (行们.length && 行们[行们.length - 1] === '') 行们.pop()
  行们.push('')

  fs.mkdirSync(path.dirname(一个), { recursive: true })
  // 先写临时文件再改名：写到一半断电的话，清单不至于变成半截的
  const 临时 = 一个 + '.正在写'
  fs.writeFileSync(临时, 行们.join('\n'), 'utf8')
  fs.renameSync(临时, 一个)
  return true
}

/** 末尾接一段内容前，先垫一个空行（原来已经空着就不重复垫） */
function 补空行(行们) {
  while (行们.length && 行们[行们.length - 1] === '') 行们.pop()
  if (行们.length) 行们.push('')
}

/** 统计：一共几条、做完几条 */
function 统计() {
  const 任务们 = 读()
  const 做完 = 任务们.filter((一个) => 一个.完成).length
  return { 一共: 任务们.length, 做完, 没做: 任务们.length - 做完 }
}

/**
 * 加一条。
 * @param {string} 文字
 * @returns {{好:boolean, 说明?:string, 序号?:number}}
 */
function 加(文字) {
  const 干净 = String(文字 || '').replace(/\s+/g, ' ').trim()
  if (!干净) return { 好: false, 说明: '没说要加什么' }
  if (干净.length > 200) return { 好: false, 说明: '一条任务别写这么长（200 字以内）' }

  建空的()
  const 任务们 = 读()
  // 一模一样的就不重复加了 —— 她常常会重复说同一件事
  if (任务们.some((一个) => 一个.文字 === 干净)) {
    return { 好: false, 说明: '这条已经在清单里了' }
  }
  任务们.push({ 文字: 干净, 完成: false })
  写(任务们)
  return { 好: true, 序号: 任务们.length - 1 }
}

/**
 * 勾掉 / 取消勾掉某一条。
 *
 * 【为什么要按"文字"找，不按序号】
 *   她在对话里说的是"把看课件那条勾了"，不是一个数字。
 *   而且清单是他也能改的，序号随时会变。
 *   所以这儿**按文字模糊找**：找得到就勾，找不到就如实说找不到 ——
 *   绝不"猜一个最像的勾上"。那比不勾还坏。
 *
 * @param {string} 找什么 任务文字（可以只写一部分）
 * @param {boolean} 完成
 */
function 勾(找什么, 完成 = true) {
  const 要找 = String(找什么 || '').replace(/\s+/g, ' ').trim()
  if (!要找) return { 好: false, 说明: '没说要勾哪一条' }

  const 任务们 = 读()
  if (!任务们.length) return { 好: false, 说明: '清单里现在一条任务都没有' }

  // 先找一模一样的，再找"包含"的
  let 位置 = 任务们.findIndex((一个) => 一个.文字 === 要找)
  if (位置 < 0) {
    const 像的 = 任务们
      .map((一个, 号) => ({ 号, 一个 }))
      .filter(({ 一个 }) => 一个.文字.includes(要找) || 要找.includes(一个.文字))
    if (像的.length > 1) {
      return {
        好: false,
        说明: `「${要找}」能对上好几条，我不敢乱勾：${像的.map((x) => x.一个.文字).join('；')}`,
      }
    }
    if (像的.length === 1) 位置 = 像的[0].号
  }

  if (位置 < 0) {
    return { 好: false, 说明: `清单里没有「${要找}」这一条，我没动它` }
  }

  任务们[位置].完成 = Boolean(完成)
  写(任务们)
  return { 好: true, 序号: 位置, 文字: 任务们[位置].文字, 完成: Boolean(完成) }
}

/** 删掉一条（同样按文字找，同样不许猜） */
function 删(找什么) {
  const 要找 = String(找什么 || '').replace(/\s+/g, ' ').trim()
  if (!要找) return { 好: false, 说明: '没说要删哪一条' }

  const 任务们 = 读()
  const 位置 = 任务们.findIndex((一个) => 一个.文字 === 要找)
  if (位置 < 0) return { 好: false, 说明: `清单里没有「${要找}」这一条` }

  任务们.splice(位置, 1)
  写(任务们)
  return { 好: true, 文字: 要找 }
}

/**
 * 拼一段"你们现在有什么任务"给**她**看。
 *
 * 【为什么带上序号和完成状态】
 *   她需要知道"哪几条还没做"，才能接着往下安排；
 *   也需要知道"这条已经做完了"，免得又提一遍。
 *
 * 【为什么空清单也说一句】
 *   不说的话她不知道"是没任务"还是"没读到文件" ——
 *   而那两件事对她的下一步完全不同。
 */
function 拼给她() {
  const 任务们 = 读()
  const 行 = ['===== 你们的学习待办 =====', '']

  if (!任务们.length) {
    行.push('（清单是空的 —— 还没有安排任务。该安排的时候你主动提一句。）')
  } else {
    const { 一共, 做完 } = 统计()
    行.push(`一共 ${一共} 条，做完 ${做完} 条：`)
    行.push('')
    任务们.forEach((一个, 号) => {
      行.push(`  ${号 + 1}. [${一个.完成 ? 'x' : ' '}] ${一个.文字}`)
    })
    行.push('')
    行.push('还没做的那几条，是你们说好接下来要弄的。他要是问"接下来干嘛"，就照这个说。')
  }

  行.push('')
  行.push('这份清单在：' + 路径())
  行.push('（你想加一条、或者勾掉一条，用 [任务:] 那个标记，别直接写文件。）')
  行.push('')
  return 行.join('\n')
}

