/**
 * 把一个路径"洗干净"并检查它能不能碰。
 *
 * @param {string} 她写的路径  她写的可能是相对路径（相对项目根或工作区根）
 * @returns {{好:true, 绝对路径:string} | {好:false, 原因:string}}
 */
function 查路径(她写的) {
  const 原文 = String(她写的 || '').trim()
  if (!原文) return { 好: false, 原因: '路径是空的' }

  // 绝对路径就直接用，相对路径按"项目根 → 工作区根"依次试
  const 候选 = []
  if (path.isAbsolute(原文)) {
    候选.push(原文)
  } else {
    候选.push(path.resolve(项目根, 原文))
    候选.push(path.resolve(工作区根, 原文))
  }

  for (const 候选路径 of 候选) {
    // 规范化（把 .. 和 . 都算掉），这样 "记忆\..\..\C盘" 这种也会露馅
    const 规范 = path.resolve(候选路径)

    // 1. 必须在白名单里的某一个目录下面
    const 在白名单 = 白名单().some((目录) => {
      const 规范目录 = path.resolve(目录)
      return 规范 === 规范目录 || 规范.startsWith(规范目录 + path.sep)
    })
    if (!在白名单) continue

    // 2. 路径里不能撞上禁地
    const 分段 = 规范.split(path.sep)
    const 撞禁地 = 禁地.find((禁) => 分段.includes(禁) || 规范.endsWith(path.sep + 禁))
    if (撞禁地) return { 好: false, 原因: `那个地方不能看（${撞禁地}）` }

    // 3. 得真的存在
    if (!fs.existsSync(规范)) continue

    return { 好: true, 绝对路径: 规范 }
  }

  return { 好: false, 原因: `找不到这个地方，或者不在她能看的范围里：${原文}` }
}

