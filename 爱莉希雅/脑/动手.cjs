/** 把 HTML 里的标签扒掉，只留文字 */
function 去标签(html) {
  return String(html)
    .replace(/<[^>]+>/g, '')
    // HTML 实体：&nbsp; &ensp; &#123; 之类全都换成空格（不然会夹在摘要里）
    .replace(/&[a-zA-Z]+;/g, ' ')
    .replace(/&#\d+;/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}

/**
 * 从 Bing 的结果页里抠结果。
 *
 * 【为什么用"切块"而不是一个大正则】
 *   要跨很长的 HTML（标题、链接、摘要挨着但不一定同构），
 *   一个大正则非常脆。切成 <li class="b_algo"> 块之后，
 *   每块里各找各的，坏了一块不影响别的。
 */
function 抠搜索结果(html) {
  const 结果 = []
  const 块们 = html.split(/<li class="b_algo"/).slice(1)

  for (const 块 of 块们) {
    const 标题匹配 = 块.match(/<h2[^>]*>[\s\S]*?<a[^>]*>([\s\S]*?)<\/a>/)
    if (!标题匹配) continue
    const 链接匹配 = 块.match(/<h2[^>]*>\s*<a[^>]*href="([^"]+)"/)
    const 摘要匹配 = 块.match(/<p[^>]*>([\s\S]*?)<\/p>/)

    结果.push({
      标题: 去标签(标题匹配[1]),
      链接: 链接匹配 ? 链接匹配[1] : '',
      摘要: 摘要匹配 ? 去标签(摘要匹配[1]) : '',
    })
    if (结果.length >= 6) break
  }

  return 结果
}

/**
 * 把抓回来的页面字节解成文字 —— **要认编码**。
 *
 * 【为什么不能直接 response.text()】
 *   2026-10-01 实测：中关村在线那种中文站是 **GBK** 编码的，
 *   而 fetch 的 .text() 一律按 UTF-8 解 —— 整页变成
 *     "�ۺ�����-ZOL�йش�����"
 *   连"报价"两个字都认不出来，更别说找价格。
 *
 *   国内这些老站点（中关村、太平洋、很多论坛）大量用 GBK/GB2312。
 *   所以得先看一眼页面自己声明的编码，再决定怎么解。
 *
 * 【怎么知道它是什么编码】
 *   优先看 HTTP 头里的 charset，其次看 HTML 里的
 *   <meta charset="gbk"> 或 <meta http-equiv="Content-Type" content="...charset=gbk">。
 *   两个都没有就按 UTF-8（现在多数站是）。
 */
async function 解页面(回应) {
  const 缓冲 = Buffer.from(await 回应.arrayBuffer())

  // 从头里找
  let 编码 = (回应.headers.get('content-type') || '').match(/charset=([\w-]+)/i)?.[1]

  // 从头几个字节里找（HTML 的 meta）
  if (!编码) {
    const 头一段 = 缓冲.subarray(0, 2048).toString('latin1')
    编码 =
      头一段.match(/<meta[^>]+charset=["']?([\w-]+)/i)?.[1] ||
      头一段.match(/content=["'][^"']*charset=([\w-]+)/i)?.[1]
  }

  const 小写 = String(编码 || 'utf-8').toLowerCase()

  // GBK 那一族：用 Node 自带的 TextDecoder（它认识 gbk）
  if (/gb|gbk|gb2312|gb18030/.test(小写)) {
    try {
      return new TextDecoder('gbk').decode(缓冲)
    } catch {
      return new TextDecoder('gb18030').decode(缓冲)
    }
  }

  return 缓冲.toString('utf8')
}

/** 把 HTML 剥成纯文字（脚本样式去掉，标签去掉） */
function 剥成文字(html) {
  return String(html)
    .replace(/<script[\s\S]*?<\/script>/gi, ' ')
    .replace(/<style[\s\S]*?<\/style>/gi, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&nbsp;/g, ' ')
    .replace(/&[a-zA-Z]+;/g, ' ')
    .replace(/&#\d+;/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}

/**
 * 从一页网页里抠出带价格的句子。
 *
 * 【为什么要多这一步】
 *   2026-10-01 晚上的事：她帮使用者查"5060 多少钱"，
 *   Bing 回的那六条摘要是 ——
 *     "GeForce RTX | 探索光线追踪和 AI 新境界"
 *     "还分不清显卡型号RTX和GTX是什么意思？"
 *   **一条带价的都没有**（我换六种问法试过，六次都是 0 条带价）。
 *   她拿着这么一坨没答案的材料，被要求"讲给他听"，
 *   就搅出了「带英电竞和轻中度游戏里公认划算」这种不成词的话。
 *
 *   问题不在她会不会说话，在**给她的材料里根本没有答案**。
 *   所以往下再走一步：把结果里像"报价"的页面打开，从正文里捞价格。
 *
 * 【"像价格"怎么判 —— 修过一版】
 *   第一版要求"数字 + 元/块/￥"。实测 ZOL 的报价列表长这样：
 *     影驰GeForce RTX 5070 X2 大雪 12G 5399
 *   光秃秃一个数字，后面什么都不带 —— 于是 135 个数字一个都没捞着。
 *   现在两条路：有货币符号/价格字样的，或者**光秃秃的 3~5 位数**
 *   （排除年份、跑分、显存那种）。
 */
function 抠价格句子(页面文字) {
  const 候选 = []
  const 行们 = String(页面文字).split(/[\n。；;|]/)

  /** 这一行里的数字像不像"价格" */
  const 有像价格的数字 = (净) => {
    // 一、有货币符号或者"元/块"—— 最确定
    if (/[￥¥]\s*[0-9]|[0-9]+\s*(元|块钱|块)/.test(净)) return true

    // 二、有"价格/报价/售价"这类字样，后面跟着数字
    if (/(价格|报价|售价|到手价|券后价|现价|低至)[^0-9]{0,8}[0-9]{2,6}/.test(净)) return true

    // 三、光秃秃的数字：**只有 3~5 位、而且前面紧接着型号名**才算。
    //
    //   为什么加这么严：第一版只看"有没有 3~5 位数"，结果
    //   "超过 1000 款游戏和应用采用 RTX" 里的 1000 被当成价格捞了出来。
    //   那种假数字喂给她，比没数字更糟 —— 她会当真报给使用者。
    //
    //   真的报价行长这样（ZOL 的列表）：
    //     影驰GeForce RTX 5070 X2 大雪 12G 5399
    //   数字紧跟在显存/型号后面。所以要求前面 20 字里有"RTX/GTX/GB/G/型号数字"。
    const 数字们 = [...净.matchAll(/([0-9]{3,5})(?![0-9])/g)]
    for (const m of 数字们) {
      const 数 = Number(m[1])
      if (数 < 100 || 数 > 99999) continue
      const 后一位 = 净[m.index + m[1].length] || ''
      const 前一位 = 净[m.index - 1] || ''
      // 后面跟着量词/单位 → 不是价格
      if (/[款项个次年个月人台张份种]/.test(后一位)) continue
      // 前面是"超过/约/近/达到/第" → 不是价格
      if (/(超过|以上|约|近|达到|第|共|已|逾)$/.test(净.slice(Math.max(0, m.index - 3), m.index))) continue
      // 前面一位是数字/字母 → 多半是型号的一部分（RTX5060 里的 5060）
      if (/[0-9A-Za-z]/.test(前一位)) continue
      // 要求：前面 20 字内有型号痕迹，或者这行里有"价"字
      const 前文 = 净.slice(Math.max(0, m.index - 20), m.index)
      if (/RTX|GTX|RX|GB|Ti|super|显卡|内存|硬盘|处理器|CPU|GPU/i.test(前文) || /价/.test(净)) return true
    }

    return false
  }

  for (const 行 of 行们) {
    const 净 = 行.replace(/\s+/g, ' ').trim()
    if (净.length < 4 || 净.length > 120) continue
    if (/^[0-9]{4}\s*年/.test(净)) continue
    if (/^[0-9]+$/.test(净)) continue // 整行就一个数字，看不出是什么
    // 纯参数、纯跑分那些不要
    if (/(fps|帧数|跑分|功耗|接口|位宽|频率|核心数)/i.test(净) && !/[￥¥]|元/.test(净)) continue

    if (!有像价格的数字(净)) continue

    if (!候选.includes(净)) 候选.push(净)
    if (候选.length >= 25) break
  }

  return 候选
}

/** 打开一个网页，返回去掉标签的文字（会自动认编码） */
async function 读网页(地址) {
  const 回应 = await fetch(地址, { headers: 浏览器的头, signal: AbortSignal.timeout(12000) })
  if (!回应.ok) throw new Error('HTTP ' + 回应.status)
  const 类型 = 回应.headers.get('content-type') || ''
  if (类型 && !/text|html|json/i.test(类型)) throw new Error('不是网页（' + 类型 + '）')
  return 剥成文字(await 解页面(回应))
}

/**
 * 搜完之后，再去几个页面里捞价格。
 *
 * 【怎么挑要打开哪几个 —— 改过一版】
 *   第一版挑得太严（要求标题/链接里有"报价""京东"之类），
 *   结果实测六条结果**一条都没被打开** —— 因为那次 Bing 回的全是
 *   NVIDIA 官网和百科，一个"报价"字样都没有。功能等于没做。
 *
 *   现在改成：**先挑像的，不够就拿前两名凑数**。
 *   反正开一个页面就一两秒，宁可多开一个也不要空手而归。
 */
async function 顺手捞价(结果们) {
  const 打过分的 = 结果们
    .map((条, i) => {
      const 全 = (条.标题 || '') + ' ' + (条.链接 || '')
      let 分 = 0
      if (/报价|价格|多少钱|售价/.test(全)) 分 += 3
      if (/京东|淘宝|天猫|拼多多|中关村|zol|smzdm|值得买/i.test(全)) 分 += 2
      if (/评测|天池|天梯|百科|wiki/i.test(全)) 分 -= 1
      if (!/^https?:/.test(条.链接 || '')) 分 -= 10
      return { ...条, 序号: i, 分 }
    })
    .filter((条) => 条.分 > -10)

  const 像的 = 打过分的.filter((条) => 条.分 > 0)
  const 凑数的 = 打过分的.filter((条) => 条.分 <= 0)
  // 最多开 4 个：像的先上，不够用前两名凑
  const 要开的 = [...像的, ...凑数的].slice(0, 4)

  const 捞到的 = []
  for (const 条 of 要开的) {
    try {
      const 正文 = await 读网页(条.链接)
      const 句子们 = 抠价格句子(正文)
      if (句子们.length) {
        捞到的.push({ 站点: 条.标题, 链接: 条.链接, 句子们: 句子们.slice(0, 8) })
      }
    } catch {
      /* 开不了就算了 —— 不能因为一个页面打不开就让整个搜索失败 */
    }
  }
  return 捞到的
}

async function 查(关键词, { fetch函数 = global.fetch, 中止, 钥匙 } = {}) {
  const 词 = String(关键词 || '').trim()
  if (!词) return { 好: false, 说明: '没给要查的东西' }

  let 搜到 = await 联网搜索.搜索(词, { fetch函数, 中止, 钥匙 })
  if (!搜到.好) return 搜到
  let 结果 = 搜到.结果
  let 已重试 = false
  const { 是天气查询, 选天气结果 } = require('./搜索校验.cjs')
  const 问天气 = 是天气查询(词)
  if (问天气) {
    结果 = 选天气结果(词, 结果)
    if (!结果.length) {
      // 同一通用搜索入口有界重试一次，只限制可靠气象来源；不接专用天气接口。
      已重试 = true
      搜到 = await 联网搜索.搜索(词, {
        fetch函数, 中止, 钥匙,
        限定域名: ['weather.com.cn', 'nmc.cn', 'cma.gov.cn'],
      })
      if (搜到.好) 结果 = 选天气结果(词, 搜到.结果)
    }
    if (!结果.length) return {
      好: false, 说明: '通用搜索未取得与地点和日期匹配的气象来源，限定可靠来源重试一次后仍无有效结果。不能据此推断当地天气，也不能编造温度或降雨；若地点不明确先询问城市。',
      原因: '天气结果不可靠', 已重试: true,
      错误类别: 搜到.错误类别 || '结果不可靠',
    }
  }

  if (!结果.length) {
    return { 好: false, 说明: '搜到了页面，但一条结果都没抠出来（它可能改版了）' }
  }

  const 搜索来源 = require('./搜索来源.cjs')
  const 搜索验证 = require('./搜索验证.cjs')
  let 来源检查 = 搜索来源.评估材料(结果)
  let 材料门槛 = 搜索验证.检查门槛(词, 来源检查.审查)
  let 补搜失败说明 = ''

  // 高时效或高影响事实至少要两个不同来源；高时效还要有一条可检查日期。
  // 首次材料不足时只补搜一次。天气若已经做过限定来源重试，就不再发第三次请求。
  if (材料门槛.需要加强 && !材料门槛.通过 && !已重试) {
    已重试 = true
    const 补搜词 = 搜索验证.补搜查询(词, 材料门槛)
    const 补搜 = await 联网搜索.搜索(补搜词, { fetch函数, 中止, 钥匙 })
    if (补搜.好) {
      const 补搜结果 = 问天气 ? 选天气结果(词, 补搜.结果) : 补搜.结果
      结果 = 搜索验证.合并结果(结果, 补搜结果)
    } else {
      补搜失败说明 = 补搜.说明 || '补搜失败'
    }
    来源检查 = 搜索来源.评估材料(结果)
    材料门槛 = 搜索验证.检查门槛(词, 来源检查.审查)
  }
  结果 = 来源检查.结果
  const 冲突检查 = require('./搜索冲突.cjs').找冲突(词, 结果)

  // 拼成给她看的检索材料：标题、摘要、日期和来源。服务排名不等于事实已经核实。
  const 行 = [`通过 ${搜到.服务 || '联网搜索'} 搜索「${词}」的结果：`]
  行.push('这些是待核验的网页材料，不是搜索服务生成的答案。请优先使用官方/原始来源，检查日期；来源冲突或材料不足时明确说明。')
  行.push(`来源审查：${来源检查.审查.来源覆盖}；${来源检查.审查.日期覆盖}；证据范围仅为搜索摘要，尚未读取网页正文。`)
  行.push('域名类型只按网址结构标记，不等于已经证明该网页是目标主体的官网，也不等于多条结果已经互相印证。')
  if (材料门槛.需要加强) {
    行.push(材料门槛.通过
      ? `材料门槛：已达到最低要求（${材料门槛.原因.join('、')}查询）；仍需比较各来源正文是否真的支持同一结论。`
      : `材料门槛：不足（缺少${材料门槛.缺少.join('；')}）。不能把下面材料表述成已经核实；应说明目前找到什么、还缺什么。`)
  }
  if (补搜失败说明) 行.push(`补搜状态：已尝试一次但失败——${补搜失败说明}`)
  if (冲突检查.有冲突) {
    行.push('潜在来源冲突：不同来源的搜索摘要给出了不一致的候选值。不可擅自选择其中一个作为最终答案；请逐项列出冲突，并说明需要查看原始页面或由用户人工核对。')
    for (const 冲突 of 冲突检查.冲突们) 行.push(`- ${冲突.说明}`)
    行.push(`冲突检测边界：${冲突检查.检测范围}。`)
  }
  if (问天气) 行.push('注意：以下仅为气象网站搜索摘要，尚未验证预报发布日期与有效日期，不能称为实时实况。若摘要不能明确支持目标日期，只提供来源并说明本次未取得可核实的天气数据，不可拿旧日期回答今天。')
  结果.forEach((条, i) => {
    行.push(`\n${i + 1}. ${条.标题}`)
    if (条.摘要) 行.push(`   ${条.摘要}`)
    if (条.发布日期) 行.push(`   发布/更新：${条.发布日期}`)
    else 行.push('   发布/更新：未提供')
    行.push(`   来源检查：${条.来源类型}；${条.日期状态}；${条.证据范围}`)
    if (条.链接) 行.push(`   来源：${条.链接}`)
  })

  return {
    好: true,
    内容: 行.join('\n'),
    条数: 结果.length,
    服务: 搜到.服务,
    来源: 结果.map((一) => 一.链接),
    来源审查: 来源检查.审查,
    材料门槛,
    冲突检查,
    验证状态: 材料门槛.通过 && !冲突检查.有冲突 ? '部分验证' : '未验证',
    目标完成: 材料门槛.通过 && !冲突检查.有冲突 ? '未知' : '部分',
    错误类别: 冲突检查.有冲突
      ? (材料门槛.通过 ? '来源冲突' : '材料不足与来源冲突')
      : (材料门槛.通过 ? '' : '材料不足'),
    可重试: 材料门槛.通过 ? false : !已重试,
    证据: 结果.map((一) => ({
      类型: 一.来源类型,
      目标: 一.标题,
      说明: `${一.摘要}${一.摘要 ? '；' : ''}${一.证据范围}；${一.日期状态}`,
      来源: 一.链接,
      时间: 一.发布日期,
    })),
    消耗Credits: 搜到.消耗Credits,
    已重试,
    重试原因: 已重试 ? (问天气 ? '天气来源或材料不足' : '材料不足') : '',
    问的是价: /多少钱|价格|报价|售价|价位|行情|贵不贵|涨了|跌了/.test(词),
    有没有捞到价: 结果.some((一) => /[￥¥]|\d+\s*(元|块钱|块)|价格|报价|售价|现价/.test((一.标题 || '') + ' ' + (一.摘要 || ''))),
  }
}

