// ============================================================

async function 读(路径) {
  const 查过 = 查路径(路径)
  if (!查过.好) return { 好: false, 说明: 查过.原因 }

  let 状态
  try {
    状态 = fs.statSync(查过.绝对路径)
  } catch (错误) {
    return { 好: false, 说明: '读不到：' + 错误.message }
  }

  if (状态.isDirectory()) {
    return { 好: false, 说明: '那是个目录，不是文件。想看她有什么就用 [列:那个目录]' }
  }

  if (状态.size > 读的上限) {
    return {
      好: false,
      说明: `那个文件太大了（${Math.round(状态.size / 1024)} KB，上限 ${读的上限 / 1024} KB）—— 挑个小的，或者跟我说你要看哪一段`,
    }
  }

  let 内容
  try {
    内容 = fs.readFileSync(查过.绝对路径, 'utf8')
  } catch (错误) {
    return { 好: false, 说明: '读不出来（可能是二进制文件）：' + 错误.message }
  }

  const 相对 = path.relative(工作区根, 查过.绝对路径)
  return {
    好: true,
    内容: `文件 ${相对} 的内容：\n\n${内容}`,
    字节: 状态.size,
  }
}

// ============================================================
// 四、工具三：列目录
// ============================================================

async function 列(路径) {
  const 查过 = 查路径(路径)
  if (!查过.好) return { 好: false, 说明: 查过.原因 }

  let 项们
  try {
    项们 = fs.readdirSync(查过.绝对路径, { withFileTypes: true })
  } catch (错误) {
    return { 好: false, 说明: '列不出来：' + 错误.message }
  }

  const 行 = []
  for (const 项 of 项们) {
    if (禁地.includes(项.name)) continue
    let 尾巴 = ''
    if (项.isFile()) {
      try {
        尾巴 = `  ${Math.round(fs.statSync(path.join(查过.绝对路径, 项.name)).size / 1024)} KB`
      } catch {
        /* 读不到大小就算了 */
      }
    }
    行.push((项.isDirectory() ? '[目录] ' : '       ') + 项.name + 尾巴)
  }

  const 相对 = path.relative(工作区根, 查过.绝对路径) || '（工作区根目录）'
  return {
    好: true,
    内容: `${相对} 里有这些：\n\n${行.join('\n')}`,
    个数: 行.length,
  }
}

