const 工具箱 = { 查, 读, 列 }

/**
 * 做一件事。
 *
 * @param {'查'|'读'|'列'} 做什么
 * @param {string} 参数
 * @returns {Promise<{好:boolean, 内容?:string, 说明?:string}>}
 */
async function 做(做什么, 参数) {
  const 工具 = 工具箱[做什么]
  if (!工具) return { 好: false, 说明: `没有「${做什么}」这个本事（有的是：查、读、列）` }

  const 开始 = Date.now()
  try {
    const 结果 = await 工具(参数)
    return { ...结果, 用时: (Date.now() - 开始) / 1000 }
  } catch (错误) {
    return { 好: false, 说明: `${做什么}的时候出错了：${错误.message}` }
  }
}

/**
 * 从她的话里把她想要的工具调用抠出来。
 *
 * 【2026-10-01 修过一次 —— 她把"列"写成了"列出"】
 *   实测她写的是：`[列出: D:/新建文件夹/爱莉希雅/]`
 *   而我原来只认"列"，多一个"出"字整条就认不出来 ——
 *   认不出来等于没调工具，那个标记还会留在正文里给她看见，
 *   她就只好凭记忆答（答得还挺心虚："我可不能凭印象说"）。
 *
 *   所以词表要放宽：她是在**生成文字**，不是在查说明书，
 *   同一个意思她可能写成"查/搜/搜一下/帮我查/查查"。
 *   宁可多认几个说法，也不要放过。
 */
const 工具词表 = {
  查: ['查', '搜', '搜索', '查一下', '搜一下', '帮我查', '帮我搜', '查询', '检索', '网上查'],
  读: ['读', '看', '读取', '读一下', '看一下', '看看', '打开', '翻阅', '查看'],
  列: ['列', '列出', '列一下', '列出一下', '列表', '看看有什么', '有什么'],
}

/** 把她的说法归一成三个标准动作 */
function 归一动作(写法) {
  const 干净 = String(写法 || '').trim()
  for (const [标准, 说法们] of Object.entries(工具词表)) {
    if (说法们.includes(干净)) return 标准
  }
  // 没精确匹配上，就按"包含"猜一下（"帮我查查" 这种）
  for (const [标准, 说法们] of Object.entries(工具词表)) {
    if (说法们.some((说法) => 干净.includes(说法) || 说法.includes(干净))) return 标准
  }
  return null
}

function 拆工具(她的话) {
  const 要做 = []
  const 不认识 = []
  const 文本 = String(她的话 || '')

  // [查:xxx] / [列出:xxx] / [读一下:xxx]；中英文方括号都认，冒号也认全角。
  // 动作那一栏放宽到 1~4 个字 —— 她的说法会变。
  const 模式 = /[\[【]\s*([^\s:：\]】]{1,4})\s*[:：]\s*([^\]】]+?)\s*[\]】]/g
  let m
  while ((m = 模式.exec(文本))) {
    const 标准 = 归一动作(m[1])
    if (!标准) {
      不认识.push({ 她写的: m[1], 参数: m[2].trim() })
      continue
    }
    要做.push({ 做什么: 标准, 参数: m[2].trim(), 她写的: m[1] })
  }

  // 去掉这些标记之后剩下的正文（给显示用）。
  // 多清一遍空格：抠掉标记之后常留下"我去看看  顺便"这种双空格。
  // **认不出来的标记也要清掉** —— 那是我这边的漏洞，不该让她看见。
  let 正文 = 文本.replace(模式, '')
  for (const 没认出的 of 不认识) {
    正文 = 正文.replace(`[${没认出的.她写的}:${没认出的.参数}]`, '')
  }
  正文 = 正文
    .split('\n')
    .map((行) => 行.replace(/[ \t]{2,}/g, ' ').replace(/[ \t]+$/, ''))
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim()

  return { 要做, 正文, 不认识 }
}

