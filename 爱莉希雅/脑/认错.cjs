'use strict'

/**
 * 认错 —— 出错的时候，先分清是**哪一种**错，再决定要不要重来。
 *
 * 【为什么不能"一出错就无脑重试"】
 *   错分两类，样子挺像，处理正好相反。
 *
 *   一类是**碰巧**：网抖了一下、对面忙、对面自己抽风。
 *     这种该再试 —— 干活那一轮最多要发 5 次请求，
 *     要是第 4 次赶上抖一下，前面读过的文件、跑过的编译**全白费**。
 *     重做一遍花的钱，比多试两次多得多。
 *
 *   另一类是**必然**：钥匙不对、余额不够、请求本身写错了。
 *     这种再试一百次结果一模一样，只是白等、白花钱，
 *     而且他看着屏幕上一直在转，会以为程序卡死了。
 *
 *   所以：先分清，再动手。
 *
 * 【"能重来"只是半个条件】
 *   这儿只管"这种错值不值得再试"。
 *   另一半在 要一轮 里判：**她还没开口**。
 *   屏幕上要是已经吐了半句，重来就会把前半句再说一遍 ——
 *   宁可少说一句，不能把说过的话说两遍。
 */

/**
 * 把错误里里外外翻一遍，拼成一段能拿去匹配的文字。
 *
 * 【为什么要挖】
 *   Node 的 fetch 报错长这样：
 *     TypeError: fetch failed
 *       └─ cause: Error: read ECONNRESET
 *   光看外层只有"fetch failed"四个字，**真正的病根在 cause 里**。
 *   老的 node-fetch 还会套一层 AggregateError（errors 数组）。
 *   不挖到底，就分不清"网断了"和"对面挂了"。
 *
 * @param {any} 错误
 * @param {number} 层数 防死循环
 * @returns {string}
 */
function 挖(错误, 层数) {
  if (!错误 || 层数 > 3) return ''
  const 片 = [错误.name, 错误.message, 错误.code]
  if (Array.isArray(错误.errors)) {
    for (const 里面 of 错误.errors) 片.push(挖(里面, 层数 + 1))
  }
  if (错误.cause && 错误.cause !== 错误) 片.push(挖(错误.cause, 层数 + 1))
  return 片.filter((x) => typeof x === 'string' && x).join(' | ')
}

// 一看就是"路上出的事"的记号。
// 这些全是网络层的：连不上、被掐、超时、域名都解析不出来。
const 网的记号 =
  /fetch failed|ECONNRESET|ECONNREFUSED|ETIMEDOUT|ENOTFOUND|EAI_AGAIN|EPIPE|EHOSTUNREACH|ENETUNREACH|UND_ERR|socket hang up|other side closed|terminated|network|Headers Timeout|Body Timeout/i

/**
 * 这个错是哪一种。
 *
 * @param {Error} 错误
 * @param {number} [状态码] 有 HTTP 回应的话带上来（没有就是 0）
 * @returns {{种类:string, 能重来:boolean, 基础等待:number, 说法:string}}
 *   种类：中止 / 网 / 忙 / 对面 / 钥匙 / 欠费 / 请求 / 说不清
 *   基础等待：毫秒。真要等的话，实际等 = 基础等待 × 第几次（越试越久）
 */
function 分类(错误, 状态码) {
  const 话 = (错误 && 错误.message) || String(错误 || '')
  const 码 = Number(状态码 || (错误 && 错误.状态码) || 0)
  const 全 = 挖(错误, 0)

  // ---- 他喊停的 / 我们自己掐的 ----
  // 这不算"出错"。他要是不想听了按了停，屏幕上不该冒一句红字吓他。
  //
  // 【注意那个 是超时】
  //   首字节超时也是 abort 出来的，报错长得**一模一样**
  //   （都是 AbortError + "This operation was aborted"）。
  //   所以判"喊停"必须先把超时那一种摘出去 ——
  //   不然等太久会被当成"他自己按的停"，然后一声不吭地算了。
  const 是喊停 =
    !(错误 && 错误.是超时) &&
    ((错误 && 错误.name === 'AbortError') || /This operation was aborted/i.test(话))
  if (是喊停) {
    return { 种类: '中止', 能重来: false, 基础等待: 0, 说法: '（这次是你喊停的）' }
  }

  // ---- 钱和钥匙：这两个必须说清楚，不然他会一直试 ----
  if (码 === 401 || 码 === 403) {
    return {
      种类: '钥匙',
      能重来: false,
      基础等待: 0,
      说法: `API Key 不对了（HTTP ${码}）—— 去设置里检查或更换`,
    }
  }
  if (码 === 402 || /insufficient\s*balance|余额不足|欠费/i.test(话)) {
    return {
      种类: '欠费',
      能重来: false,
      基础等待: 0,
      说法: '账户余额不够了（HTTP 402）—— 得去充值',
    }
  }

  // ---- 对面忙 / 对面自己抽风：值得等一等 ----
  if (码 === 429) {
    return { 种类: '忙', 能重来: true, 基础等待: 2000, 说法: '模型那边忙不过来（HTTP 429）' }
  }
  if (码 >= 500) {
    return {
      种类: '对面',
      能重来: true,
      基础等待: 1200,
      说法: `模型那边自己出错了（HTTP ${码}）`,
    }
  }

  // ---- 请求本身写错了：再试一万次也一样 ----
  if (码 >= 400) {
    return {
      种类: '请求',
      能重来: false,
      基础等待: 0,
      说法: `这次请求被拒了（HTTP ${码}）：${话.slice(0, 160)}`,
    }
  }

  // ---- 路上出的事 ----
  // 包括"等太久我先掐了" —— 那个是我自己 abort 的，
  // 但病根多半也是网：包发出去了，一个字节都没回来。
  if ((错误 && 错误.是超时) || 网的记号.test(全)) {
    // 秒数这么写是为了两种场合都对：平时是整 30 秒，
    // 测试的时候会被缩成 0.3 秒 —— "等了 0 秒" 那种话等于没说。
    const 秒 = ((错误 && 错误.等了) || 0) / 1000
    const 多久 = (秒 >= 10 ? Math.round(秒) : Number(秒.toFixed(1))) + ' 秒'
    return {
      种类: '网',
      能重来: true,
      基础等待: 700,
      说法: (错误 && 错误.是超时)
        ? `等了 ${多久}，模型那边一个字都没回`
        : '连不上模型那边（网络断了？）',
    }
  }

  // ---- 剩下的是真没见过。别装懂，把原文给他 ----
  return {
    种类: '说不清',
    能重来: false,
    基础等待: 0,
    说法: '说不清哪儿出问题了：' + 话.slice(0, 200),
  }
}

/**
 * 第 几次 试之前该等多久（毫秒）。
 * 越试等得越久 —— 对面要是真忙，连着捶它只会更忙。
 */
function 等多久(判, 第几次) {
  return Math.max(0, (判 && 判.基础等待 ? 判.基础等待 : 0) * Math.max(1, 第几次))
}

/**
 * 把底层那个错误包成一个"人能读"的错误，往上抛。
 *
 * 【为什么要把说法写进 message】
 *   这条 message 一路走到 main.js 的 `说话出错: ...`，
 *   再走到界面上的「（出问题了：...）」——
 *   最后是**他**在看。所以它得是句中国话，
 *   不能是 "fetch failed" 或者 "HTTP 402"。
 *   原文不丢，挂在 错误.原文 上，要查的时候还在。
 */
function 包装(错误, 判, 试了几次) {
  const 前缀 = 试了几次 > 1 ? `试了 ${试了几次} 次都没成：` : ''
  const 新 = new Error(前缀 + 判.说法)
  新.种类 = 判.种类
  新.能重来 = 判.能重来
  新.原文 = (错误 && 错误.message) || String(错误)
  新.状态码 = Number((错误 && 错误.状态码) || 0)
  return 新
}

module.exports = { 分类, 等多久, 包装, 挖 }
