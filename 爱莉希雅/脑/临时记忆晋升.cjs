/** 把一条已确认的临时记忆晋升到长期层；过程可重复调用，不会重复写长期记录。 */
'use strict'

function 晋升到长期({ 临时库, 长期库, 编号, 去向 }) {
  if (!临时库 || !长期库) throw new Error('缺少记忆库')
  const id = String(编号 || '').trim()
  const 目标类 = String(去向 || '').trim()
  if (!id) return { 好: false, 说明: '临时记忆编号不能为空' }
  if (!['事实', '经历', '小本子'].includes(目标类)) return { 好: false, 说明: '晋升去向不对' }

  let 条 = 临时库.取一条(id)
  if (!条) return { 好: false, 说明: '没找到这条临时记忆' }
  if (条.生命周期 === '已晋升' && 条.晋升 && 条.晋升.目标编号) {
    return { 好: true, 没变化: true, 目标编号: 条.晋升.目标编号, 去向: 条.晋升.去向 || 目标类 }
  }
  if (条.生命周期 !== '有效') return { 好: false, 说明: '只有有效的临时记忆可以晋升' }
  if (条.确认状态 !== '已确认') return { 好: false, 说明: '请先确认这条临时记忆' }

  if (!条.晋升 || ['未提议', '已拒绝'].includes(条.晋升.状态)) {
    const 提议 = 临时库.提议晋升(id, 目标类)
    if (!提议.好) return 提议
    条 = 提议.条
  }
  if (条.晋升.去向 !== 目标类) return { 好: false, 说明: `这条记忆正在等待晋升到${条.晋升.去向}` }
  if (条.晋升.状态 === '待确认') {
    const 批准 = 临时库.决定晋升(id, true)
    if (!批准.好) return 批准
    条 = 批准.条
  }
  if (条.晋升.状态 !== '已批准') return { 好: false, 说明: '晋升状态不允许写入长期记忆' }

  // 临时编号是幂等键。即使上次在长期写入后、短期标记前退出，重试也只会找回原目标。
  let 目标 = 长期库.全部长期记忆().find((一) => 一.临时记忆 === id)
  if (!目标) {
    目标 = 长期库.记一条(目标类, 条.内容, '我', {
      对话: 条.来源 && 条.来源.对话,
      临时记忆: id,
      记忆类型: 条.记忆类型,
      元数据: 条.元数据,
      自主评估: 条.自主评估,
    })
  }
  if (!目标 || !目标.编号) return { 好: false, 说明: '长期记忆没有写入成功' }
  const 完成 = 临时库.完成晋升(id, 目标.编号)
  return 完成.好 ? { 好: true, 目标编号: 目标.编号, 去向: 目标类 } : 完成
}

module.exports = { 晋升到长期 }

