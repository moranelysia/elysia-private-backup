/**
 * 提示词.cjs —— 按"层次"拼那叠递给她的话
 *
 * 【为什么要分成几层，而不是拼一大坨】
 *
 *   1. 省钱的层次摆前面。
 *      DeepSeek 有个机制：请求**开头那一大段**如果跟上次一字不差，
 *      就按缓存价算（便宜约十倍）。所以"永远不变的东西"必须放在最前面，
 *      "每次都变的东西"（记忆、时间）必须放到最后。
 *      原来的拼法把"关于他"那些**会变的记忆**夹在中间，
 *      于是它后面那一整段（包括工具说明）全都命中不了缓存 —— 白花了不少钱。
 *
 *   2. 模式要能分开。
 *      chat 模式只给联网搜索和本机时间说明，文件和命令工具一个都不给 ——
 *      这是 Cyrene 的做法，也是我们该学的：**越权不该靠她自觉，
 *      该靠"她压根不知道有那么个东西"。**
 *
 *   层次从先到后：
 *     ┌ 第一层「她是谁」  永远不变（角色卡来的）        ← 缓存的主力
 *     ├ 第二层「这个模式」按模式变（聊天 / 干活）      ← 换模式才变一次
 *     ├ 第三层「她的身体」按模式变（表情那套）          ← chat 里也有，但说得少
 *     └ 第四层「她记得的」每次都可能变（记忆）+ 时间    ← 放最后，不拖累上面
 *
 * 【为什么"记忆"要放最后】
 *   记忆每次说话都可能多一条（她自己会记）。放中间的话，
 *   从那条往后的所有内容（工具说明、环境说明）缓存全废。
 *   放最后，前面那一大块就永远是同一份了。
 */
