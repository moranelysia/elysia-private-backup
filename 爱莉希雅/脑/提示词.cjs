/**
 * 这个模式能不能动手（有没有工具、要不要转多轮、会不会被打回重做）。
 *
 * 【为什么要单独抽一个函数出来】
 *   原来代码里到处写着 `模式 === 'work'`。加第三种模式的时候，
 *   每一处都得重新想一遍"学习模式要不要也一样"——
 *   漏掉一处的表现是"她一会儿能写文件一会儿不能"，
 *   不报错、不崩，只是行为怪，查起来要命。
 *   收成一个函数，以后加模式只改这一行。
 */
function 能动手吗(模式) {
  return 模式 === 'work' || 模式 === 'learn'
}

/** 读角色卡（每次都重读，所以改完立刻生效，不用重启） */
function 读角色卡() {
  const 卡片 = JSON.parse(fs.readFileSync(角色卡路径, 'utf8'))
  const 数据 = 卡片.data || {}
  const 扩展 = (数据.extensions && 数据.extensions.dshCosplay) || {}
  return { 数据, 扩展 }
}

// ============================================================
// 第一层：她是谁（永远不变）
// ============================================================

function 第一层_她是谁() {
  const { 数据, 扩展 } = 读角色卡()
  const 段 = []

  段.push(
    '你就是爱莉希雅。不是「扮演」她——你就是她，用第一人称说中文。',
    '',
    `【你是谁】${数据.personality || ''}`,
    '',
    `【你在哪儿】${数据.scenario || ''}`,
    '',
    人格边界.核心边界,
  )

  if (数据.system_prompt) 段.push(数据.system_prompt, '')
  if (扩展.style) 段.push('【你怎么说话】', 扩展.style, '')
  if (扩展.rules) 段.push('【守则】', 扩展.rules, '')
  if (扩展.behavior) 段.push('【你在场的样子】', 扩展.behavior, '')
  if (数据.mes_example) 段.push('【像你、和不像你的例子】', 数据.mes_example, '')
  if (数据.post_history_instructions) 段.push('【开口之前】', 数据.post_history_instructions, '')

  return 段.join('\n')
}

