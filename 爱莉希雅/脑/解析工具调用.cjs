/**
 * 解析工具调用.cjs —— 从她的话里读出"她想干什么"
 *
 * 【要解析的东西长这样】
 *   她一边说话一边插标记：
 *
 *     我看看共同经历里记了什么。
 *
 *     [读:共同经历.md]
 *
 *   （等结果，然后再说下一段）
 *
 *   要写文件的时候，内容放在标记下面的代码块里：
 *
 *     [写:工作区\做个PPT.py]
 *     ```python
 *     from pptx import Presentation
 *     ...
 *     ```
 *
 *   跑命令直接写：
 *
 *     [跑:python 做个PPT.py]
 *
 * 【为什么要单独一个文件，不塞进 动手.cjs】
 *   解析是纯文字活儿（正则、定位、配对），执行是另一回事（碰磁盘、跑命令）。
 *   混在一起的话，改解析会碰到执行，改执行会碰到解析 —— 那就没法单独测。
 *   分开之后这个文件能拿一堆例子反复量，不用碰任何真实文件。
 *
 * 【最容易出错的地方，所以单独说】
 *   一个标记后面跟的代码块，**必须只归它**。
 *   她可能一口气写：
 *     [写:a.py]```...```  [写:b.py]```...```
 *   也可能写：
 *     [写:a.py]
 *     ```
 *     代码
 *     ```
 *   两种都得认。规则是：**每个代码块归"它前面最近的那个标记"**，
 *   而且一个块只能被用一次。
 */
'use strict'

/**
 * 代码块的写法：``` 开头，可带语言名，到下一个 ``` 结束。
 *
 * 【三处细节，全是实测踩出来的】
 *
 *   1. 那个换行是**可选**的。
 *      第一版要求代码块必须另起一行，于是她写成一行
 *        [写:a.py]```print(1)```
 *      就配不上，表现是"她说了要写、内容却是空的"。
 *
 *   2. 语言名那一截必须是**懒惰匹配**（`*?` 不是 `*`）。
 *      贪婪的时候，` ```print(1)``` ` 里的语言名会把 `print` 也吃进去
 *      （它也是字母啊），参数就变成 `(1)` 了 —— 写出来的文件是残的，
 *      而且不报错。
 *
 *   3. 换行符要在语言名那截**里面**判定。
 *      写成 `[a-z]*[ \t]*\n?` 的话，语言名那一截可以跨过换行继续吃。
 */
const 代码块模式 = /```[a-zA-Z0-9_+-]*?[ \t]*\r?\n?([\s\S]*?)```/g

/**
 * 把代码块开头那行的"语言名"剥掉。
 *
 * 【为什么用"剥"的，而不是让正则别吃它】
 *   试过调正则（懒惰匹配 + 各种边界），但有件事它分不清：
 *     ```python\nprint(1)```   ← python 是语言名，该剥
 *     ```print(1)```          ← print(1) 是内容，不该剥
 *   两者都是"字母开头、后面跟着别的"，正则没有依据区分。
 *
 *   但**换行**是个可靠的依据：语言名后面一定跟着换行；
 *   一行写完的代码块里，那个"print"后面跟的是括号，不是换行。
 *   规则就一句：
 *     第一行只有字母数字（像个语言名）**而且后面确实有换行** → 剥掉那一行
 *     否则整块都是内容
 */
function 剥语言名(内容) {
  const 文本 = String(内容 || '').replace(/\r\n/g, '\n')
  const 换行位置 = 文本.indexOf('\n')
  if (换行位置 < 0) return 文本.replace(/\s+$/, '') // 一行写完，整块都是内容
  const 第一行 = 文本.slice(0, 换行位置).trim()
  if (/^[a-zA-Z][a-zA-Z0-9_+-]{0,14}$/.test(第一行)) {
    return 文本.slice(换行位置 + 1).replace(/\s+$/, '')
  }
  return 文本.replace(/\s+$/, '')
}

/**
 * 一个"方括号里那串东西"：整个抓下来，怎么切后面再想办法。
 *
 * 【两个细节，都是实测踩出来的】
 *
 *   1. `[^\[\]【】\n]` 里的那个 **\n 是必须的**。
 *      第一版没写它，正则就会**跨行**吃 —— 她写过这种话：
 *          [列:记忆
 *          ...
 *          [表情:超级爱莉]
 *      结果从"记忆"一路吃到"表情"那个 ] 上，参数变成
 *      "记忆\n...\n[表情:超级爱莉" 这么一坨，两个人畜无害的标记
 *      合成一个谁也不认识的东西。
 *      **标记都在一行之内**，所以按行切就对了。
 *
 *   2. 长度上限 200 是防"一整段话里只有一个 [ 没有 ]"那种情况
 *      把整篇都吞下去。
 */
const 方括号模式 = /[\[【]([^\[\]【】\n]{1,200})[\]】]/g

/**
 * 把方括号里的内容切成 { 动词, 参数 }。
 *
 * 试的顺序（先严后松）：
 *   1. 有冒号 —— 最明确，按第一个冒号切
 *   2. 第一个空格 —— "读 共同经历.md"
 *   3. 动词长度从长到短试（4、3、2、1 个字）—— 治"写入工作区/测试.md"这种
 *      没有分隔符、动词和参数粘在一起的
 *
 * 只要某一种切法切出来的**动词是认识的**，就用它。
 * 全都不认识 → 返回 null（当作她不认识的写法，抠掉不留痕）。
 *
 * @param {string} 内容  方括号里那一串
 * @param {(写法:string)=>object|null} 认工具
 */
function 切动作(内容, 认工具) {
  const 串 = String(内容 || '').trim()
  if (!串) return null

  const 试 = (动词, 参数) => {
    const 干净动词 = String(动词 || '').trim()
    const 干净参数 = String(参数 || '').trim()
    if (!干净动词) return null
    const 工具 = 认工具(干净动词)
    if (!工具) return null
    return { 工具, 她写的: 干净动词, 参数: 干净参数 }
  }

  // 1. 冒号（中英文都算）
  const 冒号位置 = 串.search(/[:：]/)
  if (冒号位置 > 0) {
    const 命中 = 试(串.slice(0, 冒号位置), 串.slice(冒号位置 + 1))
    if (命中) return 命中
  }

  // 2. 空格
  const 空格位置 = 串.search(/[\s]/)
  if (空格位置 > 0) {
    const 命中 = 试(串.slice(0, 空格位置), 串.slice(空格位置 + 1))
    if (命中) return 命中
  }

  // 3. 没有分隔符的：动词和参数粘在一起（"写入工作区/x.md"）
  //
  //    【这里试过三版，前两版都不对，所以把道理写下来】
  //      第一版：动词长度从长到短试 → "写入工作区/x.md" 撞上二字动词"写入"，
  //              切成 参数="区/x.md"，**少了个"工作"**。
  //      第二版：从短到长试 → 撞上"写"，切成 参数="入工作区/x.md"，也错。
  //      第三版：给每种切法打分（看参数像不像路径）→ 两种切法分数**一样**，
  //              还是选错。
  //
  //      真正管用的判据是这个：**动词后面紧跟的如果是中文字，那动词多半还没完。**
  //      "写" + "入…" —— "入"是中文，说明"写入"才是一个词。
  //      "写" + "工作区/x.md" —— "工"也是中文啊……
  //
  //      所以再退一步：中文参数开头通常意味着这里本来就该断开，
  //      而"入工作区"里的"入"是个**动词补语**（写-入）。
  //      与其继续猜，不如**两种切法都留着**：挑不出高下的时候，
  //      让调用方（工具自己）去试 —— 写文件工具看到"入工作区/x.md"
  //      会说"这个路径找不到"，而"工作区/x.md"能成功。
  //
  //      不过那是很绕的做法。这里用一个更简单也够用的判据：
  //      **参数的开头如果是中文字，扣分**（参数多半是路径、命令、词条，
  //      开头常是字母数字或者盘符；而粘在动词后面的补语正是中文字）。
  const 打分 = (剩下) => {
    const s = String(剩下 || '').replace(/^[:：\s]+/, '')
    if (!s) return 0
    let 分 = 1
    if (/[\\/]/.test(s)) 分 += 3 // 带路径分隔符
    if (/\.\w{1,5}$/.test(s)) 分 += 3 // 带扩展名，基本就是文件
    if (/^[A-Za-z]:/.test(s)) 分 += 2 // 盘符开头
    if (/^[\u4e00-\u9fa5]/.test(s)) 分 -= 4 // ① 中文开头 → 多半是动词的补语，扣
    if (/^[:\s]/.test(s)) 分 -= 2
    return 分
  }

  const 候选切法 = []
  for (let 长度 = 1; 长度 <= 4 && 长度 < 串.length; 长度++) {
    const 命中 = 试(串.slice(0, 长度), 串.slice(长度))
    if (!命中) continue
    const 剩下 = 串.slice(长度)
    // 分高的优先；同分取动词长的
    候选切法.push({ ...命中, 分: 打分(剩下) * 10 + 长度, 动词长: 长度 })
  }
  if (候选切法.length) {
    候选切法.sort((a, b) => b.分 - a.分)
    return 候选切法[0]
  }

  // 4. 整串就是个动词，没有参数（少见，但比如 [列出] 想看根目录）
  const 光杆 = 试(串, '')
  if (光杆) return 光杆

  return null
}

/**
 * DeepSeek 的部分兼容入口偶尔不保留项目要求的 `[写:路径]`，而是把调用包装成：
 *   <ds_system_note>本条调用工具：写:路径</ds_system_note>
 *   ```代码载荷```
 * 这属于内部协议，不应出现在气泡、历史或语音里。允许的调用转换回统一标记，
 * 让后续仍能执行并抠除载荷；当前模式不允许或无法识别时，整段内部内容直接丢弃。
 */
function 规范化外部工具标记(原文, 认工具) {
  const 文本 = String(原文 || '')
  const 模式 = /<ds_system_note>\s*([\s\S]*?)<\/ds_system_note>([ \t\r\n]*)(```[a-zA-Z0-9_+-]*?[ \t]*\r?\n?[\s\S]*?```)?/gi

  return 文本.replace(模式, (_全部, 注记, _间隔, 代码块) => {
    const 去掉标题 = String(注记 || '').replace(/^[\s\S]*?(?:本条)?调用工具\s*[:：]\s*/i, '').trim()
    const 行们 = 去掉标题.split(/\r?\n/).map((行) => 行.replace(/^\s*[-*·]\s*/, '').trim()).filter(Boolean)
    let 动作 = null
    for (const 行 of 行们) {
      动作 = 切动作(行, 认工具)
      if (动作) break
    }
    if (!动作) return ''

    const 标记 = `[${动作.工具.名字}:${动作.参数}]`
    // 写入载荷必须继续跟着标记，后面的统一解析器才会把它交给写工具并从正文抠掉。
    if (动作.工具.名字 === '写' && 代码块) return `${标记}\n${代码块}`
    // 非写工具不使用代码块作为参数；若服务意外附带一块，视为普通回答内容保留。
    return 标记 + (代码块 ? `\n${代码块}` : '')
  })
}

/**
 * DeepSeek 原生工具调用标记：`<tool_call>…</tool_call>`（可能是空的，也可能带 JSON）。
 *
 * 我们不用这套协议（自己的标记是 `[查:…]` 这种），但模型会把它混进 content，
 * 于是气泡上直接显示一行 `<tool_call></tool_call>`。这是内部协议，不该给她看见。
 *
 * 处理原则：成对的整段丢掉，落单的开/闭标签也丢掉。
 * **故意不去解析里面的 JSON** —— 格式没有官方承诺，猜错了会执行错动作；
 * 宁可这一次不执行，也不能把内部标记漏到界面上。
 */
function 去掉原生工具标记(文本) {
  return String(文本 || '')
    .replace(/<tool_calls?>[\s\S]*?<\/tool_calls?>/gi, '')
    .replace(/<\/?tool_calls?>/gi, '')
}

/**
 * 从一段话里拆出所有工具调用。
 *
 * @param {string} 她的话
 * @param {(写法:string)=>object|null} 认工具  把"列出"认成"列"的那个函数
 * @returns {{要做:Array, 正文:string, 不认识:Array}}
 *          要做： [{ 工具, 名字, 参数, 内容, 她写的, 位置 }]
 *          正文： 把所有标记和它们带的代码块抠掉之后，剩下的话
 *          不认识：认不出来的标记（也要从正文里抠掉 —— 那是我们的漏洞，不该给她看见）
 */
function 拆(她的话, 认工具) {
  const 文本 = 去掉原生工具标记(规范化外部工具标记(她的话, 认工具))

  // ---- 一、先把代码块找出来，记下位置和内容 ----
  const 块们 = []
  let m
  代码块模式.lastIndex = 0
  while ((m = 代码块模式.exec(文本))) {
    块们.push({
      开始: m.index,
      结束: m.index + m[0].length,
      内容: 剥语言名(m[1]),
      用过了: false,
    })
  }

  // ---- 二、再把标记找出来 ----
  //
  // 整串抓下来，再拿"认识的动词表"去切它（怎么切见 切动作 的注释）。
  const 标记们 = []
  方括号模式.lastIndex = 0
  while ((m = 方括号模式.exec(文本))) {
    const 里面 = m[1]

    // 【2026-10-01 加的两道检查 —— 不干净就整个跳过】
    //
    //   实测出过事：她的话里有一个孤零零的 `[`（没配对），后面某处又有
    //   一个 `]` —— 正则把它们配成了一对，**中间上千字全成了"参数"**。
    //   然后"写"的代码块按位置配错，写进文件的就是那一坨乱码
    //   （他打开 hello.py 看到第 2、3 行是"（顺手放两句心里话……"）。
    //
    //   真的标记都很短、而且在一行里。所以：
    //     · 里面有换行 → 不是标记（标记从不跨行）
    //     · 超过 80 字 → 不是标记（最长的参数也就一条路径或一句话）
    //   不满足就跳过这一处，让正则接着往后找 ——
    //   跳过之后，前面那个 `[` 就配不上后面的 `]` 了，不会误吞。
    if (/[\n\r]/.test(里面)) continue
    if (里面.length > 80) continue

    const 切好的 = 切动作(里面, 认工具)
    if (!切好的) continue // 认不出来 —— 后面按"不认识"处理
    标记们.push({
      开始: m.index,
      结束: m.index + m[0].length,
      工具: 切好的.工具,
      她写的: 切好的.她写的,
      参数: 切好的.参数,
    })
  }

  // 认不出来的方括号：也要从正文里抠掉（那是我们漏了她的写法，
  // 不该让他看见 [翻个跟头:随便] 这种东西印在聊天框里）
  const 没认出的范围 = []
  方括号模式.lastIndex = 0
  while ((m = 方括号模式.exec(文本))) {
    const 里面 = m[1]
    if (/[\n\r]/.test(里面) || 里面.length > 80) continue
    if (切动作(里面, 认工具)) continue
    没认出的范围.push([m.index, m.index + m[0].length, 里面])
  }

  // ---- 三、一个标记配一个块：配"它后面最近的那个还没被用过的" ----
  //
  // 为什么是"后面"：她的写法是先写标记再给内容。
  // 但也见过先给内容再写标记的（少见），所以配不上就往前面找一个。
  const 要做 = []
  const 不认识 = []
  const 抠掉的范围 = []

  // 认不出来的方括号也要抠掉
  for (const [起, 止, 她写的] of 没认出的范围) {
    不认识.push({ 她写的, 参数: '' })
    抠掉的范围.push([起, 止])
  }

  for (const 标记 of 标记们) {
    const 工具 = 标记.工具

    // 只在"要写"的时候才去找代码块 —— 别的工具内容都在参数里
    let 内容 = null
    if (工具.危险度 === 'write' || 工具.名字 === '写') {
      let 配上的 = 块们.find((b) => !b.用过了 && b.开始 >= 标记.结束)
      if (!配上的) {
        // 往回找一个（先给内容后写标记的写法）
        配上的 = [...块们].reverse().find((b) => !b.用过了 && b.结束 <= 标记.开始)
      }
      if (配上的) {
        配上的.用过了 = true
        内容 = 配上的.内容
        抠掉的范围.push([配上的.开始, 配上的.结束])
      }
    }

    抠掉的范围.push([标记.开始, 标记.结束])
    要做.push({
      工具,
      名字: 工具.名字,
      参数: 标记.参数,
      内容,
      她写的: 标记.她写的,
      位置: 标记.开始,
    })
  }

  // ---- 四、正文 = 把标记和用掉的代码块都抠掉 ----
  //
  // 为什么要从后往前抠：抠掉一段之后，后面那些位置的下标就变了。
  // 从后往前处理，前面的位置就不会受影响。
  抠掉的范围.sort((a, b) => b[0] - a[0])
  let 正文 = 文本
  for (const [起, 止] of 抠掉的范围) {
    正文 = 正文.slice(0, 起) + 正文.slice(止)
  }

  正文 = 正文
    .split('\n')
    .map((行) => 行.replace(/[ \t]{2,}/g, ' ').replace(/[ \t]+$/, ''))
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim()

  // ---- 五、没配到内容的"写"要标出来 ----
  //
  // 她说要写、却没给内容 —— 那不是错误，是话没说完。
  // 得让她知道"内容没收到"，不然她会以为写成了。
  for (const 一件 of 要做) {
    if (一件.名字 === '写' && !一件.内容) {
      一件.缺内容 = true
    }
  }

  return { 要做, 正文, 不认识 }
}

/**
 * 把"她还没动手就先下的结论"切掉 —— 只留到她写第一个工具标记为止。
 *
 * 【为什么要有这个 —— 2026-10-01 晚上他提的】
 *   他原话："她的请求是晚于她的输出的，导致她根本不知道自己干了什么。"
 *   意思是屏幕上这个顺序：
 *     ① 她的话哗哗地流出来（里面常常已经在说"写好了""编出来了"）
 *     ② 然后确认卡片才弹出来问他准不准
 *   人是先读到结论、再去批准那个动作的。**顺序反了。**
 *   更糟的是①那些话是她在**还没拿到任何结果**的时候写的，
 *   所以里面经常有凭空的结论 —— 卡片一弹出来，他自己就看出来对不上。
 *
 *   而且他还得白看一大段：写文件的代码块也在第一轮里，
 *   等于整份文件先刷一屏，再问他要不要写。
 *
 * 【切法】
 *   找到第一个**认得出来**的工具标记，在那儿截断。
 *   [表情:] [记住:] 那些不算 —— 它们是"说完了顺手做的装饰"，
 *   通常还在句尾，切了反而把话截没了。
 *
 *   切完要是空的（她一上来就动手），那就一个字都不吐，
 *   界面上留着"在打字"那三个点，等结果回来再说。
 *
 * @param {string} 文本
 * @param {(写法:string)=>object|null} 认工具
 */
function 切到动手之前(文本, 认工具) {
  const 文 = 规范化外部工具标记(文本, 认工具)
  方括号模式.lastIndex = 0
  let m
  while ((m = 方括号模式.exec(文))) {
    const 里面 = m[1]
    // 跟 拆() 里同一套门槛：跨行的、太长的都不当标记
    if (/[\n\r]/.test(里面) || 里面.length > 80) continue
    if (!切动作(里面, 认工具)) continue
    return 文.slice(0, m.index).replace(/\s+$/, '')
  }
  return 文
}

