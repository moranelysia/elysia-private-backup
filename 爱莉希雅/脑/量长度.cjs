/**
 * 量长度.cjs —— 量"这次要发过去的东西有多长"，而且会自己越量越准
 *
 * 【为什么需要一把自己做的尺子】
 *   上下文管理说到底就一句话：**"这次要发过去的东西有多长？"**
 *   答不出这个，就谈不上"超了没有""该不该压"。
 *
 *   精确的 token 数只有模型那边算得出来（要它的分词器）。我们手上没有，
 *   也不想为了估个长度去装几十兆的分词表。所以自己做一把**估算**的尺子 ——
 *   不追求精确，只要能稳定回答"是三千还是一万"，就够做决定了。
 *
 * 【尺子长什么样】
 *   同一个 token 能装多少字，**看是什么字**：
 *     · 中文：一个汉字占掉大半个 token
 *     · 英文和代码：四个字符才一个 token 左右
 *   所以不能拿"字符数 ÷ 一个固定值"糊弄 —— 中文和代码混在一起时，
 *   一刀切会偏得很远。
 *   （DSH 那边就栽在这儿：它的 README 自己承认那条"四字符一 token"
 *     的尺子**量中文和 JSON 会低估得很厉害**。我们全中文，正好撞它枪口上。）
 *
 *   Cyrene 那边是分开数的：非 ASCII 按 1.5 字/token，ASCII 按 4 字/token。
 *   我们跟它一个形状，但中文那个数**按我们自己的账本校准**，不照抄它 ——
 *   见下面的修正系数。
 *
 * 【这把尺子最要紧的设计：它会自己纠偏】
 *   光有估算是不够的。估算是猜的，猜错了还不报错 —— 那就成了"用一个
 *   一直偏着的数做决定"，最坏的那种。
 *
 *   好在**每一次请求，模型都会把它真实算了多少 token 报回来**
 *   （账本里那个"输入"）。那就是标准答案。所以：
 *
 *     一、**每次请求完，拿真数跟估算对一次账**（对账()），记进
 *        记忆\尺子对账.jsonl。
 *     二、**下一次估算的时候，用攒下来的比值把尺子掰正**（修正系数()）。
 *     三、同一次请求里如果只是"在原来的基础上往后加了几条"
 *        （干活那一轮就是这样：一回合接一回合），那就**直接用上一次的真数
 *        + 增量的估算** —— 那比任何估算都准。
 *
 *   第三条是跟 DSH 学的。它原话是：
 *     "Provider usage is reused only when the latest successful call's
 *      canonical request envelope matches the measured envelope."
 *   意思是：**能拿到真数就用真数，尺子只补"这次比上次多出来的那一截"。**
 *   它还老实承认那些估算出来的数字"harness 里没有任何决定是靠它做的" ——
 *   因为决定靠的是带真数锚的那份。
 *
 * 【这些参数要当成"量级"，不是"精确值"】
 *   参数是猜的，对账是真的。跑几天之后 尺子准吗() 会告诉你偏多少。
 */
'use strict'

const fs = require('node:fs')
const path = require('node:path')
const 配置 = require('./配置.cjs')

// ============================================================
// 一、参数（要调就调这里）
// ============================================================

/** 一个方块字大概占多少 token（越小 = 估得越贵） */
const 中文字 = 0.6

/** 非中文的字符，几个算一个 token */
const 西文字 = 4

/** 每条消息的固定开销：role、包一层、分隔符那些 */
const 每条开销 = 4

/** 中日韩方块字（含中文标点那一片常用区） */
const 是方块字 = /[\u3000-\u303f\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff\uff00-\uffef]/

/** 修正系数的合理范围 —— 超出这个范围的多半是脏数据，别让它把尺子带飞 */
const 修正下限 = 0.5
const 修正上限 = 2.5

/** 至少攒够这么多条对账，才敢用修正系数 */
const 最少几条才敢修 = 10

// ============================================================
// 二、尺子本体
// ============================================================

/**
 * 估一段文字有多少 token（纯算，不看任何历史）。
 *
 * @param {string} 文本
 * @returns {number}
 */
function 估(文本) {
  const 文 = String(文本 == null ? '' : 文本)
  if (!文) return 0

  let 方块 = 0
  // 【为什么用 for...of 而不是下标循环】
  //   下标拿到的是 UTF-16 的"半个字符"（代理对），表情和生僻字会被劈成两半，
  //   两个半片都判成非中文。for...of 按真正的字符走。
  for (const 字 of 文) {
    if (是方块字.test(字)) 方块++
  }
  const 西文 = [...文].length - 方块

  // 向上取整 —— 宁可估多别估少（估少了会以为还装得下）
  return Math.ceil(方块 * 中文字 + 西文 / 西文字)
}

/**
 * 估一整个请求（纯算）。
 *
 * @param {Array<{role:string, content:string}>} 消息们
 * @returns {{总:number, 每条:number[]}}
 */
function 估消息们(消息们) {
  const 每条 = (消息们 || []).map((一条) => 估(一条 && 一条.content) + 每条开销)
  return { 总: 每条.reduce((和, n) => 和 + n, 0), 每条 }
}

// ============================================================
// 三、锚：能拿真数就别用估的
// ============================================================
//
// 【它治的是什么】
//   干活那一轮，程序会连着发好几次请求（一回合一次）：
//     第 1 次：系统提示 + 历史 + 他这句话
//     第 2 次：上面那些 + 她的话 + 工具结果
//     第 3 次：再往后接……
//   **后面的每一次都是在前面的基础上往后接**，前面那一大坨一个字没变。
//   所以第一次的真数拿到手，后面只要加上"新接的那几条"的估算就行 ——
//   比整段重估准得多。
//
// 【凭什么敢说"前面没变"】
//   判据是**同一个数组**（引用相同）。说话() 里就是往同一个 消息们 上 push，
//   中间不插不改。所以"同一个数组且更长"就等于"只是往后接了东西"。
//   换个对话、换一轮说话，数组是新建的，锚自动失效 —— 不会张冠李戴。

/** 上一次的真数锚 */
let 锚 = null // { 数组, 条数, 真实 }

/**
 * 记下这次请求的真数（模型报的），留给下一次当锚。
 *
 * @param {Array} 消息们  刚才发过去的那个数组（要引用，不是副本）
 * @param {number} 真实   prompt_tokens
 */
function 记真数(消息们, 真实) {
  if (!Array.isArray(消息们) || !真实) return
  锚 = { 数组: 消息们, 条数: 消息们.length, 真实: Number(真实) }
}

/** 把锚忘掉（换对话、清历史的时候该叫一声） */
function 忘掉锚() {
  锚 = null
}

/** 现在有没有锚可以用 */
function 有锚吗() {
  return !!(锚 && 锚.真实)
}

// ============================================================
// 四、对账：让尺子自己纠偏
// ============================================================

const 对账文件 = path.join(配置.数据目录, '尺子对账.jsonl')

/** 修正系数缓存（免得每轮都去读一遍文件） */
let 修正缓存 = null
let 修正读到第几条 = 0

/**
 * 记一笔对账。
 *
 * 【为什么比值永远对着"纯估"算，不对着"报出去的那个数"算】
 *   报出去的那个数可能已经吃过修正系数了。要是拿它去算比值，
 *   下一轮的修正系数就会把上一次的修正当成尺子本身的性质——
 *   自己修自己，数据看着越来越准，其实是自欺。
 *   所以**永远拿没修过的那个数**当基准，偏多少就是多少。
 *
 * @param {number} 纯估    没吃过修正的估算
 * @param {number} 实际    账本里模型报的输入 token
 * @param {string} [备注]
 * @param {string} [靠]    '真数锚' | '修正系数' | '纯估'
 * @param {string} [模式]  'chat' | 'work'
 * @returns {number|null}  实际 / 纯估
 */
function 对账(纯估, 实际, 备注 = '', 靠 = '', 模式 = '') {
  if (!纯估 || !实际) return null
  const 比值 = 实际 / 纯估
  try {
    fs.mkdirSync(path.dirname(对账文件), { recursive: true })
    const d = new Date()
    const 补 = (n) => String(n).padStart(2, '0')
    fs.appendFileSync(
      对账文件,
      JSON.stringify({
        时间: `${d.getFullYear()}-${补(d.getMonth() + 1)}-${补(d.getDate())} ${补(d.getHours())}:${补(d.getMinutes())}`,
        纯估,
        实际,
        比值: Number(比值.toFixed(3)),
        靠,
        // 【为什么非记这个模式不可】
        //   他 2026-10-03 说得很准："这两个 token 消耗量差得太大了。"
        //   而这个比值**多半是按模式分的**：
        //     聊天模式全是中文对话 —— 中文密度高
        //     干活模式夹着路径、命令、工具说明 —— ASCII 多，密度低
        //   不记模式的话，攒两百条也是一锅粥，回头想分开都分不开。
        //   现在先记着，**等两边各自攒够几十条再决定要不要各修各的** ——
        //   不能还没数据就先替它做主。
        模式,
        备注,
      }) + '\n',
      'utf8',
    )
    // 有新数据了，把缓存的修正系数作废
    修正缓存 = null
  } catch {
    /* 记不上就算了 —— 不能因为量长度把正事耽误了 */
  }
  return 比值
}

/** 读对账记录 */
function 读对账(最近几条 = 200) {
  try {
    return fs
      .readFileSync(对账文件, 'utf8')
      .replace(/^\uFEFF/, '')
      .split('\n')
      .filter((行) => 行.trim())
      .slice(-最近几条)
      .map((行) => JSON.parse(行))
  } catch {
    return []
  }
}

/**
 * 修正系数：拿攒下来的对账，把尺子掰正。
 *
 * 【为什么用中位数，不用平均数】
 *   平均数怕极端值 —— 有一次估得特别离谱（比如某次工具结果特别长），
 *   整个系数就被带跑了。中位数不受影响。
 *
 * @returns {number|null} 拿实际 token 除以估出来的，大致该乘多少
 */
function 修正系数() {
  if (修正缓存 !== null) return 修正缓存

  const 行们 = 读对账()
  修正读到第几条 = 行们.length
  if (行们.length < 最少几条才敢修) {
    修正缓存 = null // 数据太少，宁可不修
    return null
  }

  const 比值们 = 行们
    .map((一) => 一.比值)
    .filter((n) => typeof n === 'number' && isFinite(n) && n > 0)
    .sort((a, b) => a - b)

  if (!比值们.length) {
    修正缓存 = null
    return null
  }

  const 中位 = 比值们[Math.floor(比值们.length / 2)]
  // 夹一下 —— 脏数据别把尺子带飞
  修正缓存 = Math.min(修正上限, Math.max(修正下限, Number(中位.toFixed(3))))
  return 修正缓存
}

// ============================================================
// 五、对外就这一个口：估这次请求
// ============================================================

/**
 * 估这次（要）发过去的请求有多长。**优先用真数。**
 *
 * @param {Array<{role:string, content:string}>} 消息们
 * @returns {{tok:number, 纯:number, 靠:string}}
 *          tok  —— 拿去做决定用这个
 *          纯   —— 没吃过修正的原值，对账的时候要用它
 *          靠   —— 这个数是怎么来的（'真数锚' / '修正系数' / '纯估'）
 */
function 估请求(消息们) {
  const 数组 = Array.isArray(消息们) ? 消息们 : []
  const 纯 = 估消息们(数组).总

  // 一、同一个数组往后接了东西 → 上次真数 + 增量
  if (锚 && 锚.数组 === 数组 && 数组.length >= 锚.条数 && 锚.条数 > 0) {
    const 新增 = 数组.slice(锚.条数)
    const 增量 = 估消息们(新增).总
    const k = 修正系数()
    return {
      tok: 锚.真实 + Math.ceil(增量 * (k || 1)),
      纯,
      靠: '真数锚',
    }
  }

  // 二、没锚 → 用修正系数掰一下
  const k = 修正系数()
  if (k) return { tok: Math.ceil(纯 * k), 纯, 靠: '修正系数' }

  // 三、什么都没有 → 就用裸的估
  return { tok: 纯, 纯, 靠: '纯估' }
}

/**
 * 尺子最近准不准。**按模式分开算** —— 他关心的就是这个。
 *
 * @param {number} [最近几条]
 * @returns {{条数, 平均比值, 中位比值, 修正, 说法, 各模式}}
 */
function 尺子准吗(最近几条 = 200) {
  const 行们 = 读对账(最近几条)
  if (!行们.length) {
    return { 条数: 0, 平均比值: null, 中位比值: null, 修正: null, 说法: '还没有对过账', 各模式: {} }
  }

  const 算一批 = (批) => {
    const 比值们 = 批.map((一) => 一.比值).filter((n) => typeof n === 'number' && isFinite(n) && n > 0)
    if (!比值们.length) return null
    const 排序 = [...比值们].sort((a, b) => a - b)
    return {
      条数: 批.length,
      平均比值: Number((比值们.reduce((和, n) => 和 + n, 0) / 比值们.length).toFixed(3)),
      中位比值: Number(排序[Math.floor(排序.length / 2)].toFixed(3)),
    }
  }

  const 总体 = 算一批(行们)
  const 各模式 = {}
  // 三种模式分别算 —— 学习模式得单独看：它跟干活混在一起的话，
  // "陪他学"这件事到底花多少就看不出来了。
  for (const 名 of ['chat', 'work', 'learn']) {
    const 批 = 行们.filter((一) => 一.模式 === 名)
    if (批.length) 各模式[名] = 算一批(批)
  }

  return {
    条数: 行们.length,
    平均比值: 总体.平均比值,
    中位比值: 总体.中位比值,
    修正: 修正系数(),
    各模式,
    说法:
      总体.中位比值 > 1.15
        ? '估少了（实际比估的多），修正系数会往上掰'
        : 总体.中位比值 < 0.85
          ? '估多了（实际比估的少），修正系数会往下掰'
          : '挺准的',
  }
}

/** 把修正系数的缓存忘掉（下次现算） */
function 忘掉修正() {
  修正缓存 = null
}

