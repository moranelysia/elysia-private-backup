/**
 * 工具回执.cjs —— 把旧工具各说各话的结果，收成同一种可判断的回执。
 *
 * T1 只做兼容归一和本地闸门：旧工具仍可返回 { 好, 内容, 说明 }，
 * 这里给它补上执行、验证和目标三层状态。各工具更强的后置验证留给 T2。
 */
'use strict'

const 执行状态们 = ['成功', '失败', '拒绝', '超时', '取消']
const 验证状态们 = ['已验证', '部分验证', '未验证', '不适用']
const 目标完成们 = ['是', '部分', '否', '未知']

function 截(值, 最长 = 360) {
  const 字 = String(值 == null ? '' : 值).replace(/\r/g, '').trim()
  return 字.length <= 最长 ? 字 : 字.slice(0, Math.max(0, 最长 - 1)) + '…'
}

function 限定(值, 可选, 回退) {
  return 可选.includes(值) ? 值 : 回退
}

function 推执行状态(结果) {
  if (!结果 || typeof 结果 !== 'object') return '失败'
  if (执行状态们.includes(结果.执行状态)) return 结果.执行状态
  if (结果.已取消 || 结果.取消) return '取消'
  if (结果.被拒绝 || 结果.需要确认) return '拒绝'
  const 说明 = String(结果.说明 || 结果.内容 || '')
  if (结果.超时 || /超过\s*\d+(?:\.\d+)?\s*秒.*停止|timed?\s*out/i.test(说明)) return '超时'
  return 结果.好 === true ? '成功' : '失败'
}

function 默认验证状态(名字, 执行状态) {
  if (执行状态 !== '成功') return '不适用'
  if (名字 === '任务') return '已验证'
  if (['写', '交付', '读', '列', '找', '跑'].includes(名字)) return '部分验证'
  return '未验证'
}

function 默认目标完成(名字, 执行状态) {
  if (执行状态 !== '成功') return '否'
  // 这三项的旧实现已经直接改变或确认了目标对象；T2 会继续加强独立后验。
  if (['写', '交付', '任务'].includes(名字)) return '是'
  // 其余工具只证明拿到材料/跑过一步，不能单独证明整件事已经完成。
  return '未知'
}

function 推错误类别(结果, 执行状态) {
  if (结果 && 结果.错误 && typeof 结果.错误 === 'object' && 结果.错误.类别) return 截(结果.错误.类别, 80)
  if (结果 && 结果.错误类别) return 截(结果.错误类别, 80)
  if (执行状态 === '拒绝') return '权限拒绝'
  if (执行状态 === '超时') return '超时'
  if (执行状态 === '取消') return '用户取消'
  if (结果 && (结果.原因 === '天气结果不可靠' || /结果不可靠/.test(String(结果.原因 || '')))) return '结果不可靠'
  return 执行状态 === '失败' ? '执行失败' : ''
}

function 推截断(结果) {
  const 已有 = 结果 && 结果.截断
  if (已有 && typeof 已有 === 'object') {
    return {
      有: !!已有.有,
      原始量: Number(已有.原始量) || 0,
      保留量: Number(已有.保留量) || 0,
    }
  }
  const 文本 = String((结果 && (结果.内容 || 结果.说明)) || '')
  return { 有: /中间省掉|输出太长|纸条太长|只留了/.test(文本), 原始量: 0, 保留量: 0 }
}

function 洗证据(证据) {
  if (!Array.isArray(证据)) return []
  return 证据.slice(0, 8).map((一) => ({
    类型: 截(一 && 一.类型, 40) || '工具返回',
    目标: 截(一 && 一.目标, 240),
    说明: 截(一 && 一.说明, 360),
    来源: 截(一 && 一.来源, 500),
    时间: 截(一 && 一.时间, 40),
  }))
}

function 洗来源(来源) {
  const 清单 = Array.isArray(来源) ? 来源 : 来源 ? [来源] : []
  return [...new Set(清单.map((一) => 截(一, 500)).filter(Boolean))].slice(0, 8)
}

function 默认依据(名字, 原, 元, 摘要) {
  const 参数 = 截(元 && 元.参数, 240)
  if (['写', '交付'].includes(名字) && 原.路径) {
    return [{ 类型: '文件', 目标: 截(原.路径, 500), 说明: 截(原.动作 || 摘要, 360), 来源: '', 时间: '' }]
  }
  if (名字 === '任务' && 摘要) {
    return [{ 类型: '任务清单', 目标: 参数, 说明: 摘要, 来源: '', 时间: '' }]
  }
  if (名字 === '跑' && typeof 原.退出码 === 'number') {
    return [{ 类型: '退出码', 目标: 参数, 说明: `退出码 ${原.退出码}`, 来源: '', 时间: '' }]
  }
  return []
}

function 归一(名字, 结果, 元 = {}) {
  const 原 = 结果 && typeof 结果 === 'object' ? 结果 : {}
  const 已有 = 原.回执 && typeof 原.回执 === 'object' ? 原.回执 : {}
  const 执行状态 = 限定(已有.执行状态 || 原.执行状态 || 推执行状态(原), 执行状态们, '失败')
  const 验证状态 = 限定(
    已有.验证状态 || 原.验证状态 || 默认验证状态(名字, 执行状态),
    验证状态们,
    '未验证',
  )
  const 目标完成 = 限定(
    已有.目标完成 || 原.目标完成 || 默认目标完成(名字, 执行状态),
    目标完成们,
    '未知',
  )
  const 摘要 = 截(已有.摘要 || 原.说明 || 原.摘要 || 原.内容 || 原.路径 || '工具没有返回说明')
  const 证据 = 洗证据(已有.证据 || 原.证据)
  if (!证据.length) 证据.push(...默认依据(名字, 原, 元, 摘要))
  const 来源 = 洗来源(已有.来源 || 原.来源 || ((['写', '交付'].includes(名字) && 原.路径) ? [原.路径] : []))
  const 错误类别 = 推错误类别({ ...原, 错误: 已有.错误 || 原.错误, 错误类别: 已有.错误类别 || 原.错误类别 }, 执行状态)
  const 错误说明 = 执行状态 === '成功' ? '' : 截((已有.错误 && 已有.错误.说明) || 原.说明 || 原.内容 || 摘要)
  return {
    版本: 1,
    工具: 截(名字 || 元.名字 || '未知工具', 60),
    时间: 截(已有.时间 || 原.时间 || new Date().toISOString(), 40),
    执行状态,
    验证状态,
    目标完成,
    摘要,
    证据,
    来源,
    可重试: typeof 已有.可重试 === 'boolean' ? 已有.可重试
      : typeof 原.可重试 === 'boolean' ? 原.可重试
      : !['成功', '拒绝', '取消'].includes(执行状态),
    重试次数: Math.max(0, Number(已有.重试次数 ?? 原.重试次数 ?? (原.已重试 ? 1 : 0)) || 0),
    截断: 推截断({ ...原, 截断: 已有.截断 || 原.截断 }),
    错误: { 类别: 错误类别, 说明: 错误说明 },
    兼容: { 好: 原.好 === true },
  }
}

function 附上(名字, 结果, 元 = {}) {
  const 原 = 结果 && typeof 结果 === 'object'
    ? 结果
    : { 好: false, 说明: '工具没有返回结果' }
  return { ...原, 回执: 归一(名字, 原, 元) }
}

function 取(调用) {
  const 名字 = 调用 && (调用.名字 || (调用.工具 && 调用.工具.名字))
  return 归一(名字, 调用 && 调用.结果, { 参数: 调用 && 调用.参数 })
}

function 已实际执行(回执) {
  return !!回执 && ['成功', '失败', '超时', '取消'].includes(回执.执行状态)
}

function 已验证完成(回执) {
  return !!回执 && 回执.执行状态 === '成功' && 回执.目标完成 === '是' && Array.isArray(回执.证据) && 回执.证据.length > 0
}

function 从工具判断状态(工具们) {
  const 清单 = Array.isArray(工具们) ? 工具们 : []
  if (!清单.length) return '已完成'
  const 回执们 = 清单.map(取)
  const 有成功执行 = 回执们.some((一) => 一.执行状态 === '成功')
  const 有失败动作 = 回执们.some((一) => 一.执行状态 !== '成功')
  const 有完成证据 = 回执们.some(已验证完成)
  const 有部分或未知 = 回执们.some((一) => 一.目标完成 === '部分' || 一.目标完成 === '未知')
  const 有明确未完成 = 回执们.some((一) => 一.目标完成 === '否')
  if (有失败动作) return 有成功执行 || 有完成证据 ? '部分完成' : '失败'
  if (有完成证据 && !有明确未完成) return '已完成'
  if (有成功执行 || 有部分或未知) return '部分完成'
  return '失败'
}

module.exports = {
  归一,
  附上,
  取,
  已实际执行,
  已验证完成,
  从工具判断状态,
  执行状态们,
  验证状态们,
  目标完成们,
}
