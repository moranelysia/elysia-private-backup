/** 她写标记时用的那些名字，直接放行（程序不用猜） */
const 全都认识 = new Set()

/**
 * 从一段话里认表情。
 *
 * @param {string} 她的话
 * @param {object} [状态] 上一次的状态，用来避免同一个形态反复按
 * @param {string} [状态.粘住]  当前保持着的形态（比如"女仆形态"）
 * @returns {{表情:string[], 粘住:string|null}}
 */
function 认表情(她的话, 状态 = {}) {
  const 文本 = String(她的话 || '')
  const 要做 = []
  let 粘住 = 状态.粘住 || null

  for (const 规则 of 规则表) {
    // 这条规则有没有被提到
    const 命中 = 规则.词.some((词) => 文本.includes(词))
    if (!命中) continue

    if (规则.粘住) {
      // 已经是这个形态了就别重复按 —— 按一下会重新播一遍动画，很吵
      if (粘住 === 规则.表情) {
        粘住 = 规则.表情
        continue
      }
      粘住 = 规则.表情
    }

    if (!要做.includes(规则.表情)) 要做.push(规则.表情)

    // 一条规则命中就够，同一类不重复加
  }

  // 形态只有一个：要是这一句里同时出现两个形态词，只留最后命中的那个
  const 形态们 = ['人律形态', '妖精小姐', '女仆形态', '侵蚀']
  const 命中的形态 = 要做.filter((名) => 形态们.includes(名))
  if (命中的形态.length > 1) {
    const 留 = 命中的形态[命中的形态.length - 1]
    for (const 名 of 命中的形态) {
      if (名 !== 留) 要做.splice(要做.indexOf(名), 1)
    }
  }

  // 别的表情最多做一个，一次做一堆会像抽风
  const 别的 = 要做.filter((名) => !形态们.includes(名))
  const 最终 = [...要做.filter((名) => 形态们.includes(名)), ...别的.slice(0, 1)]

  return { 表情: 最终, 粘住 }
}

/** 让她把表情表里所有名字都注册进来 —— 她自己在标记里写什么，就直接放行 */
function 注册认识的名字(表情表) {
  for (const 类别 of ['表情', '动画', '语音']) {
    for (const 名 of Object.keys((表情表 && 表情表[类别]) || {})) 全都认识.add(名)
  }
  // 这些一定认识（表里可能有、也可能改过名，写死一层保险）
  for (const 名 of [
    '人律形态', '妖精小姐', '女仆形态', '侵蚀',
    '星星眼', '眯眯眼', '脸红', '脸黑', '流汗', '流泪眼', '吃西瓜', '痴呆', '疑问',
    '背后装饰出现', '背后装饰消失', '剪刀', '超级爱莉', '爱门',
    '星星眼消失', '眯眯眼消失', '脸红消失', '脸黑消失', '流汗消失',
    '流泪眼消失', '吃西瓜消失', '痴呆消失', '疑问消失',
  ]) {
    全都认识.add(名)
  }
}

