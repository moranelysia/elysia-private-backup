/**
 * 对话.cjs —— 把话递给她，再把她的回话接回来
 *
 * 这一节讲清楚"一次对话"到底发生了什么（你以后想改哪儿，看这里就够了）：
 *
 *   1. 你打了一句话
 *   2. 程序把三样东西拼在一起递过去：
 *        · 她是谁      （人格.cjs 拼的，一大段，每次一模一样）
 *        · 现在几点    （每次都变，所以单独放，免得影响缓存省钱）
 *        · 你们最近聊的（最近 20 句）
 *   3. 模型一个字一个字地吐回话
 *   4. 程序一边收一边把新字发到窗口上显示（这叫"流式"，不然要干等好几秒）
 *   5. 收完了再看她有没有在末尾留标记：[表情:星星眼] / [记住:...] / [经历:...]
 *      —— 有的话，把标记从显示的文字里去掉，交给对应的模块去办
 *
 * 【为什么要"一边收一边显示"】
 *   她整段话可能要三四秒才生成完。等完了再一起显示，你会以为程序卡了。
 *   流式就是让她的话"边说边出现"，跟你真的听人说话一样。
 *
 * 【那个"省钱"的讲究】
 *   DeepSeek 对"每次开头都一样"的请求有折扣（缓存命中，便宜约十倍）。
 *   所以第 2 步里那三样要**按固定顺序**拼：不变的在前，会变的在后。
 *   人格那一大段有九千多字，占了绝大部分开销 —— 它被缓存住了，就很便宜。
 */
