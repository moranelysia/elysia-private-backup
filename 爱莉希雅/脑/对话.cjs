/**
 * 把 [表情:星星眼] 这类标记挑出来，剩下的才是要显示给你看的正文。
 *
 * 支持三种：
 *   [表情:星星眼]            → 让桌面上的她变表情
 *   [记住:你明天有早课]      → 记进"关于眼前这个人的事实"
 *   [经历:你今天第一次弹和弦] → 记进"我们一起经历的"
 *   [更正事实:编号|新内容]     → 精确改正一条已有事实
 */
function 拆标记(原文) {
  const 表情们 = []
  const 记住们 = []
  const 经历们 = []
  const 更正事实们 = []

  let 正文 = 原文

  // 表情
  正文 = 正文.replace(/[\[【]\s*表情\s*[:：]\s*([^\]】]+?)\s*[\]】]/g, (_全, 名字) => {
    表情们.push(名字.trim())
    return ''
  })

  // 纠错只认提示里真实出现的稳定编号。程序随后还会按编号精确校验，找不到就不改。
  正文 = 正文.replace(/[\[【]\s*更正事实\s*[:：]\s*([^|\]】]{1,120})\|([^\]】]+?)\s*[\]】]/g, (_全, 编号, 内容) => {
    更正事实们.push({ 编号: 编号.trim(), 内容: 内容.trim() })
    return ''
  })

  // 记进"关于他的事实"
  正文 = 正文.replace(/[\[【]\s*记住\s*[:：]\s*([^\]】]+?)\s*[\]】]/g, (_全, 内容) => {
    记住们.push(内容.trim())
    return ''
  })

  // 记进"共同经历"
  正文 = 正文.replace(/[\[【]\s*经历\s*[:：]\s*([^\]】]+?)\s*[\]】]/g, (_全, 内容) => {
    经历们.push(内容.trim())
    return ''
  })

  // 标记常常单独占一行，抠掉之后会留下空行，收拾一下
  正文 = 正文
    .split('\n')
    .map((行) => 行.replace(/[ \t]+$/, ''))
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim()

  return { 正文, 表情: 表情们, 记住: 记住们, 经历: 经历们, 更正事实: 更正事实们 }
}

