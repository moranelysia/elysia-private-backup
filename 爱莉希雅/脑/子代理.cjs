/**
 * 子代理.cjs —— 派一个小助手去把脏活干完，只把结论带回来
 *
 * 【为什么要有这个 —— 2026-10-04】
 *   上下文管理有三种收拾法，我们已经做了两种：
 *     · 丢（修剪工具结果）—— 摊满了就把最老的那些大块裁掉
 *     · 压（摘要）—— 还没做
 *     · **派**（就是把脏活拿到别处去干，只把结论带回来）
 *
 *   这一条治的是很实在的一件事：
 *     她 [读:] 一个文件，最多吞 20000 字 ≈ 12000 token 进她的上下文；
 *     她 [查:] 一次，六条网页摘要整段赖在那儿。
 *     而她要的往往只是"里面说了什么" —— 那几百字，不是那一万二。
 *
 *   所以：**让子代理去读、去搜、去翻，回来交一张小纸条。**
 *   她的上下文里只多几百 token。
 *
 * 【它跟 DSH / Cyrene 那边是一回事】
 *   Cyrene 有 subagents（"任务委派 / 子 Harness"），DSH 有 subagent / ralph。
 *   它们的子代理都有一条共同规矩：**不许看见某些工具**（Cyrene 专门写了
 *   "必须保持对子代理不可见，否则子 agent 会绕过主 Loop 的规则"）。
 *   我们这儿最要紧的是不许看见【派】—— 不然它能一层层派下去，没底。
 *
 * 【三条设计上的硬规矩】
 *   一、**没有人设**。它是去干活的，不是爱莉希雅。
 *       不带那 21 条守则、不带语气、不带"像不像她"——
 *       一来省 token（那 6000 多 token 白给它看没用），
 *       二来它要是学着爱莉希雅的口吻汇报，那些语气会顺着结论爬回她的上下文。
 *   二、**工具照样要经过他同意**。它 [写:] [跑:] 的时候，卡片照弹 ——
 *       审批那一层是全局的（脑\确认.cjs），不分子代理还是主代理。
 *   三、**只回一段话**。中间读了什么、搜了什么，一个字都不带回来。
 *       带回来的多了，派它就没有意义了 —— 那就等于自己干。
 */
'use strict'

const path = require('node:path')

const 工具表 = require('./工具表.cjs')
const 解析工具调用 = require('./解析工具调用.cjs')
const 工具回执 = require('./工具回执.cjs')

/** 子代理最多转几轮（每轮 = 说一句话 + 用一次工具） */
const 最多几轮 = 3

/** 它最后交回来的那张纸条最多多少字（超了截，并且说清楚截了） */
const 结论上限 = 2000

/** 它一次最多说多少 token */
const 最多多少字 = 1500

/**
 * 给子代理的那份说明书。
 *
 * 【为什么这么短】
 *   它的上下文里除了这份就是任务本身，**没有历史、没有记忆、没有人设**。
 *   短就是它的价值 —— 主代理那边一份说明书六千多 token，它这份两百。
 */
function 助手提示() {
  const 能用的 = 工具表.表.filter((t) => t.名字 !== '派').map((t) => t.名字)
  return [
    '你是爱莉希雅派出去办事的助手 —— 一句话：**去把这件事办完，回来交张纸条**。',
    '',
    '【你是谁】',
    '你不是爱莉希雅。没有人设、不用她的口吻、不要卖萌、不要演。',
    '你是个干活的：说事实、报数字、给路径。',
    '',
    '【怎么办】',
    ' · 需要现实世界的信息就去拿，别凭记忆答、别猜。',
    ' · 你能用的工具：' + 能用的.join('、'),
    '   写法跟爱莉希雅一样，比如 [读:某个文件] [查:要搜的话] [跑:一条命令]。',
    ' · **一步一步来**：先看，再动。别一上来就写一大堆。',
    ' · 要写文件、要跑命令的时候程序会先问他 —— 他不同意就别硬来。',
    '',
    '【最后交什么】',
    ' 一段话，**不超过 400 字**。里面要有：',
    ' · 直接回答他派你去的那个问题',
    ' · 具体的东西（数字、路径、命令、错误原文）—— 照抄，别转述',
    ' · 拿不准的地方直说拿不准',
    '',
    '**别写**：你查了哪些步骤、用了什么工具、你打算怎么做。',
    '**别编**：没查到就说没查到。宁可交一张空纸条，也别给他一个像真的假答案。',
    '他只看最后那段话，中间的你干了什么他看不见。',
  ].join('\n')
}

/** 把几件工具的结果拼成一条"给他的材料" */
function 拼结果(结果们) {
  return (
    '【你刚才要的东西】\n\n' +
    结果们
      .map(({ 项, 结果 }) =>
        结果.好
          ? `【${项.名字}：${项.参数}】\n${结果.内容}`
          : `【${项.名字}：${项.参数}】没成 —— ${结果.说明 || 结果.内容 || '（没给原因）'}`,
      )
      .join('\n\n') +
    '\n\n（接着办。办完了就交纸条。）'
  )
}

/**
 * 派一个小助手去办一件事。
 *
 * @param {string} 任务      要它干什么（一句中文）
 * @param {object} [选项]
 * @param {Function} [选项.问]   遇到要点头的事，走这条路问他（跟主代理共用同一条）
 * @param {AbortSignal} [选项.中止]
 * @returns {Promise<{好:boolean, 结论?:string, 用了几轮?:number, 用过的工具?:Array, 用了?:object, 说明?:string}>}
 */
async function 派(任务, 选项 = {}) {
  const 要它干什么 = String(任务 || '').trim()
  if (!要它干什么) return { 好: false, 说明: '没说要它干什么' }
  if (要它干什么.length > 500) return { 好: false, 说明: '派下去的事说得太长了（上限 500 字）—— 一句话说清要什么就行' }

  // 【这个 require 为什么写在函数里面，不写在文件头上】
  //   要一轮() 住在 对话.cjs 里，而 对话.cjs 会 require 工具表.cjs，
  //   工具表.cjs 又 require 这个文件 —— 三边一绕就是个环。
  //   写在函数里，等真要用的时候再取：那会儿 对话.cjs 早加载完了。
  //   （文件头上写的话，加载顺序会咬到自己。）
  const { 要一轮, 记一笔账 } = require('./对话.cjs')

  // 认得出来的工具：跟主代理同一张表，**唯独没有【派】**
  const 认 = (写法) => {
    const 工具 = 工具表.认工具(写法)
    return 工具 && 工具.名字 !== '派' ? 工具 : null
  }

  const 消息们 = [
    { role: 'system', content: 助手提示() },
    { role: 'user', content: 要它干什么 },
  ]

  const 用过的工具 = []
  let 最后的话 = ''
  let 用了 = null
  let 转了几轮 = 0

  for (let 轮 = 1; 轮 <= 最多几轮; 轮++) {
    转了几轮 = 轮
    let 一轮
    try {
      一轮 = await 要一轮({
        消息们,
        温度: 0.2, // 干活的温度：要的是准，不是有意思
        最多多少字,
        中止: 选项.中止,
      })
    } catch (错误) {
      // 子代理出错不该把主代理那一轮也拖垮 —— 交一张写着原因的纸条回去
      return { 好: false, 说明: '小助手那边出错了：' + 错误.message, 用过的工具 }
    }

    最后的话 = 一轮.全文
    if (一轮.用了) {
      用了 = 一轮.用了
      // 【子代理花的钱也得进账本 —— 2026-10-04 补的】
      //   记账原来只在 说话() 的循环里做，而子代理的请求是直接从 要一轮
      //   出去的 —— **一分钱都不会记上**。
      //   这跟 10 月 1 号那次一模一样："命令行测试花的钱没进账本，
      //   账上写的比实际少。" 教训是：**凡是真发了请求的地方，都得记一笔。**
      //   备注写成"小助手"，事后能把它的样本挑出来单看
      //   （它那份提示词短得多，混进主代理的对账里会稍微带偏中位数）。
      记一笔账(一轮.用了, 消息们, '小助手', 'work')
    }

    const 拆的 = 解析工具调用.拆(一轮.全文, 认)
    if (!拆的.要做.length) break // 它说完了

    消息们.push({ role: 'assistant', content: 一轮.全文 })

    const 结果们 = await Promise.all(
      拆的.要做.slice(0, 3).map(async (一件) => {
        const 原结果 = await 一件.工具.做(一件.参数, 一件.内容, {
          // 审批走同一条路 —— 他要点头的事，子代理也一样要问
          问: 选项.问,
          中止: 选项.中止,
          他说的话: 要它干什么,
        })
        const 结果 = 工具回执.附上(一件.名字, 原结果, { 参数: 一件.参数 })
        用过的工具.push({ 名字: 一件.名字, 参数: 一件.参数, 结果 })
        return { 项: 一件, 结果 }
      }),
    )

    消息们.push({ role: 'user', content: 拼结果(结果们) })

    // 最后一轮还动了手 → 再来一次只要结论（不然交回来的是一堆标记）
    if (轮 === 最多几轮) {
      消息们.push({
        role: 'user',
        content: '【够了】别再动手了。用你手上有的东西，现在就交那张纸条。',
      })
      try {
        const 收尾 = await 要一轮({ 消息们, 温度: 0.2, 最多多少字, 中止: 选项.中止 })
        最后的话 = 收尾.全文
        if (收尾.用了) {
          用了 = 收尾.用了
          记一笔账(收尾.用了, 消息们, '小助手收尾', 'work')
        }
      } catch {
        // 收尾这一下没成就用上一轮的，总比什么都没有强
      }
    }
  }

  // 【交回来的必须是干净的一段话】
  //   她那边是把它当"材料"看的。要是里面还夹着 [读:xxx] 这种标记，
  //   主循环会**把它当成她又想动手** —— 那就乱套了。
  const 干净 = 解析工具调用.拆(最后的话, 认).正文.trim()
  if (!干净) return { 好: false, 说明: '小助手什么都没交回来', 用过的工具, 用了几轮: 转了几轮 }

  const 纸条 =
    干净.length > 结论上限
      ? 干净.slice(0, 结论上限) + `\n\n……（纸条太长了，只留了前 ${结论上限} 字）……`
      : 干净

  // 【交回去的时候必须写清楚"这是别人替你跑的"】
  //   不写的话，她会把纸条上的事讲得跟自己亲眼翻过一样 ——
  //   "我看了那份文件""我翻了一遍工作区"。
  //   那不是撒谎，是她**真的觉得自己看到了**（纸条就摆在眼前）。
  //   可他要的是"谁去看的"，不是"谁转述的"。
  //   这跟 10 月 1 号那次"她说写好了其实没写"是同一类事：**知行要分开**。
  const 内容 =
    纸条 +
    '\n\n（这是小助手替你跑回来的一张纸条。**那些东西你没有亲眼看过** ——' +
    ' 他要是问细节，就说你让小助手去看过了，别讲得跟自己翻过一样。）'

  // 她那边拿到的"工具结果"就是这一段。中间读了多少、搜了多少，一个字都不带过去。
  return {
    好: true,
    内容,
    结论: 纸条,
    用了几轮: 转了几轮,
    用过的工具,
    用了,
    说明: `小助手转了 ${转了几轮} 轮（用了 ${用过的工具.map((t) => t.名字).join('、') || '没动手'}）`,
  }
}

module.exports = { 派, 助手提示, 最多几轮, 结论上限 }
