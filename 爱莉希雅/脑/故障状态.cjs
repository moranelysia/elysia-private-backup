'use strict'

/** 把底层错误收成 renderer 可以直接展示的短状态，不把长响应或密钥送进页面。 */
function 干净文字(值, 最多 = 240) {
  const 文字 = String(值 || '')
    .replace(/sk-[A-Za-z0-9_-]{8,}/g, 'sk-***')
    .replace(/\s+/g, ' ')
    .trim()
  return 文字.length > 最多 ? 文字.slice(0, 最多 - 1) + '…' : 文字
}

function 状态(类别, 标题, 说明, 建议, 操作 = '') {
  return { 类别, 标题, 说明: 干净文字(说明), 建议, 操作 }
}

function 从对话错误(错误) {
  const 种类 = 错误 && 错误.种类
  const 说明 = (错误 && 错误.message) || '没有收到更具体的错误信息。'
  if (种类 === '网') return 状态('网络', '网络连接失败', 说明, '检查网络后重新发送。')
  if (种类 === '忙' || 种类 === '对面') {
    return 状态('模型', '模型服务暂时不可用', 说明, '稍等一会儿再发送。')
  }
  if (种类 === '钥匙') return 状态('模型', 'API Key 无法使用', 说明, '到设置里检查或更换 API Key。', '打开设置')
  if (种类 === '欠费') return 状态('模型', '模型账户余额不足', 说明, '检查模型账户余额后再试。')
  if (种类 === '请求') return 状态('模型', '模型请求被拒绝', 说明, '检查模型与请求设置。')
  return 状态('模型', '这次回复失败了', 说明, '可以稍后再试；反复出现时打开工具记录检查。')
}

function 服务(名字, 说明) {
  return 状态('服务', `${名字}没有启动`, 说明 || `没有连接到${名字}。`, `启动${名字}后再打开。`)
}

function 权限(说明) {
  return 状态('权限', '这一步没有获得权限', 说明 || '操作没有执行。', '需要时重新发起，并在确认卡中决定是否允许。')
}

module.exports = { 从对话错误, 服务, 权限, 干净文字 }
