/**
 * 修剪工具结果.cjs —— 桌子摊满了，就先把最占地方的那些收起来
 *
 * 【它治的病】
 *   干活的时候，程序会替她去跑工具，把结果一大段一大段塞回对话里。
 *   而干活一轮最多要发 5 次请求（3 回合 + 收尾 + 打回重做），
 *   **每一次都把前面攒的全部重发一遍** —— 一轮之内自己滚雪球。
 *
 *   我们的上限是这样的（见 tools\看上下文.cjs 量出来的）：
 *     [读:] 单次最多吐 20000 字 ≈ 12000 token
 *     [跑:] 单次最多吐 30000 字 ≈ 18000 token
 *     留给"对话 + 工具结果"的余量只有 49449 token
 *     → **两个满格的 [跑:] 输出就把 64K 窗口撑爆**
 *
 *   而在这之前，程序里没有任何一处在数"现在这堆有多长"。
 *
 * 【它是跟 DSH 的 pruner 学的，四条规矩照抄】
 *   一、**只在超线的时候动手** —— 没超的一个字都不碰
 *       （它的原话：below-pressure conversations remain unchanged）
 *   二、**只裁工具结果** —— 她说过的话、系统提示，一个字不动
 *   三、**头 + 标记 + 尾** —— 不花一分钱，不调模型
 *   四、**裁掉的原文留着** —— 出问题能翻回去看她当时到底拿到了什么
 *
 * 【为什么这是"丢"而不是"摘要"】
 *   摘要要再调一次模型（花钱、花时间、还有损），而工具结果的原文
 *   **通常用完就没用了** —— 她看过那份文件、跑过那条命令，结论已经在她嘴里了。
 *   而"她说过什么"要用很久。所以先丢最没用的那个，别急着压有用的。
 *
 * 【它不做什么】
 *   不做摘要（那是下一步）、不动系统提示、不动她的话、
 *   不改磁盘上任何东西（除了留档那一份）。
 */
'use strict'

const fs = require('node:fs')
const path = require('node:path')
const 配置 = require('./配置.cjs')

const 尺 = require('./量长度.cjs')

// ============================================================
// 一、参数
// ============================================================

/** 模型的上下文窗口 */
const 窗口 = 65536

/** 到窗口的百分之多少就该动手（DSH 和 Cyrene 都是 0.8，两家一致） */
const 线比例 = 0.8

/** 动手的线：估算输入超过它就裁 */
const 默认线 = Math.floor(窗口 * 线比例)

/** 单条工具结果超过这么多字才值得裁（短的不动 —— 裁了也省不下多少，还添乱） */
const 单条上限 = 8000

/** 裁完留头多少字 */
const 留头 = 5000

/** 裁完留尾多少字（错误信息常在尾巴上） */
const 留尾 = 1200

/** 最近几轮的工具结果完整留着（她正在用那份，不能动） */
const 最近几轮不动 = 1

/** 留档目录最多留几个文件（超了删最老的 —— 那是缓存，不是档案库） */
const 留档上限 = 300

/** 留档放哪儿 */
const 留档目录 = path.join(配置.缓存目录, '工具输出')

// ============================================================
// 二、块：一条"工具结果消息"是由哪几块拼的
// ============================================================
//
// 【为什么要记这个】
//   给她的那条消息不是"一件工具的结果"，是**拼起来的**：
//     前面几件工具的结果 + 最后挂着的"交代"
//   （交代 = "讲的时候像平时说话那样""拿不准就说拿不准"这类指令。）
//   裁的时候要是把整条换掉，交代也跟着没了 —— 她就不知道该怎么讲。
//   所以得记住它是哪几块拼的，裁的时候**按块换、重新拼一遍**。

/** 把几块拼成给她的那一条 */
function 拼一条(块们, 交代 = '') {
  const 身子 = (块们 || [])
    .map((块) => `【${块.标签}】\n${块.正文}`)
    .join('\n\n')
  return (
    '【内部】他看不见这段。这是你刚才要的东西，用你自己的话讲给他听：\n\n' +
    身子 +
    (交代 ? '\n\n' + 交代 : '')
  )
}

/**
 * 把"这条消息是哪几块拼的"挂到消息上。
 *
 * 【为什么用不可枚举的字段 —— 这一条很要紧】
 *   消息数组最后会被 JSON.stringify 发到模型那边去。
 *   要是把这个记录写成普通字段，**它就跟着请求发出去了** ——
 *   等于每轮白烧一大段 token 去说"我这里有几块"。
 *   defineProperty 加上 enumerable: false，JSON 就看不见它。
 */
function 挂块(消息, 块们, 交代 = '') {
  Object.defineProperty(消息, '__块们', { value: 块们, enumerable: false, writable: true, configurable: true })
  Object.defineProperty(消息, '__交代', { value: 交代, enumerable: false, writable: true, configurable: true })
  return 消息
}

/** 这条消息带着工具结果的块吗 */
function 拿块(消息) {
  return (消息 && 消息.__块们) || null
}

// ============================================================
// 三、裁一块
// ============================================================

/** 中间省掉多少字的标记 —— 要说清楚省了多少，见下面那段注释 */
function 标记(省了) {
  return `\n\n……（这里原本有一大段输出，中间省掉了 ${省了} 字）……\n\n`
}

/**
 * 裁一块。
 *
 * 【为什么标记里必须写"省掉了多少字"】
 *   不写的话，她看到的就是"那命令只吐了这么点" ——
 *   于是她会当成全部，据此下结论。
 *   那就成了"她说的和实际不一样"，正是这个项目里一直在防的那类事。
 *   写上数字，她至少知道自己手上是残缺的，会留个心眼。
 *
 * @returns {{改过:boolean, 正文:string, 省了:number}}
 */
function 裁一块(块) {
  const 原文 = String((块 && 块.正文) || '')
  if (原文.length <= 单条上限) return { 改过: false, 正文: 原文, 省了: 0 }

  const 头 = 原文.slice(0, 留头)
  const 尾 = 原文.slice(-留尾)
  const 省了 = 原文.length - 留头 - 留尾
  return { 改过: true, 正文: 头 + 标记(省了) + 尾, 省了 }
}

// ============================================================
// 四、留档
// ============================================================

/** 把标签里的路径分隔符之类的换成安全的字符（它要当文件名） */
function 安全名(文本) {
  return String(文本 || '')
    .replace(/[\\/:*?"<>|\r\n\t]/g, '_')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, 40)
}

/** 现在的时间戳，做成文件名能用的样子 */
function 时间戳() {
  const d = new Date()
  const 补 = (n) => String(n).padStart(2, '0')
  return `${d.getFullYear()}${补(d.getMonth() + 1)}${补(d.getDate())}-${补(d.getHours())}${补(d.getMinutes())}${补(d.getSeconds())}`
}

/**
 * 把裁掉的那段原文留一份。
 *
 * 【为什么值得留】
 *   不留的话，裁完那段就**真的没了** —— 磁盘上没有，日志里也没有
 *   （日志只有一行 `↳ 动手：跑(...) —— 成功`）。
 *   哪天她答得不对，你连"她当时到底拿到了什么"都查不了。
 *   留一份，几十 KB 换一个能复查的机会。
 *
 * @returns {string|null} 存到哪儿了
 */
function 留一份(块) {
  try {
    fs.mkdirSync(留档目录, { recursive: true })
    const 名 = `${时间戳()}-${安全名(块.工具 || '工具')}-${安全名(块.标签)}.txt`
    const 全 = path.join(留档目录, 名)
    fs.writeFileSync(
      全,
      `【这一份是修剪时裁掉的原文】\n` +
        `时间：${new Date().toLocaleString('zh-CN')}\n` +
        `工具：${块.工具 || '？'}\n` +
        `标签：${块.标签}\n` +
        `原文长度：${String(块.正文 || '').length} 字\n` +
        `${'─'.repeat(50)}\n\n` +
        String(块.正文 || ''),
      'utf8',
    )
    清一清留档()
    return 全
  } catch (错误) {
    console.log('⚠ 留档没写成: ' + 错误.message)
    return null
  }
}

/** 留档目录别无限长下去 —— 超了把最老的删掉（那是缓存，不是档案库） */
function 清一清留档() {
  try {
    const 表 = fs
      .readdirSync(留档目录)
      .filter((名) => 名.endsWith('.txt'))
      .map((名) => ({ 名, 时间: fs.statSync(path.join(留档目录, 名)).mtimeMs }))
      .sort((a, b) => a.时间 - b.时间)
    const 多的 = 表.length - 留档上限
    for (let i = 0; i < 多的; i++) fs.rmSync(path.join(留档目录, 表[i].名), { force: true })
  } catch {
    /* 清不动就算了，不影响正事 */
  }
}

// ============================================================
// 五、收拾桌子（对外的那个口）
// ============================================================

/**
 * 现在这堆有多长。
 *
 * @param {Array} 消息们
 * @returns {number} 估算 token（带真数锚和修正系数）
 */
function 现在多长(消息们) {
  return 尺.估请求(消息们).tok
}

/**
 * 该动手了吗。
 *
 * @returns {{要:boolean, 现在:number, 线:number}}
 */
function 要不要动手(消息们, 选项 = {}) {
  const 线 = 选项.线 ?? 默认线
  const 现在 = 现在多长(消息们)
  return { 要: 现在 > 线, 现在, 线 }
}

/**
 * 收拾桌子：超线的话，把最老的那些大块工具结果裁掉。
 *
 * 【顺序为什么是"先老后大"】
 *   老的先裁 —— 她多半已经用完那份了。
 *   同一个回合里，大的先裁 —— 省的 token 多，动的地方少。
 *   最近一轮**完全不碰** —— 那是她正在看的。
 *
 * 【裁完为什么要告诉尺子"锚失效了"】
 *   真数锚靠的是"这个数组只往后接、前面一个字没变"。
 *   裁过之后前缀变了，锚就不成立了 —— 还留着它，估出来的数会偏高，
 *   偏高是安全的方向（宁可早裁），但那是**错的**。
 *   所以叫一声忘掉锚，退回纯估（带修正系数），老老实实重算。
 *
 * @returns {{裁了:number, 省了字:number, 省了tok:number, 留档:string[], 说明:string}}
 */
function 收拾(消息们, 选项 = {}) {
  const 空 = { 裁了: 0, 省了字: 0, 省了tok: 0, 留档: [], 说明: '' }
  if (!Array.isArray(消息们) || !消息们.length) return 空

  const 线 = 选项.线 ?? 默认线
  const 现在 = 现在多长(消息们)

  // 一、没超线 —— 一个字都不动
  if (现在 <= 线) return { ...空, 说明: `现在 ${现在} tok，没到线（${线}），不动` }

  // 二、找出所有"带工具结果块"的消息，最近那几轮不碰
  const 带块的 = []
  消息们.forEach((条, 下标) => {
    if (拿块(条)) 带块的.push(下标)
  })
  const 可动的 = 带块的.slice(0, Math.max(0, 带块的.length - 最近几轮不动))
  if (!可动的.length) {
    return { ...空, 说明: `现在 ${现在} tok 超过线了，可只有一轮工具结果（正在用），没法裁` }
  }

  // 三、候选：先老后大
  const 候选 = []
  for (const 下标 of 可动的) {
    const 块们 = 拿块(消息们[下标])
    块们.forEach((块, 块序) => {
      if (String(块.正文 || '').length > 单条上限) 候选.push({ 下标, 块序, 块 })
    })
  }
  if (!候选.length) {
    return { ...空, 说明: `现在 ${现在} tok 超过线了，可没有单条超过 ${单条上限} 字的（都是零碎的，裁了也省不下）` }
  }

  // 四、一条条裁，够了就停
  let 剩余 = 现在
  let 省了字 = 0
  let 省了tok = 0
  const 留档 = []
  const 动过的下标 = new Set()

  const 每tok字 = 0.6 // 中文大约 0.6 token/字，用来估"这一裁省了多少"
  for (const { 下标, 块序, 块 } of 候选) {
    if (剩余 <= 线) break

    const 果 = 裁一块(块)
    if (!果.改过) continue

    const 省 = Math.ceil(果.省了 * 每tok字)
    留一份(块)
    留档.push(块.标签)

    const 块们 = 拿块(消息们[下标])
    块们[块序] = { ...块, 正文: 果.正文 } // 不能改原来那个对象 —— 留档还得用它的原文
    动过的下标.add(下标)

    省了字 += 果.省了
    省了tok += 省
    剩余 -= 省
  }

  // 五、改过的消息重新拼一遍（把交代挂回去）
  for (const 下标 of 动过的下标) {
    const 条 = 消息们[下标]
    条.content = 拼一条(拿块(条), 条.__交代 || '')
  }

  // 六、裁过就得忘掉锚（理由见函数头上那段）
  if (动过的下标.size) 尺.忘掉锚()

  return {
    裁了: 动过的下标.size,
    省了字,
    省了tok,
    留档,
    说明:
      `现在 ${现在} tok 超过线（${线}）—— 裁了 ${动过的下标.size} 条，` +
      `省下约 ${省了tok} tok（${省了字} 字），估完剩 ${剩余} tok`,
  }
}

