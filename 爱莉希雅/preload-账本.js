// preload-账本.js —— 小面板（账本）跟外面之间的那道门
//
// 跟 preload.js 是同一个道理：网页出于安全碰不到电脑上的东西，
// 所以「能做什么」得在这儿一项一项列出来。
// 这个面板要的权限极少 —— 它只负责把数字显示出来：
//
//   要账本()      拿一份最新的汇总
//   收到更新(回调) 她每次说完话，主进程把新数字推过来
//   收起来()      把面板收掉
//   打开账本文件() 用记事本打开那本流水账（一行一次对话）

const { contextBridge, ipcRenderer } = require('electron')

contextBridge.exposeInMainWorld('账本', {
  /** 拿一份汇总：这次的、今天的、一共的 */
  要账本: () => ipcRenderer.invoke('要账本'),

  /** 她说完一句，主进程会把新数字送过来 */
  收到更新: (回调) => {
    ipcRenderer.on('账本更新', (_事件, 数) => 回调(数))
  },

  /** 面板上的开关：把它自己收掉 */
  收起来: () => ipcRenderer.send('切换账本', false),

  /** 拿记事本打开那本流水账 */
  打开账本文件: () => ipcRenderer.send('打开账本文件'),
})
